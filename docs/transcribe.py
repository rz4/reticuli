"""Capture a real terminal session and the CLI reference into docs pages.

    python3 docs/transcribe.py        # writes docs/session.md and docs/cli.md

Both pages are generated by running the actual tool and recording what it
prints, because documentation for terminal users is trustworthy exactly to
the extent that its command blocks are real. Hand-written transcripts drift;
these are re-captured on every docs build. The only edits applied to
captured output are stated normalizations: the working directory is shown
as `~/demo`, and output longer than a screen is elided with a marker.

The session uses the shipped `examples/make` claim, whose producer is
`make` — so every step, including the blind rebuild, runs offline with no
model and no credentials.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOCS = REPO / "docs"
PY = sys.executable
ENV = dict(os.environ, PYTHONPATH=str(REPO / "src"), NO_COLOR="1",
           COLUMNS="80")
MAXLINES = 26


def sh(command, cwd, check=False):
    done = subprocess.run(["sh", "-c", command], cwd=cwd, env=ENV,
                          capture_output=True, text=True, timeout=600,
                          check=False)
    if check and done.returncode != 0:
        raise SystemExit(f"transcribe: step failed unexpectedly\n"
                         f"$ {command}\n{done.stdout}{done.stderr}")
    return done


def block(demo, scratch, commands):
    """Run commands in sequence; render one console block.

    A command may be a plain string or a (command, comment) pair. The
    comment is display-only — the executed string is exact — and renders as
    a shell comment: trailing and aligned when it fits, on its own line
    above otherwise, so each block reads standalone without the prose.

    A command ending in " #?" has the marker stripped and its exit status
    shown after its output, stderr included — the ordering a terminal user
    would see, which naive stdout+stderr+echo concatenation gets wrong.
    """
    ret = f"{PY} -m reticuli"
    lines = []
    for command in commands:
        comment = None
        if isinstance(command, tuple):
            command, comment = command
        wants_exit = command.endswith(" #?")
        command = command.removesuffix(" #?")
        done = sh(command, demo)
        shown = (command.replace(ret + " ", "ret ")
                 .replace(PY, "python3")
                 .replace(str(demo), "~/demo")
                 .replace(str(scratch), "~/work"))
        if comment and len(shown) <= 30:
            lines.append(f"$ {shown:<32}# {comment}")
        elif comment:
            lines.append(f"# {comment}")
            lines.append(f"$ {shown}")
        else:
            lines.append(f"$ {shown}")
        text = ((done.stdout + done.stderr)
                .replace(str(demo), "~/demo")
                .replace(str(scratch), "~/work"))
        out = [ln.rstrip() for ln in text.splitlines()]
        if len(out) > MAXLINES:
            out = out[:MAXLINES] + [f"[... {len(out) - MAXLINES} lines elided ...]"]
        lines += out
        if wants_exit:
            lines += ["$ echo $?", str(done.returncode)]
    return "```console\n" + "\n".join(lines) + "\n```"


def session():
    scratch = Path(tempfile.mkdtemp(prefix="reticuli-session-"))
    demo = scratch / "demo"
    shutil.copytree(REPO / "examples" / "make", demo)
    ret = f"{PY} -m reticuli"

    page = ["# Quickstart", "",
            ("Every block below is a real invocation, captured by "
            "`docs/transcribe.py` against the shipped `examples/make` claim "
            "and re-captured on every docs build. Normalizations, stated: "
            "the entry point is shown as `ret`, the claim directory as "
            "`~/demo`, the scratch directory as `~/work`; output longer "
            "than a screen is elided with a marker. The claim's producer is "
            "`make`, so every step runs offline."), "",
            ("The claim: a word-count program. Pinned: the acceptance gate "
            "(`check.sh`), its test cases, the `Makefile`, and the C "
            "source. Generated: the compiled binary."), "",
            ("This page is self-sufficient: after it you can verify, audit, "
            "rebuild, and record claims. Everything after it in the "
            "documentation is depth, not prerequisites."), ""]

    def step(title, prose, commands):
        page.extend([f"## {title}", "", prose, "",
                     block(demo, scratch, commands), ""])

    step("Verify: is this the claim it names?",
         "`verify` recomputes the root from the pinned bytes and compares. "
         "Exit status is the machine-readable verdict.",
         [(f"{ret} verify . #?", "recompute the root; compare; exit status is the verdict")])

    step("A claim travels without its implementation",
         "`verify` passes above — identity is intact — but `audit` "
         "refuses: the gate has nothing to judge. Identity and membership "
         "are separate questions with separate instruments.",
         [("ls", "note: no compiled binary — the implementation is not part of the claim"),
          (f"{ret} audit . #?", "re-earn the gate in a sandboxed room: nothing to judge yet")])

    step("Rebuild: regrow the implementation from the claim",
         "The producer here is `make`; for other claims, a coding agent — "
         "the contract is identical. The regrown claim lands at the same "
         "root: different bytes, same identity.",
         [(f"{ret} rebuild . --producer make --into {scratch}/M3",
           "fresh room, declared inputs only; the producer writes the binary"),
          (f"{ret} audit {scratch}/M3 #?", "the regrown claim re-earns its gate")])

    step("Tamper with a pinned byte",
         "The root no longer matches: this is a different claim, and "
         "`verify` says so, naming both roots. Identity is the bytes, not "
         "the file's history.",
         [("printf '#\\n' >> check.sh", "append one byte to the PINNED acceptance gate"),
          (f"{ret} verify . #?", "a different root: a different claim"),
          ("sed -i '' -e '$d' check.sh", "remove the byte"),
          (f"{ret} verify . #?", "identity returns")])

    step("Damage the generated output",
         "`verify` still passes — the root covers pinned material only — "
         "but the gate judges the bytes present, and `audit` refuses.",
         [(f": > {scratch}/M3/wordcount", "truncate the GENERATED binary"),
          (f"{ret} verify {scratch}/M3 #?", "identity intact: the root covers pinned bytes only"),
          (f"{ret} audit {scratch}/M3 #?", "membership lost: the gate judges the bytes present"),
          (f"rm -f {scratch}/M3/wordcount {scratch}/M3/OK", "discard the damaged member entirely"),
          (f"{ret} rebuild {scratch}/M3 --producer make --into {scratch}/M3b",
           "regrow a fresh member; same root again")])

    step("Record: evidence that travels",
         "A record freezes one machine's results in the canonical "
         "interchange format: identity, per-gate verdicts with the sandbox "
         "backend used, environment, measured cost.",
         [(f"{ret} record {scratch}/M3b --out {scratch}/record.json",
           "freeze this machine's results, canonically"),
          (f"head -c 400 {scratch}/record.json; echo",
           "identity, gates with the sandbox used, environment, cost")])

    page += ["## Where to go next", "",
             ("[The process](process.md) for the lifecycle these commands "
             "walk; [mechanisms](mechanisms.md) for rooms, the scrub, and "
             "the sandbox tiers; [the CLI reference](cli.md) for every verb."),
             ""]
    (DOCS / "quickstart.md").write_text("\n".join(page))
    shutil.rmtree(scratch, ignore_errors=True)
    print("wrote docs/quickstart.md")


def cli():
    ret = f"{PY} -m reticuli"
    top = sh(f"{ret} --help", REPO).stdout
    verbs = re.findall(r"^    ([a-z]+) {2,}", top, re.MULTILINE)
    page = ["# CLI reference", "",
            ("Generated from the tool's own help text by "
            "`docs/transcribe.py`; regenerated on every docs build."), "",
            "```text", top.rstrip(), "```", ""]
    for verb in verbs:
        done = sh(f"{ret} {verb} --help", REPO)
        text = (done.stdout + done.stderr).rstrip()
        if not text:
            continue
        page += [f"## `ret {verb}`", "", "```text", text, "```", ""]
    page += ["## Conventions", "",
             ("- Exit status 0 is the affirmative verdict; nonzero is a "
             "refusal with the reason on stderr."),
             ("- `--json` emits a machine-readable envelope on stdout, "
             "including for refusals."),
             ("- Commands that judge (`verify`, `audit`, `crosscheck`) never "
             "modify the claim they judge."), ""]
    (DOCS / "cli.md").write_text("\n".join(page))
    print(f"wrote docs/cli.md ({len(verbs)} verbs)")


if __name__ == "__main__":
    session()
    cli()
