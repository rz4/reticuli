"""Selection: find a better member, without touching the boundary.

Everything else in zeta CONTRACTS. Pressure finds unpinned surface, a
signature declares it, the class gets smaller and reconstruction gets harder.
Every lane narrows -- contraction, eviction, repair -- and none of them can
say "here is a better member", because that is not a statement about the
specification at all.

Selection is the other direction, and it is nearly free. The root excludes the
implementation by construction, `verify` compares only the root ("a generated
rebuild keeps them equal"), and membership is decided by the gate. So moving
from one member to another:

    moves no root          the implementation is generated, outside the root
    needs no signature     nothing root-moving happens
    retires no population  the root did not move, so nobody is evicted
    changes no difficulty  reconstruction faces the same boundary

Contrast the ratchet, where every click costs a root move and the whole
reconstruction population. The first genuine improvement this project found --
a reconstruction 2.5x smaller and 13% faster than the shipped tree, earning
the same gate -- was sitting in a trial's output costing nothing, while three
root moves were spent the same day making the boundary sharper.

TWO GUARDS, AND THEY ARE THE WHOLE DESIGN.

MEMBERSHIP FIRST. A candidate that does not earn the claim's gate is not a
small member, it is not a member. Measuring it alongside members would make
the frontier a ranking of programs rather than of answers, and the smallest
program is always the one that does nothing. This is the degenerate member the
project already measured: under an instruction to minimise, a producer
collapses to the blind prior in one step. Tight criteria are what make a small
member trustworthy, which is why contraction is the precondition for selection
rather than a rival to it.

AXES DECLARED BEFORE MEASURING. A fitness chosen after seeing the result is a
story about the winner. The axes below are fixed in this file, their digest
travels with every result, and adding one afterwards changes that digest --
so a reader can tell a measurement from a rationalisation.

AND SELECTION NEVER ADOPTS. It reports a frontier, not a winner. One axis here
runs the other way on purpose: `prose_bytes` counts comments and docstrings,
and MORE is better, because that is the institutional memory -- the dated
witnesses, the reason each guard exists. A reconstruction carries almost none
of it. Ranking on size alone would recommend trading away the only thing that
makes the tree maintainable by a person, and a gate cannot see that at all.
The frontier shows the trade; a human picks.
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import sys
import time
import tokenize
from pathlib import Path

SCHEMA = "zeta.selection.1"

#: Declared in advance. Each axis names what it measures, which direction is
#: better, and the fact that nothing in the root constrains it -- that is what
#: makes it available for selection rather than a criterion.
AXES = [
    {"name": "total_bytes", "better": "lower",
     "measures": "bytes of the generated implementation",
     "unpinned": "the root excludes generated bytes entirely"},
    {"name": "code_bytes", "better": "lower",
     "measures": "bytes that are not comment or docstring",
     "unpinned": "no criterion bounds implementation size"},
    {"name": "prose_bytes", "better": "higher",
     "measures": "bytes of comment and docstring: the institutional memory",
     "unpinned": "the boundary transmits behaviour, never reasoning"},
    {"name": "audit_seconds", "better": "lower",
     "measures": "wall-clock to re-earn the claim's gate with this member",
     "unpinned": "resource obligations are growth RATIOS, host-independent, "
                 "so absolute cost is not pinned"},
]


def axes_digest():
    """What was declared, before anything was measured."""
    return hashlib.sha256(json.dumps(AXES, sort_keys=True,
                                     separators=(",", ":")).encode()).hexdigest()


def _prose_split(text):
    """Comment and docstring bytes, separated from everything else."""
    comment = doc = 0
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return None
    previous = None
    for token in tokens:
        if token.type == tokenize.COMMENT:
            comment += len(token.string)
        elif token.type == tokenize.STRING and previous in (
                None, tokenize.INDENT, tokenize.NEWLINE, tokenize.NL,
                tokenize.DEDENT):
            doc += len(token.string)
        if token.type not in (tokenize.NL, tokenize.NEWLINE):
            previous = token.type
    return comment + doc


def measure_bytes(candidate, outputs):
    """Size axes, over exactly the generated outputs the recipe names."""
    total = prose = 0
    for name in outputs:
        path = Path(candidate["path"]) / Path(name).relative_to(candidate["prefix"])
        if not path.is_file():
            raise ValueError(f"{candidate['id']} is missing {name}")
        text = path.read_text(encoding="utf-8", errors="replace")
        total += len(text.encode("utf-8"))
        split = _prose_split(text)
        if split is None:
            raise ValueError(f"{candidate['id']} cannot be tokenised: {name}")
        prose += split
    return {"total_bytes": total, "prose_bytes": prose,
            "code_bytes": total - prose}


def measure(candidate, repo, kernel, outputs):
    """Membership first, then the axes. A non-member gets no measurements."""
    mapping = {name: str(Path(candidate["path"]) /
                         Path(name).relative_to(candidate["prefix"]))
               for name in outputs}
    started = time.monotonic()
    verdict = kernel.audit(str(repo), produce_from=mapping)
    seconds = time.monotonic() - started
    row = {"candidate": candidate["id"], "member": bool(verdict.get("ok")),
           "audit_seconds": round(seconds, 1)}
    if not row["member"]:
        # Reported, never measured further: a program that does not earn the
        # gate is not a cheaper answer, it is not an answer.
        row["why"] = "did not earn the claim's gate"
        return row
    row.update(measure_bytes(candidate, outputs))
    return row


def dominates(left, right):
    """Pareto: at least as good on every axis, strictly better on one."""
    better = False
    for axis in AXES:
        name, direction = axis["name"], axis["better"]
        a, b = left.get(name), right.get(name)
        if a is None or b is None:
            return False
        if direction == "lower":
            if a > b:
                return False
            if a < b:
                better = True
        else:
            if a < b:
                return False
            if a > b:
                better = True
    return better


def frontier(rows):
    """The non-dominated members. Never a winner -- a frontier.

    A single ranking would need weights across axes that trade behaviour
    against maintainability, and nothing measures the second one. Reporting
    the frontier says exactly what was found and leaves the trade to a person.
    """
    members = [r for r in rows if r.get("member")]
    return sorted(r["candidate"] for r in members
                  if not any(dominates(other, r) for other in members
                             if other is not r))


def candidates(repo):
    """Every implementation that could be a member: the shipped tree, and each
    lineage tree a succession run left behind.

    `prefix` is how a candidate spells the generated outputs the recipe names.
    The shipped tree keeps the repository layout; a lineage tree is the package
    contents with no `src/reticuli` above it, so the prefix differs and the
    paths have to be rewritten rather than assumed.
    """
    repo = Path(repo)
    found = [{"id": "shipped", "path": str(repo / "src" / "reticuli"),
              "prefix": "src/reticuli", "origin": "authored"}]
    lineages = repo / "research" / "harness" / "succession"
    for run in sorted(lineages.glob("lineages*")):
        for family in sorted(p for p in run.iterdir() if p.is_dir()):
            tree = family / "tree"
            if (tree / "kernel.py").is_file():
                tag = run.name.replace("lineages", "") or "-base"
                found.append({"id": f"{tag.lstrip('-')}:{family.name}",
                              "path": str(tree), "prefix": "src/reticuli",
                              "origin": "reconstruction"})
    return found


def survey(rows):
    return {"schema": SCHEMA, "axes": AXES, "axes_digest": axes_digest(),
            "rows": sorted(rows, key=lambda r: r["candidate"]),
            "members": sorted(r["candidate"] for r in rows if r.get("member")),
            "refused": sorted(r["candidate"] for r in rows if not r.get("member")),
            "frontier": frontier(rows),
            "adoption": "never automatic: one axis is unmeasurable by any gate, "
                        "so the frontier is reported and a person chooses"}
