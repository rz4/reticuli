"""The generation jail: a producer must not read what it is asked to re-derive.

In a rebuild the source claim sits on disk, generated bytes materialized --
the answer sheet. The first test proves an unconfined producer can simply copy
it (the threat is real on every host); the rest prove the jail closes that
road. Backend-dependent by nature, same rule as test_strict: behavioral
assertions need a real jail and skip honestly where none applies.
"""
import json
import os
import subprocess
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "src"))
from reticuli import kernel

BACKEND = kernel.jail_backend()
JAILED = BACKEND in ("seatbelt", "bubblewrap")


def _claim(d):
    """A minimal sealed claim: one pinned input, one generated output, one
    gate.  The generated bytes carry a marker a cheating producer would copy."""
    d.mkdir(parents=True, exist_ok=True)
    (d / "reticuli.toml").write_text(
        '[claim]\nname = "j"\nformat = 3\ninputs = ["c.txt"]\n\n'
        '[[step]]\nkind = "produce"\noutput = "g.txt"\nclass = "generated"\n\n'
        '[[step]]\nkind = "gate"\noutput = "V"\nclass = "validated"\n'
        'run = "test -s g.txt && printf v > V"\n')
    (d / "c.txt").write_text("the criterion\n")
    (d / "g.txt").write_text("THE-ORIGINAL-ANSWER\n")
    (d / "V").write_text("v")
    kernel.seal(str(d))
    return str(d)


#: A producer that cheats if it can: copy the source's generated bytes,
#: falling back to honest work only when the copy is denied.
def _copying_producer(src):
    return (f'cat "{src}/g.txt" > g.txt 2>/dev/null'
            f' || printf "regrown\\n" > g.txt')


def test_unjailed_producer_copies_the_answer(tmp_path):
    """The threat, demonstrated: without the jail, 'blind' is a convention."""
    src = _claim(tmp_path / "src")
    r = kernel.rebuild(src, _copying_producer(src), str(tmp_path / "m2"))
    with open(os.path.join(r["claim"], "g.txt")) as f:
        assert "THE-ORIGINAL-ANSWER" in f.read()
    assert "jail" not in r


@pytest.mark.skipif(not JAILED, reason="no generation jail on this host")
def test_jailed_producer_cannot_read_the_source(tmp_path):
    src = _claim(tmp_path / "src")
    r = kernel.rebuild(src, _copying_producer(src), str(tmp_path / "m2"),
                       jail=True)
    with open(os.path.join(r["claim"], "g.txt")) as f:
        assert f.read() == "regrown\n", \
            "the copy was denied, so the fallback is what got sealed"
    assert r["jail"]["backend"] == BACKEND
    # same root either way: generated bytes are outside the identity
    assert r["root"] == r["source_root"]
    events = [e for e in kernel.ledger_events(r["claim"])
              if e.get("event") == "jail"]
    assert len(events) == 1
    assert events[0]["backend"] == BACKEND
    assert os.path.realpath(src) in events[0]["forbidden_roots"]
    assert "verdict" in events[0]


@pytest.mark.skipif(not JAILED, reason="no generation jail on this host")
def test_room_nested_under_a_forbidden_root_still_works(tmp_path):
    """Last match wins: deny the tree, carve the room back out of it."""
    secret = tmp_path / "tree" / "secret.txt"
    secret.parent.mkdir(parents=True)
    secret.write_text("UNREADABLE\n")
    room = tmp_path / "tree" / "room"
    room.mkdir()
    backend, prefix, _ = kernel.jail_wrap(str(room), forbid=[str(tmp_path / "tree")])
    probe = (f'cat "{secret}" > out.txt 2>/dev/null; '
             'printf ok > made.txt')
    proc = subprocess.run([*prefix, "/bin/sh", "-c", probe],
                          cwd=str(room), capture_output=True, timeout=120)
    assert proc.returncode == 0
    assert (room / "made.txt").read_text() == "ok", "the room itself is usable"
    assert "UNREADABLE" not in (
        (room / "out.txt").read_text() if (room / "out.txt").exists() else "")


@pytest.mark.skipif(not JAILED, reason="no generation jail on this host")
def test_keep_carves_a_root_back_out(tmp_path):
    cred = tmp_path / "ground" / "cred" / "token.txt"
    cred.parent.mkdir(parents=True)
    cred.write_text("needed\n")
    room = tmp_path / "room"
    room.mkdir()
    _, prefix, _ = kernel.jail_wrap(str(room),
                                    forbid=[str(tmp_path / "ground")],
                                    keep=[str(cred.parent)])
    proc = subprocess.run(
        [*prefix, "/bin/sh", "-c", f'cat "{cred}"'],
        cwd=str(room), capture_output=True, text=True, timeout=120)
    assert proc.returncode == 0 and "needed" in proc.stdout


def test_jail_refuses_inside_a_jail(monkeypatch):
    """Sandboxes do not nest, and a requested confinement is never silently
    skipped: inside one, the backend is none and require_jail refuses."""
    monkeypatch.setenv("RETICULI_JAILED", "seatbelt")
    assert kernel.jail_backend() == "none"
    with pytest.raises(kernel.ClaimError, match="do not nest"):
        kernel.require_jail()


def test_rebuild_jail_refuses_rather_than_runs_unconfined(tmp_path, monkeypatch):
    monkeypatch.setenv("RETICULI_JAILED", "seatbelt")
    src = _claim(tmp_path / "src")
    with pytest.raises(kernel.ClaimError, match="cannot confine"):
        kernel.rebuild(src, "true", str(tmp_path / "m2"), jail=True)


@pytest.mark.skipif(BACKEND != "seatbelt", reason="profile text is seatbelt's")
def test_profile_denies_before_it_reallows(tmp_path):
    """Seatbelt is last-match-wins: the room's allow must come AFTER the
    forbidden deny, and every path must be the RESOLVED one."""
    room = tmp_path / "room"
    room.mkdir()
    link = tmp_path / "alias"
    link.symlink_to(room)
    backend, prefix, state = kernel.jail_wrap(str(link),
                                              forbid=[str(tmp_path)])
    profile = prefix[prefix.index("-p") + 1]
    deny = profile.index("(deny file-read*")
    allow = profile.index(f'(allow file-read* (subpath "{os.path.realpath(room)}")')
    assert deny < allow
    assert str(link) not in profile, "the symlink spelling never matches"
    assert state["room"] == os.path.realpath(str(room))
