"""Reproduce the outside reviewer's finding #1 at runtime.

A claim DECLARES tolerance = 2.0. M1 carries no cost ledger, M3 does, so the
two share no comparable unit. spec/claim-format.md: "a band that could not be
measured at all ... makes the verdict incomplete rather than accepted."
"""
import json, os, shutil, subprocess, sys, tempfile
sys.path.insert(0, "src")
from reticuli import kernel

RECIPE = ('[claim]\nname = "tol"\ntolerance = 2.0\ninputs = ["check.py"]\n\n'
          '[[step]]\nkind = "produce"\noutput = "impl.py"\nclass = "generated"\n\n'
          '[[step]]\nkind = "gate"\noutput = "OK"\nclass = "validated"\n'
          'run = "python3 check.py && printf ok > OK"\n')
CHECK = ("from impl import answer\nassert answer == 42\n"
         "open('OK','w').write('ok')\n")

d = tempfile.mkdtemp(prefix="tolrepro-")
try:
    m1 = os.path.join(d, "m1"); os.makedirs(m1)
    for n, b in {"reticuli.toml": RECIPE, "check.py": CHECK,
                 "impl.py": "answer = 42\n", "OK": "ok"}.items():
        open(os.path.join(m1, n), "w").write(b)
    kernel.seal(m1)

    # M2: byte-for-byte transfer of M1 (same generated bytes)
    m2 = os.path.join(d, "m2"); shutil.copytree(m1, m2)
    # strip M1's ledger so M1 reports NO cost at all
    led = os.path.join(m1, ".reticuli", "ledger.jsonl")
    if os.path.isfile(led):
        os.remove(led)

    # M3: an independent redo, which WILL carry a ledger (rebuild writes one)
    prod = os.path.join(d, "p.py")
    open(prod, "w").write("open('impl.py','w').write('answer = 6 * 7\\n')\n")
    m3 = os.path.join(d, "m3")
    kernel.rebuild(m1, f"{sys.executable} {prod}", m3)

    print("M1 cost:", kernel.cost(m1))
    print("M3 cost:", kernel.cost(m3))

    r = kernel.crosscheck(m1, m2, m3)
    print()
    print("declared tolerance :", kernel.load_recipe(m1)["claim"]["tolerance"])
    print("cost.comparable    :", r["cost"]["comparable"])
    print("cost.unit          :", r["cost"]["unit"])
    print("rejected           :", r["rejected"])
    print("incomplete         :", r["incomplete"])
    print("VERDICT            :", r["verdict"])
    print()
    spec = "incomplete"
    print(f"spec/claim-format.md requires: {spec}")
    print("DEFECT CONFIRMED" if r["verdict"] != spec and r["cost"]["comparable"] is None
          else "not reproduced")
finally:
    shutil.rmtree(d, ignore_errors=True)
