"""Transfer: a claim as a portable archive.

Declared content only, byte-deterministic, and verified on arrival. An export
that walked the directory tree instead of the recipe would leak the
workspace; one that carried the ledger would make a machine's private
bookkeeping part of what travels.
"""
import io
import os
import shutil
import sys
import tarfile

from . import kernel
from . import registry
from ._util import safe_path

#: Where a received claim keeps the component claims that came with it.
DEPS = ".reticuli/deps"


def _claim_members(claim: str, blind: bool = False,
                   generated: bool = True) -> list:
    """(archive name, source path) for everything this claim declares."""
    parsed = kernel.load_recipe(claim)
    members = []
    recipe_file = kernel.recipe_path(claim)
    members.append((os.path.basename(recipe_file), recipe_file))
    manifest = os.path.join(claim, kernel.MANIFEST)
    if os.path.isfile(manifest):
        members.append((kernel.MANIFEST, manifest))
    for declared in kernel.load_recipe(claim).get("claim", {}).get(
            "inputs", []) or []:
        path = safe_path(claim, declared)
        if path and os.path.isfile(path):
            members.append((declared, path))
    table = parsed.get("claim") or {}
    for extra in (table.get("environment"), table.get("inputs_manifest")):
        path = safe_path(claim, extra or "")
        if extra and path and os.path.isfile(path):
            members.append((extra, path))
    if table.get("inputs_manifest"):
        from ._kernel.recipe import _read_input_manifest
        for listed in _read_input_manifest(claim, table["inputs_manifest"]):
            path = safe_path(claim, listed)
            if path and os.path.isfile(path):
                members.append((listed, path))
    for step in parsed.get("step") or []:
        output = step.get("output")
        path = safe_path(claim, output or "")
        if not output or not path or not os.path.isfile(path):
            continue
        is_generated = (step.get("kind") == "produce"
                        and kernel.step_class(step) == "generated")
        if is_generated and (blind or not generated):
            continue
        members.append((output, path))
    attest_dir = os.path.join(claim, ".reticuli", "attest")
    if os.path.isdir(attest_dir):
        for name in sorted(os.listdir(attest_dir)):
            path = os.path.join(attest_dir, name)
            if os.path.isfile(path):
                members.append((f".reticuli/attest/{name}", path))
    return members


def _component_members(claim: str, ws: str | None = None) -> list:
    """A component's CLAIM travels: recipe, inputs, pins, manifest.

    Never its generated bytes -- the dependent ships those, and the component's
    gate re-earns them on arrival.
    """
    dirs = registry._stores(claim, ws)
    members = []
    for (name, root), _group in registry._grouped(registry._links(claim)):
        resolved = registry._resolve(name, root, dirs)
        if resolved is None:
            continue
        for inner, path in _claim_members(resolved, generated=False):
            members.append((f"{DEPS}/{name}/{inner}", path))
    return members


def _write(members: list, handle) -> None:
    """A deterministic tar: sorted names, no clock, no owner."""
    with tarfile.open(fileobj=handle, mode="w", format=tarfile.GNU_FORMAT) \
            as archive:
        for name, source in sorted(set(members)):
            info = tarfile.TarInfo(name)
            stat = os.stat(source)
            info.size = stat.st_size
            info.mtime = 0
            info.mode = 0o755 if stat.st_mode & 0o100 else 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.type = tarfile.REGTYPE
            with open(source, "rb") as payload:
                archive.addfile(info, payload)


def export(claim: str, path: str, blind: bool = False,
           ws: str | None = None) -> dict:
    """Write a portable archive of exactly what the claim declares."""
    members = _claim_members(claim, blind=blind)
    members.extend(_component_members(claim, ws))
    if path == "-":
        buffer = io.BytesIO()
        _write(members, buffer)
        sys.stdout.buffer.write(buffer.getvalue())
        sys.stdout.buffer.flush()
        return {"path": "-", "members": len(set(members)), "blind": blind}
    parent = os.path.dirname(os.path.abspath(path))
    os.makedirs(parent, exist_ok=True)
    with open(path, "wb") as handle:
        _write(members, handle)
    return {"path": path, "members": len(set(members)), "blind": blind}


def _safe_extract(archive, dest: str) -> list:
    root = os.path.realpath(dest)
    names = []
    for info in archive.getmembers():
        if not info.isfile():
            continue
        target = os.path.realpath(os.path.join(root, info.name))
        if target != root and not target.startswith(root + os.sep):
            raise kernel.ClaimError(
                f"the archive names a path outside the target: {info.name!r}")
        os.makedirs(os.path.dirname(target), exist_ok=True)
        source = archive.extractfile(info)
        with open(target, "wb") as handle:
            shutil.copyfileobj(source, handle)
        os.chmod(target, 0o755 if info.mode & 0o100 else 0o644)
        names.append(info.name)
    return names


def import_(path: str, dest: str) -> dict:
    """Restore an archive and verify it from the received bytes alone."""
    os.makedirs(dest, exist_ok=True)
    if path == "-":
        payload = io.BytesIO(sys.stdin.buffer.read())
        try:
            archive = tarfile.open(fileobj=payload, mode="r:*")
        except tarfile.TarError as exc:
            raise kernel.ClaimError(f"no archive on standard input: {exc}") \
                from exc
    else:
        if not os.path.isfile(path):
            raise kernel.ClaimError(f"no archive at {path}")
        try:
            archive = tarfile.open(path, mode="r:*")
        except tarfile.TarError as exc:
            raise kernel.ClaimError(f"no archive at {path}: {exc}") from exc
    try:
        names = _safe_extract(archive, dest)
    finally:
        archive.close()
    checked = kernel.verify(dest)
    return {"ok": bool(checked["ok"]), "root": checked["root"],
            "name": checked["name"], "recomputed": checked["recomputed"],
            "members": len(names), "path": dest}
