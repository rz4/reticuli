"""Kernel seal: freezing identity, and confirming it.

`seal` records the root onto the manifest; `verify` recomputes it from the
bytes present. The invariant that IS the equivalence class: the root is a
function of the pinned inputs and independent of the generated bytes.
"""
import os

from . import identity as _identity
from . import recipe as _recipe
from .core import (ClaimError, MANIFEST, PARTS, STORE, _read_json,
                   _write_json)


def _hold_constrains(parsed: dict, claim: str) -> None:
    """A declared criterion target must be an output this claim OWNS.

    A criterion declared over a supplied module constrains a file that never
    ships -- the gate validates the producer's local copy and assembly
    discards it for the owning room's -- so the seal refuses and names the
    claim the criterion belongs in.
    """
    table = parsed.get("claim") or {}
    declared = table.get("constrains")
    if not declared:
        return
    supplied = {s["output"]: s.get("from")
                for s in _recipe.produces(parsed) if s.get("output")}
    owned = set(_recipe.owned_outputs(parsed))
    for key, targets in declared.items():
        for target in targets:
            if target in owned:
                continue
            component = supplied.get(target)
            if component:
                raise ClaimError(
                    f"[claim] constrains: {key!r} constrains {target!r}, "
                    f"which this claim is supplied from {component!r} -- the "
                    f"bytes that ship belong to {component}, so the criterion "
                    f"belongs in the {component} claim")
            raise ClaimError(
                f"[claim] constrains: {key!r} constrains {target!r}, which "
                f"this claim does not own as a produce output")


def read_manifest(claim: str) -> dict:
    """`{name, root}` plus whatever residue the implementation keeps."""
    document = _read_json(os.path.join(claim, MANIFEST), "manifest")
    if not isinstance(document, dict):
        raise ClaimError(f"manifest at {claim} is not an object")
    name, root = document.get("name"), document.get("root")
    if not isinstance(name, str):
        raise ClaimError(f"manifest name must be a string, not {name!r}")
    if not isinstance(root, str):
        raise ClaimError(f"manifest root must be a string, not {root!r}")
    return document


def _parts_path(claim: str) -> str:
    return os.path.join(claim, PARTS)


def _changed_parts(claim: str, parsed: dict | None = None) -> list:
    """Which declared files moved since the seal, read from the parts residue.

    The residue is outside every root; where it is absent nothing can be
    named, which is reported as an empty list rather than guessed at.
    """
    try:
        sealed = _read_json(_parts_path(claim), "parts residue")
    except ClaimError:
        return []
    if not isinstance(sealed, dict):
        return []
    if parsed is None:
        parsed = _recipe.load_recipe(claim)
    try:
        now = _identity._parts(parsed, claim)
    except ClaimError:
        return sorted(k.split(":", 1)[-1] for k in sealed if ":" in k)
    moved = []
    for key, digest in sealed.items():
        if ":" not in key:
            continue
        if now.get(key) != digest:
            moved.append(key.split(":", 1)[1])
    for key in now:
        if ":" in key and key not in sealed:
            moved.append(key.split(":", 1)[1])
    return sorted(set(moved))


def seal(claim: str, **residue) -> dict:
    """Compute the root and write the manifest; hand back what was written."""
    parsed = _recipe.load_recipe(claim)
    _hold_constrains(parsed, claim)
    parts = _identity._parts(parsed, claim)
    computed = _identity._sha256_hex(_identity._canonical(parts))
    try:
        document = dict(read_manifest(claim))
    except ClaimError:
        document = {}
    document["name"] = parsed["claim"]["name"]
    document["root"] = computed
    for key, value in residue.items():
        if value is None:
            document.pop(key, None)
        else:
            document[key] = value
    os.makedirs(os.path.join(claim, STORE), exist_ok=True)
    _write_json(os.path.join(claim, MANIFEST), document)
    _write_json(_parts_path(claim), parts)
    return document


def verify(claim: str) -> dict:
    """Recompute the root from the bytes present -- identity only, no gate."""
    parsed = _recipe.load_recipe(claim)
    manifest = read_manifest(claim)
    recomputed = _identity.root(parsed, claim)
    ok = recomputed == manifest["root"]
    return {"ok": ok,
            "name": manifest["name"],
            "root": manifest["root"],
            "recomputed": recomputed,
            "changed": [] if ok else _changed_parts(claim, parsed)}
