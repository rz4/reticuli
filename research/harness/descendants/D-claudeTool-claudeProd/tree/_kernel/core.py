def _safe(claim: str, name: str) -> str:
    """The path boundary: a recipe-declared name, resolved inside the claim.

    Refused: an absolute or empty name, any `..` component, and any component
    that is a symlink -- even one whose target stays inside the claim, because
    an internal link can alias generated bytes as a pinned name.
    """
    if not isinstance(name, str) or not name:
        raise ClaimError("a declared path may not be empty")
    if os.path.isabs(name) or name.startswith("/"):
        raise ClaimError(f"a declared path may not be absolute: {name!r}")
    parts = [p for p in name.replace("\\", "/").split("/") if p not in ("", ".")]
    if not parts:
        raise ClaimError(f"a declared path names nothing: {name!r}")
    if any(p == ".." for p in parts):
        raise ClaimError(f"a declared path may not climb out: {name!r}")
    base = os.path.realpath(claim)
    here = base
    for part in parts:
        here = os.path.join(here, part)
        if os.path.islink(here):
            raise ClaimError(
                f"a declared path may not pass through a symlink: {name!r}")
    resolved = os.path.normpath(here)
    if not (resolved == base or resolved.startswith(base + os.sep)):
        raise ClaimError(f"a declared path escapes the claim: {name!r}")
    return resolved


def _hash_file(path: str) -> str:
    """The bytes boundary: a plain sha256 of a regular, single-link file."""
    try:
        info = os.lstat(path)
    except OSError as exc:
        if exc.errno in (errno.ENOENT, errno.ENOTDIR):
            raise ClaimError(f"declared file is missing: {path}") from exc
        raise ClaimError(f"cannot read declared file {path}: {exc}") from exc
    import stat as _stat
    if _stat.S_ISLNK(info.st_mode):
        raise ClaimError(f"declared file is a symlink: {path}")
    if not _stat.S_ISREG(info.st_mode):
        raise ClaimError(f"declared file is not a regular file: {path}")
    if info.st_nlink != 1:
        raise ClaimError(
            f"declared file has more than one hard link: {path}")
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 16), b""):
            digest.update(block)
    return digest.hexdigest()


def _is_executable(path: str) -> bool:
    """Whether the owner-execute bit is set (format 6 commits exactly this)."""
    return bool(os.stat(path).st_mode & 0o100)


def _copy_into(source: str, target: str) -> None:
    """Copy one file into place, making its parent and carrying its mode."""
    parent = os.path.dirname(target)
    if parent:
        os.makedirs(parent, exist_ok=True)
    shutil.copyfile(source, target)
    try:
        shutil.copymode(source, target)
    except OSError:
        pass


def _write_json(path: str, document) -> None:
    """Atomic JSON write: a reader never sees a half-written document."""
    parent = os.path.dirname(path) or "."
    os.makedirs(parent, exist_ok=True)
    handle = tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=parent, delete=False, suffix=".tmp")
    try:
        json.dump(document, handle, sort_keys=True)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    finally:
        handle.close()
    os.replace(handle.name, path)


def _read_json(path: str, what: str = "document"):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError as exc:
        raise ClaimError(f"no {what} at {path}") from exc
    except (ValueError, UnicodeDecodeError, OSError) as exc:
        raise ClaimError(f"damaged {what} at {path}: {exc}") from exc


def _canonical(document) -> bytes:
    """The one serialization: sorted keys, default separators, ASCII, UTF-8."""
    return json.dumps(document, sort_keys=True).encode("utf-8")


def _sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _finite(value) -> bool:
    import math
    return _is_number(value) and math.isfinite(float(value))
