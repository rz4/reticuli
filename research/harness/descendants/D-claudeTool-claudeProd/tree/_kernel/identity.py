"""Kernel identity: the canonical serialization (spec/identity.md).

The root is interchange currency, so the preimage is laid out here exactly as
the specification states it and nowhere else: sorted keys, DEFAULT JSON
separators, non-ASCII escaped, the recipe embedded as a JSON *string*.
"""
import copy
import json
import os

from . import recipe as _recipe
from .core import (DIGEST, GUIDANCE_KEYS, _canonical, _hash_file,
                   _is_executable, _safe, _sha256_hex)


def _claim_format(parsed: dict) -> int:
    """The declared format; absent means 1."""
    return _recipe._claim_format(parsed)


def _preimage_recipe(parsed: dict) -> dict:
    """The recipe as the root names it.

    Format 3 and above strip every step's producer hint -- guidance helps a
    producer FIND a realization and must never decide whether one is accepted.
    Formats 4 and 5 additionally canonicalize the step list into a set;
    format 6 withdraws that, because gates can depend on each other.
    """
    fmt = _claim_format(parsed)
    document = copy.deepcopy(parsed)
    if fmt < 3:
        return document
    steps = document.get("step")
    if isinstance(steps, list):
        stripped = []
        for step in steps:
            if isinstance(step, dict):
                step = {k: v for k, v in step.items()
                        if k not in GUIDANCE_KEYS}
            stripped.append(step)
        if 4 <= fmt <= 5:
            stripped.sort(key=lambda s: json.dumps(s, sort_keys=True))
        document["step"] = stripped
    return document


def _parts(parsed: dict, claim: str) -> dict:
    """The string-to-string map the root hashes."""
    parts = {"digest": DIGEST,
             "recipe": json.dumps(_preimage_recipe(parsed), sort_keys=True)}
    for path in _recipe._inputs(parsed, claim):
        parts["input:" + path] = _hash_file(_safe(claim, path))
    for step in _recipe._steps(parsed):
        if _recipe.step_class(step) == "generated":
            continue
        output = step.get("output")
        if not output:
            continue
        parts["pinned:" + output] = _hash_file(_safe(claim, output))
    return parts


def root(parsed: dict, claim: str) -> str:
    """The claim's identity: lowercase hex sha256 over the canonical parts."""
    return _sha256_hex(_canonical(_parts(parsed, claim)))


def build_digest(claim: str) -> str:
    """The concrete generated bytes a signature froze.

    One entry per produce step that carries no `from`, is classed generated,
    and whose output is present. At format 6 the entry is a triple whose third
    element records the owner-execute bit.
    """
    parsed = _recipe.load_recipe(claim)
    fmt = _claim_format(parsed)
    own = []
    for step in _recipe.produces(parsed):
        if step.get("from"):
            continue
        if _recipe.step_class(step) != "generated":
            continue
        output = step.get("output")
        if not output:
            continue
        path = _safe(claim, output)
        if not os.path.isfile(path):
            continue
        entry = [output, _hash_file(path)]
        if fmt >= 6:
            entry.append("x" if _is_executable(path) else "-")
        own.append(entry)
    return _sha256_hex(json.dumps(sorted(own), sort_keys=True).encode("utf-8"))
