"""The launcher: running software that is only latent in a claim.

A runnable claim keeps only its CLAIM durable -- pinned inputs, gate,
verdicts. The implementation is a cache entry: `run` makes the claim
executable (checking a standing build, or regrowing a fresh one with a
producer) and `strip` deletes the generated bytes back to latency. Deleting is
always safe, because the claim is the identity.

    python3 -m reticuli.launcher run <claim> [-- args...]

The launcher speaks ONLY on stderr: stdout belongs entirely to the
entrypoint, because claims test byte-exact output.
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import tomllib

from . import kernel
from ._util import read_json, safe_path, write_json

#: The package declaration a runnable claim pins.
PACKAGE = "package.toml"

#: Launcher state: consent, and the bytes consent bound. Residue.
LAUNCHER = ".launcher"
STATE = ".launcher/state.json"

#: Exit codes. Interchange currency: orchestrators depend on these.
NOT_RUNNABLE = 3
CONSENT_REQUIRED = 4
TRUST_REFUSED = 5
DRIFTED = 6
NO_PRODUCER = 7


def _say(message: str) -> None:
    print(message, file=sys.stderr)


def _digest(path: str) -> str:
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def _state(claim: str) -> dict:
    document = read_json(os.path.join(claim, STATE))
    return document if isinstance(document, dict) else {}


def _save(claim: str, document: dict) -> None:
    write_json(os.path.join(claim, STATE), document)


def _confined(claim: str, parsed: dict):
    """Every recipe-derived path, checked before anything is touched.

    A recipe naming an absolute or climbing path is refused before a byte is
    deleted, written, or executed: safety here must not be left to the draw.
    """
    for step in parsed.get("step") or []:
        output = step.get("output")
        if output and safe_path(claim, output) is None:
            return f"the recipe names a path outside the claim: {output!r}"
    for declared in (parsed.get("claim") or {}).get("inputs") or []:
        if safe_path(claim, declared) is None:
            return f"the recipe names a path outside the claim: {declared!r}"
    return None


def _entrypoint(claim: str, parsed: dict):
    """The package contract: `package.toml`, pinned, naming a file inside."""
    declared = (parsed.get("claim") or {}).get("inputs") or []
    produced = [s.get("output") for s in parsed.get("step") or []
                if s.get("kind") == "produce"]
    if PACKAGE in produced and PACKAGE not in declared:
        return None, (f"{PACKAGE} is offered as a generated output; it must "
                      f"be a pinned input, or what runs could drift from "
                      f"what the gate exercised")
    if PACKAGE not in declared:
        return None, (f"this claim is not runnable: it pins no {PACKAGE}")
    where = safe_path(claim, PACKAGE)
    if not where or not os.path.isfile(where):
        return None, f"{PACKAGE} is declared but missing"
    try:
        with open(where, "rb") as handle:
            document = tomllib.load(handle)
    except (tomllib.TOMLDecodeError, OSError) as exc:
        return None, f"{PACKAGE} is damaged: {exc}"
    entry = (document.get("package") or {}).get("entrypoint")
    if not isinstance(entry, str) or not entry:
        return None, f"{PACKAGE} declares no [package] entrypoint"
    if safe_path(claim, entry) is None:
        return None, (f"the entrypoint {entry!r} escapes the claim root")
    return entry, None


def _generated(parsed: dict) -> list:
    return kernel.generated_outputs(parsed)


def _materialized(claim: str, parsed: dict) -> bool:
    outputs = _generated(parsed)
    return bool(outputs) and all(
        os.path.isfile(os.path.join(claim, o)) for o in outputs)


def _scrub(claim: str, backend: str) -> dict:
    """The entrypoint never inherits the caller's environment."""
    scratch = os.path.join(claim, LAUNCHER, "tmp")
    os.makedirs(scratch, exist_ok=True)
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"),
           "LANG": os.environ.get("LANG", "C.UTF-8"),
           "LC_ALL": os.environ.get("LC_ALL", ""),
           "TZ": os.environ.get("TZ", ""),
           "HOME": os.path.realpath(scratch),
           "TMPDIR": os.path.realpath(scratch),
           "PYTHONDONTWRITEBYTECODE": "1"}
    env = {k: v for k, v in env.items() if v != ""}
    if backend in ("seatbelt", "bubblewrap"):
        env["RETICULI_JAILED"] = backend
    elif backend == "inherited":
        env["RETICULI_JAILED"] = os.environ.get("RETICULI_JAILED",
                                                "inherited")
    return env


def _regrow(claim: str, parsed: dict, producer: str) -> dict:
    """Regrow the generated bytes in a scratch room and land them here."""
    room = tempfile.mkdtemp(prefix="reticuli-latent-")
    try:
        target = os.path.join(room, "build")
        kernel.rebuild(claim, producer, target)
        fresh = {}
        for output in _generated(parsed):
            source = os.path.join(target, output)
            if not os.path.isfile(source):
                continue
            landing = safe_path(claim, output)
            os.makedirs(os.path.dirname(landing), exist_ok=True)
            shutil.copyfile(source, landing)
            shutil.copymode(source, landing)
            fresh[output] = _digest(landing)
        return fresh
    finally:
        shutil.rmtree(room, ignore_errors=True)


def _run(args) -> int:
    claim = os.path.abspath(args.claim)
    try:
        parsed = kernel.load_recipe(claim)
    except kernel.ClaimError as exc:
        _say(f"ret: launcher: {exc}")
        return NOT_RUNNABLE
    escape = _confined(claim, parsed)
    if escape:
        _say(f"ret: launcher: {escape}")
        return NOT_RUNNABLE
    entry, why = _entrypoint(claim, parsed)
    if entry is None:
        _say(f"ret: launcher: {why}")
        return NOT_RUNNABLE

    try:
        phase = kernel.phase(claim)
    except kernel.ClaimError as exc:
        _say(f"ret: launcher: {exc}")
        return NOT_RUNNABLE
    _say(f"claim = {os.path.basename(claim)}  phase = {phase}")
    if args.signed_only and phase != "signed":
        _say("ret: launcher: --signed-only refused: this claim is "
             f"{phase}, not signed to you")
        return TRUST_REFUSED

    state = _state(claim)
    if not _materialized(claim, parsed):
        producer = os.environ.get("RETICULI_PRODUCER")
        if not producer:
            _say("ret: launcher: this claim is latent and no producer is "
                 "configured; set RETICULI_PRODUCER to regrow it")
            return NO_PRODUCER
        try:
            fresh = _regrow(claim, parsed, producer)
        except kernel.ClaimError as exc:
            _say(f"ret: launcher: the rebuild did not land: {exc}")
            return DRIFTED
        state = {"fresh": fresh}
        _save(claim, state)
        _say("the implementation was regrown and has not been accepted; "
             "pass --accept-generated to execute and accept these bytes")
        if not args.accept_generated:
            return CONSENT_REQUIRED

    current = {output: _digest(os.path.join(claim, output))
               for output in _generated(parsed)
               if os.path.isfile(os.path.join(claim, output))}
    if args.accept_generated:
        state = {"accepted": current}
        _save(claim, state)
    elif state.get("fresh"):
        _say("the implementation is freshly generated and unaccepted; "
             "pass --accept-generated to execute and accept these bytes")
        return CONSENT_REQUIRED
    elif state.get("accepted"):
        if state["accepted"] != current:
            moved = sorted(name for name, digest in current.items()
                           if state["accepted"].get(name) != digest)
            _say("ret: launcher: this build has drifted from what was "
                 f"accepted ({', '.join(moved)}); nothing was executed and "
                 "nothing modified. Run `strip` and regrow to recover")
            return DRIFTED
    else:
        judged = kernel.audit(claim)
        if not judged["ok"]:
            _say("ret: launcher: this build does not re-earn its claim "
                 f"({judged['verdict']}); nothing was executed. Run `strip` "
                 "and regrow to recover")
            return DRIFTED

    backend = "off" if args.no_sandbox else kernel.sandbox_backend()
    env = _scrub(claim, backend)
    prefix = []
    if backend in ("seatbelt", "bubblewrap"):
        from ._kernel.run import _sandbox_argv
        prefix = _sandbox_argv(claim, backend)
    _say(f'quarantine = "{backend}"')
    argv = prefix + [sys.executable, entry] + list(args.args or [])
    done = subprocess.run(argv, cwd=claim, env=env, check=False)
    return done.returncode


def _strip(args) -> int:
    claim = os.path.abspath(args.claim)
    try:
        parsed = kernel.load_recipe(claim)
    except kernel.ClaimError as exc:
        _say(f"ret: launcher: {exc}")
        return NOT_RUNNABLE
    escape = _confined(claim, parsed)
    if escape:
        _say(f"ret: launcher: {escape}; nothing was deleted")
        return NOT_RUNNABLE
    removed = []
    for output in _generated(parsed):
        where = safe_path(claim, output)
        if where and os.path.isfile(where):
            os.remove(where)
            removed.append(output)
    shutil.rmtree(os.path.join(claim, LAUNCHER), ignore_errors=True)
    _say(f"stripped {len(removed)} generated file(s); the claim remains")
    return 0


def _ls(args) -> int:
    for target in args.claims:
        claim = os.path.abspath(target)
        try:
            parsed = kernel.load_recipe(claim)
            manifest = kernel.read_manifest(claim)
            phase = kernel.phase(claim)
        except kernel.ClaimError as exc:
            print(f"{os.path.basename(claim)}  -  unreadable  ({exc})")
            continue
        entry, _why = _entrypoint(claim, parsed)
        body = "materialized" if _materialized(claim, parsed) else "latent"
        print(f"{manifest['name']}  {manifest['root'][:8]}  {phase}  {body}"
              f"  {entry or '-'}")
    return 0


SYNOPSIS = """the launcher makes a latent claim executable.

  run   <claim> [--accept-generated] [--signed-only] [--no-sandbox] [-- args...]
  strip <claim>
  ls    <claim>...

  --accept-generated   execute freshly generated bytes, and accept them
  --signed-only        refuse a claim that is not signed to you
  --no-sandbox         execute unconfined, and report that honestly

Exit codes: the entrypoint's own when it runs; 3 not runnable, 4 consent
required, 5 trust refused, 6 drifted build, 7 latent with no producer.
The launcher speaks only on stderr; stdout belongs to the entrypoint.
"""


def _parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="reticuli.launcher", description=SYNOPSIS,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="verb")
    run = sub.add_parser("run", help="execute a claim's entrypoint")
    run.add_argument("claim")
    run.add_argument("--accept-generated", action="store_true",
                     help="execute freshly generated bytes, and accept them")
    run.add_argument("--signed-only", action="store_true",
                     help="refuse a claim that is not signed to you")
    run.add_argument("--no-sandbox", action="store_true",
                     help="execute unconfined, and report that honestly")
    strip = sub.add_parser("strip", help="delete the generated bytes")
    strip.add_argument("claim")
    listing = sub.add_parser("ls", help="identity, phase, and whether the "
                                        "bytes are on hand")
    listing.add_argument("claims", nargs="+")
    return ap


def main(argv=None) -> int:
    raw = list(sys.argv[1:] if argv is None else argv)
    passthrough = []
    if "--" in raw:
        cut = raw.index("--")
        raw, passthrough = raw[:cut], raw[cut + 1:]
    ap = _parser()
    args = ap.parse_args(raw)
    if args.verb == "run":
        args.args = passthrough
        return _run(args)
    if args.verb == "strip":
        return _strip(args)
    if args.verb == "ls":
        return _ls(args)
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
