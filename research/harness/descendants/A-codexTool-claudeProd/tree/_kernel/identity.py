"""The canonical serializations: the root, and the build digest.

Both are interchange currency, which is why they are pinned by VALUE rather
than merely by behavior.  If two kernels lay the preimage out differently
they compute different names for the same claim, each reads the other's
claims as tampered, and claims stop travelling; if they digest generated
bytes differently, signatures stop travelling.  So this module is
`spec/identity.md` byte for byte, and the golden vectors in `spec/vectors/`
are its conformance test for implementations in any language.

`canonical_json` is exactly `json.dumps(x, sort_keys=True)` with every other
argument left at its default, encoded UTF-8: keys sorted by code point,
DEFAULT separators (a space after every colon and comma — not compact),
non-ASCII escaped as `\\uXXXX`, integers in exact decimal at arbitrary
precision, floats as CPython's shortest round-tripping `repr`.
"""
import hashlib
import json
import os

from .core import DIGEST, GUIDANCE_KEYS, _hash_file, _safe
from . import recipe as _recipe


def _canonical(value) -> str:
    """The one serialization both implementations produce."""
    return json.dumps(value, sort_keys=True)


def _claim_format(parsed: dict) -> int:
    """The declared format; absent means 1, so an old claim keeps its name."""
    try:
        fmt = int(parsed.get("claim", {}).get("format", 1) or 1)
    except (TypeError, ValueError):
        fmt = 1
    return fmt


def _preimage_recipe(parsed: dict) -> dict:
    """The recipe as the preimage sees it.

    Format 3 strips every step's producer hint: guidance helps a producer
    FIND a realization and must never decide whether one is ACCEPTED, so two
    claims differing only in wording are one acceptance boundary.  Formats 4
    and 5 additionally canonicalize the step list, because those formats
    treat it as a SET — steps are serialized in the lexicographic order of
    their own canonical encodings.  Format 6 withdraws the sorting (step
    order decides acceptance where gates chain, which was measured) and keeps
    the strip.  Formats 1 and 2 serialize the whole recipe unchanged, so
    every root sealed under them is unchanged.
    """
    fmt = _claim_format(parsed)
    if fmt < 3:
        return parsed
    steps = [{k: v for k, v in step.items() if k not in GUIDANCE_KEYS}
             for step in _recipe._steps(parsed)]
    if 4 <= fmt <= 5:
        steps = sorted(steps, key=_canonical)
    out = dict(parsed)
    out["step"] = steps
    return out


def _parts(parsed: dict, claimdir: str) -> dict:
    """The root's string-to-string preimage map.

        parts["digest"]         = "sha256"
        parts["recipe"]         = canonical_json(the parsed recipe)
        parts["input:<path>"]   = sha256(bytes of each pinned input)
        parts["pinned:<out>"]   = sha256(bytes of each non-generated output)

    Generated outputs never enter it: that freedom IS the equivalence class.
    Note the double serialization — the recipe is embedded as a JSON string,
    never as a nested object.
    """
    parts = {"digest": DIGEST,
             "recipe": _canonical(_preimage_recipe(parsed))}
    for path in _recipe._inputs(parsed, claimdir):
        parts["input:" + path] = _hash_file(_safe(claimdir, path))
    for output in _recipe.pinned_outputs(parsed):
        parts["pinned:" + output] = _hash_file(_safe(claimdir, output))
    return parts


def root(parsed: dict, claimdir: str) -> str:
    """The claim's identity: lowercase hex sha256 over the canonical parts."""
    preimage = _canonical(_parts(parsed, claimdir)).encode("utf-8")
    return hashlib.sha256(preimage).hexdigest()


def build_digest(claimdir: str) -> str:
    """The digest a signature binds: the concrete generated bytes present.

    The root answers *is this the same claim*; this answers *are these the
    same bytes*.  Computed over `json.dumps(sorted(own), sort_keys=True)`,
    where `own` holds one entry per produce step that carries no `from` (such
    an output belongs to a component, whose own signature already covers it),
    has class `generated`, and whose file is present on disk.  An absent
    output is omitted rather than refused; no such outputs digests the empty
    list.

    At format 6 each entry is a triple — the third element `"x"` or `"-"`
    recording the owner-execute bit — because content alone does not
    determine whether a gate can run its own output: `chmod 644` on a
    generated program left this digest byte-identical while a cold audit went
    from `earned` to `Permission denied`.
    """
    parsed = _recipe.load_recipe(claimdir)
    fmt = _claim_format(parsed)
    own = []
    for step in _recipe.produces(parsed):
        if "from" in step:
            continue
        if _recipe.step_class(step, fmt) != "generated":
            continue
        path = _safe(claimdir, step["output"])
        if not os.path.isfile(path):
            continue
        entry = [step["output"], _hash_file(path)]
        if fmt >= 6:
            entry.append("x" if os.stat(path).st_mode & 0o100 else "-")
        own.append(entry)
    preimage = _canonical(sorted(own)).encode("utf-8")
    return hashlib.sha256(preimage).hexdigest()
