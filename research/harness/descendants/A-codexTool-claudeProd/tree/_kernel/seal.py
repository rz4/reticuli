"""Freezing identity onto the manifest, and confirming it from the bytes.

`seal` computes the root and records it; `verify` recomputes it from the
bytes present and reports whether they still hash to the sealed value.  The
invariant that IS the equivalence class lives here: the root is a function of
the pinned inputs and independent of the generated bytes, so editing an
implementation keeps the name and editing a criterion moves it.

`verify` is identity ONLY — no gate is executed.  That division is
load-bearing: identity is a hash comparison answering "is this still the same
claim?" in milliseconds, and a verdict is earned only by running the gates
(`audit`).  A verifier that ran gates under the name `verify` would blur the
one distinction the whole design exists to keep sharp.
"""
import os

from .core import (ClaimError, MANIFEST, PARTS, STORE, _read_json,
                   _write_json)
from . import identity as _identity
from . import recipe as _recipe


def read_manifest(claimdir: str) -> dict:
    """`{name, root}` plus optional residue; malformed bytes refused."""
    path = os.path.join(claimdir, MANIFEST)
    if not os.path.isfile(path):
        raise ClaimError(f"{claimdir!r} holds no sealed manifest")
    manifest = _read_json(path)
    if not isinstance(manifest, dict):
        raise ClaimError(f"{path}: a manifest is a JSON object")
    if not isinstance(manifest.get("name"), str):
        raise ClaimError(
            f"{path}: the manifest's name is not a string — a damaged claim, "
            f"not data")
    if not isinstance(manifest.get("root"), str):
        raise ClaimError(f"{path}: the manifest's root is not a string")
    return manifest


def seal(claimdir: str, **residue) -> dict:
    """Compute the root and write the manifest; hand back what was written.

    The return value is the manifest, not None: one conformant rebuild
    returned each, and a caller reading `seal(d)["root"]` worked on one and
    raised on the other.  The schema beyond name/root stays free; that those
    two come back as strings does not.
    """
    parsed = _recipe.load_recipe(claimdir)
    _hold_constrains(parsed, claimdir)
    parts = _identity._parts(parsed, claimdir)
    import hashlib
    import json
    root = hashlib.sha256(
        json.dumps(parts, sort_keys=True).encode("utf-8")).hexdigest()

    path = os.path.join(claimdir, MANIFEST)
    manifest = {}
    if os.path.isfile(path):
        try:
            existing = _read_json(path)
            if isinstance(existing, dict):
                manifest = existing
        except ClaimError:
            manifest = {}
    manifest["name"] = parsed["claim"]["name"]
    manifest["root"] = root
    for key, value in residue.items():
        if value is None:
            manifest.pop(key, None)
        else:
            manifest[key] = value
    os.makedirs(os.path.join(claimdir, STORE), exist_ok=True)
    _write_json(path, manifest)
    # Residue, outside the root: the parts map, so a broken verify can NAME
    # the file that moved instead of reporting a bare hash mismatch.
    _write_json(os.path.join(claimdir, PARTS), parts)
    return manifest


def _hold_constrains(parsed: dict, claimdir: str) -> None:
    """A declared `constrains` is held to at seal (format 5).

    A criterion declared over a SUPPLIED module constrains a file that never
    ships — the gate validates the producer's local copy, and assembly
    discards it for the owning room's — so the seal refuses and names the
    claim the criterion belongs in.
    """
    claim = parsed.get("claim", {})
    constrains = claim.get("constrains")
    if not constrains:
        return
    fmt = _identity._claim_format(parsed)
    owned, supplied = {}, {}
    for step in _recipe.produces(parsed):
        if "from" in step:
            supplied[step["output"]] = step["from"]
        else:
            owned[step["output"]] = _recipe.step_class(step, fmt)
    for criterion, targets in constrains.items():
        for target in targets:
            if target in supplied:
                raise ClaimError(
                    f"[claim] constrains declares {criterion!r} over "
                    f"{target!r}, which this claim is SUPPLIED from "
                    f"{supplied[target]!r} — the criterion belongs in the "
                    f"{supplied[target]!r} claim, which owns those bytes")
            if target not in owned:
                raise ClaimError(
                    f"[claim] constrains declares {criterion!r} over "
                    f"{target!r}, which this claim does not produce")


def _changed_parts(claimdir: str, parsed: dict, parts: dict) -> list:
    """Which declared files moved since the seal — read from the residue.

    The root alone can only say "different"; the sealed parts map says WHICH
    byte moved, which is the difference between a diagnostic and a shrug.
    """
    path = os.path.join(claimdir, PARTS)
    if not os.path.isfile(path):
        return []
    try:
        before = _read_json(path)
    except ClaimError:
        return []
    if not isinstance(before, dict):
        return []
    moved = []
    for key in sorted(set(before) | set(parts)):
        if before.get(key) == parts.get(key):
            continue
        if key == "digest":
            continue
        if key == "recipe":
            moved.append(_recipe.recipe_path(claimdir).rsplit(os.sep, 1)[-1])
        else:
            moved.append(key.split(":", 1)[1])
    return moved


def verify(claimdir: str) -> dict:
    """Recompute the root from the bytes present and compare — identity only."""
    manifest = read_manifest(claimdir)
    parsed = _recipe.load_recipe(claimdir)
    parts = _identity._parts(parsed, claimdir)
    import hashlib
    import json
    recomputed = hashlib.sha256(
        json.dumps(parts, sort_keys=True).encode("utf-8")).hexdigest()
    ok = recomputed == manifest["root"]
    return {
        "ok": ok,
        "name": parsed["claim"]["name"],
        "root": manifest["root"],
        "recomputed": recomputed,
        "sealed": manifest["root"],
        "changed": [] if ok else _changed_parts(claimdir, parsed, parts),
    }
