"""A second, independent implementation of the identity computation.

This module exists to disagree.  A conformance vector proves that two
implementations compute one hash; it cannot prove that either is right, and a
single implementation cannot be checked against itself at all.  So the root
and the build digest are computed here a second time, from
`spec/identity.md` rather than from `reticuli.kernel`, and
`criteria/vectors_check.py` requires the two to agree on every vector.

It therefore imports NOTHING from the kernel — not the constants, not the
path boundary, not the hashing.  Sharing any of it would make the agreement
a tautology.  It is also deliberately plainer: no caching, no residue, no
verdicts.  Reading a claim and naming it is the whole job.

    python3 -m reticuli.reference root   <claim-directory>
    python3 -m reticuli.reference digest <claim-directory>
"""
import hashlib
import json
import os
import stat
import sys
import tomllib

#: The two names a recipe is found under, canonical first.
NAMES = ("reticuli.toml", "claim.toml")
#: Both spellings of a producer hint.  Format 3 and above strip them.
HINTS = ("guidance", "request")
#: The newest format this reader understands.
NEWEST = 6


class Refused(Exception):
    """This claim has no computable identity, and here is why."""


def _canonical(value) -> str:
    """json.dumps(x, sort_keys=True) with every other argument defaulted.

    Sorted keys; DEFAULT separators, so there is a space after every colon
    and comma; non-ASCII escaped, so the text is ASCII and its UTF-8
    encoding changes nothing; integers in exact decimal at arbitrary
    precision; floats as CPython's shortest round-tripping repr.
    """
    return json.dumps(value, sort_keys=True)


def _digest(path: str) -> str:
    """The sha256 of a file's bytes, with the aliasing adversaries refused."""
    info = os.lstat(path)
    if stat.S_ISLNK(info.st_mode):
        raise Refused(f"{path}: a declared file may not be a symlink")
    if not stat.S_ISREG(info.st_mode):
        raise Refused(f"{path}: not a regular file")
    if info.st_nlink != 1:
        raise Refused(f"{path}: {info.st_nlink} hard links")
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def _resolve(claim: str, declared: str) -> str:
    """A declared path, confined to the claim, or a refusal.

    Absolute names, empty names, `..` components and symlink components are
    all refused rather than followed; a link can alias generated bytes as a
    pinned name, and with a link in play no lexical reading of `..` is
    trustworthy.
    """
    if not isinstance(declared, str) or not declared.strip():
        raise Refused("a declared path must be a non-empty string")
    if declared.startswith("/") or os.path.isabs(declared):
        raise Refused(f"{declared!r} is absolute")
    pieces = [p for p in declared.replace("\\", "/").split("/")
              if p not in ("", ".")]
    if not pieces:
        raise Refused(f"{declared!r} names nothing")
    if ".." in pieces:
        raise Refused(f"{declared!r} climbs out of the claim")
    base = os.path.realpath(claim)
    walked = base
    for piece in pieces:
        walked = os.path.join(walked, piece)
        if os.path.islink(walked):
            raise Refused(f"{declared!r} passes through a symlink")
    if walked != base and not walked.startswith(base + os.sep):
        raise Refused(f"{declared!r} escapes the claim")
    return walked


def read(claim: str) -> dict:
    """Parse the recipe, under either of its two names."""
    for name in NAMES:
        path = os.path.join(claim, name)
        if os.path.isfile(path):
            with open(path, "rb") as handle:
                try:
                    tables = tomllib.load(handle)
                except tomllib.TOMLDecodeError as exc:
                    raise Refused(f"{path}: not TOML ({exc})") from None
            break
    else:
        raise Refused(f"{claim}: no {' or '.join(NAMES)}")
    if not isinstance(tables.get("claim"), dict):
        raise Refused(f"{claim}: no [claim] table")
    if not isinstance(tables["claim"].get("name"), str):
        raise Refused(f"{claim}: [claim] name must be a string")
    version = tables["claim"].get("format", 1)
    if not isinstance(version, int) or isinstance(version, bool) \
            or version < 1:
        raise Refused(f"{claim}: [claim] format must be a positive integer")
    if version > NEWEST:
        raise Refused(f"claim format {version} is newer than this reader "
                      f"understands (format {NEWEST})")
    return tables


def version(tables: dict) -> int:
    """The declared format; absent means 1."""
    return int(tables["claim"].get("format", 1) or 1)


def steps(tables: dict) -> list:
    value = tables.get("step")
    return list(value) if isinstance(value, list) else []


def classify(step: dict) -> str:
    """A step's effective class: produce defaults free, anything else pinned."""
    declared = step.get("class")
    if declared in ("generated", "pinned", "validated", "carried"):
        return declared
    if declared is None:
        return "generated" if step.get("kind") == "produce" else "pinned"
    return "pinned"


def manifest_paths(claim: str, name: str) -> list:
    """The paths an `inputs_manifest` lists, one per line.

    A fixed list, never a pattern: a wildcard evaluated when a verifier
    reads the claim would make identity depend on directory contents at read
    time.
    """
    with open(_resolve(claim, name), encoding="utf-8") as handle:
        body = handle.read()
    found = []
    for line in body.splitlines():
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue
        fields = entry.split()
        found.append(fields[-1] if len(fields) > 1 else fields[0])
    return found


def pinned_inputs(claim: str, tables: dict) -> list:
    """The pinned-input set, which is WIDER than `[claim] inputs`.

    It is the union of the declared list, the file `[claim] environment`
    names (dependency versions decide what "passes" means, so they are
    criteria), and at format 2 and above the `inputs_manifest` plus every
    path that file lists.
    """
    table = tables["claim"]
    found = list(table.get("inputs") or [])
    if table.get("environment"):
        found.append(table["environment"])
    listing = table.get("inputs_manifest")
    if version(tables) >= 2 and listing:
        found.append(listing)
        found.extend(manifest_paths(claim, listing))
    return found


def preimage(tables: dict) -> dict:
    """The recipe as the preimage sees it.

    Format 3 drops every producer hint — a hint helps a producer find a
    realization and must never decide whether one is accepted.  Formats 4
    and 5 also sort the steps, treating the list as a SET; format 6
    withdraws that and keeps file order, because a gate reading what an
    earlier gate wrote makes the order decide acceptance.
    """
    level = version(tables)
    if level < 3:
        return tables
    stripped = [{key: value for key, value in step.items()
                 if key not in HINTS} for step in steps(tables)]
    if 4 <= level <= 5:
        stripped.sort(key=_canonical)
    return dict(tables, step=stripped)


def parts(claim: str, tables: dict) -> dict:
    """The root's preimage map: the algorithm, the recipe, and file digests."""
    mapping = {"digest": "sha256", "recipe": _canonical(preimage(tables))}
    for declared in pinned_inputs(claim, tables):
        mapping["input:" + declared] = _digest(_resolve(claim, declared))
    for step in steps(tables):
        if classify(step) == "generated":
            continue                 # the implementation is the free part
        output = step.get("output")
        if not isinstance(output, str):
            raise Refused("every step needs an output")
        mapping["pinned:" + output] = _digest(_resolve(claim, output))
    return mapping


def root(claim: str) -> str:
    """The claim's identity, as this implementation reads the specification."""
    tables = read(claim)
    return hashlib.sha256(
        _canonical(parts(claim, tables)).encode("utf-8")).hexdigest()


def build_digest(claim: str) -> str:
    """The digest a signature binds: the generated bytes actually present.

    One entry per produce step that carries no `from` (such an output
    belongs to a component, already covered by that component's own
    signature), has class `generated`, and whose file exists.  An absent
    output is omitted; none at all digests the empty list.  At format 6 each
    entry gains a third element recording the owner-execute bit, because
    content alone does not decide whether a gate can run its own output.
    """
    tables = read(claim)
    level = version(tables)
    present = []
    for step in steps(tables):
        if step.get("kind") != "produce" or "from" in step:
            continue
        if classify(step) != "generated":
            continue
        where = _resolve(claim, step["output"])
        if not os.path.isfile(where):
            continue
        entry = [step["output"], _digest(where)]
        if level >= 6:
            entry.append("x" if os.stat(where).st_mode & stat.S_IXUSR
                         else "-")
        present.append(entry)
    present.sort()
    return hashlib.sha256(
        _canonical(present).encode("utf-8")).hexdigest()


def main(argv=None) -> int:
    """`root` or `digest`, one claim directory, one hex line on stdout."""
    words = list(sys.argv[1:] if argv is None else argv)
    if len(words) != 2 or words[0] not in ("root", "digest"):
        print("usage: python3 -m reticuli.reference {root|digest} <claim>",
              file=sys.stderr)
        return 2
    what, claim = words
    try:
        print(root(claim) if what == "root" else build_digest(claim))
    except (Refused, OSError, ValueError) as exc:
        print(f"reference: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
