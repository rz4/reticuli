"""Running software that exists only latently in a claim.

A runnable claim keeps only its CLAIM durable — the pinned inputs, the gate,
the recorded verdicts.  The implementation is a cache entry: `run` makes the
claim executable (checking a standing build, or regrowing a fresh one with a
producer), and `strip` deletes the generated bytes back to latency.  Deleting
is always safe, because the claim, not the code, is the identity.

    run   <claim> [--accept-generated] [--signed-only] [--no-sandbox] [-- args]
    strip <claim>
    ls    <claim>...

THE PACKAGE CONTRACT.  A runnable claim declares `package.toml` as a PINNED
INPUT:

    [package]
    entrypoint = "hello.py"

Pinned, not generated: an entrypoint declaration that could drift from what
the gate exercised would divorce *what was proven* from *what runs*.

EXIT CODES are interchange currency — orchestrators depend on them.  When the
entrypoint runs, its exit code IS the launcher's; otherwise 3 not runnable,
4 newly generated bytes awaiting consent, 5 trust refused, 6 drifted build,
7 latent with no producer configured.

CHANNEL DISCIPLINE: the launcher speaks only on **stderr**.  stdout belongs
entirely to the entrypoint, because claims test byte-exact stdout — which is
also why the entrypoint is executed directly rather than through the gate
runner's pipes.

FRESHNESS vs DRIFT is the distinction worth the state file.  *Fresh* means the
launcher generated these bytes and nobody has accepted them: refuse politely
and offer the flag.  Accepting an implementation RECORDS ITS BYTE DIGESTS —
consent binds bytes, not a mood — so *drift* is an accepted implementation
whose bytes no longer match, even if the new bytes would still pass the gate:
an edit inside the equivalence class is still an unreviewed substitution.
Refuse loudly, execute nothing, modify nothing; `strip` is the recovery path.
An implementation the launcher never generated or accepted runs on audit
alone: the launcher guards what the launcher accepted.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import tomllib

from . import _util, kernel

#: Launcher state: residue, outside every root, removed by strip.
STATE_DIR = ".launcher"
STATE = ".launcher/state.json"
PACKAGE = "package.toml"

NOT_RUNNABLE = 3
CONSENT_REQUIRED = 4
TRUST_REFUSED = 5
DRIFTED = 6
NO_PRODUCER = 7


def _say(*parts) -> None:
    """The launcher's only channel."""
    print(*parts, file=sys.stderr)


def _state(claim: str) -> dict:
    return _util.read_json(os.path.join(claim, STATE), {}) or {}


def _remember(claim: str, state: dict) -> None:
    _util.write_json(os.path.join(claim, STATE), state)


def _digests(claim: str, outputs: list) -> dict:
    out = {}
    for name in outputs:
        path = os.path.join(claim, name)
        if os.path.isfile(path):
            out[name] = kernel._hash_file(path)
    return out


def _confined_paths(claim: str, parsed: dict) -> list:
    """Every recipe-derived path, confined BEFORE anything is read or written.

    A tampered recipe naming `../VICTIM` once made an honest implementation's
    `strip` delete outside its claim.  Safety is not left to the draw: the
    confinement happens first, and a refusal costs nothing.
    """
    names = list(kernel.declared_inputs(parsed, claim))
    names += [s["output"] for s in parsed.get("step", []) if s.get("output")]
    return [_util.safe_path(claim, name) for name in names]


def _package(claim: str, parsed: dict) -> str:
    """The declared entrypoint, or a refusal naming what is wrong."""
    fmt = int(parsed.get("claim", {}).get("format", 1) or 1)
    declared = set(kernel.declared_inputs(parsed, claim))
    produced = {s["output"]: kernel.step_class(s, fmt)
                for s in kernel.produces(parsed)}
    if PACKAGE in produced and PACKAGE not in declared:
        raise kernel.ClaimError(
            f"{PACKAGE} is offered as a generated output; it must be a "
            f"pinned input, or what runs could drift from what the gate "
            f"proved")
    if PACKAGE not in declared:
        raise kernel.ClaimError(
            f"this claim declares no {PACKAGE}, so it is not runnable")
    path = _util.safe_path(claim, PACKAGE)
    if not os.path.isfile(path):
        raise kernel.ClaimError(f"{PACKAGE} is declared but missing")
    try:
        with open(path, "rb") as handle:
            table = tomllib.load(handle)
    except (tomllib.TOMLDecodeError, OSError) as exc:
        raise kernel.ClaimError(f"{PACKAGE}: not readable ({exc})") from None
    entrypoint = (table.get("package") or {}).get("entrypoint")
    if not isinstance(entrypoint, str) or not entrypoint:
        raise kernel.ClaimError(
            f"{PACKAGE} declares no [package] entrypoint")
    # Confined, but not required to EXIST yet: a latent claim's entrypoint
    # is exactly the thing a producer is about to regrow, and refusing it
    # here would report "not runnable" where the honest answer is "latent".
    _util.safe_path(claim, entrypoint)
    return entrypoint


def _regrow(claim: str, parsed: dict) -> None:
    """Regrow the generated bytes with the configured producer, in place."""
    producer = os.environ.get(kernel._ENV_PRODUCER)
    scratch = tempfile.mkdtemp(prefix="launcher-regrow-")
    try:
        room = os.path.join(scratch, "room")
        kernel.rebuild(claim, producer, room)
        for name in kernel.generated_outputs(parsed):
            source = os.path.join(room, name)
            if os.path.isfile(source):
                _util.copy_into(source, _util.safe_path(claim, name))
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


def run(claim: str, args: list, accept_generated: bool = False,
        signed_only: bool = False, no_sandbox: bool = False) -> int:
    """Make a claim executable, then hand stdout to its entrypoint."""
    where = os.path.abspath(claim)
    try:
        parsed = kernel.load_recipe(where)
        _confined_paths(where, parsed)
        entrypoint = _package(where, parsed)
    except kernel.ClaimError as exc:
        _say(f"ret run: {exc}")
        return NOT_RUNNABLE

    try:
        standing = kernel.phase(where)
    except kernel.ClaimError as exc:
        _say(f"ret run: {exc}")
        return NOT_RUNNABLE
    if signed_only and standing != "signed":
        _say(f"ret run: this claim is {standing}, not signed to you; "
             f"--signed-only refuses it")
        return TRUST_REFUSED

    outputs = kernel.generated_outputs(parsed)
    state = _state(where)
    missing = [name for name in outputs
               if not os.path.isfile(os.path.join(where, name))]
    if missing:
        if not os.environ.get(kernel._ENV_PRODUCER):
            _say(f"ret run: this claim is latent ({', '.join(missing)} is "
                 f"not materialized) and RETICULI_PRODUCER names no producer")
            return NO_PRODUCER
        try:
            _regrow(where, parsed)
        except kernel.ClaimError as exc:
            _say(f"ret run: the producer did not regrow this claim: {exc}")
            return NOT_RUNNABLE
        state = {"fresh": _digests(where, outputs)}
        _remember(where, state)
    if state.get("fresh") and not state.get("accepted"):
        if not accept_generated:
            _say("ret run: these bytes were newly generated and nobody has "
                 "accepted them; pass --accept-generated to execute and "
                 "accept them")
            return CONSENT_REQUIRED
        state = {"accepted": _digests(where, outputs)}
        _remember(where, state)
    elif state.get("accepted"):
        if _digests(where, outputs) != state["accepted"]:
            _say("ret run: this build has drifted from the bytes that were "
                 "accepted; nothing was executed and nothing was modified. "
                 "Run `strip` and regrow to recover")
            return DRIFTED
    else:
        verdict = kernel.audit(where)
        if not verdict["ok"]:
            _say(f"ret run: this claim does not re-earn its verdicts "
                 f"({verdict['verdict']}); nothing was executed. Run `strip` "
                 f"and regrow to recover")
            return DRIFTED

    if not os.path.isfile(os.path.join(where, entrypoint)):
        _say(f"ret run: the entrypoint {entrypoint!r} is not a file in this "
             f"claim")
        return NOT_RUNNABLE

    scratch = os.path.join(where, STATE_DIR, "tmp")
    os.makedirs(scratch, exist_ok=True)
    jail = kernel.confinement(where, strict=not no_sandbox,
                              scratch=os.path.realpath(scratch))
    _say(f'phase = "{standing}"  quarantine = "{jail["quarantine"]}"')
    argv = jail["argv"] + [sys.executable, entrypoint] + list(args)
    done = subprocess.run(argv, cwd=jail["cwd"], env=jail["env"], check=False)
    return done.returncode


def strip(claim: str) -> int:
    """Delete the generated bytes, keep the claim — latency is safe."""
    where = os.path.abspath(claim)
    try:
        parsed = kernel.load_recipe(where)
        _confined_paths(where, parsed)
        targets = [_util.safe_path(where, name)
                   for name in kernel.generated_outputs(parsed)]
    except kernel.ClaimError as exc:
        _say(f"ret strip: {exc}")
        return NOT_RUNNABLE
    removed = []
    for path in targets:
        if os.path.isfile(path):
            os.remove(path)
            removed.append(os.path.relpath(path, where))
    shutil.rmtree(os.path.join(where, STATE_DIR), ignore_errors=True)
    _say(f"stripped {len(removed)} generated file(s); the claim is latent")
    return 0


def ls(claims: list) -> int:
    """Identity, phase, and whether the bytes are on hand."""
    for claim in claims:
        where = os.path.abspath(claim)
        name, root, standing, held = os.path.basename(where), "-", "-", "-"
        try:
            parsed = kernel.load_recipe(where)
            checked = kernel.verify(where)
            name, root = checked["name"], checked["root"]
            standing = kernel.phase(where)
            outputs = kernel.generated_outputs(parsed)
            present = [o for o in outputs
                       if os.path.isfile(os.path.join(where, o))]
            if not outputs or len(present) == len(outputs):
                held = "materialized"
            elif present:
                held = "partial"
            else:
                held = "latent"
        except kernel.ClaimError as exc:
            held = f"unreadable ({exc})"
        print(f"{name}  {root}  {standing}  {held}")
    return 0


def main(argv: list = None) -> int:
    raw = list(sys.argv[1:] if argv is None else argv)
    passthrough = []
    if "--" in raw:
        cut = raw.index("--")
        raw, passthrough = raw[:cut], raw[cut + 1:]

    parser = argparse.ArgumentParser(
        prog="reticuli.launcher",
        description="run software that is only latent in a claim",
        epilog="run <claim> [--accept-generated] [--signed-only] "
               "[--no-sandbox] [-- args...] | strip <claim> | ls <claim>...")
    sub = parser.add_subparsers(dest="verb")
    runner = sub.add_parser("run", help="execute a claim's entrypoint")
    runner.add_argument("claim")
    runner.add_argument("--accept-generated", action="store_true",
                        help="execute and accept newly generated bytes")
    runner.add_argument("--signed-only", action="store_true",
                        help="refuse a claim that is not signed to you")
    runner.add_argument("--no-sandbox", action="store_true",
                        help="execute without confinement, and say so")
    stripper = sub.add_parser("strip", help="delete the generated bytes")
    stripper.add_argument("claim")
    lister = sub.add_parser("ls", help="list claims and their state")
    lister.add_argument("claim", nargs="+")

    args = parser.parse_args(raw)
    if args.verb == "run":
        return run(args.claim, passthrough,
                   accept_generated=args.accept_generated,
                   signed_only=args.signed_only, no_sandbox=args.no_sandbox)
    if args.verb == "strip":
        return strip(args.claim)
    if args.verb == "ls":
        return ls(args.claim)
    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
