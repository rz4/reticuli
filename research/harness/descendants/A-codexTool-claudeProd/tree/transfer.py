"""Transport: a claim travels as declared content, and nothing else.

An export carries exactly what the recipe declares — the recipe, the pinned
inputs, the carried files, the recorded verdicts, the generated bytes unless
the room is blind, the manifest, any attestations about it, and each
component's own claim.  It carries no ledger and no stray file from the
author's working directory: an export that walked the tree instead of the
recipe would leak the workspace, and laptop junk is not part of a claim.

The archive is **byte-deterministic**.  Two exports of one claim produce
identical bytes, so the archive itself can be cited by digest — which means
fixing every field a tar writes that is about the machine rather than about
the content: times, owners, modes beyond the one bit a build digest commits,
and the order of the names.

`--blind` is the rebuilder's room: the same claim minus its generated
outputs.  The identity travels whole, because the root never covered the
implementation, so the room verifies on import and what the tar withholds is
exactly what a producer is asked to regrow.
"""
import io
import os
import tarfile

from . import _util, kernel

#: A fixed timestamp for every member, so an archive is about its content.
_EPOCH = 1577836800        # 2020-01-01T00:00:00Z


def _members(claimdir: str, blind: bool) -> list:
    """The declared content, as (archive name, source path) pairs."""
    parsed = kernel.load_recipe(claimdir)
    fmt = int(parsed.get("claim", {}).get("format", 1) or 1)
    out = [(os.path.basename(kernel.recipe_path(claimdir)),
            kernel.recipe_path(claimdir))]
    for name in kernel.declared_inputs(parsed, claimdir):
        out.append((name, kernel._safe(claimdir, name)))
    for step in parsed.get("step", []):
        output = step.get("output")
        if not output:
            continue
        cls = kernel.step_class(step, fmt)
        if blind and cls == "generated":
            continue                       # the implementation stays home
        path = kernel._safe(claimdir, output)
        if os.path.isfile(path):
            out.append((output, path))
    manifest = os.path.join(claimdir, kernel.MANIFEST)
    if os.path.isfile(manifest):
        out.append((kernel.MANIFEST, manifest))

    attest_dir = os.path.join(claimdir, ".reticuli", "attest")
    if os.path.isdir(attest_dir):
        for base, _dirs, files in os.walk(attest_dir):
            for name in sorted(files):
                path = os.path.join(base, name)
                out.append((os.path.relpath(path, claimdir).replace(
                    os.sep, "/"), path))

    # Each component's CLAIM travels — recipe, inputs, verdicts, manifest —
    # so an import can re-earn every layer from the bytes it received.  Its
    # generated bytes do not: the dependent already ships those, and that is
    # what the deep audit judges.
    for link in (kernel.read_manifest(claimdir).get("components") or []
                 if os.path.isfile(manifest) else []):
        name = link.get("component")
        where = None
        for drawer in ("sealed", "deps"):
            candidate = os.path.join(claimdir, kernel.STORE, drawer, name)
            if os.path.isdir(candidate):
                where = candidate
                break
        if not where:
            continue
        for member, path in _members(where, blind=True):
            out.append((f"{kernel.STORE}/deps/{name}/{member}", path))

    seen, unique = set(), []
    for member, path in out:
        if member in seen:
            continue
        seen.add(member)
        unique.append((member, path))
    return sorted(unique)


def export(claimdir: str, archive: str, blind: bool = False) -> dict:
    """Write a portable archive of exactly this claim's declared content."""
    members = _members(claimdir, blind)
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.PAX_FORMAT) \
            as handle:
        for member, path in members:
            with open(path, "rb") as source:
                payload = source.read()
            info = tarfile.TarInfo(member)
            info.size = len(payload)
            info.mtime = _EPOCH
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            # Exactly one mode bit is about the claim — the owner-execute bit
            # a format-6 build digest commits.  The rest is the operator's.
            executable = bool(os.stat(path).st_mode & 0o100)
            info.mode = 0o755 if executable else 0o644
            handle.addfile(info, io.BytesIO(payload))
    payload = buffer.getvalue()
    if archive in ("-", "/dev/stdout"):
        import sys
        sys.stdout.buffer.write(payload)
        sys.stdout.buffer.flush()
    else:
        os.makedirs(os.path.dirname(os.path.abspath(archive)), exist_ok=True)
        with open(archive, "wb") as sink:
            sink.write(payload)
    return {"archive": archive, "members": [m for m, _ in members],
            "blind": blind, "bytes": len(payload)}


def _safe_extract(handle: tarfile.TarFile, dest: str) -> None:
    """Extract, refusing any member that would land outside the destination."""
    base = os.path.realpath(dest)
    for info in handle.getmembers():
        if not info.isfile():
            raise kernel.ClaimError(
                f"{info.name!r}: an archive carries regular files only")
        target = os.path.realpath(os.path.join(dest, info.name))
        if target != base and not target.startswith(base + os.sep):
            raise kernel.ClaimError(
                f"{info.name!r} would land outside the destination")
    handle.extractall(dest, filter="data")


def import_(archive: str, dest: str) -> dict:
    """Restore an archive and verify the identity from the received bytes.

    Verification on import is the whole point of M2: nothing corrupted or
    substituted in transit, judged from what arrived rather than from what
    the sender said.
    """
    if archive in ("-", "/dev/stdin"):
        import sys
        payload = sys.stdin.buffer.read()
        if not payload:
            raise kernel.ClaimError("no archive on standard input")
        source = io.BytesIO(payload)
        opener = {"fileobj": source}
    else:
        if not os.path.isfile(archive):
            raise kernel.ClaimError(f"no archive at {archive!r}")
        opener = {"name": archive}
    os.makedirs(dest, exist_ok=True)
    try:
        with tarfile.open(mode="r:*", **opener) as handle:
            _safe_extract(handle, dest)
    except tarfile.TarError as exc:
        raise kernel.ClaimError(f"{archive}: not a readable archive ({exc})") \
            from None
    checked = kernel.verify(dest)
    return {"ok": checked["ok"], "root": checked["root"],
            "recomputed": checked["recomputed"], "name": checked["name"],
            "into": dest}
