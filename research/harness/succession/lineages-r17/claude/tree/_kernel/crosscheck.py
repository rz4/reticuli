def _leg(path: str) -> dict:
    if os.path.isfile(path):
        doc = record_read(path)
        claim_known = doc.get("record", 1) >= 2
        gates_list = doc.get("gates", [])
        audited_ok = all(g["status"] == "ok" for g in gates_list) if gates_list else True
        return {
            "kind": "record", "root": doc["root"], "build_digest": doc["build_digest"],
            "audited_ok": audited_ok, "cost": doc.get("cost"),
            "claim": doc.get("claim", {}) if claim_known else {},
            "claim_known": claim_known, "producer": _record_producer(doc),
            "path": None,
        }
    v = verify(path)
    parsed = load_recipe(path)
    claim_decl = parsed.get("claim", {})
    declared = {k: claim_decl[k] for k in _CLAIM_OBLIGATIONS if k in claim_decl}
    a = audit(path)
    return {
        "kind": "dir", "root": v["root"], "build_digest": identity.build_digest(path),
        "audited_ok": a["ok"], "cost": run.cost(path), "claim": declared,
        "claim_known": True, "producer": independence(path), "path": path,
    }


def _compare_cost(cost1, cost3, tolerance):
    if not cost1 or not cost3:
        return None
    for unit in core.COST_LADDER:
        if unit in cost1 and unit in cost3:
            v1, v3 = cost1[unit], cost3[unit]
            if v1 == v3:
                return True
            lo, hi = min(v1, v3), max(v1, v3)
            if lo <= 0:
                return False
            return (hi / lo) <= tolerance
    return None


def crosscheck(m1, m2, m3, mutants: int = None) -> dict:
    reals = {os.path.realpath(m1), os.path.realpath(m2), os.path.realpath(m3)}
    if len(reals) < 3:
        raise ClaimError("crosscheck requires three distinct machines")

    legs = {"M1": _leg(m1), "M2": _leg(m2), "M3": _leg(m3)}
    roots = {k: legs[k]["root"] for k in legs}
    equivalence = len(set(roots.values())) == 1
    reuse = legs["M1"]["build_digest"] == legs["M2"]["build_digest"]
    audited = {k: legs[k]["audited_ok"] for k in legs}

    hard_fail, incomplete = [], []
    if not equivalence:
        hard_fail.append("root")
    if not reuse:
        hard_fail.append("reuse")
    for k in ("M1", "M2", "M3"):
        if not audited[k]:
            hard_fail.append(f"audit {k}")

    claim_known = legs["M1"]["claim_known"]
    declared = legs["M1"]["claim"] if claim_known else {}

    cost1, cost3 = legs["M1"]["cost"], legs["M3"]["cost"]
    tolerance = declared.get("tolerance", core.TOLERANCE)
    comparable = _compare_cost(cost1, cost3, tolerance)

    envelope_report = {}
    if claim_known and "envelope" in declared:
        for unit, ceiling in declared["envelope"].items():
            measured = cost3.get(unit) if cost3 else None
            if measured is None:
                envelope_report[unit] = {"within": None}
                incomplete.append(f"envelope {unit}")
            else:
                within = measured <= ceiling
                envelope_report[unit] = {"within": within}
                if not within:
                    hard_fail.append(f"envelope {unit}")

    if claim_known and "tolerance" in declared:
        if comparable is None:
            incomplete.append("cost band")
        elif comparable is False:
            hard_fail.append("cost band")

    mutation_report = None
    if claim_known and "mutation_floor" in declared:
        floor = declared["mutation_floor"]
        if mutants is not None and legs["M3"]["kind"] == "dir":
            score = mutation_score(legs["M3"]["path"], max_mutants=mutants)
            ok = score["rate"] >= floor
            mutation_report = dict(score, ok=ok)
            if not ok:
                hard_fail.append("mutation floor")
        else:
            incomplete.append("mutation floor")

    if not claim_known:
        incomplete.append("declared conditions")

    if hard_fail:
        verdict = "reject"
    elif incomplete:
        verdict = "incomplete"
    else:
        verdict = "accept"

    prod3 = legs["M3"]["producer"] or {}
    if prod3.get("vendor") and prod3.get("model"):
        workspace = "blind" if prod3.get("blind") else "sighted"
        independence_str = (f"declared: {prod3['vendor']}/{prod3['model']}, "
                             f"{workspace} workspace (not proven)")
    else:
        independence_str = "unestablished (no producer declared)"

    return {
        "satisfied": verdict == "accept",
        "verdict": verdict,
        "rejected": hard_fail,
        "incomplete": incomplete,
        "roots": roots,
        "equivalence": equivalence,
        "reuse": reuse,
        "audited": audited,
        "cost": {"comparable": comparable, "envelope": envelope_report},
        "mutation_score": mutation_report,
        "independence": independence_str,
    }
