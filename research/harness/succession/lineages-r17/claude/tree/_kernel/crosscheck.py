"""Crosscheck: rebuild, audit, the three-machine test, and their helpers.

This module assembles the public verbs that compose the primitives in the
sibling modules (`core`, `recipe`, `identity`, `seal`, `run`, `build`,
`attest`) into the full kernel surface: `rebuild` (regrow generated outputs
until the gates pass, with a scrubbed producer environment and a snapshot
that refuses a producer that rewrites pinned bytes or the recipe), `audit`
(re-earn every gate cold, judging a format-3+ claim against the same
guidance-stripped recipe the room would see), `crosscheck` (the three-machine
test, over directories or frozen records interchangeably), `phase` (the
signature state machine), `sign_node` (the bottom-anchored signature fold),
`mutation_score` (deterministic mutants of the generated code, drawn from the
root), `vacuous_gates` / `gate_deciders` (which files a gate's run line
actually reads), and the record-transport functions re-specified to cover
the version-2 declared-obligations extension the lower `attest` module does
not yet implement.

Stdlib only, never the network.
"""
