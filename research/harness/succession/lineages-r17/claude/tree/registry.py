"""Registry: claims meet claims (`spec/layers.md`).

A workspace keeps sealed claims under `.reticuli/sealed/<name>`.
`detect_components` finds content-addressed links between a workspace's
pinned inputs and another claim's pinned/generated bytes; `seal_with`
records those links (and a recorded proof) as manifest residue -- outside
the root, never affecting identity. `claims`/`deps` read the store back as
a DAG. `rebuild_chain` is the DAG-aware rebuild: every declared component is
regrown leaf-first (or, with `reuse=True`, threaded from its existing
sealed bytes without asking the producer for it at all), and the result
keeps its own provenance. `pull` materializes a claim as a plain dependency
of a fresh workspace. `sign_root` folds a signed identity bottom-up over the
DAG (`kernel.sign_node`), localizing: editing one layer's bytes moves its
node and every node above, never one below. `audit_deep`/`crosscheck_deep`
walk the WHOLE chain -- gates compose, verdicts never carry: a dependent
that ships a component's code must have that code re-earned by the
component's OWN gate, on the shipped bytes, however deep the chain runs.

Only the public kernel surface is used here -- never a kernel private.
Stdlib only.
"""
import os
import shutil
import subprocess
import tempfile
import time

from reticuli import _util, kernel

_PRODUCER_TIMEOUT = 900.0


# =============================================================================
# locating a component: embedded under the claim's own store, or (when a
# workspace is given) under the workspace's sealed store
# =============================================================================

def _locate_component(d: str, ws, name: str):
    candidates = []
    if ws is not None:
        candidates.append(os.path.join(ws, kernel.STORE, "sealed", name))
    candidates.append(os.path.join(d, kernel.STORE, "sealed", name))
    candidates.append(os.path.join(d, kernel.STORE, "deps", name))
    for c in candidates:
        if os.path.isdir(c):
            return c
    return None


# =============================================================================
# detect_components: a content-addressed link between a workspace's pinned
# input and a sealed component's pinned/generated output
# =============================================================================

def detect_components(ws: str, input_names) -> list:
    base = os.path.join(ws, kernel.STORE, "sealed")
    links = []
    if not os.path.isdir(base):
        return links
    comp_names = sorted(n for n in os.listdir(base)
                         if os.path.isdir(os.path.join(base, n)))
    for input_name in input_names:
        path = os.path.join(ws, input_name)
        if not os.path.isfile(path):
            continue
        with open(path, "rb") as f:
            digest = _util.hash_bytes(f.read())
        for name in comp_names:
            comp_dir = os.path.join(base, name)
            try:
                parsed = kernel.load_recipe(comp_dir)
            except kernel.ClaimError:
                continue
            for step in parsed.get("step", []):
                output = step.get("output")
                if not output:
                    continue
                out_path = os.path.join(comp_dir, output)
                if not os.path.isfile(out_path):
                    continue
                with open(out_path, "rb") as f:
                    out_digest = _util.hash_bytes(f.read())
                if out_digest == digest:
                    try:
                        comp_root = kernel.verify(comp_dir)["root"]
                    except kernel.ClaimError:
                        continue
                    links.append({"input": input_name, "component": name,
                                  "root": comp_root, "output": output})
    return links


# =============================================================================
# seal_with: seal, plus the residue a composed claim carries (components,
# a recorded proof) -- outside the root, never affecting identity
# =============================================================================

def seal_with(d: str, components=None, proof=None) -> dict:
    manifest = kernel.seal(d)
    changed = False
    if components is not None:
        manifest["components"] = components
        changed = True
    if proof is not None:
        manifest["proof"] = proof
        changed = True
    if changed:
        _util.write_json(os.path.join(d, kernel.MANIFEST), manifest)
    return manifest


# =============================================================================
# claims / deps: the store read back as a DAG
# =============================================================================

def claims(ws: str) -> list:
    base = os.path.join(ws, kernel.STORE, "sealed")
    out = []
    if not os.path.isdir(base):
        return out
    for name in sorted(os.listdir(base)):
        d = os.path.join(base, name)
        if not os.path.isdir(d):
            continue
        try:
            manifest = kernel.read_manifest(d)
        except kernel.ClaimError:
            continue
        try:
            ph = kernel.phase(d)
        except kernel.ClaimError:
            ph = "draft"
        out.append({"name": manifest.get("name", name),
                     "root": manifest.get("root"), "phase": ph})
    return out


def deps(ws: str) -> dict:
    base = os.path.join(ws, kernel.STORE, "sealed")
    out = []
    if not os.path.isdir(base):
        return {"claims": out}
    for name in sorted(os.listdir(base)):
        d = os.path.join(base, name)
        if not os.path.isdir(d):
            continue
        try:
            manifest = kernel.read_manifest(d)
        except kernel.ClaimError:
            continue
        depends_on = []
        for link in manifest.get("components") or []:
            comp_name = link["component"]
            comp_dir = _locate_component(d, ws, comp_name)
            status = "missing"
            if comp_dir is not None:
                try:
                    comp_root = kernel.verify(comp_dir)["root"]
                    status = "ok" if comp_root == link.get("root") else "root-mismatch"
                except kernel.ClaimError:
                    status = "broken"
            depends_on.append({"input": link.get("input"),
                                "component": comp_name,
                                "root": link.get("root"), "status": status})
        out.append({"name": manifest.get("name", name), "depends_on": depends_on})
    return {"claims": out}


# =============================================================================
# pull: materialize a claim as a plain dependency of a fresh workspace
# =============================================================================

def pull(d: str, into: str) -> dict:
    parsed = kernel.load_recipe(d)
    os.makedirs(into, exist_ok=True)
    recipe_name = _util.recipe_name(d)
    shutil.copy2(os.path.join(d, recipe_name), os.path.join(into, recipe_name))

    inputs = [n for n in _util.declared_inputs(d)
              if os.path.isfile(_util.safe_path(d, n))]
    _util.copy_into(d, into, inputs)

    for step in parsed.get("step", []):
        output = step.get("output")
        if not output:
            continue
        src = _util.step_output(d, step)
        if os.path.isfile(src):
            _util.copy_into(d, into, [output])

    manifest = kernel.read_manifest(d)
    return {"materialized": True, "root": manifest["root"]}


# =============================================================================
# the DAG-aware rebuild: materialize, produce (only what a sibling component
# did not already supply), judge, seal -- reimplemented here, rather than
# delegated whole to kernel.rebuild, because a composed claim must steer
# which output the producer is asked for next (never a `from` output), and
# kernel.rebuild always asks for the FIRST declared generated output
# regardless of what a caller already supplied via produce_from.
# =============================================================================

def _build_room(d: str, producer: str, into: str, *, produce_from=None,
                 input_from=None, guidance: bool = True,
                 producer_env: dict = None) -> dict:
    parsed = kernel.load_recipe(d)
    if os.path.isdir(into):
        if os.listdir(into):
            raise kernel.ClaimError(f"rebuild target already holds bytes: {into!r}")
    elif os.path.exists(into):
        raise kernel.ClaimError(f"rebuild target already exists: {into!r}")
    else:
        os.makedirs(into)

    recipe_name = _util.recipe_name(d)
    shutil.copy2(os.path.join(d, recipe_name), os.path.join(into, recipe_name))
    inputs = [n for n in _util.declared_inputs(d)
              if os.path.isfile(_util.safe_path(d, n))]
    _util.copy_into(d, into, inputs)

    if input_from:
        for name, src in input_from.items():
            dst = _util.safe_path(into, name)
            os.makedirs(os.path.dirname(dst) or into, exist_ok=True)
            shutil.copy2(src, dst)

    produce_from = produce_from or {}
    for output, src in produce_from.items():
        dst = _util.safe_path(into, output)
        os.makedirs(os.path.dirname(dst) or into, exist_ok=True)
        shutil.copy2(src, dst)

    all_outputs = [s["output"] for s in parsed.get("step", [])
                   if s.get("kind") == "produce"
                   and s.get("class", "generated") == "generated"]
    own_outputs = [o for o in all_outputs if o not in produce_from]

    if own_outputs or not all_outputs:
        extra = {}
        if own_outputs:
            extra["RETICULI_OUTPUT"] = os.path.join(
                os.path.realpath(into), own_outputs[0])
            import json as _json
            extra["RETICULI_OUTPUTS"] = _json.dumps(own_outputs)
        if guidance:
            hints = []
            for step in parsed.get("step", []):
                if step.get("kind") != "produce" or step.get("output") not in own_outputs:
                    continue
                for key in ("guidance", "request"):
                    if step.get(key) is not None:
                        hints.append(step[key])
                        break
            if hints:
                extra["RETICULI_REQUEST"] = "\n".join(hints)
        extra["RETICULI_USAGE"] = os.path.join(
            os.path.realpath(into), ".reticuli", "usage.json")
        if producer_env:
            extra.update(producer_env)
        env = dict(os.environ)
        env.update(extra)
        os.makedirs(os.path.join(into, kernel.STORE), exist_ok=True)
        start = time.monotonic()
        try:
            result = subprocess.run(
                ["/bin/sh", "-c", producer], cwd=into, env=env,
                timeout=_PRODUCER_TIMEOUT, capture_output=True)
        except subprocess.TimeoutExpired as e:
            raise kernel.ClaimError(f"producer timed out: {e}") from e
        if result.returncode != 0:
            raise kernel.ClaimError(
                f"producer failed (exit {result.returncode}): "
                f"{result.stderr.decode('utf-8', 'replace')}")
        _util.ledger_add(into, {"event": "producer", "seconds": time.monotonic() - start})

    quarantine = None
    for step in parsed.get("step", []):
        if step.get("kind") != "gate":
            continue
        result = kernel.run_gate(step["run"], into, parsed)
        quarantine = result["quarantine"]
        if result["status"] != "ok":
            raise kernel.ClaimError(f"gate {step['output']!r} {result['status']}")

    manifest = kernel.seal(into)
    return {"root": manifest["root"], "quarantine": quarantine}


def rebuild_chain(d: str, producer: str, into: str, *, ws=None, reuse: bool = False,
                   input_from=None, guidance: bool = True,
                   producer_env: dict = None) -> dict:
    manifest = kernel.read_manifest(d)
    components = manifest.get("components") or []
    parsed = kernel.load_recipe(d)

    from_steps = {s["output"]: s.get("from") for s in parsed.get("step", [])
                  if s.get("kind") == "produce" and s.get("from")}

    by_name = {}
    for link in components:
        by_name.setdefault(link["component"], []).append(link)

    rebuilt_components = []
    produce_from = {}
    embed = []

    for name, links in by_name.items():
        comp_dir = _locate_component(d, ws, name)
        if comp_dir is None:
            raise kernel.ClaimError(f"declared component missing: {name!r}")
        if reuse:
            src_dir = comp_dir
        else:
            comp_room = tempfile.mkdtemp(prefix=f"reticuli-chain-{name}-")
            comp_result = rebuild_chain(
                comp_dir, producer, comp_room, ws=ws, reuse=reuse,
                guidance=guidance, producer_env=producer_env)
            rebuilt_components.append({"component": name, "root": comp_result["root"]})
            rebuilt_components.extend(comp_result.get("rebuilt_components", []))
            src_dir = comp_room
        embed.append((name, src_dir))
        for link in links:
            if from_steps.get(link["input"]) == name:
                src_path = os.path.join(src_dir, link["output"])
                if os.path.isfile(src_path):
                    produce_from[link["input"]] = src_path

    result = _build_room(d, producer, into, produce_from=produce_from or None,
                          input_from=input_from, guidance=guidance,
                          producer_env=producer_env)

    for name, src_dir in embed:
        dest = os.path.join(into, kernel.STORE, "sealed", name)
        if not os.path.isdir(dest):
            shutil.copytree(src_dir, dest)

    if components:
        rebuilt_manifest = kernel.read_manifest(into)
        rebuilt_manifest["components"] = components
        _util.write_json(os.path.join(into, kernel.MANIFEST), rebuilt_manifest)

    result["rebuilt_components"] = rebuilt_components
    return result


# =============================================================================
# sign_root: the bottom-anchored signature fold, over the declared DAG
# =============================================================================

def sign_root(d: str, ws=None) -> str:
    manifest = kernel.read_manifest(d)
    v = kernel.verify(d)
    links = []
    seen = set()
    for link in manifest.get("components") or []:
        name = link["component"]
        if name in seen:
            continue
        seen.add(name)
        comp_dir = _locate_component(d, ws, name)
        if comp_dir is None:
            raise kernel.ClaimError(f"declared component missing: {name!r}")
        links.append(sign_root(comp_dir, ws))
    return kernel.sign_node(v["root"], kernel.build_digest(d), links)


# =============================================================================
# audit_deep: walk the whole chain. A dependent that ships a component's
# code (a `from` produce step) must have that code re-earned by the
# component's OWN gate, on the shipped bytes -- recursively, so a broken
# grandparent, invisible to every gate above it, fails the composed verdict.
# =============================================================================

def _audit_deep(d: str, layers: list, override: dict) -> bool:
    try:
        manifest = kernel.read_manifest(d)
        parsed = kernel.load_recipe(d)
    except kernel.ClaimError:
        return True

    from_groups = {}
    for step in parsed.get("step", []):
        if step.get("kind") == "produce" and step.get("from"):
            from_groups.setdefault(step["from"], []).append(step["output"])
    by_name_root = {link["component"]: link.get("root")
                    for link in (manifest.get("components") or [])}

    ok_all = True
    for name, outputs in from_groups.items():
        comp_dir = _locate_component(d, None, name)
        effective = {o: override.get(o, _util.safe_path(d, o)) for o in outputs}
        if comp_dir is None:
            layers.append({"name": name, "root": by_name_root.get(name),
                            "ok": False, "status": "unresolved",
                            "bytes_from": sorted(outputs)})
            ok_all = False
            continue
        produce_from = {o: p for o, p in effective.items() if os.path.isfile(p)}
        result = kernel.audit(comp_dir, produce_from=produce_from)
        layers.append({"name": name, "root": by_name_root.get(name),
                        "ok": result["ok"], "status": "audited",
                        "bytes_from": sorted(outputs)})
        if not result["ok"]:
            ok_all = False
        if not _audit_deep(comp_dir, layers, effective):
            ok_all = False
    return ok_all


def audit_deep(d: str) -> dict:
    layers = []
    ok = _audit_deep(d, layers, {})
    return {"ok": ok, "layers": layers}


def crosscheck_deep(m1: str, m2: str, m3: str) -> dict:
    shallow = kernel.crosscheck(m1, m2, m3)
    result = dict(shallow)
    deep_reports = {}
    deep_ok = True
    for label, path in (("M1", m1), ("M2", m2), ("M3", m3)):
        if os.path.isdir(path):
            dr = audit_deep(path)
            deep_reports[label] = dr
            if not dr["ok"]:
                deep_ok = False
    result["deep"] = deep_reports
    if not deep_ok:
        result["rejected"] = sorted(set(result.get("rejected", [])) | {"deep audit"})
        result["verdict"] = "reject"
        result["satisfied"] = False
    return result
