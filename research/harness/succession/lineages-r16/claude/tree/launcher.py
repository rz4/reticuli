"""The launcher: run software that exists only latently in a claim.

A runnable claim is an ordinary claim whose pinned inputs include
`package.toml` naming an entrypoint. `run` executes it -- auditing a build
already on hand, or regrowing one with a producer and asking for consent
before executing freshly generated bytes -- and `strip` deletes the
generated bytes back to latency. State the launcher itself needs (which
bytes it regrew, which it has consent to run) lives under `<claim>/.launcher/`
and is removed by strip; the claim's identity never depends on it.

Speaks only on stderr; stdout belongs to the entrypoint.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import tomllib

from reticuli import kernel
from reticuli import _util

LAUNCHER_DIR = ".launcher"
ACCEPTED_FILE = "accepted.json"
FRESH_FILE = "fresh.json"

_SEATBELT_OK = None
_BWRAP_OK = None


# -------------------------------------------------------------- recipe reads
def _generated_outputs(recipe: dict) -> list:
    return [s["output"] for s in recipe.get("step", [])
            if s.get("kind") == "produce"
            and s.get("class", "generated") == "generated"]


def _read_input_manifest(path: str) -> list:
    with open(path, "r", encoding="utf-8") as f:
        lines = f.readlines()
    paths = []
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        head, _, rest = line.partition(" ")
        if len(head) == 64 and rest.strip() and all(
            c in "0123456789abcdef" for c in head
        ):
            paths.append(rest.strip())
        else:
            paths.append(line)
    return paths


def _declared_inputs(recipe: dict, d: str) -> list:
    claim = recipe.get("claim", {})
    inputs = list(claim.get("inputs", []))
    manifest_name = claim.get("inputs_manifest")
    if manifest_name:
        inputs.append(manifest_name)
        inputs.extend(_read_input_manifest(_util.safe_path(d, manifest_name)))
    environment = claim.get("environment")
    if environment:
        inputs.append(environment)
    return inputs


def _current_hashes(d: str, outputs: list) -> dict:
    hashes = {}
    for out in outputs:
        path = _util.safe_path(d, out)
        if os.path.isfile(path):
            hashes[out] = kernel._hash_file(path)
    return hashes


# ------------------------------------------------------------- launcher state
def _state_path(d: str, name: str) -> str:
    return os.path.join(d, LAUNCHER_DIR, name)


def _read_state(d: str, name: str):
    path = _state_path(d, name)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            doc = json.load(f)
    except (OSError, json.JSONDecodeError):
        return None
    return doc if isinstance(doc, dict) else None


def _write_state(d: str, name: str, doc: dict) -> None:
    path = _state_path(d, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(doc, f, sort_keys=True)
    os.replace(tmp, path)


def _remove_state(d: str, name: str) -> None:
    path = _state_path(d, name)
    if os.path.isfile(path):
        os.remove(path)


# ---------------------------------------------------------------- sandboxing
_DEV_SINKS = ("/dev/null", "/dev/zero", "/dev/tty", "/dev/stdout",
              "/dev/stderr", "/dev/urandom")


def _quote_sb(path: str) -> str:
    return path.replace("\\", "\\\\").replace('"', '\\"')


def _seatbelt_profile(workdir: str, home: str, tmp: str) -> str:
    paths = sorted({workdir, home, tmp})
    writes = " ".join(f'(subpath "{_quote_sb(p)}")' for p in paths)
    sinks = " ".join(f'(literal "{d}")' for d in _DEV_SINKS)
    return (
        "(version 1)(deny default)"
        "(allow file-read*)"
        f"(allow file-write* {writes} {sinks})"
        "(allow process-fork)(allow process-exec)"
        "(allow sysctl-read)"
    )


def _bwrap_argv(exe: str, workdir: str, home: str, tmp: str, argv: list) -> list:
    out = [exe, "--ro-bind", "/", "/", "--dev", "/dev", "--proc", "/proc",
           "--bind", workdir, workdir]
    for extra in (home, tmp):
        if extra != workdir:
            out += ["--bind", extra, extra]
    out += ["--unshare-net", "--die-with-parent", "--chdir", workdir]
    out += argv
    return out


def _seatbelt_usable() -> bool:
    global _SEATBELT_OK
    if _SEATBELT_OK is not None:
        return _SEATBELT_OK
    exe = shutil.which("sandbox-exec")
    if not exe:
        _SEATBELT_OK = False
        return False
    try:
        with tempfile.TemporaryDirectory() as allowed, \
                tempfile.TemporaryDirectory() as denied:
            allowed_r = os.path.realpath(allowed)
            profile = _seatbelt_profile(allowed_r, allowed_r, allowed_r)
            ok = subprocess.run(
                [exe, "-p", profile, "/bin/sh", "-c", f"printf x > {allowed}/ok"],
                capture_output=True, timeout=10)
            bad = subprocess.run(
                [exe, "-p", profile, "/bin/sh", "-c", f"printf x > {denied}/leak"],
                capture_output=True, timeout=10)
            _SEATBELT_OK = (ok.returncode == 0
                            and os.path.isfile(os.path.join(allowed, "ok"))
                            and bad.returncode != 0)
    except Exception:
        _SEATBELT_OK = False
    return _SEATBELT_OK


def _bwrap_usable() -> bool:
    global _BWRAP_OK
    if _BWRAP_OK is not None:
        return _BWRAP_OK
    exe = shutil.which("bwrap")
    if not exe:
        _BWRAP_OK = False
        return False
    try:
        with tempfile.TemporaryDirectory() as allowed, \
                tempfile.TemporaryDirectory() as denied:
            allowed_r = os.path.realpath(allowed)
            argv_ok = _bwrap_argv(exe, allowed_r, allowed_r, allowed_r,
                                  ["/bin/sh", "-c", "printf x > ok"])
            ok = subprocess.run(argv_ok, capture_output=True, timeout=10)
            argv_bad = _bwrap_argv(exe, allowed_r, allowed_r, allowed_r,
                                   ["/bin/sh", "-c", f"printf x > {denied}/leak"])
            bad = subprocess.run(argv_bad, capture_output=True, timeout=10)
            _BWRAP_OK = (ok.returncode == 0
                        and os.path.isfile(os.path.join(allowed, "ok"))
                        and bad.returncode != 0)
    except Exception:
        _BWRAP_OK = False
    return _BWRAP_OK


def _sandbox_backend(no_sandbox: bool) -> str:
    if no_sandbox:
        return "off"
    if os.environ.get(kernel._JAILED, "") not in ("", "0"):
        return "inherited"
    if sys.platform == "darwin" and _seatbelt_usable():
        return "seatbelt"
    if _bwrap_usable():
        return "bubblewrap"
    return "none"


# ---------------------------------------------------------------- execution
def _execute(d: str, entrypoint: str, args: list, backend: str) -> int:
    run_store = os.path.join(d, LAUNCHER_DIR, "run")
    os.makedirs(run_store, exist_ok=True)
    scratch = tempfile.mkdtemp(dir=run_store)
    home = os.path.join(scratch, "home")
    tmp = os.path.join(scratch, "tmp")
    os.makedirs(home, exist_ok=True)
    os.makedirs(tmp, exist_ok=True)
    home_real = os.path.realpath(home)
    tmp_real = os.path.realpath(tmp)

    env = {}
    for name in ("PATH", "LANG", "LC_ALL", "TZ"):
        if name in os.environ:
            env[name] = os.environ[name]
    env["HOME"] = home_real
    env["TMPDIR"] = tmp_real

    argv = ["python3", entrypoint] + list(args)
    d_real = os.path.realpath(d)

    if backend == "seatbelt":
        env[kernel._JAILED] = "seatbelt"
        exe = shutil.which("sandbox-exec") or "/usr/bin/sandbox-exec"
        profile = _seatbelt_profile(d_real, home_real, tmp_real)
        full_argv = [exe, "-p", profile] + argv
    elif backend == "bubblewrap":
        env[kernel._JAILED] = "bubblewrap"
        exe = shutil.which("bwrap") or "bwrap"
        full_argv = _bwrap_argv(exe, d_real, home_real, tmp_real, argv)
    elif backend == "inherited":
        if kernel._JAILED in os.environ:
            env[kernel._JAILED] = os.environ[kernel._JAILED]
        full_argv = argv
    else:
        full_argv = argv

    print(f'quarantine = "{backend}"', file=sys.stderr)
    proc = subprocess.run(full_argv, cwd=d, env=env)
    return proc.returncode


# -------------------------------------------------------------------- verbs
def cmd_run(rest: list) -> int:
    accept_generated = signed_only = no_sandbox = False
    claim_arg = None
    entry_args = []
    i = 0
    while i < len(rest):
        tok = rest[i]
        if tok == "--":
            entry_args = list(rest[i + 1:])
            break
        if tok == "--accept-generated":
            accept_generated = True
        elif tok == "--signed-only":
            signed_only = True
        elif tok == "--no-sandbox":
            no_sandbox = True
        elif claim_arg is None:
            claim_arg = tok
        i += 1

    if claim_arg is None:
        print("run: a claim path is required", file=sys.stderr)
        return 3
    d = claim_arg

    try:
        recipe = kernel.load_recipe(d)
        ph = kernel.phase(d)
        generated = _generated_outputs(recipe)
        inputs = _declared_inputs(recipe, d)
        if "package.toml" in generated:
            raise kernel.ClaimError(
                "package.toml must be a pinned input, not a generated output")
        if "package.toml" not in inputs:
            raise kernel.ClaimError("no package.toml pinned input declared")
        pkg_path = _util.safe_path(d, "package.toml")
        if not os.path.isfile(pkg_path):
            raise kernel.ClaimError("package.toml is declared but missing")
        with open(pkg_path, "rb") as f:
            pkg_doc = tomllib.load(f)
        pkg_section = pkg_doc.get("package")
        if not isinstance(pkg_section, dict):
            raise kernel.ClaimError("package.toml needs a [package] table")
        entrypoint = pkg_section.get("entrypoint")
        if not isinstance(entrypoint, str) or not entrypoint:
            raise kernel.ClaimError("package.toml [package] entrypoint missing")
        _util.safe_path(d, entrypoint)  # raises on an escaping entrypoint
    except (kernel.ClaimError, tomllib.TOMLDecodeError, OSError) as e:
        print(f"run: refused: {e}", file=sys.stderr)
        return 3

    print(f'launcher: claim phase = "{ph}"', file=sys.stderr)

    if signed_only and ph != "signed":
        print(f"run: refused: --signed-only requires a signed claim "
              f"(phase is {ph!r}, not signed)", file=sys.stderr)
        return 5

    try:
        current = _current_hashes(d, generated)
    except kernel.ClaimError as e:
        print(f"run: refused: {e}", file=sys.stderr)
        return 3
    all_present = all(o in current for o in generated)

    if not all_present:
        producer = os.environ.get("RETICULI_PRODUCER")
        if not producer:
            print("run: refused: claim is latent and no producer is "
                  "configured (set RETICULI_PRODUCER)", file=sys.stderr)
            return 7
        room = tempfile.mkdtemp()
        try:
            kernel.rebuild(d, producer, room)
        except kernel.ClaimError as e:
            shutil.rmtree(room, ignore_errors=True)
            print(f"run: refused: rebuild failed: {e}", file=sys.stderr)
            return 1
        for out in generated:
            src = _util.safe_path(room, out)
            if os.path.isfile(src):
                _util.copy_into(src, _util.safe_path(d, out))
        shutil.rmtree(room, ignore_errors=True)
        current = _current_hashes(d, generated)
        _write_state(d, FRESH_FILE, current)
        if not accept_generated:
            print("run: newly generated bytes landed -- materialized but "
                  "not executed; pass --accept-generated to execute and "
                  "accept them", file=sys.stderr)
            return 4
        _write_state(d, ACCEPTED_FILE, current)
        _remove_state(d, FRESH_FILE)
    else:
        fresh = _read_state(d, FRESH_FILE)
        accepted = _read_state(d, ACCEPTED_FILE)
        if fresh is not None and fresh == current:
            if not accept_generated:
                print("run: generated bytes are fresh and not yet accepted "
                      "-- pass --accept-generated to execute and accept "
                      "them", file=sys.stderr)
                return 4
            _write_state(d, ACCEPTED_FILE, current)
            _remove_state(d, FRESH_FILE)
        elif accepted is not None and accepted == current:
            pass
        elif accepted is not None:
            print("run: refused: drifted build -- the accepted "
                  "implementation's bytes no longer match what was "
                  "accepted; strip and rebuild to recover", file=sys.stderr)
            return 6
        else:
            try:
                result = kernel.audit(d)
            except kernel.ClaimError as e:
                print(f"run: refused: audit error: {e}", file=sys.stderr)
                return 6
            if not result.get("ok"):
                print("run: refused: audit failed -- drifted build; strip "
                      "and rebuild to recover", file=sys.stderr)
                return 6

    return _execute(d, entrypoint, entry_args, _sandbox_backend(no_sandbox))


def cmd_strip(rest: list) -> int:
    if not rest:
        print("strip: a claim path is required", file=sys.stderr)
        return 3
    d = rest[0]
    try:
        recipe = kernel.load_recipe(d)
        generated = _generated_outputs(recipe)
        targets = [_util.safe_path(d, out) for out in generated]
    except kernel.ClaimError as e:
        print(f"strip: refused: {e}", file=sys.stderr)
        return 3
    for path in targets:
        if os.path.isfile(path) or os.path.islink(path):
            os.remove(path)
    launcher_dir = os.path.join(d, LAUNCHER_DIR)
    if os.path.isdir(launcher_dir):
        shutil.rmtree(launcher_dir)
    return 0


def cmd_ls(rest: list) -> int:
    if not rest:
        print("ls: at least one claim path is required", file=sys.stderr)
        return 3
    for d in rest:
        try:
            manifest = kernel.read_manifest(d)
            name = manifest["name"]
            root_hash = manifest["root"]
            ph = kernel.phase(d)
        except kernel.ClaimError:
            name = os.path.basename(os.path.abspath(d))
            root_hash = "-" * 8
            ph = "draft"
        try:
            recipe = kernel.load_recipe(d)
            generated = _generated_outputs(recipe)
            materialized = all(
                os.path.isfile(_util.safe_path(d, o)) for o in generated)
        except kernel.ClaimError:
            materialized = False
        state = "materialized" if materialized else "latent"
        print(f"{name}  {root_hash}  {ph}  {state}")
    return 0


def _print_help() -> None:
    print(
        "usage: python3 -m reticuli.launcher <verb> [options]\n"
        "\n"
        "verbs:\n"
        "  run   <claim> [--accept-generated] [--signed-only] "
        "[--no-sandbox] [-- args...]\n"
        "  strip <claim>\n"
        "  ls    <claim>...\n"
    )


def main(argv: list) -> int:
    if not argv or argv[0] in ("--help", "-h"):
        _print_help()
        return 0
    verb, rest = argv[0], argv[1:]
    if verb == "run":
        return cmd_run(rest)
    if verb == "strip":
        return cmd_strip(rest)
    if verb == "ls":
        return cmd_ls(rest)
    print(f"unknown verb: {verb!r}", file=sys.stderr)
    _print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
