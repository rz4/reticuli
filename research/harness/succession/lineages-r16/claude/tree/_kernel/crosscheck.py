# ---------------------------------------------------------------- deciders
_INTERPRETERS = frozenset({'Rscript', 'awk', 'lua', 'python', 'python3', 'python2', 'node', 'ruby', 'perl', 'dash', 'deno', 'py.test', 'zsh', 'tclsh', 'php', 'sh', 'bash', 'py', 'pytest'})
_OPERATORS = frozenset({'&', '\n', '|', '||', '&&', ';'})
_SKIP_VALUE = frozenset({'-m', '-p', '--module', '-X', '-c', '-e'})

_OP_SPLIT = re.compile('|'.join(re.escape(op) for op in sorted(_OPERATORS, key=len, reverse=True)))


def _split_segments(run: str) -> list:
    """`run`'s independent shell segments, split on the pinned operators."""
    return _OP_SPLIT.split(run)


def gate_deciders(run: str) -> list:
    """Which files a gate's shell command actually invokes.

    An interpreter's first non-flag argument (a `-m module` consumed whole,
    since a module name is not a file), or a bare command that is itself a
    relative/absolute path. A plain builtin (`printf`, `grep`) decides
    nothing: beyond the pinned vectors this heuristic is implementation
    freedom (`spec/verification.md`).
    """
    deciders = []
    for segment in _split_segments(run):
        segment = segment.strip()
        if not segment:
            continue
        try:
            tokens = shlex.split(segment)
        except ValueError:
            continue
        if not tokens:
            continue
        first = tokens[0]
        if first in _INTERPRETERS:
            i = 1
            while i < len(tokens):
                tok = tokens[i]
                if tok.startswith('-'):
                    i += 2 if tok in _SKIP_VALUE else 1
                    continue
                deciders.append(tok)
                i += 1
        elif '/' in first:
            deciders.append(first[2:] if first.startswith('./') else first)
    return deciders


def vacuous_gates(recipe: dict) -> list:
    """Gate outputs whose every decider is itself `generated`."""
    generated = set(_recipe.generated_outputs(recipe))
    out = []
    for step in _recipe.gates(recipe):
        deciders = gate_deciders(step["run"])
        if deciders and all(dec in generated for dec in deciders):
            out.append(step["output"])
    return out


# ----------------------------------------------------------------- mutants
_COMPARISON = ('>', '<', '>=', '<=', '==', '!=')
_ARITHMETIC = ('+', '-', '*', '/', '//', '%', '**')
_OP_KIND = {op: "comparison" for op in _COMPARISON}
_OP_KIND.update({op: "arithmetic" for op in _ARITHMETIC})
_OP_ALTS = {
    '>': '<=', '<': '>=', '>=': '<', '<=': '>', '==': '!=', '!=': '==',
    '+': '-', '-': '+', '*': '/', '/': '*', '//': '%', '%': '//', '**': '*',
}
_WORD_ALTS = {'True': 'False', 'False': 'True', 'and': 'or', 'or': 'and'}
_STRING_LITERAL = re.compile(
    r'(\"\"\"(?:.|\n)*?\"\"\"|\'\'\'(?:.|\n)*?\'\'\'|"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\')'
)


def _line_starts(source: str) -> list:
    starts = [0]
    for line in source.splitlines(keepends=True):
        starts.append(starts[-1] + len(line))
    return starts


def _offset(line_starts: list, row: int, col: int) -> int:
    return line_starts[row - 1] + col


def _node_span(node, source: str, line_starts: list = None) -> tuple:
    """An AST node's (start, end) character offsets within `source`."""
    if line_starts is None:
        line_starts = _line_starts(source)
    start = _offset(line_starts, node.lineno, node.col_offset)
    end = _offset(line_starts, node.end_lineno, node.end_col_offset)
    return (start, end)


def _span_text(source: str, span: tuple) -> str:
    return source[span[0]:span[1]]


def _splice(source: str, span: tuple, replacement: str) -> str:
    return source[:span[0]] + replacement + source[span[1]:]


def _edit(source: str, mutant: dict) -> str:
    """Apply one mutant descriptor (from `_mutants`) to `source`."""
    return _splice(source, mutant["span"], mutant["new"])


def _docstring_spans(source: str) -> list:
    """Character spans of every module/class/function docstring in `source`."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    line_starts = _line_starts(source)
    spans = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = getattr(node, "body", [])
            if (body and isinstance(body[0], ast.Expr)
                    and isinstance(body[0].value, ast.Constant)
                    and isinstance(body[0].value.value, str)):
                spans.append(_node_span(body[0].value, source, line_starts))
    return spans


def _token_mutants(source: str) -> list:
    """Comparison/arithmetic operators and boolean words, flipped in place."""
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(source).readline))
    except Exception:
        return []
    line_starts = _line_starts(source)
    doc_spans = _docstring_spans(source)

    def _in_docstring(start, end):
        return any(s <= start and end <= e for s, e in doc_spans)

    mutants = []
    for tok_type, tok_str, start, end, _line in tokens:
        if tok_type == tokenize.OP and tok_str in _OP_ALTS:
            span = (_offset(line_starts, *start), _offset(line_starts, *end))
            if _in_docstring(*span):
                continue
            mutants.append({"span": span, "old": tok_str, "new": _OP_ALTS[tok_str],
                             "kind": _OP_KIND.get(tok_str, "operator")})
        elif tok_type == tokenize.NAME and tok_str in _WORD_ALTS:
            span = (_offset(line_starts, *start), _offset(line_starts, *end))
            if _in_docstring(*span):
                continue
            mutants.append({"span": span, "old": tok_str, "new": _WORD_ALTS[tok_str],
                             "kind": "word"})
    return mutants


def _structural_mutants(source: str) -> list:
    """Statement-level mutants; none are drawn beyond the token sample."""
    return []


def _mutants(source: str) -> list:
    """Every candidate mutant for one generated source file."""
    return _token_mutants(source) + _structural_mutants(source)


def _named(output: str, mutant: dict) -> str:
    """A stable, human-readable name for one (output, mutant) pair."""
    return f"{output}:{mutant['kind']}:{mutant['old']}->{mutant['new']}@{mutant['span'][0]}"


def _label(output: str, mutant: dict) -> str:
    """A survivor's representation in a mutation-score report."""
    return _named(output, mutant)


def _draw_order(items: list, seed: str) -> list:
    """`items`, ordered by a hash of `seed` and position -- deterministic,
    and a function of the claim's own root, not of file order."""
    keyed = [(hashlib.sha256(f"{seed}:{i}".encode("utf-8")).hexdigest(), i, item)
             for i, item in enumerate(items)]
    keyed.sort(key=lambda t: t[0])
    return [item for _digest, _i, item in keyed]


def _mutant_order(candidates: list, seed: str) -> list:
    """The order `mutation_score` draws candidates in, before capping."""
    return _draw_order(candidates, seed)


def _machine(path: str) -> dict:
    """Normalize one crosscheck leg -- a claim directory or a record file --
    into the same shape: root, build digest, whether it audited clean, cost,
    declared obligations, and any declared producer. `declared` is `None`
    only for a version-1 record, which cannot say what the claim declares."""
    if os.path.isdir(path):
        recipe = _recipe.load_recipe(path)
        claim = recipe.get("claim", {})
        aud = audit(path)
        declared = {k: claim[k] for k in ("tolerance", "envelope", "mutation_floor")
                    if k in claim}
        return {
            "kind": "dir", "path": path, "name": claim.get("name"),
            "root": aud["root"], "build_digest": _identity.build_digest(path),
            "audited": bool(aud.get("ok")), "cost": _run.cost(path),
            "declared": declared, "producer": _producer_declaration(path),
        }
    doc = _attest.record_read(path)
    audited_ok = all(g["status"] == "ok" for g in doc["gates"])
    declared = doc.get("claim") if doc.get("record") == 2 else None
    return {
        "kind": "record", "path": path, "name": doc.get("name"),
        "root": doc["root"], "build_digest": doc["build_digest"],
        "audited": audited_ok, "cost": doc.get("cost"),
        "declared": declared, "producer": doc.get("producer"),
    }


def _producer_declaration(path: str):
    """The most recent declared-producer ledger event, or `None`."""
    for event in reversed(_run.ledger_events(path)):
        if event.get("event") == "producer":
            return {k: event[k] for k in ("vendor", "model", "blind") if k in event}
    return None


# ------------------------------------------------------------------- audit
def audit(d: str, *, produce_from: dict = None) -> dict:
    """Re-earn every gate, cold: nothing regrown, nothing trusted.

    `produce_from` substitutes a dependent's bytes for one or more generated
    outputs before judging -- a composed claim's check re-earns its own
    criteria against a layer above's bytes (`spec/kernel-api.md`). A tampered
    pinned input moves the root before any gate runs, so this refuses at the
    identity check; a missing `requires` or an unfurnishable `environment`
    is reported `environment`, not a verdict.
    """
    recipe = _recipe.load_recipe(d)
    manifest = _seal.read_manifest(d)
    recomputed = _identity.root(recipe, d)
    if recomputed != manifest["root"]:
        return {"ok": False,
                "verdict": "identity mismatch: the bytes present no longer "
                           "recompute the sealed root",
                "root": recomputed, "gates": [], "environment": []}

    missing = _run.preflight(recipe)
    room = tempfile.mkdtemp()
    try:
        _build._materialize(recipe, d, room, include_generated=True)
        for output, source in (produce_from or {}).items():
            _core._copy_into(source, _core._safe(room, output))

        furnish_bin = None
        furnish_failed = False
        if not missing:
            fr = _run.furnish(recipe, room)
            if fr["status"] != "ok":
                furnish_failed = True
            else:
                furnish_bin = fr.get("bin")
        cant_judge = bool(missing) or furnish_failed

        results = []
        old_path = os.environ.get("PATH")
        try:
            if furnish_bin:
                os.environ["PATH"] = furnish_bin + os.pathsep + (old_path or "")
            for step in _recipe.gates(recipe):
                output = step["output"]
                if cant_judge:
                    results.append({"output": output, "status": "environment",
                                     "quarantine": None})
                    continue
                outcome = _run.run_gate(step["run"], room, recipe)
                if outcome["status"] == "ok":
                    status = "ok" if _build._compare_pin(d, room, output) else "mismatch"
                else:
                    status = outcome["status"]
                results.append({"output": output, "status": status,
                                 "quarantine": outcome["quarantine"]})
        finally:
            if furnish_bin:
                if old_path is None:
                    os.environ.pop("PATH", None)
                else:
                    os.environ["PATH"] = old_path

        ok = all(g["status"] == "ok" for g in results)
        return {"ok": ok, "verdict": "earned" if ok else "broken",
                "root": recomputed, "gates": results, "environment": missing}
    finally:
        shutil.rmtree(room, ignore_errors=True)


# ------------------------------------------------------------- mutation score
def mutation_score(d: str, *, max_mutants: int = None) -> dict:
    """Deterministic mutants of `d`'s generated Python, re-judged cold.

    Mutants are token-level operator/word flips, drawn in an order seeded by
    the claim's own root (`_draw_order`) and capped at `max_mutants`. A
    mutant is killed when the gates no longer pass against it; the kill
    rate is written as residue (`core.MUTATION_RESIDUE`) and never touches
    the root.
    """
    recipe = _recipe.load_recipe(d)
    manifest = _seal.read_manifest(d)
    cap = max_mutants if max_mutants is not None else _core.MUTANT_CEILING

    sources = {}
    candidates = []
    for output in _recipe.generated_outputs(recipe):
        if not output.endswith(".py"):
            continue
        path = _core._safe(d, output)
        if not os.path.isfile(path):
            continue
        with open(path, "r", encoding="utf-8") as f:
            sources[output] = f.read()
        for m in _mutants(sources[output]):
            candidates.append((output, m))

    selected = _mutant_order(candidates, manifest["root"])[:cap]
    total = len(selected)
    survivors = []

    if total:
        room = tempfile.mkdtemp()
        try:
            _build._materialize(recipe, d, room, include_generated=True)
            for output, mutant in selected:
                original = sources[output]
                target = _core._safe(room, output)
                with open(target, "w", encoding="utf-8") as f:
                    f.write(_edit(original, mutant))
                killed = False
                for step in _recipe.gates(recipe):
                    outcome = _run.run_gate(step["run"], room, recipe)
                    if outcome["status"] != "ok":
                        killed = True
                        break
                with open(target, "w", encoding="utf-8") as f:
                    f.write(original)
                if not killed:
                    survivors.append(_label(output, mutant))
        finally:
            shutil.rmtree(room, ignore_errors=True)

    rate = 0.0 if total == 0 else (total - len(survivors)) / total
    result = {"mutants": total, "rate": rate, "survivors": survivors}
    os.makedirs(os.path.join(d, _core.STORE), exist_ok=True)
    _core._write_json(os.path.join(d, _core.MUTATION_RESIDUE), result)
    return result


# ------------------------------------------------------------------ crosscheck
def crosscheck(m1: str, m2: str, m3: str, *, mutants: int = None) -> dict:
    """The three-machine test (`spec/verification.md`): one root across all
    three legs, M1/M2 byte reuse, every leg's gates earned, and every
    condition the claim itself declares. A leg may be a claim directory or a
    record file; the two transports mix freely and reach the same verdict.
    """
    paths = (m1, m2, m3)
    if len({os.path.realpath(p) for p in paths}) < 3:
        raise ClaimError("crosscheck requires three distinct machines")

    leg1, leg2, leg3 = (_machine(p) for p in paths)
    roots = {"M1": leg1["root"], "M2": leg2["root"], "M3": leg3["root"]}
    equivalence = len(set(roots.values())) == 1
    reuse = (leg1["build_digest"] == leg2["build_digest"]) if equivalence else None
    audited = {"M1": leg1["audited"], "M2": leg2["audited"], "M3": leg3["audited"]}

    reject, incomplete = [], []
    if not equivalence:
        reject.append("equivalence")
    if equivalence and not reuse:
        reject.append("reuse")
    if not all(audited.values()):
        reject.append("audited")

    declared = leg1["declared"]
    c1, c3 = leg1["cost"], leg3["cost"]
    tol = declared["tolerance"] if declared and "tolerance" in declared else _core.TOLERANCE
    comparable = None
    if c1 and c3:
        for unit in _core.COST_LADDER:
            if unit in c1 and unit in c3:
                a, b = c1[unit], c3[unit]
                if a == 0 and b == 0:
                    comparable = True
                elif a == 0 or b == 0:
                    comparable = False
                else:
                    comparable = (max(a, b) / min(a, b)) <= tol
                break

    envelope_report = {}
    mutation_result = None

    if declared is None:
        incomplete.append("declared-conditions")
    else:
        if "tolerance" in declared:
            if comparable is None:
                incomplete.append("tolerance")
            elif not comparable:
                reject.append("tolerance")

        for unit, ceiling in (declared.get("envelope") or {}).items():
            measured = (c3 or {}).get(unit)
            if measured is None:
                envelope_report[unit] = {"within": None}
                incomplete.append(f"envelope {unit}")
            else:
                within = measured <= ceiling
                envelope_report[unit] = {"within": within}
                if not within:
                    reject.append(f"envelope {unit}")

        if "mutation_floor" in declared:
            floor = declared["mutation_floor"]
            if mutants is not None and os.path.isdir(m3):
                ms = dict(mutation_score(m3, max_mutants=mutants))
                ms["ok"] = ms["rate"] >= floor
                mutation_result = ms
                if not ms["ok"]:
                    reject.append("mutation_floor")
            else:
                incomplete.append("mutation_floor")

    if reject:
        verdict = "reject"
    elif incomplete:
        verdict = "incomplete"
    else:
        verdict = "accept"

    producer3 = leg3.get("producer")
    if producer3 and producer3.get("vendor"):
        vendor, model = producer3["vendor"], producer3.get("model") or "unknown"
        blind = producer3.get("blind", False)
        independence_line = (f"declared: {vendor}/{model}, "
                              f"{'blind' if blind else 'unblinded'} workspace (not proven)")
    else:
        independence_line = "unestablished (no producer declared)"

    return {
        "satisfied": verdict == "accept",
        "verdict": verdict,
        "rejected": reject,
        "incomplete": incomplete,
        "equivalence": equivalence,
        "reuse": reuse,
        "audited": audited,
        "roots": roots,
        "cost": {"comparable": comparable, "envelope": envelope_report},
        "mutation_score": mutation_result,
        "independence": independence_line,
    }
