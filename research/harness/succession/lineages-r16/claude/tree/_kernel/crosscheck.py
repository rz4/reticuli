"""Deep re-earning, the three-machine test, and the mutant sampler.

`audit` is the kernel's only verb that re-earns a verdict: it materializes a
fresh judging room with the claim's current generated bytes in place
(optionally substituting a dependent's bytes, `produce_from`, so a
component's check re-earns a composed claim's bytes rather than its own
sealed copy), furnishes the room when `[claim] environment` names one, and
re-runs every gate inside it -- classifying each outcome against the bytes
already pinned at the claim's own root. The public status vocabulary is the
one `spec/verification.md` pins (`ok`/`mismatch`/`failed`/`timeout`/
`environment`); a gate the host cannot judge (a missing `requires`, or a
room that cannot be furnished) is reported `environment` with no sandbox
applied (`quarantine: None`), never a verdict.

`gate_deciders` reads which files a gate's shell command actually invokes --
an interpreter's positional (non-flag, non-module) argument, or a bare
relative/absolute path run directly -- so `vacuous_gates` can name a gate
whose every decider is itself `generated`: a verdict that depends on no
pinned claim at all.

`mutation_score` draws a deterministic sample of token-level mutants (a
comparison or arithmetic operator flipped to its negation, a boolean word
swapped) from a claim's generated Python sources, re-runs the gates against
each mutated copy in a scratch room, and reports the kill rate as residue
(`spec/claim-format.md`'s `mutation_floor`) -- never touching the root.

`crosscheck` is the three-machine test (`spec/verification.md`): one root
across all three legs, M1/M2 byte reuse, every leg's gates earned, the cost
band and every condition the claim itself declares (tolerance, envelope,
mutation floor). A leg is either a claim directory (judged on the spot) or a
signed record (`spec/record.md`, read in place of one) -- `_machine`
normalizes either into the same shape, so the two transports reach the same
verdict. A hard condition the claim declared but this run never measured is
`incomplete`, not accepted; incomplete can never accept, because unknown
evidence is not evidence.
"""
import ast
import hashlib
import io
import os
import re
import shlex
import shutil
import tempfile
import tokenize

from . import attest as _attest
from . import build as _build
from . import core as _core
