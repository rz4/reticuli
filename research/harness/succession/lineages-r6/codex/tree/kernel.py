def record_proof(m1: str, m2: str, m3: str) -> dict[str, Any]:
    if not os.path.isdir(m1):
        raise ClaimError('proof needs a directory for M1')
    records = []
    for path in (m2, m3):
        if os.path.isfile(path):
            anchor = os.environ.get(core._ENV_SIGNERS)
            if not anchor:
                raise ClaimError('record proof needs a trust anchor')
            signer = record_signer(path, anchor)
            records.append({'digest': record_digest(record_read(path)), 'signer': signer})
    result = crosscheck(m1, m2, m3)
    result['proof_recorded'] = result['satisfied']
    if result['satisfied']:
        manifest = read_manifest(m1)
        manifest['proof'] = {'kind': 'crosscheck', 'roots': result['roots'], 'records': records}
        core._write_json(core._safe(m1, MANIFEST), manifest)
    return result
