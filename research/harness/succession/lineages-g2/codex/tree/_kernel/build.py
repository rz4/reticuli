"""Materialize claims, re-earn their gates, and rebuild generated outputs."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
from collections.abc import Mapping

from . import core, identity, recipe, run, seal


def _toml_value(value: object) -> str:
    """Encode the JSON-compatible values accepted by the recipe reader."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(
            f"{json.dumps(key)} = {_toml_value(item)}"
            for key, item in value.items()) + " }"
    raise core.ClaimError(f"cannot write recipe value: {value!r}")


def _toml_recipe(document: Mapping) -> str:
    lines: list[str] = []
    for table, values in document.items():
        if table == "step":
            continue
        if not isinstance(values, dict):
            lines.append(f"{json.dumps(table)} = {_toml_value(values)}")
            continue
        lines.append(f"[{json.dumps(table)}]")
        for key, value in values.items():
            lines.append(f"{json.dumps(key)} = {_toml_value(value)}")
        lines.append("")
    for step in document.get("step", []):
        lines.append("[[step]]")
        for key, value in step.items():
            lines.append(f"{json.dumps(key)} = {_toml_value(value)}")
        lines.append("")
    return "\n".join(lines) + "\n"


def _step_guidance(step: Mapping) -> str | None:
    return step.get("guidance", step.get("request"))


def _compare_pin(source: str, room: str, name: str) -> bool:
    try:
        return core._hash_file(core._safe(source, name)) == core._hash_file(
            core._safe(room, name))
    except core.ClaimError:
        return False


def _materialize(source: str, destination: str, parsed: Mapping, *,
                 generated: bool = False) -> None:
    """Copy the identity-bearing inputs and optionally current generated bytes."""
    os.makedirs(destination, exist_ok=True)
    version = parsed["claim"].get("format", 1)
    if version >= 3:
        target = core._safe(destination, core.RECIPE)
        with open(target, "w", encoding="utf-8") as stream:
            stream.write(_toml_recipe(identity._preimage_recipe(parsed)))
    else:
        original = recipe.recipe_path(source)
        core._copy_into(original, core._safe(destination, os.path.basename(original)))
    for name in recipe._inputs(parsed, source):
        core._copy_into(core._safe(source, name), core._safe(destination, name))
    for step in recipe._steps(parsed):
        name = step["output"]
        cls = step.get("class", "generated" if step["kind"] == "produce" else "pinned")
        if step["kind"] == "gate":
            continue
        if cls in ("generated", "free") and not generated and "from" not in step:
            continue
        src = core._safe(source, name)
        if os.path.isfile(src):
            core._copy_into(src, core._safe(destination, name))


def _read_usage(directory: str) -> dict:
    path = core._safe(directory, core.USAGE)
    if not os.path.isfile(path):
        return {}
    try:
        with open(path, encoding="utf-8") as stream:
            value = json.load(stream)
        return {key: value[key] for key in ("usd", "tokens", "calls", "vendor", "model")
                if key in value} if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def _produce(command: str, directory: str, output: str, outputs: list[str],
             guidance: str | None = None, producer_env: Mapping[str, str] | None = None) -> dict:
    """Run the caller's producer with its HOME and ambient reachability."""
    env = {key: os.environ[key] for key in core._KEEP_ENV if key in os.environ}
    env.setdefault("PATH", os.defpath)
    env.update({core._ENV_OUTPUT: core._safe(directory, output),
                core._ENV_OUTPUTS: json.dumps(outputs),
                core._ENV_CLAIM: os.path.realpath(directory)})
    if guidance is not None:
        env[core._ENV_REQUEST] = guidance
    if producer_env:
        env.update({str(key): str(value) for key, value in producer_env.items()})
    result = run._run([core._SHELL, "-c", command], directory, env,
                      core.PRODUCER_TIMEOUT)
    result["quarantine"] = "inherited" if os.environ.get(core._JAILED) else "none"
    return result


def _ssh_verify(signature: str, message: str, allowed_signers: str,
                principal: str, namespace: str = core.SIGN_NAMESPACE) -> bool:
    try:
        result = subprocess.run(
            ["ssh-keygen", "-Y", "verify", "-f", allowed_signers, "-I", principal,
             "-n", namespace, "-s", signature], input=message.encode(),
            capture_output=True, timeout=20)
        return result.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _authorized(*args: object, **kwargs: object) -> bool:
    """Check an explicitly supplied SSH signature against an anchor."""
    return _ssh_verify(*args, **kwargs) if len(args) >= 4 else False


def _run_gates(source: str, room: str, parsed: Mapping) -> list[dict]:
    rows = []
    missing = run.preflight(parsed)
    try:
        bindir = run.furnish(room, parsed) if not missing else None
    except core.ClaimError as exc:
        missing.append(str(exc))
        bindir = None
    for step in recipe.gates(parsed):
        name = step["output"]
        if missing:
            rows.append({"output": name, "status": "environment",
                         "quarantine": run.sandbox_backend(), "detail": ", ".join(missing)})
            continue
        extra = None
        if bindir:
            extra = {"PATH": bindir + os.pathsep + os.environ.get("PATH", os.defpath)}
        result = run.run_gate(step["run"], room, parsed, extra_env=extra)
        status = result["status"]
        cls = step.get("class", "pinned")
        if status == "ok" and cls not in ("generated", "free"):
            status = "reproduced" if _compare_pin(source, room, name) else "mismatch"
        rows.append({"output": name, "status": status,
                     "quarantine": result["quarantine"],
                     "stdout": result["stdout"], "stderr": result["stderr"]})
    return rows


def audit(directory: os.PathLike[str] | str, **kwargs: object) -> dict:
    """Re-run gates on present generated bytes in a fresh room."""
    source = os.path.realpath(os.fspath(directory))
    verified = seal.verify(source)
    if not verified["ok"]:
        return {"ok": False, "root": verified["root"], "gates": [],
                "verdict": "identity mismatch"}
    parsed = recipe.load_recipe(source)
    with tempfile.TemporaryDirectory(prefix="reticuli-audit-") as room:
        _materialize(source, room, parsed, generated=True)
        rows = _run_gates(source, room, parsed)
    ok = bool(rows) and all(row["status"] in ("ok", "reproduced") for row in rows)
    return {"ok": ok, "root": verified["root"], "gates": rows,
            "verdict": "earned" if ok else "carried or broken"}


def rebuild(directory: os.PathLike[str] | str, producer: str,
            into: os.PathLike[str] | str, *, produce_from: str | None = None,
            input_from: str | None = None, guidance: bool = True,
            producer_env: Mapping[str, str] | None = None) -> dict:
    """Build in a fresh directory and seal only after all pins re-earn."""
    source = os.path.realpath(os.fspath(directory))
    destination = os.path.realpath(os.fspath(into))
    verified = seal.verify(source)
    if not verified["ok"]:
        raise core.ClaimError("source claim identity does not match its seal")
    if os.path.exists(destination) and os.listdir(destination):
        raise core.ClaimError(f"rebuild destination is not empty: {destination}")
    parsed = recipe.load_recipe(source)
    _materialize(source, destination, parsed)
    outputs = [s["output"] for s in recipe.produces(parsed)
               if s.get("class", "generated") in ("generated", "free") and "from" not in s]
    production = []
    for step in recipe.produces(parsed):
        name = step["output"]
        if name not in outputs:
            continue
        hint = _step_guidance(step) if guidance else None
        result = _produce(producer, destination, name, outputs, hint, producer_env)
        production.append(result)
        run.ledger(destination, {"kind": "producer", "output": name,
                                 "seconds": result["seconds"],
                                 "quarantine": result["quarantine"],
                                 **_read_usage(destination)})
        if result["status"] != "ok":
            raise core.ClaimError(f"producer failed for {name}: {result['stderr']}")
        core._hash_file(core._safe(destination, name))
    rows = _run_gates(source, destination, parsed)
    if any(row["status"] not in ("ok", "reproduced") for row in rows):
        raise core.ClaimError(f"rebuild gates failed: {rows!r}")
    sealed = seal.seal(destination)
    if sealed["root"] != verified["root"]:
        raise core.ClaimError("rebuilt root differs from source root")
    return {"root": sealed["root"], "gates": rows,
            "quarantine": production[-1]["quarantine"] if production else run.sandbox_backend(),
            "build_digest": identity.build_digest(destination)}
