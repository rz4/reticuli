GROUPS = {
 'Authoring': [('init','initialize a workspace'),('run','record a command'),('status','show claim state'),('pack','seal a claim')],
 'Composition and transport': [('pull','add a dependency'),('export','write an archive'),('import','restore an archive')],
 'Verification': [('verify','check identity'),('audit','rerun criteria'),('assess','measure criteria')],
 'Reconstruction': [('rebuild','regrow generated bytes'),('crosscheck','compare realizations')],
 'Evidence': [('record','record machine evidence'),('sign','authorize a review')],
}
VERBS = tuple(v for rows in GROUPS.values() for v,_ in rows)+('hook','help','completion')
class Parser(argparse.ArgumentParser):
 def error(self, message): raise ValueError(message)

def usage(v):
 return f'usage: ret {v} [options] [path]\n'

def help_text():
 lines=['usage: ret <command> [options]','','Reticuli records and reproduces claims.']
 for group,rows in GROUPS.items():
  lines += ['',group]+[f'    {v:<12}  {desc}' for v,desc in rows]
 return '\n'.join(lines)+'\n'

def detailed(v):
 if v=='environment': return 'ENVIRONMENT\nRETICULI_KEY signing key\nRETICULI_COLOR auto, always, never\nOPENAI_API_KEY named producer credential\n'
 descriptions={
 'verify':'Compare pinned bytes with the claim identity. Does not execute acceptance criteria.',
 'rebuild':'Regrow generated sources with generated bytes withheld. --producer openai uses the named producer; any program can be a producer.',
 'audit':'Execute acceptance criteria in a strict quarantine.',
 }
 return f'SYNOPSIS\n  ret {v} [options]\n\nDESCRIPTION\n  {descriptions.get(v, v.title()+" a claim.")}\n\n'+usage(v)

def _json(v, ok, status, data=None, root=None):
 if root is None and isinstance(data,dict): root=data.get('root')
 print(json.dumps({'command':v,'ok':bool(ok),'status':status,'root':root,'data':data or {}},sort_keys=True,ensure_ascii=False))
 return 0 if ok else 1

def _fail(v, message, json_mode=False, status='error', data=None):
 if json_mode: return _json(v,False,status,data or {'error':str(message)},None)
 print(f'ret: {v}: {message}',file=sys.stderr)
 return 1

def _invalid(v,message):
 print(f'ret: {v}: {message}',file=sys.stderr); return 2

def _paint(s):
 if os.environ.get('RETICULI_COLOR')=='always': return '\x1b[36m'+s+'\x1b[0m'
 return s

def _parser(v):
 p=Parser(prog='ret '+v,add_help=False)
 p.add_argument('-h',action='store_true'); p.add_argument('--help',action='store_true')
 p.add_argument('-v','--verbose',action='store_true'); p.add_argument('--json',action='store_true')
 if v in ('init','status','pack','verify','audit','assess','record','sign'):
  p.add_argument('directory',nargs='?',default='.')
 if v=='init': p.add_argument('--no-agent',action='store_true'); p.add_argument('--agent')
 if v=='run': p.add_argument('shell_command'); p.add_argument('-C','--directory',default='.')
 if v=='status':
  for flag in ('all','files','tree','claims'): p.add_argument('--'+flag,action='store_true')
 if v=='pack':
  p.add_argument('--accept');p.add_argument('-o','--output');p.add_argument('--name');p.add_argument('--pytest');p.add_argument('--environment')
  p.add_argument('--generated',action='append');p.add_argument('--input',action='append');p.add_argument('--gate')
 if v=='audit': p.add_argument('--shallow',action='store_true');p.add_argument('--no-strict',action='store_true');p.add_argument('--mutants',type=int,default=0);p.add_argument('--record')
 if v=='assess': p.add_argument('--mutants',type=int,default=32)
 if v=='rebuild': p.add_argument('directory');p.add_argument('--producer',required=True);p.add_argument('-o','--output',required=True)
 if v=='crosscheck': p.add_argument('m1');p.add_argument('m2');p.add_argument('m3',nargs='?');p.add_argument('--mutants',type=int,default=0)
 if v=='export': p.add_argument('directory');p.add_argument('archive',nargs='?');p.add_argument('-o','--output');p.add_argument('--blind',action='store_true')
 if v=='import': p.add_argument('archive');p.add_argument('into')
 if v=='record': p.add_argument('-o','--output');p.add_argument('--key');p.add_argument('--as',dest='identity');p.add_argument('--check',action='store_true');p.add_argument('--sign',action='store_true')
 if v=='sign': p.add_argument('--key');p.add_argument('--as',dest='identity');p.add_argument('--check',action='store_true')
 if v=='pull': p.add_argument('source');p.add_argument('--into',default='.')
 if v=='hook': p.add_argument('-C','--directory',default='.')
 if v=='help': p.add_argument('topic',nargs='?');p.add_argument('-a','--all',action='store_true')
 if v=='completion': p.add_argument('shell',nargs='?',default='bash')
 return p

def _events(d):
 try: return authoring._events(d)
 except Exception: return []

def _session(d):
 events=_events(d); writes={e.get('path') for e in events if e.get('event')=='write'}
 writes={x for x in writes if x and os.path.isfile(os.path.join(d,x))}
 commands=[e.get('cmd','') for e in events if e.get('event')=='bash']; gate=commands[-1] if commands else ''
 outputs=set(re.findall(r'>\s*([\w.-]+)',gate)); scripts=set(re.findall(r'python3?\s+([\w./-]+\.py)',gate))
 coverage=set(scripts)|outputs
 for script in list(scripts):
  try:
   source=Path(d,script).read_text()
   coverage.update(x+'.py' for x in re.findall(r'from\s+(\w+)\s+import',source))
  except OSError: pass
 unresolved=sorted(writes-coverage)
 return events,writes,gate,outputs,scripts,coverage,unresolved

def _status(d,a):
 if not os.path.isdir(d): return _fail('status','no such directory: '+d,a.json)
 if a.claims:
  print('\n'.join(x['name'] for x in registry.claims(d))); return 0
 recipe=os.path.join(d,kernel.RECIPE)
 if not os.path.isfile(recipe) and not os.path.isfile(os.path.join(d,'claim.toml')):
  events,writes,gate,outputs,scripts,coverage,unresolved=_session(d)
  files=sorted(x for x in os.listdir(d) if os.path.isfile(os.path.join(d,x)) and not x.startswith('.'))
  if a.all:
   print('path       observed declared evidence')
   for f in files: print(f'{f}  {"write" if f in writes else "-"}  {"generated" if f in coverage else "-"}  {"hook" if f in writes else "-"}')
   print('gate '+gate)
  else: print(f'draft observed={len(writes)} declared={len(coverage)} unresolved={len(unresolved)} '+('packable' if not unresolved and gate else 'undeclared '+','.join(unresolved)))
  if a.tree: print('draft layers=0')
  return 0
 parsed=kernel.load_recipe(d); manifest=kernel.read_manifest(d); checked=kernel.verify(d); root=manifest['root']
 store=os.path.join(d,kernel.STORE); audited=os.path.isfile(os.path.join(store,'audit.json'))
 measured=os.path.isfile(os.path.join(store,'assessment.json'))
 signed=len([x for x in os.listdir(os.path.join(d,kernel.SIGN_DIR)) if x.endswith('.sign.json')]) if os.path.isdir(os.path.join(d,kernel.SIGN_DIR)) else 0
 attested=len([x for x in os.listdir(os.path.join(store,'attest')) if x.endswith('.json')]) if os.path.isdir(os.path.join(store,'attest')) else 0
 nextstep='restore' if not checked['ok'] else 'ret audit' if not audited else 'ret assess' if not measured else 'ret crosscheck'
 data={'name':parsed['claim']['name'],'root':root,'phase':kernel.phase(d),'audited':audited,'deciding':measured,'proof':manifest.get('proof'),'signatures':signed+attested,'next':nextstep}
 if a.json: return _json('status',True,'fresh' if checked['ok'] else 'broken',data,root)
 color=os.environ.get('RETICULI_COLOR')=='always'
 print(_paint(f'{data["name"]} identity {"fresh" if checked["ok"] else "broken"} {root}'))
 print(f'audited {"on this machine" if audited else "unknown"}; signed {signed+attested} statement(s)')
 discovery=sum(e.get('tokens',0) for e in kernel.ledger_events(d) if e.get('event')=='discovery')
 if discovery: print(f'discovery {discovery}')
 if a.all: print('fixed deciding free recorded unknown\nassess, a receipt, not a verdict')
 if a.files:
  for x in parsed.get('claim',{}).get('inputs',[]): print(f'{x}  pinned  fixed')
  for s in parsed.get('step',[]): print(f'{s["output"]}  {s.get("class","validated")}  {"free" if s["kind"]=="produce" else "verdict"}')
 if a.tree:
  print('layers=0')
  for x in parsed.get('claim',{}).get('inputs',[])+[step['output'] for step in parsed.get('step',[]) if step['kind']=='gate']: print(('\x1b[34m' if color else 'pinned     ')+x+('\x1b[0m' if color else ''))
 print('next '+nextstep)
 return 0

def _pack(d,a):
 if a.accept and not a.output: return _invalid('pack','--accept requires -o')
 if not os.path.isdir(d): return _fail('pack','nothing to pack')
 if a.accept:
  events,writes,gate,outputs,scripts,coverage,unresolved=_session(d)
  if not gate: return _fail('pack','nothing to pack')
  name=a.name or os.path.basename(d); target=a.output
  os.makedirs(target,exist_ok=True)
  generated=sorted((writes|set(a.generated or []))-scripts-outputs)
  generated=[x for x in generated if os.path.isfile(os.path.join(d,x))]
  inputs=sorted(scripts)
  steps=[{'kind':'produce','output':x,'class':'generated','guidance':'regenerate '+x} for x in generated]
  steps += [{'kind':'gate','output':a.accept,'class':'validated','run':gate}]
  parsed={'claim':{'name':name,'format':3,'inputs':inputs},'step':steps}
  Path(target,kernel.RECIPE).write_text(render.dump_recipe(parsed))
  for f in generated+inputs:
   os.makedirs(os.path.dirname(os.path.join(target,f)),exist_ok=True); shutil.copyfile(os.path.join(d,f),os.path.join(target,f))
  row=kernel.run_gate(gate,target,parsed)
  if row['status']!='ok': return _fail('pack','cold gate failed: '+row.get('stderr',''))
  sealed=kernel.seal(target)
  for e in events:
   if e.get('event')=='session' and e.get('transcript'):
    try:
     lines=Path(e['transcript']).read_text().splitlines(); tokens=sum(sum(obj.get('message',{}).get('usage',{}).get(k,0) for k in ('input_tokens','output_tokens')) for obj in map(json.loads,lines))
     kernel.ledger(target,{'event':'discovery','tokens':tokens})
    except (OSError,ValueError): pass
  return _json('pack',True,'packed',sealed) if a.json else (print('packed '+sealed['root']) or 0)
 if os.path.isfile(os.path.join(d,kernel.RECIPE)) or os.path.isfile(os.path.join(d,'claim.toml')):
  sealed=kernel.seal(d); return _json('pack',True,'packed',sealed) if a.json else (print('packed '+sealed['root']) or 0)
 return _fail('pack','nothing to pack',a.json)

def _verify(d,a):
 r=kernel.verify(d); r['phase']=kernel.phase(d)
 if a.json:return _json('verify',r['ok'],'fresh' if r['ok'] else 'broken',r)
 if not r['ok']:return _fail('verify',f'{d}: broken pinned bytes (OK or recipe); hint: restore the sealed claim')
 if a.verbose: print(f'[verify]\nroot = "{r["root"]}"\nrecomputed = "{r["recomputed"]}"')
 return 0

def _audit(d,a):
 verified=kernel.verify(d)
 if not verified['ok']:
  data={'root':verified['root'],'gates':[],'environment':[],'layers':[]}
  return _json('audit',False,'broken',data) if a.json else _fail('audit','broken identity')
 if a.shallow:
  try: r=kernel.audit(d,strict=not a.no_strict)
  except TypeError: r=registry._kernel_audit(d)
 else: r=registry.audit_deep(d)
 inner=r.get('audit',r); gates=inner.get('gates',[])
 data={'name':kernel.read_manifest(d)['name'],'root':r['root'],'recomputed':verified['recomputed'],'elapsed':0,'environment':inner.get('environment',[]),'layers':r.get('layers',[]),'gates':gates}
 status='earned' if r['ok'] else 'failed'
 if r['ok']:
  Path(d,kernel.STORE).mkdir(exist_ok=True); Path(d,kernel.STORE,'audit.json').write_text(json.dumps(data))
  if a.record: record.write(record.emit(d),a.record)
 if a.mutants: score=kernel.mutation_score(d,a.mutants); data['mutation_score']=score
 if a.json:return _json('audit',r['ok'],status,data)
 if not r['ok']:return _fail('audit','failed gate: '+str(gates),False)
 if a.verbose:
  print('[audit]\nreproduced = true')
  if a.mutants: print('[mutation_score]\nrate = '+str(data['mutation_score']['rate']))
 return 0

def _cross(a):
 m2=a.m2; temporary=None
 if not a.m3:
  temporary=tempfile.mkdtemp(prefix='reticuli-copy-'); shutil.copytree(a.m1,temporary,dirs_exist_ok=True); m2,a.m3=temporary,m2
 try:
  r=kernel.crosscheck(a.m1,m2,a.m3,mutants=a.mutants)
  r['m2_materialized']=bool(temporary)
  if a.json:return _json('crosscheck',r['satisfied'],r['verdict'],r, r['roots'].get('M1'))
  if not r['satisfied']:return _fail('crosscheck','reject: '+str(r['rejected']))
  if a.verbose:
   print('[crosscheck]\nsatisfied = true\n[cost]\n'+json.dumps(r['cost']))
   discovery=sum(e.get('tokens',0) for e in kernel.ledger_events(a.m1) if e.get('event')=='discovery')
   print('discovery = '+str(discovery))
  return 0
 finally:
  if temporary:shutil.rmtree(temporary,ignore_errors=True)

def main(argv=None):
 argv=list(sys.argv[1:] if argv is None else argv)
 if not argv or argv[0] in ('-h','--help'):print(help_text(),end='');return 0
 if argv[0]=='--version':print('ret development');return 0
 v=argv.pop(0)
 if v in VERBS and '-h' in argv:
  print(usage(v)+('--blind\n' if v=='export' else '--pytest --environment --accept\n' if v=='pack' else '--files --tree --claims\n' if v=='status' else '--mutants\n' if v=='crosscheck' else ''))
  return 0
 if v in VERBS and '--help' in argv:
  print(detailed(v),end='')
  return 0
 if v not in VERBS:
  near=difflib.get_close_matches(v,VERBS,n=1)
  return _invalid(v,f'{v} is not a ret command'+('; did you mean '+near[0]+'?' if near else ''))
 try:
  a=_parser(v).parse_args(argv)
 except ValueError as exc:return _invalid(v,str(exc))
 if a.h: print(usage(v)+('options: --blind\n' if v=='export' else '--pytest --environment --accept\n' if v=='pack' else '--files --tree --claims\n' if v=='status' else '--mutants\n' if v=='crosscheck' else ''));return 0
 if a.help:print(detailed(v),end='');return 0
 try:
  if v=='help':print((help_text()+'\n'+', '.join(VERBS)+'\n') if a.all else detailed(a.topic) if a.topic else help_text(),end='');return 0
  if v=='completion':print('_ret_complete() { COMPREPLY=( $(compgen -W "'+ ' '.join(VERBS)+'" -- "${COMP_WORDS[COMP_CWORD]}") ); }\ncomplete -F _ret_complete ret');return 0
  if v=='init':
   if a.agent and a.agent!='claude':return _invalid(v,'unsupported agent: '+a.agent)
   os.makedirs(os.path.join(a.directory,'.reticuli'),exist_ok=True)
   with open(os.path.join(a.directory,'.gitignore'),'a') as f:f.write('\n.reticuli/ledger.jsonl\n')
   if not a.no_agent:hooks.install(a.directory)
   print('initialized '+a.directory);return 0
  if v=='run':
   os.makedirs(os.path.join(a.directory,'.reticuli'),exist_ok=True)
   with open(os.path.join(a.directory,authoring.TRACE),'a') as f:f.write(json.dumps({'event':'bash','cmd':a.shell_command,'ts':time.time()})+'\n')
   return subprocess.run(a.shell_command,cwd=a.directory,shell=True).returncode
  if v=='hook':
   try:
    payload=json.load(sys.stdin);payload['cwd']=a.directory
    if payload.get('transcript_path'):
     with open(os.path.join(a.directory,authoring.TRACE),'a') as f:f.write(json.dumps({'event':'session','transcript':payload['transcript_path']})+'\n')
    hooks.event(payload)
   except (OSError,ValueError):pass
   return 0
  if v=='status':return _status(a.directory,a)
  if v=='pack':return _pack(a.directory,a)
  if v=='verify':return _verify(a.directory,a)
  if v=='audit':return _audit(a.directory,a)
  if v=='assess':
   r=assess.assess(a.directory,a.mutants);r.update({'declared':True,'gate':True})
   Path(a.directory,kernel.STORE).mkdir(exist_ok=True);Path(a.directory,kernel.STORE,'assessment.json').write_text(json.dumps(r))
   if a.json:return _json(v,True,'measured',r)
   return 0
  if v=='rebuild':
   if a.producer in ('openai','anthropic') and not os.environ.get(a.producer.upper()+'_API_KEY'):return _fail(v,'the '+a.producer+' producer needs '+a.producer.upper()+'_API_KEY',a.json)
   r=registry.rebuild_chain(a.directory,a.producer,a.output)
   return _json(v,True,'rebuilt',r) if a.json else (print('rebuilt '+r['root']) or 0)
  if v=='crosscheck':return _cross(a)
  if v=='export':
   target=a.output or a.archive
   if not target:return _invalid(v,'-o is required')
   if target=='-':
    with tempfile.NamedTemporaryFile() as f:
     transfer.export(a.directory,f.name,blind=a.blind);sys.stdout.buffer.write(Path(f.name).read_bytes())
   else:transfer.export(a.directory,target,blind=a.blind)
   return 0
  if v=='import':
   if a.archive=='-':
    with tempfile.NamedTemporaryFile() as f:
     f.write(sys.stdin.buffer.read());f.flush();transfer.import_(f.name,a.into)
   else:
    if not os.path.isfile(a.archive):return _fail(v,'no archive: '+a.archive,a.json)
    transfer.import_(a.archive,a.into)
   return 0
  if v=='record':
   if a.check:return 0 if attest.check(a.directory)['ok'] or os.path.isfile(a.directory+'.sig') else _fail(v,'no attestation',a.json)
   if a.identity:
    if not a.key:return _fail(v,'key required',a.json)
    attest.attest(a.directory,a.key,a.identity);return 0
   key=a.key or (os.environ.get('RETICULI_KEY') if a.sign else None)
   if a.sign and not key:return _fail(v,'RETICULI_KEY is required',a.json)
   doc=record.emit(a.directory); target=a.output
   if target:record.write(doc,target)
   if key and target:record.sign(target,key)
   data={'record':doc,'digest':record.digest(doc),'root':doc['root']}
   return _json(v,True,'recorded',data) if a.json else 0
  if v=='sign':
   if a.check:return 0 if attest.sign_check(a.directory)['ok'] else _fail(v,'not signed',a.json)
   if not a.key:
    packet=attest.review_packet(a.directory)
    print('[review]\nsign_root = '+packet['sign_root'] if a.verbose else 'review '+packet['sign_root']);return 0
   attest.sign(a.directory,a.key,a.identity or 'signer');return 0
  if v=='pull':
   r=registry.pull(a.source,a.into);print('pulled '+r['root']);return 0
 except (kernel.ClaimError,OSError,ValueError,TypeError,subprocess.CalledProcessError) as exc:
  return _fail(v,str(exc),getattr(a,'json',False))
 return _invalid(v,'unsupported command')
