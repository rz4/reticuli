"""Materialize claims, re-earn their gates, and rebuild generated outputs."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import time
from collections.abc import Mapping

from . import core, identity, recipe, run, seal


def _toml_value(value: object) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {_toml_value(item)}" for key, item in value.items()) + " }"
    raise core.ClaimError(f"cannot write TOML value: {value!r}")


def _room_recipe(parsed: Mapping) -> str:
    """Write a parseable representation of the identity preimage."""
    preimage = identity._preimage_recipe(parsed)
    lines = ["[claim]"]
    for key, value in preimage["claim"].items():
        lines.append(f"{key} = {_toml_value(value)}")
    for step in preimage.get("step", []):
        lines.extend(("", "[[step]]"))
        for key, value in step.items():
            lines.append(f"{json.dumps(key) if key == 'from' else key} = {_toml_value(value)}")
    return "\n".join(lines) + "\n"


def _materialize(source: str, target: str, parsed: Mapping | None = None,
                 *, generated: bool = False) -> None:
    """Copy only declared inputs and, for an audit, generated bytes."""
    parsed = parsed or recipe.load_recipe(source)
    os.makedirs(target, exist_ok=True)
    if parsed["claim"].get("format", 1) >= 3:
        with open(os.path.join(target, core.RECIPE), "w", encoding="utf-8") as stream:
            stream.write(_room_recipe(parsed))
    else:
        path = recipe.recipe_path(source)
        core._copy_into(path, os.path.join(target, os.path.basename(path)))
    for name in recipe._inputs(parsed, source):
        core._copy_into(core._safe(source, name), core._safe(target, name))
    if generated:
        for name in recipe.generated_outputs(parsed):
            path = core._safe(source, name)
            if os.path.lexists(path):
                core._copy_into(path, core._safe(target, name))


def _compare_pin(source: str, target: str, name: str) -> bool:
    try:
        return core._hash_file(core._safe(source, name)) == core._hash_file(core._safe(target, name))
    except core.ClaimError:
        return False


def _step_guidance(step: Mapping, enabled: bool = True) -> str:
    if not enabled:
        return ""
    return str(step.get("guidance", step.get("request", "")))


def _read_usage(directory: str) -> dict:
    path = os.path.join(directory, core.USAGE)
    try:
        with open(path, "r", encoding="utf-8") as stream:
            value = json.load(stream)
        if not isinstance(value, dict):
            raise ValueError("usage must be an object")
        return {key: value[key] for key in ("usd", "tokens", "calls") if key in value}
    except FileNotFoundError:
        return {}
    except (OSError, ValueError) as exc:
        raise core.ClaimError(f"cannot read usage: {exc}") from exc


def _produce(command: str, directory: str, step: Mapping, outputs: list[str],
             *, guidance: bool = True, producer_env: Mapping[str, str] | None = None) -> dict:
    """Run the caller's producer with its reachability and HOME intact."""
    environment = {key: os.environ[key] for key in core._KEEP_ENV if key in os.environ}
    environment.setdefault("PATH", os.defpath)
    environment.update(producer_env or {})
    environment[core._ENV_OUTPUT] = core._safe(directory, step["output"])
    environment[core._ENV_OUTPUTS] = json.dumps(outputs)
    environment[core._ENV_REQUEST] = _step_guidance(step, guidance)
    result = run._run([core._SHELL, "-c", command], directory, environment,
                      core.PRODUCER_TIMEOUT)
    return result


def _ssh_verify(*args, **kwargs) -> bool:
    """Check a detached SSH signature when an anchor is supplied."""
    if len(args) < 3:
        return False
    data, signature, allowed_signers = args[:3]
    namespace = kwargs.get("namespace", core.SIGN_NAMESPACE)
    principal = kwargs.get("principal", core.NAMESPACE)
    try:
        done = subprocess.run(
            ["ssh-keygen", "-Y", "verify", "-f", str(allowed_signers),
             "-I", principal, "-n", namespace, "-s", str(signature)],
            input=data if isinstance(data, bytes) else str(data).encode(),
            capture_output=True, check=False)
        return done.returncode == 0
    except OSError:
        return False


def _authorized(*args, **kwargs) -> bool:
    return _ssh_verify(*args, **kwargs)


def _earn_gates(source: str, room: str, parsed: Mapping) -> list[dict]:
    rows = []
    try:
        bin_dir = run.furnish(source, parsed)
    except core.ClaimError as exc:
        return [{"output": step["output"], "status": "environment",
                 "quarantine": run.sandbox_backend(), "stderr": str(exc)}
                for step in recipe.gates(parsed)]
    for step in recipe.gates(parsed):
        name = step["output"]
        result = run.run_gate(step["run"], room, parsed)
        if result["status"] == "ok" and not _compare_pin(source, room, name):
            result["status"] = "mismatch"
        result["output"] = name
        rows.append(result)
    return rows


def audit(directory: str, *, shallow: bool = False) -> dict:
    """Re-run gates against present generated bytes in a fresh room."""
    manifest = seal.read_manifest(directory)
    parsed = recipe.load_recipe(directory)
    checked = seal.verify(directory)
    if not checked["ok"]:
        return {"ok": False, "root": manifest["root"], "gates": [],
                "verdict": "identity mismatch"}
    with tempfile.TemporaryDirectory(prefix="reticuli-audit-") as room:
        _materialize(directory, room, parsed, generated=True)
        rows = _earn_gates(directory, room, parsed)
    ok = all(row["status"] == "ok" for row in rows)
    return {"ok": ok, "root": manifest["root"], "gates": rows,
            "verdict": "earned" if ok else "carried or broken"}


def rebuild(directory: str, producer: str, into: str, *, produce_from=None,
            input_from=None, guidance: bool = True,
            producer_env: Mapping[str, str] | None = None) -> dict:
    """Build a claim using only its declared inputs and a producer command."""
    original = seal.read_manifest(directory)
    parsed = recipe.load_recipe(directory)
    if not seal.verify(directory)["ok"]:
        raise core.ClaimError("cannot rebuild a claim whose pinned identity changed")
    if os.path.exists(into) and os.listdir(into):
        raise core.ClaimError(f"rebuild target is not empty: {into}")
    source = input_from or directory
    _materialize(source, into, parsed)
    outputs = recipe.generated_outputs(parsed)
    produced = []
    for step in recipe.produces(parsed):
        if step.get("class", "generated") != "generated" or "from" in step:
            continue
        started = time.monotonic()
        result = _produce(producer, into, step, outputs,
                          guidance=guidance, producer_env=producer_env)
        elapsed = time.monotonic() - started
        if result["status"] != "ok":
            raise core.ClaimError(f"producer failed for {step['output']}: {result['stderr']}")
        event = {"seconds": elapsed, "calls": 1,
                 "quarantine": run.sandbox_backend()}
        event.update(_read_usage(into))
        run.ledger(into, event)
        produced.append(result)
    rows = _earn_gates(directory, into, parsed)
    if any(row["status"] != "ok" for row in rows):
        raise core.ClaimError(f"rebuild gates did not reproduce: {rows}")
    rebuilt = seal.seal(into)
    if rebuilt["root"] != original["root"]:
        raise core.ClaimError("rebuild did not reproduce the sealed root")
    return {"root": rebuilt["root"], "name": rebuilt["name"],
            "gates": rows, "quarantine": run.sandbox_backend(),
            "build_digest": identity.build_digest(into)}
