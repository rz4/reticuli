"""reticuli._kernel.crosscheck -- the three-machine test, and the mutation
engine that gives the equivalence class a measured width.

`crosscheck(m1, m2, m3, mutants=None)` is the three-machine test
(`spec/verification.md`): one root across all three legs, byte reuse between
M1 and M2, every verdict re-earned (audit), the cost envelope and band, and
-- where the claim declares one -- the mutation floor. A leg is either a
claim directory (judged on the spot) or a record file (`spec/record.md`,
a frozen statement); the two transports mix freely and reach the same
verdict. The result is three-valued: `accept` only when every hard
condition the claim declares is both measured and true; a declared
condition nobody measured is `incomplete`, never a silent accept; anything
definitely false is `reject`.

`mutation_score(d, max_mutants=None)` measures how many deterministic
mutants of the claim's generated Python source the claim's own gate can
tell apart from the original -- kill rate, residue on `.reticuli/`, never
the root. `gate_deciders` / `vacuous_gates` are the claim-boundary check: a
gate whose every decider is itself generated bytes decides nothing a claim
can be blamed for.

Stdlib only. Never the network.
"""
