"""reticuli._kernel.seal -- freezing identity, and confirming it.

`seal` computes a claim's root (`spec/identity.md`) and records it onto
the manifest, `.reticuli/manifest.json`. `verify` recomputes the root from
the bytes present in the claim directory and reports whether it still
matches the sealed value -- identity only; no gate is executed
(`spec/verification.md`). This is the invariant the whole format rests
on: the root is a function of the pinned inputs and independent of the
generated bytes, so editing a generated output leaves it in place while
editing a pinned input moves it.
"""
import json
import os

from . import core
from . import identity
from . import recipe as _recipe


def _changed_parts(before: dict, after: dict) -> list:
    """The sorted keys whose value differs between two `_parts`-shaped maps."""
    keys = set(before) | set(after)
    return sorted(k for k in keys if before.get(k) != after.get(k))


def seal(d: str, **kwargs) -> dict:
    """Compute `d`'s root and write it to the manifest; return the manifest."""
    parsed = _recipe.load_recipe(d)
    name = parsed.get("claim", {}).get("name")
    if not isinstance(name, str):
        raise core.ClaimError(f"[claim] name must be a string, got {name!r}")
    manifest = {"name": name, "root": identity.root(parsed, d)}
    path = core._safe(d, core.MANIFEST)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    core._write_json(path, manifest)
    return manifest


def read_manifest(d: str) -> dict:
    """Read `d`'s manifest: `{name, root, ...}`. Refuses malformed bytes."""
    path = core._safe(d, core.MANIFEST)
    try:
        with open(path, "r", encoding="utf-8") as f:
            manifest = json.load(f)
    except OSError as exc:
        raise core.ClaimError(f"no manifest at {path!r}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise core.ClaimError(f"malformed manifest {path!r}: {exc}") from exc
    if not isinstance(manifest, dict):
        raise core.ClaimError(f"manifest {path!r} is not a JSON object")
    if not isinstance(manifest.get("name"), str):
        raise core.ClaimError(f"manifest {path!r} is missing a name")
    root = manifest.get("root")
    if not isinstance(root, str) or len(root) != 64:
        raise core.ClaimError(f"manifest {path!r} has a malformed root")
    return manifest


def verify(d: str) -> dict:
    """Recompute `d`'s root from the bytes present; compare with the manifest.

    Identity only -- no gate is executed. Returns `{ok, root, recomputed,
    name}`: `root` is the sealed value, `recomputed` is fresh from the
    bytes on disk now, and `ok` is whether they match.
    """
    manifest = read_manifest(d)
    parsed = _recipe.load_recipe(d)
    recomputed = identity.root(parsed, d)
    return {
        "ok": recomputed == manifest["root"],
        "root": manifest["root"],
        "recomputed": recomputed,
        "name": manifest["name"],
    }
