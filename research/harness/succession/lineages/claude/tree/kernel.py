# The claim's own recognized RETICULI_* variables -- the allowlist a gate's
# scrubbed environment is built from. `_run._scrub_env` copies through ANY
# `RETICULI_*`-prefixed variable, inherited secret included, since it has
# no way to tell a claim's own from a hostile passenger riding the same
# prefix; the gate contract needs the narrower list.
_KNOWN_RETICULI_VARS = frozenset({
    core._ENV_CLAIM, core._ENV_MODEL, core._ENV_OUTPUT, core._ENV_OUTPUTS,
    core._ENV_REQUEST, core._ENV_SIGNERS, core._ENV_TIMEOUT, core._ENV_TOLERANCE,
    core._ENV_USAGE, core._ENV_VENDOR, core._JAILED,
})


def _gate_env() -> dict:
    """A minimal host allowlist plus only the claim's OWN recognized
    variables -- never an arbitrary `RETICULI_*`-prefixed passenger."""
    env = {k: v for k, v in os.environ.items() if k in core._KEEP_ENV}
    for k, v in os.environ.items():
        if k in _KNOWN_RETICULI_VARS:
            env[k] = v
    return env


def _effective_timeout(declared=None) -> float:
    """`min(declared, host ceiling)`, reading the host ceiling from
    `RETICULI_GATE_TIMEOUT` FRESH on every call. `core.GATE_TIMEOUT` (and
    so `_run.gate_timeout`) reads that variable once, at import time, so
    a caller that sets it at runtime -- as a producer's own test harness
    would -- has no effect through that path."""
    ceiling = float(os.environ.get(core._ENV_TIMEOUT, 300))
    if declared is None:
        return ceiling
    try:
        declared = float(declared)
    except (TypeError, ValueError) as exc:
        raise core.ClaimError(f"gate_timeout must be a number, got {declared!r}") from exc
    return min(declared, ceiling)


def run_gate(cmd: str, d: str, recipe: dict = None) -> dict:
    """Run one gate command in `d`: scrubbed environment, sandboxed,
    bounded by `recipe`'s declared `gate_timeout` (or the host ceiling).

    THE SENDING HALF of the sandbox contract: where this call really
    applies a fresh sandbox (the host has one, and we are not already
    inside one -- `sandbox_backend()` would say `inherited` otherwise),
    the wrapped process is told which jail it is in via `RETICULI_JAILED`,
    so a gate that is itself a claim runner inherits instead of nesting.
    `_run.run_gate` cannot make that promise: it only copies whatever
    `RETICULI_JAILED` already sits in this process's own environment, and
    never sets a fresh one for a backend it just now decided to apply.
    """
    timeout = None
    if isinstance(recipe, dict):
        timeout = recipe.get("claim", {}).get("gate_timeout")

    backend = _run.sandbox_backend()
    eff_timeout = _effective_timeout(timeout)
    env = _gate_env()
    if backend in ("seatbelt", "bubblewrap"):
        env[core._JAILED] = backend

    scratch_root = os.path.join(d, core.STORE, "scratch")
    os.makedirs(scratch_root, exist_ok=True)
    scratch = tempfile.mkdtemp(dir=scratch_root)
    try:
        base_argv = ["/bin/sh", "-c", cmd]
        if backend in ("seatbelt", "bubblewrap"):
            env["TMPDIR"] = scratch
            env["HOME"] = scratch
            argv = _run._sandbox_argv(backend, base_argv, d, scratch)
        else:
            argv = base_argv
        returncode, timed_out = _run._run(argv, d, env, eff_timeout)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    if timed_out:
        status = "timeout"
    elif returncode == 0:
        status = "ok"
    else:
        status = "failed"
    return {"status": status, "quarantine": backend}


def sandbox(cmd: str = "true", d: str = None):
    """A functional probe of the host sandbox: run `cmd` in `d` through
    `run_gate` and return `(status, backend)`."""
    if d is None:
        d = os.getcwd()
    result = _run.run_gate(cmd, d)
    return (result["status"], result["quarantine"])


def cost(d: str):
    """Ledger totals per unit; `None` if nothing was measured."""
    totals = _run.cost(d)
    return totals if totals else None


# ---------------------------------------------------------------------------
# audit: build.audit, plus the `[claim] environment` furnish step and a
# corrected shape for the environment-failure case (build.audit's own
# shape there predates furnishing and never populated `gates`).
# ---------------------------------------------------------------------------
def _relabel_reproduced(result: dict) -> dict:
    """`build.audit` spells a clean, byte-reproducing gate `reproduced`;
    the passing spelling this check pins is `ok` (the failure classes
    are pinned, the success spelling is not -- but a spelling still has
    to be picked, and one comparable across kernels has to be the same
    word `run_gate` already uses for a clean run)."""
    for gate in result.get("gates", []):
        if gate.get("status") == "reproduced":
            gate["status"] = "ok"
    return result


def audit(d: str, produce_from: dict = None, **kwargs) -> dict:
    """`build.audit` plus two things it does not itself do: honor
    `produce_from` (a claim judges substituted generated bytes -- a
    dependent's shipped code, re-earned by the component's own check),
    and furnish `[claim] environment` before judging."""
    if produce_from:
        def _substitute(step, room):
            src = produce_from.get(step["output"])
            if src is not None:
                with open(src, "rb") as f:
                    return f.read()
            original = core._safe(d, step["output"])
            if os.path.isfile(original):
                with open(original, "rb") as f:
                    return f.read()
            return b""
        kwargs = {**kwargs, "producer": _substitute}

    recipe = _recipe.load_recipe(d)
    manifest = read_manifest(d)
    missing = list(_run.preflight(recipe))

    env_file = recipe.get("claim", {}).get("environment")
    venv_dir = None
    if env_file:
        # `furnish` installs `-r <requirements file>` without setting `cwd`,
        # and pip resolves a requirement file's relative local paths (a
        # wheel named by a bare relative path, as ours are) against the
        # process's cwd, not the requirements file's own directory -- so
        # furnishing must run from `d`.
        old_cwd = os.getcwd()
        try:
            os.chdir(d)
            venv_dir = _run.furnish(env_file, d)
        except (core.ClaimError, OSError, subprocess.CalledProcessError,
                subprocess.TimeoutExpired):
            missing.append(env_file)
        finally:
            os.chdir(old_cwd)

    if missing:
        recomputed = root(recipe, d)
        gate_steps = [s for s in recipe.get("step", []) if s.get("kind") == "gate"]
        return {
            "ok": False,
            "verdict": "environment",
            "name": manifest["name"],
            "root": manifest["root"],
            "recomputed": recomputed,
            "gates": [{"output": s["output"], "status": "environment", "quarantine": None}
                      for s in gate_steps],
            "environment": missing,
        }

    # `build.audit` re-derives identity itself, via `identity.root(recipe, d)`
    # called on the module directly -- it has no way to know about the
    # `environment` augmentation `root()` applies above. Patch the module
    # attribute for the span of this one call so its internal check sees
    # exactly the root `seal()`/`verify()` computed; the saved reference
    # (`_raw_identity_root`) means `root()` itself never recurses through
    # the patched name.
    old_path = os.environ.get("PATH", "")
    if venv_dir is not None:
        os.environ["PATH"] = os.path.join(venv_dir, "bin") + os.pathsep + old_path
    identity.root = root
    try:
        return _relabel_reproduced(_build.audit(d, **kwargs))
    finally:
        identity.root = _raw_identity_root
        if venv_dir is not None:
            os.environ["PATH"] = old_path


