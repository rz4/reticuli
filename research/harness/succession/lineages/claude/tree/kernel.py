# phase: draft / sealed / signed
# ---------------------------------------------------------------------------
def _signed(d: str, verified_root: str) -> bool:
    sign_dir = core._safe(d, core.SIGN_DIR)
    if not os.path.isdir(sign_dir):
        return False
    manifest = read_manifest(d)
    if not manifest.get("proof"):
        return False
    signers_path = os.environ.get(core._ENV_SIGNERS)
    if not signers_path or not os.path.isfile(signers_path):
        return False

    recipe = _recipe.load_recipe(d)
    current_digest = identity.build_digest(d)

    for fname in sorted(os.listdir(sign_dir)):
        if not fname.endswith(".sign.json"):
            continue
        spath = os.path.join(sign_dir, fname)
        sig_path = spath + ".sig"
        if not os.path.isfile(sig_path):
            continue
        try:
            with open(spath, "r", encoding="utf-8") as f:
                statement = json.load(f)
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(statement, dict):
            continue
        if statement.get("root") != verified_root or not statement.get("proof_recorded"):
            continue
        signer_id = statement.get("identity")
        if not isinstance(signer_id, str):
            continue
        with open(spath, "rb") as f:
            data = f.read()
        if not _build._ssh_verify(data, sig_path, signers_path, core.SIGN_NAMESPACE,
                                   signer=signer_id):
            continue

        prefix = fname[: -len(".sign.json")]
        packet_path = os.path.join(sign_dir, prefix + ".packet.json")
        if not os.path.isfile(packet_path):
            continue
        try:
            with open(packet_path, "r", encoding="utf-8") as f:
                packet = json.load(f)
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(packet, dict):
            continue
        packet_digest = hashlib.sha256(
            json.dumps(packet, sort_keys=True).encode("utf-8")).hexdigest()
        if packet_digest != statement.get("packet_digest"):
            continue
        if packet.get("root") != verified_root:
            continue
        if packet.get("build_digest") != current_digest:
            continue
        if not packet.get("proof"):
            continue
        return True
    return False


def phase(d: str) -> str:
    manifest_path = core._safe(d, core.MANIFEST)
    if not os.path.isfile(manifest_path):
        _recipe.load_recipe(d)
        return "draft"
    v = verify(d)
    if not v["ok"]:
        raise core.ClaimError(f"claim identity does not match its sealed manifest: {d!r}")
    if _signed(d, v["root"]):
        return "signed"
    return "sealed"


# ---------------------------------------------------------------------------
# sign_node: the signature-chain fold, bottom-anchored
# ---------------------------------------------------------------------------
def sign_node(root_hash: str, digest: str, links) -> str:
    payload = {"root": root_hash, "build_digest": digest, "links": sorted(links)}
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# rebuild: regrow the generated outputs until the gates pass
# ---------------------------------------------------------------------------
def _snapshot_room(room: str, exclude_names) -> dict:
    snapshot = {}
    for dirpath, dirnames, filenames in os.walk(room):
        dirnames[:] = [dn for dn in dirnames if dn != ".reticuli"]
        for fn in filenames:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, room)
            if rel in exclude_names:
                continue
            snapshot[rel] = core._hash_file(full)
    return snapshot


def _invoke_producer(step: dict, producer_cmd: str, room: str, guidance: str) -> None:
    output_abs = os.path.abspath(core._safe(room, step["output"]))
    os.makedirs(os.path.dirname(output_abs) or room, exist_ok=True)
    usage_path = os.path.abspath(os.path.join(room, core.USAGE))
    os.makedirs(os.path.dirname(usage_path), exist_ok=True)
    if os.path.isfile(usage_path):
        os.remove(usage_path)

    env = dict(os.environ)
    env[core._ENV_OUTPUT] = output_abs
    env[core._ENV_REQUEST] = guidance or ""
    env[core._ENV_USAGE] = usage_path

    t0 = time.monotonic()
    done = subprocess.run(producer_cmd, shell=True, cwd=os.path.abspath(room), env=env,
                          capture_output=True, timeout=core.PRODUCER_TIMEOUT, check=False)
    elapsed = time.monotonic() - t0
    if done.returncode != 0:
        detail = (done.stderr or done.stdout or b"").decode("utf-8", errors="replace")
        raise core.ClaimError(
            f"producer failed for {step['output']!r}: {detail[-300:]}")

    event = {"event": "oracle", "calls": 1, "seconds": elapsed}
    vendor = os.environ.get(core._ENV_VENDOR)
    model = os.environ.get(core._ENV_MODEL)
    if vendor:
        event["vendor"] = vendor
    if model:
        event["model"] = model
    if vendor or model:
        event["blind"] = True

    if os.path.isfile(usage_path):
        usage = None
        try:
            with open(usage_path, "r", encoding="utf-8") as f:
                usage = json.load(f)
        except (OSError, json.JSONDecodeError):
            usage = None
        if isinstance(usage, dict):
            for key in ("tokens", "usd", "calls"):
                v = usage.get(key)
                if isinstance(v, (int, float)) and not isinstance(v, bool):
                    event[key] = v

    _run.ledger(room, event)


def rebuild(d: str, producer_cmd: str, into: str, *, produce_from=None, input_from=None) -> dict:
    produce_from = produce_from or {}
    input_from = input_from or {}
    into_abs = os.path.abspath(into)

    if os.path.isdir(into_abs):
        if os.listdir(into_abs):
            raise core.ClaimError(f"rebuild target already holds bytes: {into!r}")
    else:
        os.makedirs(into_abs)

    recipe = _recipe.load_recipe(d)
    missing = _run.preflight(recipe)
    if missing:
        raise core.ClaimError(f"environment: host is missing {missing}")

    _build._materialize(d, into_abs, recipe)
    for name, src in input_from.items():
        core._copy_into(into_abs, name, src)

    outputs = {s["output"] for s in recipe.get("step", []) if s.get("kind") == "produce"}
    before = _snapshot_room(into_abs, outputs)

    for step in recipe.get("step", []):
        if step.get("kind") != "produce":
            continue
        output = step["output"]
        if output in produce_from:
            core._copy_into(into_abs, output, produce_from[output])
            _run.ledger(into_abs, {"event": "reuse", "output": output})
            continue
        guidance = step.get("guidance") or step.get("request") or ""
        _invoke_producer(step, producer_cmd, into_abs, guidance)

    after = _snapshot_room(into_abs, outputs)
    if before != after:
        raise core.ClaimError(
            "a producer rewrote pinned bytes outside its declared output")

    host = core._judging_host()
    backend = _run.sandbox_backend()
    _run.ledger(into_abs, {"event": "environment", "python": host["python"],
                           "quarantine": backend})

    for step in recipe.get("step", []):
        if step.get("kind") != "gate":
            continue
        result = run_gate(step["run"], into_abs, recipe)
        _run.ledger(into_abs, {"event": "gate", "output": step["output"],
                               "status": result["status"],
                               "quarantine": result["quarantine"]})
        if result["status"] != "ok":
            raise core.ClaimError(f"gate {step['output']!r} did not pass: {result['status']}")

    return _seal.seal(into_abs)


# ---------------------------------------------------------------------------
# record_proof: run the crosscheck; on a pass, seal the proof onto M1
# ---------------------------------------------------------------------------
def _anchor_principals(anchor_path: str) -> list:
    principals = []
    with open(anchor_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            principals.append(line.split()[0])
    return principals


def record_proof(m1: str, m2: str, m3: str) -> dict:
    if not os.path.isdir(m1):
        raise core.ClaimError("a proof requires M1 to be a directory")
    result = crosscheck(m1, m2, m3)
    if not result["satisfied"]:
        return {"proof_recorded": False, **result}

    records_trail = []
    for leg_path in (m2, m3):
        if os.path.isdir(leg_path):
            continue
        anchor = os.environ.get(core._ENV_SIGNERS)
        if not anchor or not os.path.isfile(anchor):
            raise core.ClaimError(f"no trust anchor for record leg {leg_path!r}")
        signer_id = None
        for candidate in _anchor_principals(anchor):
            try:
                record_signer(leg_path, anchor, signer=candidate)
                signer_id = candidate
                break
            except core.ClaimError:
                continue
        if signer_id is None:
            raise core.ClaimError(f"record leg {leg_path!r} has no anchored signature")
        doc = record_read(leg_path)
        records_trail.append({"digest": record_digest(doc), "signer": signer_id})

    proof = {"kind": "crosscheck"}
    if records_trail:
        proof["records"] = records_trail
    manifest = read_manifest(m1)
    manifest["proof"] = proof
    core._write_json(core._safe(m1, core.MANIFEST), manifest)
