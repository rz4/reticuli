# ---------------------------------------------------------------------------
# Identity and the store
#
# `core._safe` resolves a declared name via `realpath` and refuses an
# escape -- but realpath FOLLOWS symlinks, so a pinned name that is itself
# a symlink to a file inside the claim resolves to a path inside the
# claim and passes. That is exactly the alias `spec/identity.md` refuses:
# it lets sealing hash generated bytes into the root through the pinned
# name. `_check_declared_path` adds the stricter boundary in front of
# `identity.root` -- no `..` component regardless of where it lexically
# ends up (a `..` next to a symlink resolves against the link's target,
# so no `..` path is trustworthy), no symlink component anywhere along
# the path, and the named file itself must be a regular file with a
# single hard link (never a FIFO, device, directory, or a hardlink to an
# inode outside the claim).
# ---------------------------------------------------------------------------
def _check_declared_path(d: str, name: str) -> None:
    core._safe(d, name)
    parts = name.split(os.sep)
    if ".." in parts:
        raise core.ClaimError(f"'..' component refused: {name!r}")
    partial = d
    for part in parts:
        partial = os.path.join(partial, part)
        if os.path.islink(partial):
            raise core.ClaimError(f"symlink component refused: {name!r}")
    if os.path.exists(partial):
        st = os.stat(partial, follow_symlinks=False)
        if not stat.S_ISREG(st.st_mode):
            raise core.ClaimError(f"not a regular file: {name!r}")
        if st.st_nlink != 1:
            raise core.ClaimError(f"file has more than one hard link: {name!r}")


# `[claim] environment` names a file that is "automatically a pinned
# input" (`spec/claim-format.md`): dependency versions decide what a
# gate's pass means, so the file's bytes must be in the root even when
# the recipe's own `inputs` list forgets to name it. `identity.root`
# (given, unmodifiable) only ever hashes `claim.inputs` -- it has no
# notion of `environment` at all -- so the augmentation happens here,
# in front of it.
_raw_identity_root = identity.root


def _augmented_recipe(recipe: dict) -> dict:
    env_file = recipe.get("claim", {}).get("environment")
    if not env_file:
        return recipe
    inputs = list(recipe.get("claim", {}).get("inputs", []))
    if env_file in inputs:
        return recipe
    augmented = dict(recipe)
    augmented["claim"] = {**recipe.get("claim", {}), "inputs": inputs + [env_file]}
    return augmented


def root(recipe: dict, d: str) -> str:
    recipe = _augmented_recipe(recipe)
    for path in recipe.get("claim", {}).get("inputs", []):
        _check_declared_path(d, path)
    for step in recipe.get("step", []):
        cls = step.get("class")
        if cls is None:
            cls = "generated" if step.get("kind") == "produce" else "pinned"
        if cls == "generated":
            continue
        _check_declared_path(d, step["output"])
    return _raw_identity_root(recipe, d)


build_digest = identity.build_digest


_COST_UNITS = frozenset({"usd", "tokens", "calls", "seconds"})


def _validate_envelope(envelope) -> None:
    if not isinstance(envelope, dict) or not envelope:
        raise core.ClaimError(f"[claim] envelope must be a non-empty table, got {envelope!r}")
    for unit, ceiling in envelope.items():
        if unit not in _COST_UNITS:
            raise core.ClaimError(f"[claim] envelope has an unknown unit: {unit!r}")
        if isinstance(ceiling, bool) or not isinstance(ceiling, (int, float)) or ceiling <= 0:
            raise core.ClaimError(
                f"[claim] envelope.{unit} must be a positive number, got {ceiling!r}")


def load_recipe(d: str) -> dict:
    """`_recipe.load_recipe` plus the validation rules it does not itself
    enforce (`spec/claim-format.md`): `[claim] name` is required and must
    be a string, and a declared `[claim] envelope` must be a non-empty
    table of positive numbers over a known cost unit."""
    parsed = _recipe.load_recipe(d)
    name = parsed.get("claim", {}).get("name")
    if not isinstance(name, str):
        raise core.ClaimError(f"[claim] name must be a string, got {name!r}")
    envelope = parsed.get("claim", {}).get("envelope")
    if envelope is not None:
        _validate_envelope(envelope)
    return parsed


def _wrap_claim_errors(func):
    """Hostile claim bytes are refused in band, never a raw traceback.
    `_seal.read_manifest`/`verify` already catch OSError and
    JSONDecodeError, but not a manifest whose bytes are not valid UTF-8
    at all -- one more way a corrupt file can crash a naive reader."""
    def wrapped(*args, **kwargs):
        try:
            return func(*args, **kwargs)
        except core.ClaimError:
            raise
        except (UnicodeDecodeError, ValueError, TypeError, KeyError,
                AttributeError, LookupError) as exc:
            raise core.ClaimError(f"malformed claim bytes: {exc}") from exc
    return wrapped


read_manifest = _wrap_claim_errors(_seal.read_manifest)


def seal(d: str, **kwargs) -> dict:
    """`_seal.seal`, but computing the root through `root()` above so an
    `environment` pin is honored -- `_seal.seal` calls `identity.root`
    directly and knows nothing about it."""
    parsed = load_recipe(d)
    name = parsed.get("claim", {}).get("name")
    manifest = {"name": name, "root": root(parsed, d)}
    path = core._safe(d, core.MANIFEST)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    core._write_json(path, manifest)
    return manifest


def verify(d: str) -> dict:
    """`_seal.verify`, but recomputing through `root()` for the same
    reason `seal` does."""
    manifest = read_manifest(d)
    parsed = load_recipe(d)
    recomputed = root(parsed, d)
    return {
        "ok": recomputed == manifest["root"],
        "root": manifest["root"],
        "recomputed": recomputed,
        "name": manifest["name"],
    }


verify = _wrap_claim_errors(verify)

