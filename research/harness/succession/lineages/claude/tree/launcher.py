"""reticuli.launcher -- run software that exists only latently in a claim.

A runnable claim is an ordinary claim whose pinned inputs include
`package.toml` (`[package] entrypoint = "..."`). `run` makes it executable:
if the generated bytes are missing it regrows them with a producer, then
executes `python3 <entrypoint> <args...>` with the claim root as cwd. `strip`
deletes the generated bytes -- and this module's own consent state -- back
to latency; deleting is always safe because the claim, not the code, is the
identity (`spec/identity.md`).

Consent is a durable state, not per-invocation friction. Three kinds of
generated bytes are distinguished, tracked under `<claim>/.launcher/`:

  * fresh    -- this launcher just regrew them; unaccepted until a `run
                --accept-generated` executes them (`fresh.json`).
  * accepted -- a prior `--accept-generated` recorded their digests
                (`accepted.json`); they run with no further flag, and DRIFT
                (accepted digests no longer matching present bytes) refuses
                loudly rather than silently re-trusting an edit.
  * neither  -- an implementation this launcher never generated or accepted
                (packed by hand, imported): no memory to drift from, so it
                runs on a fresh `kernel.audit` every time instead.

Every recipe-declared path (inputs, and every step's output, generated
included) is confined to the claim root before anything is read, written,
or deleted: `kernel.root()` only checks non-generated paths (generated
bytes are outside the identity by design, `spec/identity.md`), so a
generated output naming an escaping path is a gap only this layer closes.

Stdlib only. Never the network.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import tomllib

from . import kernel
from . import _util

LAUNCHER_DIR = ".launcher"
FRESH_FILE = "fresh.json"
ACCEPTED_FILE = "accepted.json"

_KEEP_ENV_RUN = ("PATH", "LANG", "LC_ALL", "LC_CTYPE", "TZ")

_HELP = """\
reticuli launcher -- run software that is only latent in a claim.

usage:
  python3 -m reticuli.launcher run <claim> [--accept-generated] \
[--signed-only] [--no-sandbox] [-- args...]
  python3 -m reticuli.launcher strip <claim>
  python3 -m reticuli.launcher ls <claim>...

flags:
  --accept-generated   accept freshly regrown bytes and execute them
  --signed-only        refuse a claim that is not signed to you
  --no-sandbox         run the entrypoint unconfined (quarantine = "off")

exit codes: 3 not runnable, 4 consent required, 5 trust refused,
6 drifted build, 7 latent with no producer, otherwise the entrypoint's own.
"""


def _err(message: str) -> None:
    sys.stderr.write("reticuli launcher: " + message + "\n")


# ---------------------------------------------------------------------------
# Recipe helpers: generated-step discovery and the confinement sweep
# ---------------------------------------------------------------------------
def _generated_steps(recipe: dict) -> list:
    steps = []
    for step in recipe.get("step", []):
        if step.get("kind") != "produce":
            continue
        if (step.get("class") or "generated") == "generated":
            steps.append(step)
    return steps


def _check_all_paths(d: str, recipe: dict) -> None:
    """Every declared path -- inputs and every step's output, generated
    included -- must resolve inside `d`. `kernel.root()` never checks a
    generated output (it is outside the identity), so this is the only
    place that stands between a tampered recipe and a delete or a write."""
    for name in recipe.get("claim", {}).get("inputs", []):
        _util.safe_path(d, name)
    for step in recipe.get("step", []):
        _util.safe_path(d, step["output"])


# ---------------------------------------------------------------------------
# The package contract
# ---------------------------------------------------------------------------
def _package_entrypoint(d: str, recipe: dict):
    """`(entrypoint, None)` on success, or `(None, message)` on refusal."""
    inputs = recipe.get("claim", {}).get("inputs", [])
    generated_names = {s["output"] for s in _generated_steps(recipe)}
    if "package.toml" in generated_names:
        return None, "package.toml must be a pinned input, not a generated output"
    if "package.toml" not in inputs:
        return None, "no package.toml pinned input declared in this claim"
    try:
        with open(_util.safe_path(d, "package.toml"), "rb") as f:
            package = tomllib.load(f)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        return None, f"malformed package.toml: {exc}"
    entrypoint = package.get("package", {}).get("entrypoint")
    if not isinstance(entrypoint, str) or not entrypoint:
        return None, "package.toml has no [package] entrypoint"
    try:
        _util.safe_path(d, entrypoint)
    except kernel.ClaimError as exc:
        return None, f"entrypoint escapes the claim root: {exc}"
    return entrypoint, None


# ---------------------------------------------------------------------------
# Materialization and consent state
# ---------------------------------------------------------------------------
def _sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _materialized(d: str, recipe: dict) -> bool:
    steps = _generated_steps(recipe)
    return all(os.path.isfile(_util.safe_path(d, s["output"])) for s in steps)


def _current_digests(d: str, recipe: dict) -> dict:
    digests = {}
    for step in _generated_steps(recipe):
        path = _util.safe_path(d, step["output"])
        if os.path.isfile(path):
            digests[step["output"]] = _sha256_file(path)
    return digests


def _state_path(d: str, fname: str) -> str:
    return os.path.join(d, LAUNCHER_DIR, fname)


def _read_state(d: str, fname: str):
    path = _state_path(d, fname)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return None


def _write_state(d: str, fname: str, obj) -> None:
    path = _state_path(d, fname)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, sort_keys=True)


def _remove_state(d: str, fname: str) -> None:
    path = _state_path(d, fname)
    if os.path.isfile(path):
        os.remove(path)


# ---------------------------------------------------------------------------
# Regrowing: `kernel.rebuild` grows a fresh room, never `d` in place; the
# generated bytes are copied back onto the sealed claim afterward.
# ---------------------------------------------------------------------------
def _regrow(d: str, recipe: dict, producer_cmd: str) -> dict:
    staging = tempfile.mkdtemp(prefix="reticuli-launcher-")
    try:
        kernel.rebuild(d, producer_cmd, staging)
        digests = {}
        for step in _generated_steps(recipe):
            out = step["output"]
            src = _util.safe_path(staging, out)
            dst = _util.safe_path(d, out)
            os.makedirs(os.path.dirname(dst) or d, exist_ok=True)
            shutil.copyfile(src, dst)
            digests[out] = _sha256_file(dst)
        return digests
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def _ensure_runnable(d: str, recipe: dict, accept_generated: bool):
    """`None` when execution may proceed; otherwise the exit code to return
    (a refusal message has already been printed)."""
    if not _materialized(d, recipe):
        producer_cmd = os.environ.get("RETICULI_PRODUCER")
        if not producer_cmd:
            _err("claim is latent; set RETICULI_PRODUCER to regrow it")
            return 7
        try:
            digests = _regrow(d, recipe, producer_cmd)
        except kernel.ClaimError as exc:
            _err(f"regrow failed: {exc}")
            return 1
        if accept_generated:
            _write_state(d, ACCEPTED_FILE, digests)
            _remove_state(d, FRESH_FILE)
            return None
        _write_state(d, FRESH_FILE, digests)
        _err("freshly generated bytes await consent; "
             "pass --accept-generated to execute and accept them")
        return 4

    current = _current_digests(d, recipe)
    accepted = _read_state(d, ACCEPTED_FILE)
    if accepted is not None:
        if current != accepted:
            _err("accepted implementation has drifted from what was accepted; "
                 "strip and regrow to recover")
            return 6
        return None

    fresh = _read_state(d, FRESH_FILE)
    if fresh is not None:
        if current != fresh:
            _write_state(d, FRESH_FILE, current)
        if not accept_generated:
            _err("freshly generated bytes await consent; "
                 "pass --accept-generated to execute and accept them")
            return 4
        _write_state(d, ACCEPTED_FILE, current)
        _remove_state(d, FRESH_FILE)
        return None

    # Never generated or accepted by this launcher (packed by hand, imported):
    # no consent memory to trust, so it runs on a fresh audit every time.
    try:
        result = kernel.audit(d)
    except kernel.ClaimError as exc:
        _err(f"audit failed: {exc}")
        return 6
    if not result.get("ok"):
        _err("implementation does not pass its own gates; "
             "strip and regrow to recover")
        return 6
    return None


# ---------------------------------------------------------------------------
# Execution: scrubbed environment, claim-local HOME/TMPDIR, sandboxed where
# the host actually supports one -- functionally probed, never assumed.
# ---------------------------------------------------------------------------
def _probe_sandbox() -> str:
    if os.environ.get("RETICULI_JAILED"):
        return "inherited"
    if sys.platform == "darwin" and shutil.which("sandbox-exec"):
        try:
            done = subprocess.run(
                ["sandbox-exec", "-p", "(version 1)(allow default)", "/usr/bin/true"],
                capture_output=True, timeout=10, check=False)
            if done.returncode == 0:
                return "seatbelt"
        except (OSError, subprocess.TimeoutExpired):
            pass
    if sys.platform.startswith("linux") and shutil.which("bwrap"):
        try:
            done = subprocess.run(
                ["bwrap", "--ro-bind", "/", "/", "--unshare-net", "true"],
                capture_output=True, timeout=10, check=False)
            if done.returncode == 0:
                return "bubblewrap"
        except (OSError, subprocess.TimeoutExpired):
            pass
    return "none"


def _quote_sb(path: str) -> str:
    return path.replace("\\", "\\\\").replace('"', '\\"')


def _sandbox_argv(backend: str, argv: list, d: str, scratch: str) -> list:
    if backend == "seatbelt":
        profile = (
            "(version 1)(allow default)(deny network*)"
            f'(allow file-write* (subpath "{_quote_sb(os.path.realpath(d))}"))'
            f'(allow file-write* (subpath "{_quote_sb(os.path.realpath(scratch))}"))'
        )
        return ["sandbox-exec", "-p", profile] + argv
    if backend == "bubblewrap":
        return [
            "bwrap",
            "--ro-bind", "/", "/",
            "--dev", "/dev",
            "--proc", "/proc",
            "--bind", d, d,
            "--bind", scratch, scratch,
            "--unshare-net",
            "--die-with-parent",
            "--",
        ] + argv
    return argv


def _entry_env(backend: str, scratch: str) -> dict:
    env = {k: v for k, v in os.environ.items() if k in _KEEP_ENV_RUN}
    env["HOME"] = scratch
    env["TMPDIR"] = scratch
    if backend in ("seatbelt", "bubblewrap"):
        env["RETICULI_JAILED"] = backend
    return env


def _execute(d: str, entrypoint: str, trailing: list, no_sandbox: bool, phase: str) -> int:
    backend = "off" if no_sandbox else _probe_sandbox()
    scratch_root = os.path.join(d, LAUNCHER_DIR, "scratch")
    os.makedirs(scratch_root, exist_ok=True)
    scratch = tempfile.mkdtemp(dir=scratch_root)
    try:
        env = _entry_env(backend, scratch)
        base_argv = [sys.executable, entrypoint] + list(trailing)
        if backend in ("seatbelt", "bubblewrap"):
            argv = _sandbox_argv(backend, base_argv, d, scratch)
        else:
            argv = base_argv
        _err(f"running {entrypoint!r} (phase: {phase})")
        sys.stderr.write(f'quarantine = "{backend}"\n')
        sys.stderr.flush()
        proc = subprocess.run(argv, cwd=d, env=env, check=False)
        return proc.returncode
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


# ---------------------------------------------------------------------------
# Verbs
# ---------------------------------------------------------------------------
def cmd_run(args: list) -> int:
    accept_generated = False
    signed_only = False
    no_sandbox = False
    claim_arg = None
    trailing = []
    i = 0
    while i < len(args):
        tok = args[i]
        if tok == "--":
            trailing = args[i + 1:]
            break
        if tok == "--accept-generated":
            accept_generated = True
        elif tok == "--signed-only":
            signed_only = True
        elif tok == "--no-sandbox":
            no_sandbox = True
        elif claim_arg is None:
            claim_arg = tok
        i += 1

    if claim_arg is None:
        _err("run requires a claim path")
        return 3

    d = os.path.abspath(claim_arg)
    if not os.path.isdir(d):
        _err(f"no such claim directory: {claim_arg}")
        return 3

    try:
        recipe = kernel.load_recipe(d)
        _check_all_paths(d, recipe)
    except kernel.ClaimError as exc:
        _err(f"refused -- {exc}")
        return 3

    entrypoint, message = _package_entrypoint(d, recipe)
    if message:
        _err(message)
        return 3

    try:
        phase = kernel.phase(d)
    except kernel.ClaimError as exc:
        _err(f"refused -- {exc}")
        return 3

    if signed_only and phase != "signed":
        _err(f"claim is not signed to you; --signed-only refuses it (phase: {phase})")
        return 5

    exit_code = _ensure_runnable(d, recipe, accept_generated)
    if exit_code is not None:
        return exit_code

    return _execute(d, entrypoint, trailing, no_sandbox, phase)


def cmd_strip(args: list) -> int:
    if not args:
        _err("strip requires a claim path")
        return 3
    d = os.path.abspath(args[0])
    if not os.path.isdir(d):
        _err(f"no such claim directory: {args[0]}")
        return 3
    try:
        recipe = kernel.load_recipe(d)
        _check_all_paths(d, recipe)
    except kernel.ClaimError as exc:
        _err(f"refused -- {exc}")
        return 3

    for step in _generated_steps(recipe):
        path = _util.safe_path(d, step["output"])
        if os.path.isfile(path):
            os.remove(path)

    state_dir = os.path.join(d, LAUNCHER_DIR)
    if os.path.isdir(state_dir):
        shutil.rmtree(state_dir)
    return 0


def cmd_ls(args: list) -> int:
    if not args:
        _err("ls requires at least one claim path")
        return 3
    lines = []
    for claim_arg in args:
        d = os.path.abspath(claim_arg)
        try:
            recipe = kernel.load_recipe(d)
        except kernel.ClaimError as exc:
            lines.append(f"{claim_arg}  error: {exc}")
            continue
        name = recipe.get("claim", {}).get("name", claim_arg)
        root = "(unsealed)"
        try:
            manifest = kernel.read_manifest(d)
            root = manifest.get("root", root)
            name = manifest.get("name", name)
        except kernel.ClaimError:
            pass
        try:
            phase = kernel.phase(d)
        except kernel.ClaimError:
            phase = "unknown"
        status = "materialized" if _materialized(d, recipe) else "latent"
        lines.append(f"{name}  {root}  {phase}  {status}")
    print("\n".join(lines))
    return 0


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ("-h", "--help"):
        print(_HELP)
        return 0
    verb, rest = argv[0], argv[1:]
    if verb == "run":
        return cmd_run(rest)
    if verb == "strip":
        return cmd_strip(rest)
    if verb == "ls":
        return cmd_ls(rest)
    _err(f"unknown verb: {verb!r}")
    return 3


if __name__ == "__main__":
    sys.exit(main())
