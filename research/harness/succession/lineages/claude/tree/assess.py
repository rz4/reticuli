"""reticuli.assess -- how much a claim's own tests prove.

`vacuous_gates` (`spec/verification.md`) already tells apart a gate whose
every decider is itself generated bytes: such a gate decides nothing a
claim can be blamed for, so its verdict is `not_applicable` here.  Of the
remaining gates, `mutation_score` mutates the claim's generated Python
source and reports how many mutants the claim's own tests tell apart
from the original; a gate is `measured` once at least one mutant was
drawn, and `not_measured` when the claim has no generated Python source
for mutation testing to draw one from at all.

Stdlib only.  Never the network.
"""
from . import kernel


def assess(d: str, mutants: int = None) -> dict:
    """Bucket every gate by what mutation testing showed it.

    Returns `{measured, not_measured, not_applicable, mutation_score}`,
    where the first three are lists of gate output names and the last is
    `kernel.mutation_score`'s own result (residue on `.reticuli/`, never
    the root).
    """
    recipe = kernel.load_recipe(d)
    gate_outputs = [step["output"] for step in recipe.get("step", []) if step.get("kind") == "gate"]
    vacuous = set(kernel.vacuous_gates(recipe))

    score = kernel.mutation_score(d, max_mutants=mutants)

    measured, not_measured, not_applicable = [], [], []
    for output in gate_outputs:
        if output in vacuous:
            not_applicable.append(output)
        elif score["mutants"] > 0:
            measured.append(output)
        else:
            not_measured.append(output)

    return {
        "measured": measured,
        "not_measured": not_measured,
        "not_applicable": not_applicable,
        "mutation_score": score,
    }
