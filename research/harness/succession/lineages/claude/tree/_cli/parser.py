def _add_verbose_json(sp: argparse.ArgumentParser) -> None:
    """Add the flags every verb's output shares: `-v/--verbose` for a
    fuller human render, `--json` for the machine envelope, and `--color`
    for whether to paint the human one."""
    sp.add_argument("-v", "--verbose", action="store_true",
                     help="show a fuller human-readable render")
    sp.add_argument("--json", action="store_true",
                     help="print the five-field machine envelope and nothing else")
    sp.add_argument("--color", choices=("auto", "always", "never"), default="auto",
                     help="colorize human output (default: auto)")


def _add_claim(sp: argparse.ArgumentParser, help_="the claim directory (default: current directory)") -> None:
    sp.add_argument("claim", nargs="?", default=None, help=help_)


def _json_map_arg(path: str):
    """argparse `type=`: a JSON file's parsed object, read at parse time --
    used for `rebuild`'s substitution maps so `_report._r_rebuild` sees a
    plain dict without knowing it ever came from a file."""
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


# ---------------------------------------------------------------------------
# Dispatchers that fold a retired verb's behavior onto a porcelain one
# ---------------------------------------------------------------------------
def _v_init(args) -> int:
    """`init`: create the store and, unless `--no-agent`, wire the agent
    hooks -- the 2026-09-22 fold of the old `hooks` verb."""
    d = args.claim if args.claim else os.getcwd()
    data = handlers.init(d, no_agent=getattr(args, "no_agent", False))
    if not getattr(args, "json", False):
        output._line(f"initialized {data['claim']}", args, color="cyan")
    return output._finish("init", data, True, "initialized", args)


def _v_run(args) -> int:
    """`run`: trace one shell command scoped to the session workspace."""
    ws = args.claim if args.claim else os.getcwd()
    rc = handlers.run(args.cmd, ws)
    ok = rc == 0
    data = {"claim": ws, "cmd": args.cmd, "exit": rc}
    return output._finish("run", data, ok, ("ok" if ok else "failed"), args)


def _v_status(args) -> int:
    """`status`: the per-claim view by default; `--tree`, `--claims`,
    `--deps`, `--structure` switch to the workspace-scope views the
    retired `tree`/`claims`/`deps`/`structure` verbs used to be."""
    if getattr(args, "tree", False):
        return _statusview._r_tree(args)
    if getattr(args, "claims", False):
        return _statusview._r_claims(args)
    if getattr(args, "deps", False):
        return _statusview._r_deps(args)
    if getattr(args, "structure", False):
        return _statusview._r_structure(args)
    return _statusview._r_status_draft(args)


def _v_record(args) -> int:
    """`record`: emit and (optionally) sign a record by default; `--key`
    together with `--as` attests instead (the 2026-09-22 fold of the old
    `attest` verb), and `--check` reports whether that attestation holds."""
    if getattr(args, "check", False):
        return _report._r_attest_check(args)
    if getattr(args, "key", None) and getattr(args, "identity", None):
        return _report._r_attest(args)
    return _report._r_record(args)


def _v_sign(args) -> int:
    """`sign`: run the signing ceremony by default; `--review` shows the
    packet a keyholder would review without signing it, `--check` reports
    whether an existing signature is trustworthy."""
    if getattr(args, "review", False):
        return _report._r_review(args)
    if getattr(args, "check", False):
        return _report._r_sign_check(args)
    return _report._r_sign(args)


def _v_hook(args) -> int:
    """`hook`: the plumbing counterpart to `python3 -m reticuli.hooks` --
    read one hook payload from stdin, trace it if it names a session, and
    always exit clean; a hook must never block the agent's tool call."""
    try:
        payload = json.load(sys.stdin)
    except (ValueError, TypeError):
        return 0
    try:
        _hooks.event(payload)
    except kernel.ClaimError:
        pass
    return 0


