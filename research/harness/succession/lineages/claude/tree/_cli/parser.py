def _build_authoring(sub) -> None:
    sp = sub.add_parser("init", help="initialize a workspace")
    _add_claim(sp, "the workspace to initialize (default: current directory)")
    sp.add_argument("--no-agent", action="store_true",
                     help="skip wiring the coding-agent hooks")
    _add_verbose_json(sp)
    sp.set_defaults(func=_v_init)

    sp = sub.add_parser("run", help="run and observe a command")
    sp.add_argument("cmd", help="the shell command to run and trace")
    _add_claim(sp, "the session workspace (default: current directory)")
    _add_verbose_json(sp)
    sp.set_defaults(func=_v_run)

    sp = sub.add_parser("status", help="show work, claims, and unresolved inputs")
    _add_claim(sp)
    sp.add_argument("--tree", action="store_true",
                     help="show the claim's declared files as a tree (retired: tree)")
    sp.add_argument("--claims", action="store_true",
                     help="list claims sealed in the workspace's store (retired: claims)")
    sp.add_argument("--deps", action="store_true",
                     help="show the workspace's store as a dependency graph")
    sp.add_argument("--structure", action="store_true",
                     help="show the workspace's store as claims and their edges")
    _add_verbose_json(sp)
    sp.set_defaults(func=_v_status)

    sp = sub.add_parser("pack", help="create a claim from a project")
    _add_claim(sp)
    sp.add_argument("--name", required=True, help="the claim's name")
    sp.add_argument("--generated", nargs="+", required=True, metavar="PATTERN",
                     help="glob patterns naming the regrowable implementation")
    sp.add_argument("--inputs", nargs="+", required=True, metavar="PATTERN",
                     help="glob patterns naming the claim's own pinned files")
    sp.add_argument("--run", required=True, metavar="CMD", help="the gate command")
    sp.add_argument("--output", required=True, metavar="NAME",
                     help="the gate's declared output")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_pack)


def _build_composition(sub) -> None:
    sp = sub.add_parser("pull", help="add another claim as a dependency")
    _add_claim(sp, "the claim to pull (default: current directory)")
    sp.add_argument("--into", required=True, metavar="WORKSPACE",
                     help="the workspace that gains the dependency")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_pull)

    sp = sub.add_parser("export", help="write a portable claim archive")
    _add_claim(sp)
    sp.add_argument("--out", required=True, metavar="TAR", help="the archive to write")
    sp.add_argument("--blind", action="store_true",
                     help="withhold generated bytes -- the rebuilder's room")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_export)

    sp = sub.add_parser("import", help="restore a claim archive")
    sp.add_argument("tar", help="the archive to extract")
    _add_claim(sp, "the directory to extract into (default: current directory)")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_import)


def _build_verification(sub) -> None:
    sp = sub.add_parser("verify", help="verify claim identity")
    _add_claim(sp)
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_verify)

    sp = sub.add_parser("audit", help="rerun acceptance criteria")
    _add_claim(sp)
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_audit)

    sp = sub.add_parser("assess", help="measure specification strength")
    _add_claim(sp)
    sp.add_argument("--mutants", type=int, default=None, metavar="N",
                     help="cap the number of mutants drawn")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_assess)


def _build_reconstruction(sub) -> None:
    sp = sub.add_parser("rebuild", help="rebuild an implementation from a claim")
    sp.add_argument("producer", help="the producer command (or a known name)")
    sp.add_argument("into", help="the directory to rebuild into")
    _add_claim(sp)
    sp.add_argument("--produce-from", dest="produce_from", type=_json_map_arg,
                     default=None, metavar="FILE",
                     help="JSON file mapping a generated output to a substituted source")
    sp.add_argument("--input-from", dest="input_from", type=_json_map_arg,
                     default=None, metavar="FILE",
                     help="JSON file mapping a pinned input to a substituted source")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_rebuild)

    sp = sub.add_parser("crosscheck", help="compare independent realizations")
    sp.add_argument("m2", help="the second machine's claim directory")
    sp.add_argument("m3", help="the third machine's claim directory")
    _add_claim(sp, "the first machine's claim directory (default: current directory)")
    sp.add_argument("--mutants", type=int, default=None, metavar="N",
                     help="cap the number of mutants drawn")
    _add_verbose_json(sp)
    sp.set_defaults(func=_report._r_crosscheck)


def _build_evidence(sub) -> None:
    sp = sub.add_parser("record", help="write an execution record")
    _add_claim(sp)
    sp.add_argument("--out", default=None, metavar="PATH", help="where to write the record")
