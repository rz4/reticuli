"""reticuli._cli.parser -- the `ret` argv grammar.

Porcelain/plumbing, git's own split: `PORCELAIN` is the fourteen verbs a
person actually reaches for (`_DESC`'s four groups -- Authoring,
Composition and transport, Verification, Reconstruction, Evidence);
`ALIASES` is where an accepted-but-secondary spelling of one of them would
live, kept as its own dict so the grammar can grow one without ever
touching `PORCELAIN`'s count; `hook`, `help`, and `completion` are
plumbing -- machinery the porcelain verbs stand on rather than claim
things about a project. `verbs()` is the one place all three are
combined, so the parser and `ret help -a` can never drift apart.

Several v1 verbs were retired outright (`condense`, `realize`, `prove`,
`mint`, `records`, `hydrate`, `inspect`); a second, 2026-09-22 wave folded
what remained of the old verb surface into flags on a porcelain verb
instead of leaving it a command of its own: `seal` into `pack --accept`
(`reticuli.pack.pack` already seals in place), `hooks` into `init` (wired
automatically unless `--no-agent`, `reticuli._cli.handlers.init`),
`tree`/`claims`/`deps`/`structure` into `status --tree` / `--claims` /
`--deps` / `--structure`, and `attest` into `record --key --as` /
`record --check`. None of those retired spellings are registered below;
`checks/parser_check.py` pins that they stay gone.

Every verb ends through `_cli.output._finish` (the `--json` envelope) or
its refusal through `_cli.output._err` -- this module only wires argv to
the function that already knows how to do that; it decides nothing about
a claim itself.

Stdlib only. Never the network.
"""
