def _is_signed(d: str, current_root: str) -> bool:
    manifest = _seal.read_manifest(d)
    if not manifest.get("proof"):
        return False
    anchor = os.environ.get(_core._ENV_SIGNERS)
    if not anchor:
        return False
    sign_dir = os.path.join(d, _core.SIGN_DIR)
    if not os.path.isdir(sign_dir):
        return False

    for fn in sorted(os.listdir(sign_dir)):
        if not fn.endswith(".sign.json"):
            continue
        stmt_path = os.path.join(sign_dir, fn)
        sig_path = stmt_path + ".sig"
        if not os.path.isfile(sig_path):
            continue
        try:
            with open(stmt_path, "rb") as f:
                stmt_bytes = f.read()
            stmt = json.loads(stmt_bytes)
        except (OSError, ValueError):
            continue
        if not isinstance(stmt, dict):
            continue
        signer = stmt.get("identity")
        if not signer or not _build._authorized(anchor, signer):
            continue
        if not _build._ssh_verify(stmt_bytes, sig_path, anchor, _core.SIGN_NAMESPACE, signer):
            continue
        if stmt.get("root") != current_root:
            continue
        if not stmt.get("proof_recorded"):
            continue

        prefix = fn[: -len(".sign.json")]
        packet_path = os.path.join(sign_dir, prefix + ".packet.json")
        if not os.path.isfile(packet_path):
            continue
        try:
            with open(packet_path, "r", encoding="utf-8") as f:
                packet = json.load(f)
        except (OSError, ValueError):
            continue
        if not isinstance(packet, dict):
            continue
        packet_digest = hashlib.sha256(
            json.dumps(packet, sort_keys=True).encode("utf-8")).hexdigest()
        if packet_digest != stmt.get("packet_digest"):
            continue
        if packet.get("proof") != manifest.get("proof"):
            continue
        if packet.get("build_digest") != build_digest(d):
            continue
        return True
    return False


def phase(d: str) -> str:
    """`draft` (no manifest yet) / `sealed` (identity holds) / `signed`
    (a trusted signature over a coherent, proven packet, on undrifted
    bytes)."""
    load_recipe(d)
    manifest_path = os.path.join(d, _core.MANIFEST)
    if not os.path.isfile(manifest_path):
        return "draft"

    v = verify(d)
    if not v["ok"]:
        raise ClaimError(f"claim {d!r} does not verify: sealed root does not match recomputed bytes")

    if _is_signed(d, v["root"]):
        return "signed"
    return "sealed"
