"""The kernel's public surface (spec/kernel-api.md).

Most verbs here are thin re-exports of `_kernel`'s submodules. Three are
reimplemented rather than delegated, because the public contract grew past
what the lower layer alone provides:

- `run_gate`/`sandbox` fix the sending half of the sandbox-signal contract
  (spec/claim-format.md): a gate this process actually confines must see
  `RETICULI_JAILED` named *as its backend* (`"seatbelt"`/`"bubblewrap"`),
  not a bare flag, so a gate that is itself a claim runner inherits rather
  than nests.
- `rebuild` adds what the recipe alone cannot promise: a produce step may
  be supplied generated bytes directly (`produce_from`), not only one that
  names a `from` component; a pinned input may be threaded from elsewhere
  (`input_from`, by name); a producer's own cost is counted as one oracle
  call; and the pinned bytes a producer was handed are snapshotted and
  checked unchanged afterward, so a producer cannot rewrite the question it
  was judged against.
- `audit` furnishes a claim's declared `[claim] environment` before judging
  in it (spec/claim-format.md), and supports judging substituted generated
  bytes (`produce_from`) for a dependent's re-earning of a component's gate.
"""
