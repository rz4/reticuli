def _safe_lexical(name: str) -> None:
    """Path-string safety only -- no absolute path, no empty component, no
    `..` -- deliberately WITHOUT the symlink-crossing refusal: used for a
    GENERATED output, whose bytes are never hashed into the root, so an
    internal symlink there is audit's confinement problem to catch (when it
    actually copies the bytes), not load_recipe's to pre-empt."""
    if not isinstance(name, str) or not name:
        raise ClaimError(f"refuses an empty path: {name!r}")
    if os.path.isabs(name):
        raise ClaimError(f"refuses an absolute path: {name!r}")
    if any(part in ("", ".", "..") for part in name.split("/")):
        raise ClaimError(f"path escapes the claim: {name!r}")


def _parse_recipe(d: str) -> dict:
    """Parse and validate a claim's recipe exactly as `_recipe.load_recipe`
    does, except that a step whose own class is GENERATED is confined only
    lexically, not against symlinks -- a generated byte is never hashed, so
    a symlinked generated output is confinement's problem for `audit` (which
    actually copies it) rather than a reason to refuse the whole recipe."""
    path = _recipe.recipe_path(d)
    try:
        with open(path, "rb") as f:
            parsed = tomllib.load(f)
    except tomllib.TOMLDecodeError as exc:
        raise ClaimError(f"malformed recipe {path!r}: {exc}") from exc
    except OSError as exc:
        raise ClaimError(f"cannot read recipe {path!r}: {exc}") from exc

    claim = parsed.get("claim")
    if not isinstance(claim, dict):
        raise ClaimError(f"recipe {path!r} is missing a [claim] table")
    name = claim.get("name")
    if not isinstance(name, str) or not name:
        raise ClaimError(f"recipe {path!r}: [claim] name is required and must be a string")

    fmt = claim.get("format", 1)
    if isinstance(fmt, bool) or not isinstance(fmt, int) or fmt < 1:
        raise ClaimError(f"recipe {path!r}: [claim] format must be a positive integer")
    if fmt > _core.FORMAT:
        raise ClaimError(
            f"claim format {fmt} is newer than this kernel understands "
            f"(format {_core.FORMAT}); upgrade reticuli to read it"
        )

    inputs = claim.get("inputs", [])
    if not isinstance(inputs, list) or not all(isinstance(p, str) for p in inputs):
        raise ClaimError(f"recipe {path!r}: [claim] inputs must be a list of strings")
    for p in inputs:
        _core._safe(d, p)

    manifest_name = claim.get("inputs_manifest")
    if manifest_name is not None:
        if not isinstance(manifest_name, str) or not manifest_name:
            raise ClaimError(f"recipe {path!r}: inputs_manifest must be a string")
        _core._safe(d, manifest_name)

    environment = claim.get("environment")
    if environment is not None:
        if not isinstance(environment, str) or not environment:
            raise ClaimError(f"recipe {path!r}: environment must be a string")
        _core._safe(d, environment)

    envelope = claim.get("envelope")
    if envelope is not None:
        if not isinstance(envelope, dict) or not envelope:
            raise ClaimError(f"recipe {path!r}: [claim] envelope must be a non-empty table")
        unknown_units = set(envelope) - set(_core.COST_UNITS)
        if unknown_units:
            raise ClaimError(f"recipe {path!r}: envelope carries unknown unit(s): {sorted(unknown_units)}")
        for unit, ceiling in envelope.items():
            if isinstance(ceiling, bool) or not isinstance(ceiling, (int, float)) or ceiling <= 0:
                raise ClaimError(f"recipe {path!r}: envelope.{unit} must be a positive number")

    steps = parsed.get("step", [])
    if not isinstance(steps, list):
        raise ClaimError(f"recipe {path!r}: [[step]] must be an array of tables")
    for step in steps:
        if not isinstance(step, dict):
            raise ClaimError(f"recipe {path!r}: each step must be a table")
        kind = step.get("kind")
        if kind not in _core.KINDS:
            raise ClaimError(
                f"recipe {path!r}: step kind must be one of "
                f"{sorted(_core.KINDS)}, got {kind!r}"
            )
        output = step.get("output")
        if not isinstance(output, str) or not output:
            raise ClaimError(f"recipe {path!r}: every step needs a string output")
        effective_class = step.get("class", "generated" if kind == "produce" else "pinned")
        if effective_class == "generated":
            _safe_lexical(output)
        else:
            _core._safe(d, output)
        if kind == "gate" and not step.get("run"):
            raise ClaimError(f"recipe {path!r}: a gate step needs a run command")
        if "class" not in step:
            step["class"] = effective_class

    return parsed


def load_recipe(d: str) -> dict:
    return _in_band(_parse_recipe, d)


def root(recipe: dict, d: str) -> str:
    return _in_band(_identity.root, recipe, d)


def build_digest(d: str) -> str:
    return _in_band(_identity.build_digest, d)


def seal(d: str) -> dict:
    recipe = load_recipe(d)
    name = recipe["claim"]["name"]
    r = root(recipe, d)
    manifest = {"name": name, "root": r}
    path = os.path.join(d, _core.MANIFEST)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    _core._write_json(path, manifest)
    return manifest


def read_manifest(d: str) -> dict:
    return _in_band(_seal.read_manifest, d)


def verify(d: str) -> dict:
    recipe = load_recipe(d)
    manifest = read_manifest(d)
    recomputed = root(recipe, d)
    return {"ok": recomputed == manifest["root"], "root": manifest["root"],
            "recomputed": recomputed, "name": manifest["name"]}


