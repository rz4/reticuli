def _in_band(fn, *args, **kwargs):
    """Call `fn`, turning any exception the lower layer leaves unwrapped
    (a missing pinned input surfaces as a raw `FileNotFoundError` from
    `_hash_file`, for one) into a `ClaimError` -- the claim's own bytes are
    untrusted input all the way up to this surface, not only where the
    lower layer happened to catch it itself."""
    try:
        return fn(*args, **kwargs)
    except ClaimError:
        raise
    except Exception as exc:
        raise ClaimError(f"{getattr(fn, '__name__', fn)} failed: {exc}") from exc

