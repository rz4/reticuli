def _hash_tree(root_dir: str) -> dict:
    """Every regular file under `root_dir`, outside the store, by its
    sha256 -- the baseline a producer's own bytes are checked against."""
    snap = {}
    store_abs = os.path.realpath(os.path.join(root_dir, _core.STORE))
    for dirpath, dirnames, filenames in os.walk(root_dir):
        dirnames[:] = [dn for dn in dirnames
                       if not (os.path.realpath(os.path.join(dirpath, dn)) == store_abs
                               or os.path.realpath(os.path.join(dirpath, dn))
                               .startswith(store_abs + os.sep))]
        for fn in filenames:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root_dir)
            try:
                snap[rel] = _core._hash_file(full)
            except ClaimError:
                pass
    return snap


def rebuild(d: str, producer: str, into: str, *, produce_from: dict = None,
            input_from: dict = None, guidance: bool = True,
            producer_env: dict = None) -> dict:
    """Regrow `d`'s generated outputs into the fresh directory `into`.

    `produce_from` supplies bytes for a named generated output directly,
    bypassing the producer for that one output, whether or not its step
    declares a `from` component. `input_from` threads a replacement source
    file for a named pinned input, overriding the one carried from `d`.
    `guidance` withholds every producer hint from the room's environment
    when false. `producer_env` is merged into the producer's own
    environment past the host's -- the one road an inherited credential may
    travel, by the caller's deliberate hand.
    """
    recipe = load_recipe(d)
    if os.path.isdir(into) and os.listdir(into):
        raise ClaimError(f"refuses a non-empty rebuild target: {into!r}")

    missing = _run.preflight(recipe)
    if missing:
        raise ClaimError(f"environment: host is missing {missing}")

    _build._materialize(d, into, recipe)
    for name, replacement in (input_from or {}).items():
        _core._copy_into(replacement, _core._safe(into, name))

    before = _hash_tree(into)

    outs = _recipe.generated_outputs(recipe)
    usage_total = {}
    produced_calls = 0
    produce_from = produce_from or {}
    for step in _recipe.produces(recipe):
        if step.get("class", "generated") != "generated":
            continue
        output = step["output"]
        supplied = produce_from.get(output) or step.get("from")
        if supplied and os.path.isfile(supplied):
            _core._copy_into(supplied, _core._safe(into, output))
            _run.ledger(into, {"event": "reuse", "output": output})
            continue
        usage = _produce(into, recipe, step, outs, producer,
                          guidance=guidance, producer_env=producer_env)
        produced_calls += 1
        for key, value in usage.items():
            usage_total[key] = usage_total.get(key, 0) + value

    after = _hash_tree(into)
    for rel, digest in before.items():
        if after.get(rel) != digest:
            raise ClaimError(f"a producer rewrote a pinned byte: {rel!r}")

    quarantine = "none"
    gates_result = []
    ok = True
    for step in _recipe.gates(recipe):
        output = step["output"]
        path = _core._safe(into, output)
        if os.path.isfile(path):
            os.remove(path)
        result = _run_gate(step["run"], into, recipe)
        quarantine = result["quarantine"]
        gates_result.append({"output": output, "status": result["status"],
                              "quarantine": quarantine})
        _run.ledger(into, {"event": "gate", "output": output,
                            "status": result["status"], "quarantine": quarantine})
        if result["status"] != "ok":
            ok = False

    if not ok:
        raise ClaimError(f"rebuild did not earn its gates: {gates_result!r}")

    manifest = seal(into)
    if produced_calls:
        usage_total["calls"] = usage_total.get("calls", 0) + produced_calls
    _run.ledger(into, {
        "event": "environment",
        "when": _core._now(),
        "quarantine": quarantine,
        "python": platform.python_version(),
        "platform": sys.platform,
        **usage_total,
    })
    vendor = os.environ.get(_core._ENV_VENDOR)
    model = os.environ.get(_core._ENV_MODEL)
    if vendor or model:
        _run.ledger(into, {"event": "producer", "vendor": vendor, "model": model,
                            "blind": not bool(produce_from)})
    return {"root": manifest["root"], "name": manifest["name"],
            "quarantine": quarantine, "gates": gates_result}


def _furnish(d: str, recipe: dict) -> str:
    """Build (or reuse a cached) private venv for the claim's pinned
    `environment` file, same as `_run.furnish`, except the install runs
    with its `cwd` set to the claim directory -- a relative local wheel
    path in the requirements file resolves against the claim, not against
    whatever directory happened to call `audit`."""
    claim = (recipe or {}).get("claim", {}) if recipe else {}
    env_file = claim.get("environment")
    if not env_file:
        return None
    path = _core._safe(d, env_file)
    if not os.path.isfile(path):
        raise ClaimError(f"environment file is gone: {env_file!r}")
    digest = _core._hash_file(path)
    key = f"{digest}-{platform.python_version()}-{sys.platform}-{platform.machine()}"
    venv_dir = os.path.join(_run._env_cache_dir(), key)
    bin_name = "Scripts" if sys.platform == "win32" else "bin"
    bin_dir = os.path.join(venv_dir, bin_name)
    if os.path.isdir(venv_dir):
        return bin_dir

    tmp_dir = venv_dir + ".tmp"
    shutil.rmtree(tmp_dir, ignore_errors=True)
    subprocess.run([sys.executable, "-m", "venv", tmp_dir], check=True,
                    capture_output=True, text=True, timeout=_core.FURNISH_TIMEOUT)
    pip = os.path.join(tmp_dir, bin_name, "pip")
    result = subprocess.run(
        [pip, "install", "--require-hashes", "--only-binary=:all:", "-r", path],
        cwd=d, capture_output=True, text=True, timeout=_core.FURNISH_TIMEOUT,
    )
    if result.returncode != 0:
        shutil.rmtree(tmp_dir, ignore_errors=True)
        raise ClaimError(f"cannot furnish environment {env_file!r}: {result.stderr.strip()}")
    os.replace(tmp_dir, venv_dir)
    return bin_dir


# ----------------------------------------------------------------- audit --

def _restore_substitution(d: str, substituted: dict) -> None:
    for output, backup in substituted.items():
        path = _core._safe(d, output)
        if backup is not None:
            shutil.move(backup, path)
        elif os.path.isfile(path):
            os.remove(path)


def audit(d: str, *, produce_from: dict = None) -> dict:
    """Re-earn every gate's verdict cold, in place, then re-check identity.

    Where the claim declares `[claim] environment`, the room is furnished
    first (a private venv from exactly the hash-pinned artifacts); a room
    that cannot be furnished is an `environment` failure, never a verdict.
    `produce_from` substitutes bytes for a named generated output before
    judging -- a dependent re-earning a component's gate on its own shipped
    bytes -- and restores the claim's own bytes afterward regardless of the
    outcome.
    """
    recipe = load_recipe(d)
    manifest = read_manifest(d)

    for step in _recipe.produces(recipe):
        if step.get("class", "generated") == "generated":
            out_path = os.path.join(d, step["output"])
            if os.path.lexists(out_path):
                _core._safe(d, step["output"])

    missing = _run.preflight(recipe)
    if missing:
        gates_result = [{"output": s["output"], "status": "environment", "quarantine": None}
                         for s in _recipe.gates(recipe)]
        return {"ok": False, "root": manifest["root"], "recomputed": None,
                "gates": gates_result, "environment": missing, "verdict": "environment"}

    # THE ROOM MATCHES THE NAME: a gate that reads its own recipe file must
    # find exactly what the root names. format >= 3 strips guidance from
    # the preimage, so the on-disk recipe is temporarily replaced with that
    # same stripped form while gates run here -- in place, not a fresh
    # room -- and restored afterward regardless of outcome.
    recipe_path = _recipe.recipe_path(d)
    original_recipe_bytes = None
    if _identity._claim_format(recipe) >= 3:
        with open(recipe_path, "rb") as f:
            original_recipe_bytes = f.read()
        _build._write_recipe_toml(recipe_path, _identity._preimage_recipe(recipe))

    substituted = {}
    for output, src in (produce_from or {}).items():
        path = _core._safe(d, output)
        if os.path.isfile(path):
            backup = path + ".audit-orig"
            shutil.copy2(path, backup)
            substituted[output] = backup
        else:
            substituted[output] = None
        _core._copy_into(src, path)

    try:
        try:
            bin_dir = _furnish(d, recipe)
        except ClaimError as exc:
            gates_result = [{"output": s["output"], "status": "environment", "quarantine": None}
                             for s in _recipe.gates(recipe)]
            return {"ok": False, "root": manifest["root"], "recomputed": None,
                    "gates": gates_result, "environment": [str(exc)], "verdict": "environment"}

        gates_result = []
        ok = True
        for step in _recipe.gates(recipe):
            output = step["output"]
            path = _core._safe(d, output)
            before = _core._hash_file(path) if os.path.isfile(path) else None
            if os.path.isfile(path):
                os.remove(path)

            result = _run_gate(step["run"], d, recipe, extra_path=bin_dir)
            quarantine = result["quarantine"]

            if result["status"] != "ok":
                ok = False
                gates_result.append({"output": output, "status": result["status"],
                                      "quarantine": quarantine})
                continue
            if not os.path.isfile(path):
                ok = False
                gates_result.append({"output": output, "status": "failed",
                                      "quarantine": quarantine})
                continue
            if before is not None and _core._hash_file(path) != before:
                ok = False
                gates_result.append({"output": output, "status": "mismatch",
                                      "quarantine": quarantine})
                continue
            gates_result.append({"output": output, "status": "ok", "quarantine": quarantine})

        try:
            recomputed = root(recipe, d)
        except ClaimError:
            # a gate that failed to recreate a pinned output (status
            # already failed/mismatch above) can leave a pinned byte
            # missing -- the claim is already broken; recompute is
            # informational, not a second way to raise.
            recomputed = None
        if recomputed != manifest["root"]:
            ok = False

        return {
            "ok": ok, "root": manifest["root"], "recomputed": recomputed,
            "gates": gates_result, "verdict": "earned" if ok else "broken",
        }
    finally:
        _restore_substitution(d, substituted)
        if original_recipe_bytes is not None:
            with open(recipe_path, "wb") as f:
                f.write(original_recipe_bytes)


