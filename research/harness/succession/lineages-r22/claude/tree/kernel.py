def _scrub_env(d: str, recipe: dict, backend: str, scratch: str = None) -> dict:
    """The gate's own environment: a minimal host allowlist, with
    `RETICULI_JAILED` named as the backend *only* when this call is the one
    applying a real sandbox -- an inherited or absent signal passes through
    untouched, so a kernel already inside one never re-announces."""
    env = {k: os.environ[k] for k in _core._KEEP_ENV if k in os.environ}
    if backend not in ("none", "inherited"):
        env[_core._JAILED] = backend
    if scratch is not None:
        env["TMPDIR"] = scratch
        env["HOME"] = scratch
    return env


def _run_gate(cmd: str, d: str, recipe: dict, extra_path: str = None) -> dict:
    backend = _run.sandbox_backend()
    timeout = _run.gate_timeout(recipe)
    scratch = None
    if backend not in ("none", "inherited"):
        scratch_root = os.path.join(d, _core.STORE, "scratch")
        os.makedirs(scratch_root, exist_ok=True)
        scratch = tempfile.mkdtemp(dir=scratch_root)
    env = _scrub_env(d, recipe, backend, scratch)
    if extra_path:
        env["PATH"] = extra_path + os.pathsep + env.get("PATH", os.defpath)
    argv = _run._sandbox_argv(backend, cmd, d, scratch if scratch is not None else d)
    returncode, timed_out = _run._run(argv, d, env, timeout)
    if timed_out:
        status = "timeout"
    elif returncode == 0:
        status = "ok"
    else:
        status = "failed"
    return {"status": status, "quarantine": backend}


def run_gate(cmd: str, d: str, recipe: dict) -> dict:
    """Run one gate command inside `d`: scrubbed environment, sandboxed
    under whatever backend is actually functional, bounded by the
    declared (or default) wall-clock ceiling."""
    return _run_gate(cmd, d, recipe)


def sandbox(cmd: str, d: str):
    """A functional probe of the host sandbox: run `cmd` inside `d` under
    whatever confinement applies, returning `(status, backend)`."""
    result = _run_gate(cmd, d, {})
    return (result["status"], result["quarantine"])


def _produce(into: str, recipe: dict, step: dict, outs: list, producer: str,
             *, guidance: bool = True, producer_env: dict = None) -> dict:
    """Run `producer` once for one produce step. The producer's environment
    is the same scrubbed allowlist a gate gets -- an inherited host secret
    never reaches it unhanded -- plus the room's own control variables and
    whatever `producer_env` the caller deliberately hands over past the
    scrub (spec/claim-format.md: the room's environment is a boundary, both
    ways)."""
    output = step["output"]
    target = _core._safe(into, output)
    os.makedirs(os.path.dirname(target) or into, exist_ok=True)

    env = {k: os.environ[k] for k in _core._KEEP_ENV if k in os.environ}
    env[_core._ENV_OUTPUT] = target
    env[_core._ENV_OUTPUTS] = json.dumps(outs)
    env[_core._ENV_CLAIM] = recipe.get("claim", {}).get("name", "")
    if guidance:
        hint = _build._step_guidance(step)
        if hint is not None:
            env[_core._ENV_REQUEST] = hint

    fd, usage_path = tempfile.mkstemp(prefix=".reticuli-usage-", suffix=".json")
    os.close(fd)
    env[_core._ENV_USAGE] = usage_path
    if producer_env:
        env.update(producer_env)

    try:
        start = time.monotonic()
        result = subprocess.run(
            [_core._SHELL, "-c", producer], cwd=into, env=env,
            capture_output=True, text=True, timeout=_core.PRODUCER_TIMEOUT,
        )
        elapsed = time.monotonic() - start
        if result.returncode != 0:
            raise ClaimError(
                f"producer failed for {output!r}: exit {result.returncode}: "
                f"{(result.stderr or result.stdout).strip()[-300:]}"
            )
        usage = _build._read_usage(usage_path)
        usage["seconds"] = elapsed
        return usage
    finally:
        try:
            os.unlink(usage_path)
        except OSError:
            pass


