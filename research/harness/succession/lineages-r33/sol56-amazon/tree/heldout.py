"""Run verifier-supplied checks without adding them to a claim's identity.

Held-out checks are useful measurements, not claim verdicts.  They execute in
a disposable copy and therefore cannot modify either the claim or its sealed
manifest.
"""
from __future__ import annotations

import os
import shutil
import stat
import tempfile
from collections.abc import Mapping
from typing import Any

from . import kernel


def _relative(name: Any) -> str:
    if not isinstance(name, str) or not name or "\0" in name or os.path.isabs(name):
        raise kernel.ClaimError("held-out file name must be a non-empty relative path")
    value = name.replace("\\", "/")
    if ".." in value.split("/"):
        raise kernel.ClaimError("held-out file escapes the checking room")
    return value


def _copy_regular(source: str, target: str) -> None:
    info = os.lstat(source)
    if not stat.S_ISREG(info.st_mode):
        raise kernel.ClaimError("held-out input is not a regular file")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    shutil.copyfile(source, target)


def run(d: str | os.PathLike[str], command: str,
        files: Mapping[str, str | os.PathLike[str]] | None = None,
        env: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Run one held-out *command* against the concrete bytes in claim *d*.

    ``files`` maps disposable-room names to verifier-owned source files.  The
    result uses the ordinary gate status vocabulary and adds ``heldout=True``;
    no passing result is written into the claim's manifest or ledger.
    """
    if not isinstance(command, str) or not command:
        raise kernel.ClaimError("held-out command must be a non-empty string")
    source = os.path.abspath(os.fspath(d))
    verification = kernel.verify(source)
    if not verification.get("ok"):
        raise kernel.ClaimError("cannot test a claim whose identity does not hold")
    if files is not None and not isinstance(files, Mapping):
        raise kernel.ClaimError("held-out files must be a mapping")

    parent = tempfile.mkdtemp(prefix="reticuli-heldout-")
    room = os.path.join(parent, "room")
    try:
        # copytree rather than working in place: generated bytes are required
        # by a held-out test, while private residue and symlinks are not.
        def ignore(_directory: str, names: list[str]) -> set[str]:
            return {name for name in names if name == kernel.STORE}
        shutil.copytree(source, room, symlinks=False, ignore=ignore)
        for name, path in (files or {}).items():
            relative = _relative(name)
            target = os.path.abspath(os.path.join(room, relative.replace("/", os.sep)))
            if os.path.commonpath((room, target)) != room:
                raise kernel.ClaimError("held-out file escapes the checking room")
            _copy_regular(os.path.abspath(os.fspath(path)), target)
        result = kernel.run_gate(command, room, kernel.load_recipe(room), env=env)
        return {**result, "heldout": True, "root": verification.get("root")}
    except kernel.ClaimError:
        raise
    except (OSError, TypeError, ValueError) as exc:
        raise kernel.ClaimError("cannot prepare held-out check: " + str(exc)) from None
    finally:
        shutil.rmtree(parent, ignore_errors=True)


def check(*args: Any, **kwargs: Any) -> dict[str, Any]:
    """Alias for :func:`run`."""
    return run(*args, **kwargs)


__all__ = ["check", "run"]
