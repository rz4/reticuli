"""Canonical claim and realization identity computations.

The serializations in this module are protocol bytes.  In particular they use
``json.dumps`` with sorted keys and all of its other defaults (including the
spaces in the default separators and ASCII escaping).
"""

from __future__ import annotations

import copy
import hashlib
import json
import os
import stat
from typing import Any

from . import core, recipe as recipe_module


def _canonical(value: Any) -> str:
    """Return the canonical JSON spelling used by claim identity."""

    return json.dumps(value, sort_keys=True)


def _claim_format(recipe: dict[str, Any]) -> int:
    """Return the declared claim format; an omitted format means format 1."""

    try:
        value = recipe["claim"].get("format", 1)
    except (KeyError, AttributeError, TypeError):
        raise core.ClaimError("recipe requires a [claim] table") from None
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise core.ClaimError("[claim] format must be a positive integer")
    if value > core.FORMAT:
        raise core.ClaimError(
            f"claim format {value} is newer than this kernel understands "
            f"(format {core.FORMAT}); upgrade reticuli to read it"
        )
    return value


def _preimage_recipe(recipe: dict[str, Any]) -> dict[str, Any]:
    """Return the recipe object that belongs in the root preimage.

    Formats 1 and 2 retain the authored recipe.  Format 3 removes producer
    guidance, and format 4 additionally treats the step array as a set by
    sorting steps on their own canonical JSON encodings.  A fresh object is
    returned so identity computation never edits its caller's parsed recipe.
    """

    version = _claim_format(recipe)
    result = copy.deepcopy(recipe)
    if version >= 3:
        steps = result.get("step", [])
        if isinstance(steps, list):
            for step in steps:
                if isinstance(step, dict):
                    for key in core.GUIDANCE_KEYS:
                        step.pop(key, None)
            if version >= 4:
                steps.sort(key=_canonical)
    return result


def _hash_declared(d: str | os.PathLike[str], name: str) -> str:
    """Hash one declared file after enforcing the anti-aliasing rules."""

    try:
        path = core._safe(d, name)
        info = os.lstat(path)
        if not stat.S_ISREG(info.st_mode):
            raise core.ClaimError(f"declared file is not a regular file: {name}")
        if info.st_nlink != 1:
            raise core.ClaimError(f"declared file has multiple hard links: {name}")
        return core._hash_file(path)
    except core.ClaimError:
        raise
    except (OSError, TypeError, ValueError) as exc:
        raise core.ClaimError(f"cannot hash declared file {name!r}: {exc}") from None


def _parts(recipe: dict[str, Any], d: str | os.PathLike[str]) -> dict[str, str]:
    """Build the string-to-string map whose canonical digest is the root."""

    parts: dict[str, str] = {
        "digest": core.DIGEST,
        "recipe": _canonical(_preimage_recipe(recipe)),
    }

    for name in recipe_module._inputs(recipe, d):
        parts["input:" + name] = _hash_declared(d, name)

    for step in recipe_module._steps(recipe):
        kind = step.get("kind")
        default_class = "generated" if kind == "produce" else "pinned"
        step_class = step.get("class", default_class)
        if step_class not in ("generated", "free"):
            name = step["output"]
            parts["pinned:" + name] = _hash_declared(d, name)
    return parts


def root(recipe: dict[str, Any], d: str | os.PathLike[str]) -> str:
    """Compute the canonical SHA-256 identity of a parsed claim recipe."""

    preimage = _canonical(_parts(recipe, d)).encode("utf-8")
    return hashlib.sha256(preimage).hexdigest()


def build_digest(d: str | os.PathLike[str]) -> str:
    """Digest the generated bytes currently present in claim directory *d*.

    Component-supplied outputs are excluded, and a declared generated output
    which is not present is omitted.  Thus a claim with no present generated
    outputs hashes the canonical empty list.
    """

    parsed = recipe_module.load_recipe(d)
    files: list[list[str]] = []
    for name in recipe_module.generated_outputs(parsed):
        try:
            path = core._safe(d, name)
            if not os.path.lexists(path):
                continue
            digest = _hash_declared(d, name)
        except core.ClaimError:
            raise
        files.append([name, digest])
    files.sort(key=lambda item: item[0])
    return hashlib.sha256(_canonical(files).encode("utf-8")).hexdigest()
