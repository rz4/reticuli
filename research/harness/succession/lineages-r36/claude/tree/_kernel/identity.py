"""The canonical serializations: the root, and the build digest.

Both are interchange currency. The ROOT answers *is this the same claim* and
must come out byte-identical from every conforming implementation, or claims
cannot travel. The BUILD DIGEST answers *are these the same bytes* and must
too, or signatures cannot travel.

`canonical_json` is exactly `json.dumps(x, sort_keys=True)` with every other
argument left at its default -- sorted keys, DEFAULT separators (a space
after every colon and comma), non-ASCII escaped, integers in exact decimal,
floats as CPython's repr -- encoded UTF-8. An earlier draft of the
specification said "no insignificant whitespace"; a reimplementation
following that sentence would compute a different root for every claim in
existence.
"""
import hashlib
import json
import os

from . import recipe as _recipe
from .core import DIGEST, ClaimError, _hash_file, _is_exec, _safe


def _claim_format(parsed: dict) -> int:
    return _recipe._claim_format(parsed)


def _canonical(value) -> str:
    return json.dumps(value, sort_keys=True)


def _preimage_recipe(parsed: dict) -> dict:
    """The recipe the preimage serializes.

    Format 3 strips every step's guidance. Formats 4 and 5 additionally
    canonicalize the step list, serializing steps in the lexicographic order
    of their canonical JSON encodings. Format 6 WITHDRAWS that sort: gates
    run in file order in one shared workspace, so a gate that reads what an
    earlier gate wrote makes the order decide acceptance -- two orderings
    are two claims, which is what they always were.
    """
    fmt = _claim_format(parsed)
    lean = _recipe.strip_guidance(parsed, fmt)
    if fmt in (4, 5) and "step" in lean:
        lean = dict(lean)
        lean["step"] = sorted(lean["step"], key=_canonical)
    return lean


def _refuse_unserializable(parsed: dict) -> None:
    """TOML dates and times give JSON no canonical form, so they cannot
    enter a preimage; they are refused at sealing rather than guessed at."""
    import datetime

    def walk(value):
        if isinstance(value, (datetime.date, datetime.datetime,
                              datetime.time)):
            raise ClaimError(
                "a TOML date or time value cannot enter the root preimage: "
                "JSON gives it no canonical form")
        if isinstance(value, dict):
            for item in value.values():
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
    walk(parsed)


def _parts(parsed: dict, claim: str) -> dict:
    """The string-to-string map the root hashes.

        parts["digest"]         = "sha256"
        parts["recipe"]         = canonical_json(recipe)
        parts["input:<path>"]   = sha256(bytes of path)
        parts["pinned:<out>"]   = sha256(bytes of a non-generated output)

    Generated outputs never enter it: that freedom IS the equivalence class.
    """
    _refuse_unserializable(parsed)
    parts = {"digest": DIGEST,
             "recipe": _canonical(_preimage_recipe(parsed))}
    for path in _recipe._inputs(parsed, claim):
        parts["input:" + path] = _hash_file(_safe(claim, path))
    for output in _recipe.pinned_outputs(parsed):
        parts["pinned:" + output] = _hash_file(_safe(claim, output))
    return parts


def root(parsed: dict, claim: str) -> str:
    """A claim's identity: the sha256 of the canonical preimage."""
    preimage = _canonical(_parts(parsed, claim)).encode("utf-8")
    return hashlib.sha256(preimage).hexdigest()


def build_digest(claim: str, parsed: dict | None = None) -> str:
    """The digest a signature binds: the concrete generated bytes present.

    One entry per step that is `kind = "produce"`, carries NO `from` (such an
    output belongs to a component, and that component's own signature
    already covers it), has `class = "generated"`, and whose output file is
    PRESENT on disk. An absent generated output is omitted; a claim with no
    such outputs digests the empty list.

    At format 6 each entry is a triple carrying the owner-execute bit:
    content alone does not determine whether a gate can run its own output,
    and `chmod 644` on a generated program once left this digest identical
    while a cold audit went from earned to Permission denied.
    """
    if parsed is None:
        parsed = _recipe.load_recipe(claim)
    fmt = _claim_format(parsed)
    own = []
    for step in _recipe.produces(parsed):
        if step.get("from") is not None:
            continue
        if _recipe.step_class(step) != "generated":
            continue
        path = _safe(claim, step["output"])
        if not os.path.isfile(path):
            continue
        entry = [step["output"], _hash_file(path)]
        if fmt >= 6:
            entry.append("x" if _is_exec(path) else "-")
        own.append(entry)
    return hashlib.sha256(
        _canonical(sorted(own)).encode("utf-8")).hexdigest()
