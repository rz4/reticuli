# -- the path boundary -----------------------------------------------------
def _safe(claim: str, declared: str) -> str:
    """Resolve a declared name inside the claim, or refuse.

    Identity may depend only on bytes and on declarations, never on what a
    particular host's filesystem is willing to resolve. So: no absolute
    name, no empty name, no `..` component, and no component that is a
    symlink -- not even one whose target stays inside the claim, because such
    a link can alias generated bytes under a pinned name.
    """
    if not isinstance(declared, str) or not declared:
        raise ClaimError("a declared path must be a non-empty string")
    if os.path.isabs(declared) or declared.startswith("/"):
        raise ClaimError(f"declared path is absolute: {declared!r}")
    parts = declared.replace("\\", "/").split("/")
    if any(p == ".." for p in parts):
        raise ClaimError(f"declared path climbs out of the claim: {declared!r}")
    base = os.path.realpath(claim)
    here = base
    for part in parts:
        if part in ("", "."):
            continue
        here = os.path.join(here, part)
        if os.path.islink(here):
            raise ClaimError(
                f"declared path has a symlink component: {declared!r}")
    resolved = os.path.normpath(here)
    if resolved != base and not resolved.startswith(base + os.sep):
        raise ClaimError(f"declared path escapes the claim: {declared!r}")
    return resolved


# -- the bytes boundary ----------------------------------------------------
def _hash_file(path: str) -> str:
    """The sha256 of a file's bytes, with the filesystem adversaries refused.

    A hashed file must be a REGULAR file with a SINGLE hard link, so its
    bytes live inside the claim and nowhere else. A FIFO, device, socket or
    directory is not a file; a hardlink to an outside inode keeps a
    local-looking path while sealing foreign bytes as the claim's own.
    """
    if os.path.islink(path):
        raise ClaimError(f"not a regular file (symlink): {path}")
    try:
        info = os.lstat(path)
    except OSError as exc:
        raise ClaimError(f"cannot read declared file {path}: {exc}") from None
    import stat as _stat
    if not _stat.S_ISREG(info.st_mode):
        raise ClaimError(f"not a regular file: {path}")
    if info.st_nlink != 1:
        raise ClaimError(
            f"file has {info.st_nlink} hard links, so its bytes are not "
            f"the claim's alone: {path}")
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def hash_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _is_exec(path: str) -> bool:
    """Whether the owner-execute bit is set -- the one mode bit a format-6
    build digest commits, because content alone does not decide whether a
    gate can run its own output."""
    try:
        return bool(os.stat(path).st_mode & 0o100)
    except OSError:
        return False


# -- atomic json -----------------------------------------------------------
def _write_json(path: str, payload) -> None:
    parent = os.path.dirname(os.path.abspath(path))
    os.makedirs(parent, exist_ok=True)
    temporary = path + ".writing"
    with open(temporary, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, sort_keys=True)
        handle.write("\n")
    os.replace(temporary, path)


def _read_json(path: str):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        return None
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ClaimError(f"{path} is not readable JSON: {exc}") from None


# -- small shared helpers --------------------------------------------------
def _now() -> str:
    """UTC, always -- a recorded time must not depend on the host's TZ."""
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _copy_into(source: str, destination: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(destination)), exist_ok=True)
    shutil.copyfile(source, destination)
    shutil.copymode(source, destination)


def _judging_host() -> dict:
    """The verdict environment, as residue: interpreter and platform."""
    import platform
    import sys
    return {"python": f"{platform.python_implementation()} "
                      f"{platform.python_version()}",
            "platform": sys.platform,
            "machine": platform.machine() or "unknown"}


def _finite(value) -> bool:
    """A number that reports a measurement: never a boolean, never NaN or an
    infinity. Both poison the comparison a cost exists for."""
    import math
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return False
    return math.isfinite(value)
