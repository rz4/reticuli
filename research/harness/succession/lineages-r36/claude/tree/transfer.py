"""Transport: a claim as a portable archive, verified on arrival.

Three properties make the archive a transport rather than a backup.

DECLARED CONTENT ONLY. The tar is built by walking the RECIPE, never the
directory, so a stray file in someone's working copy does not travel. A
transport that leaked the workspace would make M2's pass mean "the sender's
laptop", not "the claim".

BYTE-DETERMINISTIC. Fixed mode, owner, and mtime on every member, entries in
sorted order -- so two exports of one claim are byte-identical and an
archive can itself be cited by digest.

VOLATILE HISTORY STAYS HOME. The ledger does not travel: it is residue of
one machine's runs. The manifest and the attestations do, because they are
statements ABOUT the claim that a receiver needs.
"""
import io
import os
import sys
import tarfile

from . import _util
from . import kernel
from .attest import ATTEST

DEPS = os.path.join(kernel.STORE, "deps")


def _members(claim: str, blind: bool = False) -> list:
    """Every path that travels, as (archive name, absolute source)."""
    parsed = kernel.load_recipe(claim)
    names = []
    recipe = kernel.recipe_path(claim)
    names.append((os.path.basename(recipe), recipe))
    for declared in _util.declared_inputs(parsed):
        source = os.path.join(claim, declared)
        if os.path.isfile(source):
            names.append((declared, source))
    for step in parsed.get("step") or []:
        output = step.get("output")
        if not output:
            continue
        if blind and kernel.step_class(step) == "generated":
            continue                      # the room withholds exactly this
        source = os.path.join(claim, output)
        if os.path.isfile(source):
            names.append((output, source))
    manifest = os.path.join(claim, kernel.MANIFEST)
    if os.path.isfile(manifest):
        names.append((kernel.MANIFEST, manifest))
    for drawer in (ATTEST, kernel.SIGN_DIR):
        where = os.path.join(claim, drawer)
        if not os.path.isdir(where):
            continue
        for base, _dirs, files in os.walk(where):
            for name in sorted(files):
                source = os.path.join(base, name)
                names.append((os.path.relpath(source, claim), source))
    # a component's CLAIM travels (recipe, inputs, pins) so the receiver can
    # re-earn every layer; its generated bytes do not -- those are the
    # dependent's to ship.
    for link in (kernel.read_manifest(claim).get("components")
                 if os.path.isfile(manifest) else None) or []:
        name = link.get("component")
        for drawer in ("sealed", "deps"):
            where = os.path.join(claim, kernel.STORE, drawer, name or "")
            if not os.path.isdir(where):
                continue
            for inner, source in _members(where, blind=True):
                names.append((os.path.join(DEPS, name, inner), source))
            break
    seen, ordered = set(), []
    for name, source in sorted(names):
        if name not in seen:
            seen.add(name)
            ordered.append((name, source))
    return ordered


def export(claim: str, archive: str, blind: bool = False) -> dict:
    """Write a portable archive of one claim. `-` is the standard stream."""
    kernel.load_recipe(claim)
    members = _members(claim, blind=blind)
    stream = None
    if archive == "-":
        stream = tarfile.open(fileobj=sys.stdout.buffer, mode="w|")
    else:
        stream = tarfile.open(archive, "w")
    try:
        for name, source in members:
            info = tarfile.TarInfo(name)
            with open(source, "rb") as handle:
                payload = handle.read()
            info.size = len(payload)
            info.mtime = 0
            info.mode = 0o755 if os.stat(source).st_mode & 0o100 else 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.type = tarfile.REGTYPE
            stream.addfile(info, io.BytesIO(payload))
    finally:
        stream.close()
    return {"archive": archive, "files": [n for n, _ in members],
            "blind": blind}


def _safe_extract(stream, destination: str) -> None:
    base = os.path.realpath(destination)
    for member in stream.getmembers():
        if not member.isfile():
            raise kernel.ClaimError(
                f"an archive carries only regular files: {member.name}")
        target = os.path.realpath(os.path.join(destination, member.name))
        if target != base and not target.startswith(base + os.sep):
            raise kernel.ClaimError(
                f"an archive member escapes the target: {member.name}")
    stream.extractall(destination, filter="data")


def import_(archive: str, destination: str) -> dict:
    """Restore an archive and verify the identity from the received bytes.

    A receiver trusts nothing it was sent: the root is recomputed here, from
    these bytes, and compared with the manifest that travelled with them.
    """
    if archive == "-":
        stream = tarfile.open(fileobj=sys.stdin.buffer, mode="r|*")
    else:
        if not os.path.isfile(archive):
            raise kernel.ClaimError(f"no archive at {archive}")
        stream = tarfile.open(archive, "r")
    os.makedirs(destination, exist_ok=True)
    try:
        if archive == "-":
            base = os.path.realpath(destination)
            for member in stream:
                if not member.isfile():
                    continue
                target = os.path.realpath(
                    os.path.join(destination, member.name))
                if target != base and not target.startswith(base + os.sep):
                    raise kernel.ClaimError(
                        f"an archive member escapes the target: "
                        f"{member.name}")
                stream.extract(member, destination, filter="data")
        else:
            _safe_extract(stream, destination)
    finally:
        stream.close()
    checked = kernel.verify(destination)
    return {"ok": checked["ok"], "root": checked["root"],
            "recomputed": checked["recomputed"], "name": checked["name"],
            "path": destination}
