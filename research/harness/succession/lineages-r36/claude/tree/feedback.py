"""Sensing what a session has, and what it still lacks, to be sealable.

The authoring triad, which every view of a draft reports: what was
OBSERVED (the trace saw it), what would be DECLARED (the class a pack would
give it), and what is UNRESOLVED (generated bytes no gate reaches). The
third is the one that matters: a file nothing decides is a file the claim
does not hold down, and sealing it would widen the equivalence class
silently.

Advisory, always. Nothing here refuses anything; `pack` does the refusing.
"""
import os

from . import authoring
from . import kernel

#: directories a view never descends into: the store is residue, and a
#: version-control or environment directory is not the session's work
SKIP = {".reticuli", ".git", ".hg", ".svn", "__pycache__", ".venv", "venv",
        "node_modules", ".claude", ".launcher", ".checkwork"}


def _present(ws: str) -> list:
    found = []
    for base, dirs, files in os.walk(ws):
        dirs[:] = [d for d in sorted(dirs) if d not in SKIP]
        for name in sorted(files):
            path = os.path.relpath(os.path.join(base, name), ws)
            found.append(path.replace(os.sep, "/"))
    return found


def _covered(ws: str, commands: list) -> set:
    """Which paths a gate actually reaches: named in the command, run by it,
    or imported by something it runs -- one level, which is the canonical
    Python shape."""
    reached = set()
    for command in commands:
        tokens = set(authoring._tokens(command))
        reached |= {t for t in tokens if authoring._real_entry(ws, t)}
        for decider in kernel.gate_deciders(command):
            reached.add(decider)
            reached |= set(authoring._imported_by(ws, decider))
    return reached


def survey(ws: str) -> dict:
    """The triad, per path, with where each observation came from."""
    seen = authoring.observations(ws)
    commands = authoring.gate_commands(ws)
    verdicts = set()
    for command in commands:
        verdicts |= set(authoring._redirect_targets(command))
    reached = _covered(ws, commands)
    deciders = set()
    for command in commands:
        for decider in kernel.gate_deciders(command):
            deciders.add(decider)

    paths = sorted(set(_present(ws)) | set(seen))
    rows = []
    for path in paths:
        fact = seen.get(path) or {}
        observed = fact.get("observed", "-")
        evidence = fact.get("evidence", "-")
        if observed == "-" and path in reached:
            evidence = "gate"
        if path in verdicts:
            declared = "validated"
        elif observed == "write":
            declared = "generated"
        elif path in deciders or path in reached:
            declared = "pinned"
        else:
            declared = "-"
        rows.append({"path": path, "observed": observed,
                     "declared": declared, "evidence": evidence,
                     "present": os.path.isfile(os.path.join(ws, path)),
                     "covered": path in reached or path in verdicts})
    return {"rows": rows, "gates": commands, "verdicts": sorted(verdicts)}


def advise(ws: str) -> dict:
    """Is this session sealable, and if not, what is missing?"""
    found = survey(ws)
    rows = found["rows"]
    observed = [r for r in rows if r["observed"] != "-"]
    declared = [r for r in rows if r["declared"] != "-"]
    unresolved = [r for r in rows
                  if r["declared"] == "generated" and not r["covered"]]
    verdicts = [v for v in found["verdicts"]
                if os.path.isfile(os.path.join(ws, v))]
    reasons = []
    if not found["gates"]:
        reasons.append("no command was run, so nothing declares acceptance")
    if not verdicts:
        reasons.append("no verdict file was earned by a command")
    for row in unresolved:
        reasons.append(f"{row['path']} is undeclared: no gate reaches it")
    return {"sealable": not reasons,
            "observed": len(observed),
            "declared": len(declared),
            "unresolved": len(unresolved),
            "undeclared": [r["path"] for r in unresolved],
            "verdicts": verdicts,
            "gates": found["gates"],
            "rows": rows,
            "why": reasons}
