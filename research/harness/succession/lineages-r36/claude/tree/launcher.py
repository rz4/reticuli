"""Run software that exists only latently in a claim.

A runnable claim keeps only its CLAIM durable -- the pinned inputs, the
gate, the verdicts. The implementation is a cache entry: deleting it is
always safe, because the claim, not the code, is the identity.

    python3 -m reticuli.launcher run   <claim> [flags] [-- args...]
    python3 -m reticuli.launcher strip <claim>
    python3 -m reticuli.launcher ls    <claim>...

THE PACKAGE CONTRACT. A runnable claim's pinned inputs include
`package.toml` carrying `[package] entrypoint = "..."`. It must be a PINNED
input: an entrypoint declaration that could drift from what the gate
exercised would divorce what was proven from what runs.

EXIT CODES, which orchestrators depend on: the entrypoint's own code when it
runs; 3 not runnable; 4 newly generated bytes awaiting consent; 5 trust
refused; 6 a drifted build; 7 latent with no producer configured.

CHANNEL DISCIPLINE. The launcher speaks only on stderr -- stdout belongs
entirely to the entrypoint, because claims test byte-exact stdout.

CONSENT BINDS BYTES. Accepting an implementation records its digests. An
edit inside the equivalence class still passes the gate and is still an
unreviewed substitution, so a drifted accepted build is refused loudly,
with nothing executed and nothing modified: the evidence is preserved and
`strip` is the recovery path.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import tomllib

from . import kernel

STATE = ".launcher"
NOT_RUNNABLE = 3
NEEDS_CONSENT = 4
TRUST_REFUSED = 5
DRIFTED = 6
NO_PRODUCER = 7
KEEP = ("PATH", "LANG", "LC_ALL", "TZ")


class Refused(Exception):
    def __init__(self, code: int, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


def _say(message: str) -> None:
    print(message, file=sys.stderr)


def _state_path(claim: str) -> str:
    return os.path.join(claim, STATE, "state.json")


def _state(claim: str) -> dict:
    path = _state_path(claim)
    if not os.path.isfile(path):
        return {}
    try:
        with open(path, encoding="utf-8") as handle:
            found = json.load(handle)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return {}
    return found if isinstance(found, dict) else {}


def _save_state(claim: str, state: dict) -> None:
    path = _state_path(claim)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(state, handle, sort_keys=True)


def _digests(claim: str, outputs) -> dict:
    found = {}
    for output in outputs:
        path = os.path.join(claim, output)
        if os.path.isfile(path):
            with open(path, "rb") as handle:
                import hashlib
                found[output] = hashlib.sha256(handle.read()).hexdigest()
    return found


def _confined(claim: str, outputs) -> None:
    """Every recipe-derived path stays inside the claim, or nothing happens.

    Checked BEFORE anything is deleted, written or executed: a tampered
    recipe naming `../VICTIM` once made a strip delete outside its claim.
    """
    for output in outputs:
        try:
            kernel._safe(claim, output)
        except kernel.ClaimError as exc:
            raise Refused(NOT_RUNNABLE,
                          f"a recipe path leaves the claim: {exc}") from None


def _package(claim: str, parsed: dict) -> str:
    """The declared entrypoint, held to the pinning rule."""
    declared = set((parsed.get("claim") or {}).get("inputs") or [])
    generated = set(kernel.generated_outputs(parsed))
    produced = {s.get("output") for s in kernel.produces(parsed)}
    if "package.toml" in generated or ("package.toml" in produced
                                       and "package.toml" not in declared):
        raise Refused(NOT_RUNNABLE,
                      "package.toml is offered as a generated output; it "
                      "must be a pinned input, or what runs could drift "
                      "from what the gate proved")
    if "package.toml" not in declared:
        raise Refused(NOT_RUNNABLE,
                      "this claim is not runnable: no package.toml among "
                      "its pinned inputs")
    path = os.path.join(claim, "package.toml")
    if not os.path.isfile(path):
        raise Refused(NOT_RUNNABLE,
                      "package.toml is declared but not present")
    try:
        with open(path, "rb") as handle:
            table = tomllib.load(handle)
    except (tomllib.TOMLDecodeError, OSError) as exc:
        raise Refused(NOT_RUNNABLE,
                      f"package.toml is not readable: {exc}") from None
    entrypoint = (table.get("package") or {}).get("entrypoint")
    if not isinstance(entrypoint, str) or not entrypoint:
        raise Refused(NOT_RUNNABLE,
                      "package.toml declares no [package] entrypoint")
    try:
        kernel._safe(claim, entrypoint)
    except kernel.ClaimError as exc:
        raise Refused(NOT_RUNNABLE,
                      f"the entrypoint escapes the claim: {exc}") from None
    return entrypoint


def _open(claim: str):
    where = os.path.abspath(claim)
    if not os.path.isdir(where):
        raise Refused(NOT_RUNNABLE, f"no claim at {claim}")
    try:
        parsed = kernel.load_recipe(where)
    except kernel.ClaimError as exc:
        raise Refused(NOT_RUNNABLE, str(exc)) from None
    _confined(where, [s.get("output") for s in parsed.get("step") or []
                      if s.get("output")])
    return where, parsed


def _scrubbed(claim: str, backend: str) -> dict:
    """The entrypoint gets the same hygiene a gate gets: the caller's
    secrets never reach it, and it is handed somewhere it can write."""
    env = {key: os.environ[key] for key in KEEP if key in os.environ}
    env.setdefault("PATH", os.defpath)
    scratch = os.path.join(claim, STATE, "scratch")
    os.makedirs(scratch, exist_ok=True)
    env["HOME"] = scratch
    env["TMPDIR"] = scratch
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    if backend in ("seatbelt", "bubblewrap"):
        env[kernel._JAILED] = backend
    return env


def _execute(claim: str, entrypoint: str, arguments, no_sandbox: bool) -> int:
    backend = "off" if no_sandbox else kernel.sandbox_backend()
    argv = []
    if not no_sandbox:
        argv = kernel.sandbox("", claim)[0]
    argv = argv + [sys.executable, entrypoint] + list(arguments)
    _say(f'quarantine = "{backend}"')
    done = subprocess.run(argv, cwd=claim,
                          env=_scrubbed(claim, backend), check=False)
    return done.returncode


def _regrow(claim: str, parsed: dict) -> None:
    producer = os.environ.get("RETICULI_PRODUCER")
    if not producer:
        raise Refused(NO_PRODUCER,
                      "this claim is latent and no producer is configured: "
                      "set RETICULI_PRODUCER to regrow it")
    room = tempfile.mkdtemp(prefix="launcher-regrow-")
    try:
        shutil.rmtree(room, ignore_errors=True)
        kernel.rebuild(claim, producer, room)
        for output in kernel.generated_outputs(parsed):
            source = os.path.join(room, output)
            if os.path.isfile(source):
                target = kernel._safe(claim, output)
                os.makedirs(os.path.dirname(target), exist_ok=True)
                shutil.copyfile(source, target)
                shutil.copymode(source, target)
    except kernel.ClaimError as exc:
        raise Refused(DRIFTED, f"the claim could not be regrown: {exc}") \
            from None
    finally:
        shutil.rmtree(room, ignore_errors=True)


def run(claim: str, arguments=(), accept_generated: bool = False,
        signed_only: bool = False, no_sandbox: bool = False) -> int:
    where, parsed = _open(claim)
    entrypoint = _package(where, parsed)
    try:
        phase = kernel.phase(where)
    except kernel.ClaimError as exc:
        raise Refused(NOT_RUNNABLE, str(exc)) from None
    if signed_only and phase != "signed":
        raise Refused(TRUST_REFUSED,
                      f"--signed-only was asked and this claim is {phase}, "
                      f"not signed to you: nothing was executed")
    _say(f"{kernel.read_manifest(where)['name']} {phase}")

    outputs = kernel.generated_outputs(parsed)
    state = _state(where)
    missing = [o for o in outputs
               if not os.path.isfile(os.path.join(where, o))]
    if missing:
        _regrow(where, parsed)
        state = dict(state)
        state["fresh"] = _digests(where, outputs)
        state.pop("accepted", None)
        _save_state(where, state)
        if not accept_generated:
            raise Refused(NEEDS_CONSENT,
                          "newly generated bytes are not yet accepted; pass "
                          "--accept-generated to execute and accept them")
    present = _digests(where, outputs)
    accepted = state.get("accepted")
    if state.get("fresh") and not accepted and not accept_generated:
        raise Refused(NEEDS_CONSENT,
                      "these bytes were generated here and never accepted; "
                      "pass --accept-generated to execute and accept them")
    if accepted and accepted != present:
        raise Refused(DRIFTED,
                      "the accepted implementation has drifted: consent "
                      "bound bytes, and these are not those bytes. Nothing "
                      "was executed and nothing modified -- `strip` is the "
                      "recovery path")
    if not accepted and not state.get("fresh"):
        verdict = kernel.audit(where)
        if not verdict["ok"]:
            raise Refused(DRIFTED,
                          f"this build does not re-earn its verdicts "
                          f"({verdict['verdict']}); nothing was executed. "
                          f"`strip` returns the claim to latency")
    if accept_generated:
        state = dict(state)
        state["accepted"] = present
        state.pop("fresh", None)
        _save_state(where, state)
    return _execute(where, entrypoint, arguments, no_sandbox)


def strip(claim: str) -> int:
    """Delete the generated bytes, keep the claim."""
    where, parsed = _open(claim)
    removed = []
    for output in kernel.generated_outputs(parsed):
        path = kernel._safe(where, output)
        if os.path.isfile(path):
            os.remove(path)
            removed.append(output)
    shutil.rmtree(os.path.join(where, STATE), ignore_errors=True)
    _say(f"stripped {len(removed)} generated file(s); the claim is latent")
    return 0


def ls(claims) -> int:
    for claim in claims:
        where = os.path.abspath(claim)
        try:
            parsed = kernel.load_recipe(where)
            manifest = kernel.read_manifest(where)
            phase = kernel.phase(where)
        except kernel.ClaimError as exc:
            print(f"{claim}  unreadable  {exc}")
            continue
        outputs = kernel.generated_outputs(parsed)
        whole = outputs and all(
            os.path.isfile(os.path.join(where, o)) for o in outputs)
        print(f"{manifest['name']}  {manifest['root'][:8]}  {phase}  "
              f"{'materialized' if whole else 'latent'}")
    return 0


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    # `--` ends the launcher's own flags and begins the entrypoint's
    # arguments. Split before parsing: argparse.REMAINDER would swallow a
    # launcher flag that happened to follow the claim.
    passthrough = []
    if "--" in argv:
        cut = argv.index("--")
        argv, passthrough = argv[:cut], argv[cut + 1:]
    parser = argparse.ArgumentParser(
        prog="reticuli.launcher",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description="run software that is only latent in a claim",
        epilog="run <claim> [--accept-generated] [--signed-only] "
               "[--no-sandbox] [-- args...]\n"
               "strip <claim>        delete the generated bytes\n"
               "ls <claim>...        identity, phase, and whether the "
               "bytes are on hand")
    sub = parser.add_subparsers(dest="verb")
    runner = sub.add_parser("run", help="run a claim's entrypoint")
    runner.add_argument("claim")
    runner.add_argument("--accept-generated", action="store_true",
                        help="execute and accept freshly generated bytes")
    runner.add_argument("--signed-only", action="store_true",
                        help="refuse a claim that is not signed to you")
    runner.add_argument("--no-sandbox", action="store_true",
                        help="execute without confinement, reported as off")
    stripper = sub.add_parser("strip", help="delete the generated bytes")
    stripper.add_argument("claim")
    lister = sub.add_parser("ls", help="list claims and whether they are "
                                       "materialized")
    lister.add_argument("claims", nargs="+")
    args = parser.parse_args(argv)
    if not args.verb:
        parser.print_help()
        return 0
    try:
        if args.verb == "run":
            return run(args.claim, passthrough,
                       accept_generated=args.accept_generated,
                       signed_only=args.signed_only,
                       no_sandbox=args.no_sandbox)
        if args.verb == "strip":
            return strip(args.claim)
        return ls(args.claims)
    except Refused as refusal:
        _say(f"launcher: {refusal.message}")
        return refusal.code


if __name__ == "__main__":
    sys.exit(main())
