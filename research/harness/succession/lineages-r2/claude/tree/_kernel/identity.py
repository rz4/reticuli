"""Identity: the root hash and the build digest (spec/identity.md).

The root names a claim's equivalence class: a SHA-256 digest over the
recipe's canonical serialization, the bytes of every pinned input, and the
bytes of every non-generated step output. Generated bytes never enter it,
so an implementation can be deleted and regrown byte-different without
changing the root. The build digest is the companion measurement over the
generated bytes actually present, the digest a signature binds.
"""
import hashlib
import json
import os

from . import core, recipe


def _canonical_json(obj) -> bytes:
    """`json.dumps(obj, sort_keys=True)`, encoded UTF-8 (spec/identity.md).

    Default separators (`", "` / `": "`), ASCII escaping of non-ASCII, exact
    decimal integers, floats as CPython's `repr` -- all defaults `json.dumps`
    already provides with no other argument changed.
    """
    return json.dumps(obj, sort_keys=True).encode("utf-8")


def _refuse_datetimes(obj, where: str) -> None:
    """TOML date/time values have no canonical JSON form; refuse them."""
    import datetime

    if isinstance(obj, (datetime.date, datetime.time)):
        raise core.ClaimError(f"TOML date/time values are refused at sealing: {where}")
    if isinstance(obj, dict):
        for k, v in obj.items():
            _refuse_datetimes(v, f"{where}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _refuse_datetimes(v, f"{where}[{i}]")


def _claim_format(parsed: dict) -> int:
    """The recipe's declared format; absent means 1 (spec/claim-format.md)."""
    return parsed["claim"].get("format", 1)


def _preimage_recipe(parsed: dict):
    """The recipe as it enters the root's preimage.

    Drops the loader's private `_dir` key. At format 3, every step's
    `guidance`/`request` key is stripped first: producer guidance cannot
    decide acceptance, so by the identity rule it does not belong in the
    root (spec/identity.md, "Format 3").
    """
    doc = {k: v for k, v in parsed.items() if k != recipe._DIR_KEY}
    if _claim_format(parsed) >= 3:
        doc["step"] = [
            {k: v for k, v in step.items() if k not in core.GUIDANCE_KEYS}
            for step in doc.get("step", [])
        ]
    _refuse_datetimes(doc, "recipe")
    return doc


def _parts(parsed: dict, d: str) -> dict:
    """The string-to-string map whose canonical serialization is hashed."""
    parts = {"digest": core.DIGEST,
             "recipe": _canonical_json(_preimage_recipe(parsed)).decode("ascii")}
    for path in recipe._inputs(parsed):
        parts[f"input:{path}"] = core._hash_file(os.path.join(d, path))
    for step in parsed.get("step", []):
        if step["class"] not in ("generated", "free"):
            parts[f"pinned:{step['output']}"] = core._hash_file(os.path.join(d, step["output"]))
    return parts


def root(parsed: dict, d: str) -> str:
    """The claim's identity: SHA-256 over the canonical `parts` map."""
    return hashlib.sha256(_canonical_json(_parts(parsed, d))).hexdigest()


def build_digest(d: str) -> str:
    """SHA-256 over the generated bytes present under claim directory `d`.

    One `[output, sha256]` pair per `produce` step whose class is
    `generated`/`free`, in recipe order, excluding any step with a `from`
    source and omitting any output not present on disk; the digest of the
    empty list when none exist (spec/vectors/README.md).
    """
    parsed = recipe.load_recipe(d)
    pairs = []
    for step in recipe.produces(parsed):
        if step["class"] not in ("generated", "free"):
            continue
        if "from" in step:
            continue
        path = os.path.join(d, step["output"])
        if os.path.isfile(path):
            pairs.append([step["output"], core._hash_file(path)])
    return hashlib.sha256(_canonical_json(pairs)).hexdigest()
