"""Kernel identity: the root and the build digest of a claim.

Implements spec/identity.md byte for byte.

* ``root(parsed, d)``       -- the claim's identity: sha256 of the canonical
                               JSON of the ``parts`` map (recipe text, pinned
                               inputs, pinned step outputs).
* ``build_digest(d)``       -- sha256 of the canonical JSON of the sorted
                               ``[path, sha256]`` pairs of the generated
                               outputs present (the empty list when none).
* ``_claim_format(parsed)`` -- the declared format; absent means 1.
* ``_preimage_recipe(parsed)`` -- the recipe as serialized into the preimage:
                               format 3+ strips producer guidance; format 4+
                               additionally sorts the step list by the
                               canonical JSON of each step.
* ``_parts(d, parsed)``     -- the ``parts`` map that ``root`` hashes.

Canonical JSON is ``json.dumps(x, sort_keys=True)`` with default separators
and ASCII escaping, encoded UTF-8. Stdlib only.
"""
import copy
import hashlib
import json

from reticuli._kernel import core, recipe


def _canonical(obj) -> str:
    """The canonical JSON text of ``obj`` (spec/identity.md)."""
    return json.dumps(obj, sort_keys=True)


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _claim_format(parsed: dict) -> int:
    """The declared claim format; absent means 1."""
    claim = parsed.get("claim", {})
    return claim.get("format", 1)


def _canonical_step(step: dict) -> str:
    """The canonical JSON encoding of one step (format-4 sort key)."""
    return json.dumps(step, sort_keys=True)


def _preimage_recipe(parsed: dict) -> dict:
    """The recipe as it is serialized into ``parts["recipe"]``.

    Format 1-2: the whole recipe, unchanged.
    Format 3+:  every step's guidance keys are removed.
    Format 4+:  the step list is additionally sorted by canonical step JSON.
    """
    fmt = _claim_format(parsed)
    doc = copy.deepcopy(parsed)
    steps = doc.get("step")
    if fmt >= 3 and steps is not None:
        for step in steps:
            for key in core.GUIDANCE_KEYS:
                step.pop(key, None)
    if fmt >= 4 and steps is not None:
        doc["step"] = sorted(steps, key=_canonical_step)
    return doc


def _parts(d: str, parsed: dict) -> dict:
    """The string-to-string ``parts`` map that the root hashes."""
    parts = {
        "digest": core.DIGEST,
        "recipe": _canonical(_preimage_recipe(parsed)),
    }
    for rel in recipe._inputs(d, parsed):
        full = recipe._declared_file(d, rel, "input")
        parts["input:" + rel] = core._hash_file(full)
    for step in recipe._steps(parsed):
        if recipe._class(step) == "generated":
            continue
        out = step["output"]
        full = recipe._declared_file(d, out, "pinned output")
        parts["pinned:" + out] = core._hash_file(full)
    return parts


def root(parsed: dict, d: str) -> str:
    """The identity hash of claim directory ``d`` under recipe ``parsed``."""
    return _sha256_text(_canonical(_parts(d, parsed)))


def build_digest(d: str) -> str:
    """The digest of the concrete generated bytes present in claim ``d``.

    Generated outputs only (``from`` outputs excluded); an output with no
    exact directory entry is omitted. The digest of the empty list when none.
    """
    parsed = recipe.load_recipe(d)
    pairs = []
    for out in recipe.generated_outputs(parsed):
        if not recipe._exact_entry(d, out):
            continue
        full = core._safe(d, out)
        pairs.append([out, core._hash_file(full)])
    pairs.sort()
    return _sha256_text(_canonical(pairs))
