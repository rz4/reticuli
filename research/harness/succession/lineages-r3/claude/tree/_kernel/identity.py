"""The identity computation: a claim's root and its build digest.

`root` hashes what the claim *is* -- its recipe (guidance stripped at format
3), its pinned inputs, and its non-generated step outputs -- never the
generated bytes (spec/identity.md). `build_digest` hashes only the generated
bytes actually present, so a signature can bind to a concrete realization
without touching identity. Both route through `_parts`/`_preimage_recipe` so
the one canonical-JSON rule (`spec/identity.md`, "Computation") is applied in
exactly one place.
"""
import copy
import hashlib
import json
import os

from . import core
from . import recipe as _recipe


def _canonical_json(obj) -> str:
    """`json.dumps(obj, sort_keys=True)` -- sorted keys, default separators
    (", " / ": "), non-ASCII escaped, exact-decimal integers, CPython float
    repr: every rule `spec/identity.md` pins, for free, from the stdlib
    default.
    """
    return json.dumps(obj, sort_keys=True)


def _claim_format(parsed: dict) -> int:
    """The recipe's declared format, defaulting to 1 (spec/claim-format.md)."""
    return parsed.get("claim", {}).get("format", 1)


def _preimage_recipe(parsed: dict, fmt: int) -> dict:
    """The recipe as it enters the root preimage: the parsed document minus
    any parser bookkeeping that is not part of the claim's own bytes
    (`_manifest_inputs`), and, at format 3, minus every step's producer
    guidance (`guidance` / `request` -- spec/identity.md, "Format 3").
    Formats 1 and 2 keep guidance, unchanged.
    """
    doc = copy.deepcopy(parsed)
    doc.pop("_manifest_inputs", None)
    if fmt >= 3:
        for step in doc.get("step", []):
            for key in core.GUIDANCE_KEYS:
                step.pop(key, None)
    return doc


def _parts(parsed: dict, d: str) -> dict:
    """The string-to-string map the root hashes (spec/identity.md,
    "Computation"): the algorithm name, the canonically serialized recipe,
    every pinned input's hash, and every non-generated step output's hash.
    """
    fmt = _claim_format(parsed)
    parts = {"digest": core.DIGEST, "recipe": _canonical_json(_preimage_recipe(parsed, fmt))}

    for path in _recipe._inputs(parsed):
        parts["input:" + path] = core._hash_file(core._safe(d, path))

    for step in _recipe._steps(parsed):
        default_class = "generated" if step.get("kind") == "produce" else "pinned"
        if step.get("class", default_class) == "generated":
            continue
        output = step["output"]
        parts["pinned:" + output] = core._hash_file(core._safe(d, output))

    return parts


def root(parsed: dict, d: str) -> str:
    """The claim's identity: `sha256(canonical_json(parts))` (spec/identity.md)."""
    blob = _canonical_json(_parts(parsed, d)).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()


def build_digest(d: str) -> str:
    """The digest a signature binds to: `sha256` over the generated bytes
    actually present. A `produce` step with a `from` source is excluded (its
    bytes are supplied, not generated here); an absent generated output is
    omitted rather than erroring; no generated outputs present hashes the
    empty list.
    """
    parsed = _recipe.load_recipe(d)
    entries = []
    for step in _recipe.produces(parsed):
        if step.get("class", "generated") != "generated":
            continue
        if "from" in step:
            continue
        output = step["output"]
        path = core._safe(d, output)
        if not os.path.isfile(path):
            continue
        entries.append([output, core._hash_file(path)])
    entries.sort(key=lambda e: e[0])
    blob = _canonical_json(entries).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()
