"""Held-out tests: measuring a claim past its own pinned suite (surface layer).

A claim's gates are baked into its root, and they are also the only tests a
producer ever sees while regrowing the generated bytes -- so a perfect score
against them proves the implementation matches the suite, not that it
generalizes past it. `evaluate` runs extra check commands, held out of the
recipe entirely, against the claim's present generated bytes, the same way a
gate runs (`kernel.run_gate`: scrubbed, sandboxed, bounded). The result is a
read, never a verdict: it does not touch the claim's identity, its manifest,
or its ledger.
"""
from . import kernel


def evaluate(d: str, tests) -> list:
    """Run each held-out test (a shell command, as a gate's `run` would be)
    against `d`'s current generated bytes. One entry per test, in order:
    `{"test": ..., "status": "ok"|"failed"|"timeout"|"environment"}`.
    """
    parsed = kernel.load_recipe(d)
    results = []
    for test in tests:
        outcome = kernel.run_gate(test, d, parsed)
        results.append({"test": test, "status": outcome.get("status")})
    return results


def score(d: str, tests) -> dict:
    """The held-out pass rate over `evaluate`'s results: how many of the
    tests the claim never saw still pass against its present bytes.
    """
    results = evaluate(d, tests)
    passed = sum(1 for r in results if r["status"] == "ok")
    total = len(results)
    return {
        "passed": passed,
        "total": total,
        "rate": (passed / total) if total else 1.0,
        "results": results,
    }
