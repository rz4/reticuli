"""Transfer: deterministic tar, verify-on-import, volatile history stays home.

`export` packages a claim's DECLARED content only -- its recipe, pinned
inputs, present step outputs (generated ones withheld when `blind`), its
manifest, its attestations, and (for every declared component) the
component's own CLAIM -- recipe, inputs, manifest, never its generated
bytes -- under `.reticuli/deps/<name>/`. The ledger never travels: it is
local, volatile history, not part of what a claim IS. The archive is
byte-deterministic: same claim, same bytes, regardless of when or on what
host it was built. `import_` extracts and reverifies -- identity, not
trust, is what travels.

Only `reticuli.kernel`'s pinned public surface, plus `reticuli._util`, are
consumed.
"""
import io
import os
import tarfile

from reticuli import kernel
from . import _util
from . import registry

_DEPS_DIR = ".reticuli/deps"
_ATTEST_DIR = ".reticuli/attest"


def _claim_files(d: str, parsed: dict, include_generated: bool) -> list:
    """(arcname, abspath) pairs for a claim's own declared content."""
    files = []
    recipe_name = _util.recipe_filename(d)
    files.append((recipe_name, os.path.join(d, recipe_name)))
    for p in _util.declared_inputs(d, parsed):
        files.append((p, os.path.join(d, p)))
    for step in parsed.get("step", []):
        out = step.get("output")
        cls = step.get("class") or ("generated" if step.get("kind") == "produce" else "pinned")
        if cls == "generated" and not include_generated:
            continue
        full = os.path.join(d, out)
        if os.path.isfile(full):
            files.append((out, full))
    manifest_path = os.path.join(d, kernel.MANIFEST)
    if os.path.isfile(manifest_path):
        files.append((kernel.MANIFEST, manifest_path))
    return files


def _attest_files(d: str) -> list:
    base = os.path.join(d, _ATTEST_DIR)
    out = []
    if os.path.isdir(base):
        for root, _dirs, fnames in os.walk(base):
            for fn in fnames:
                full = os.path.join(root, fn)
                arc = os.path.relpath(full, d).replace(os.sep, "/")
                out.append((arc, full))
    return out


def _find_local_component(d: str, root: str):
    for sub in ("sealed", "deps"):
        base = os.path.join(d, kernel.STORE, sub)
        if not os.path.isdir(base):
            continue
        for name in sorted(os.listdir(base)):
            p = os.path.join(base, name)
            if not os.path.isdir(p):
                continue
            try:
                if kernel.read_manifest(p)["root"] == root:
                    return p
            except kernel.ClaimError:
                continue
    return None


def _component_closure(d: str) -> list:
    """(arcname, abspath) pairs for every declared component's CLAIM --
    never its generated bytes -- recursively."""
    out = []
    seen = set()

    def visit(claim_dir):
        for link in registry.components_of(claim_dir):
            name = link["component"]
            if name in seen:
                continue
            comp_dir = _find_local_component(claim_dir, link["root"])
            if comp_dir is None:
                continue
            seen.add(name)
            parsed = kernel.load_recipe(comp_dir)
            for arcname, path in _claim_files(comp_dir, parsed, include_generated=False):
                out.append((f"{_DEPS_DIR}/{name}/{arcname}", path))
            visit(comp_dir)

    visit(d)
    return out


def export(d: str, tar_path: str, blind: bool = False) -> None:
    """Package `d`'s declared content into a byte-deterministic tar."""
    parsed = kernel.load_recipe(d)

    entries = []
    entries.extend(_claim_files(d, parsed, include_generated=not blind))
    entries.extend(_attest_files(d))
    entries.extend(_component_closure(d))

    seen_names = set()
    ordered = []
    for arcname, path in entries:
        if arcname in seen_names:
            continue
        seen_names.add(arcname)
        ordered.append((arcname, path))
    ordered.sort(key=lambda e: e[0])

    tmp_path = tar_path + ".tmp"
    with tarfile.open(tmp_path, "w") as tf:
        for arcname, path in ordered:
            with open(path, "rb") as f:
                data = f.read()
            info = tarfile.TarInfo(name=arcname)
            info.size = len(data)
            info.mtime = 0
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.mode = 0o644
            info.type = tarfile.REGTYPE
            tf.addfile(info, io.BytesIO(data))
    os.replace(tmp_path, tar_path)


def import_(tar_path: str, dest: str) -> dict:
    """Extract `tar_path` into `dest`, and reverify -- identity, not
    trust, is what travels."""
    os.makedirs(dest, exist_ok=True)
    with tarfile.open(tar_path) as tf:
        try:
            tf.extractall(dest, filter="data")
        except TypeError:
            tf.extractall(dest)
    try:
        ver = kernel.verify(dest)
    except kernel.ClaimError:
        return {"ok": False, "root": None}
    return {"ok": ver["ok"], "root": ver.get("root")}
