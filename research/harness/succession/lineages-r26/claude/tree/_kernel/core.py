class ClaimError(Exception):
    """A refusal with a reason -- the only kernel error."""


# -- the bytes boundary -------------------------------------------------------

def _hash_file(path: str) -> str:
    """sha256 hex digest of a file's bytes.

    Refuses anything that is not a plain regular file with exactly one
    hard link: a FIFO, device, socket, directory, or a hardlink to an
    outside inode must not be silently hashed as if it were claim content.
    """
    st = os.lstat(path)
    import stat as _stat
    if not _stat.S_ISREG(st.st_mode):
        raise ClaimError(f"not a regular file: {path!r}")
    if st.st_nlink != 1:
        raise ClaimError(f"refuses a file with more than one hard link: {path!r}")
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# -- the path boundary ---------------------------------------------------------

def _safe(base: str, name: str) -> str:
    """Resolve `name` to a real path under `base`, or refuse.

    Refuses an absolute or empty name, a `..` component, and any symlink
    component -- even one whose target stays inside the claim, which could
    otherwise alias generated bytes as a pinned name.
    """
    if not name:
        raise ClaimError("a claim path must not be empty")
    if os.path.isabs(name):
        raise ClaimError(f"a claim path must not be absolute: {name!r}")
    parts = name.replace("\\", "/").split("/")
    if any(p in ("", "..") for p in parts) or any(p == "." for p in parts):
        raise ClaimError(f"a claim path must not escape the claim: {name!r}")

    base_real = os.path.realpath(base)
    walked = base_real
    for part in parts:
        walked = os.path.join(walked, part)
        if os.path.islink(walked):
            raise ClaimError(f"a claim path must not pass through a symlink: {name!r}")

    resolved = os.path.realpath(os.path.join(base_real, *parts))
    if resolved != base_real and not resolved.startswith(base_real + os.sep):
        raise ClaimError(f"a claim path must not escape the claim: {name!r}")
    return resolved


# -- atomic JSON write ----------------------------------------------------------

def _write_json(path: str, obj) -> None:
    """Write `obj` as canonical JSON, atomically: never a partial file."""
    directory = os.path.dirname(path) or "."
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".tmp-", suffix=".json")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(obj, f, sort_keys=True, ensure_ascii=True)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


# -- small shared helpers ------------------------------------------------------

def _now() -> str:
    """UTC time of recording, `YYYY-MM-DDTHH:MM:SSZ`."""
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _copy_into(src: str, dst: str) -> None:
    """Copy a directory's contents into `dst`, which must already exist."""
    for entry in os.listdir(src):
        s = os.path.join(src, entry)
        d = os.path.join(dst, entry)
        if os.path.isdir(s) and not os.path.islink(s):
            shutil.copytree(s, d)
        else:
            shutil.copy2(s, d)


def _judging_host() -> dict:
    """A functional probe of the host: what this machine can offer a gate."""
    sandbox = "none"
    if platform.system() == "Darwin" and shutil.which("sandbox-exec"):
        sandbox = "seatbelt"
    elif platform.system() == "Linux" and shutil.which("bwrap"):
        sandbox = "bubblewrap"
    return {
        "platform": platform.system().lower(),
        "machine": platform.machine(),
        "runtime": f"{platform.python_implementation()} {platform.python_version()}",
        "sandbox": sandbox,
    }
