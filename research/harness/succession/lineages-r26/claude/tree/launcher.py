"""Run software that exists only latently in a claim -- see `spec/layers.md`.

A runnable claim is an ordinary claim whose pinned inputs include
`package.toml`, naming an entrypoint. `run` checks a cached build or
regrows a fresh one with a producer; `strip` deletes the generated bytes
back to latency, always safe because the claim -- not the code -- is the
identity. See `checks/launcher_check.py` for the pinned contract this
module exists to satisfy.

Stdlib only.
"""
import json
import os
import platform
import shutil
import subprocess
import sys
import tomllib

from reticuli import kernel

STATE_DIR = ".launcher"
STATE_FILE = "state.json"

EXIT_NOT_RUNNABLE = 3
EXIT_CONSENT_REQUIRED = 4
EXIT_TRUST_REFUSED = 5
EXIT_DRIFT = 6
EXIT_NO_PRODUCER = 7

HELP_TEXT = """\
usage: python3 -m reticuli.launcher <verb> ...

verbs:
  run   <claim> [--accept-generated] [--signed-only] [--no-sandbox] [-- args...]
  strip <claim>
  ls    <claim>...

run executes a runnable claim's package.toml entrypoint.
--accept-generated accepts freshly regrown bytes and executes them.
--signed-only refuses a claim that is not signed to you.
--no-sandbox opts out of sandboxed execution (reported honestly).
strip deletes a claim's generated bytes; ls reports claim identity and phase.
"""


def _err(msg: str) -> None:
    print(msg, file=sys.stderr)


# -- the path boundary, duplicated here because `kernel.load_recipe` is
# deliberately lenient about `generated`-class paths (audit's job, not
# parsing's); the launcher must confine them itself before touching
# anything (strip, regrow, or execute). ----------------------------------


def _safe_path(base: str, name: str) -> str:
    if not name or not isinstance(name, str):
        raise kernel.ClaimError("a claim path must not be empty")
    if os.path.isabs(name):
        raise kernel.ClaimError(f"a claim path must not be absolute: {name!r}")
    parts = name.replace("\\", "/").split("/")
    if any(p in ("", "..") for p in parts) or any(p == "." for p in parts):
        raise kernel.ClaimError(f"a claim path must not escape the claim: {name!r}")
    base_real = os.path.realpath(base)
    walked = base_real
    for part in parts:
        walked = os.path.join(walked, part)
        if os.path.islink(walked):
            raise kernel.ClaimError(f"a claim path must not pass through a symlink: {name!r}")
    resolved = os.path.realpath(os.path.join(base_real, *parts))
    if resolved != base_real and not resolved.startswith(base_real + os.sep):
        raise kernel.ClaimError(f"a claim path must not escape the claim: {name!r}")
    return resolved


def _generated_outputs(parsed: dict) -> list:
    """Declared `generated`-class produce outputs, with no `from`."""
    outs = []
    for step in parsed.get("step", []):
        if step.get("kind") != "produce":
            continue
        if step.get("class", "generated") != "generated":
            continue
        if "from" in step:
            continue
        out = step.get("output")
        if out:
            outs.append(out)
    return outs


# -- the package contract --------------------------------------------------


def _package_contract(d: str, parsed: dict):
    """`(entrypoint_rel, None)` on success, `(None, message)` on refusal."""
    inputs = set(parsed.get("claim", {}).get("inputs", []))
    generated = set(_generated_outputs(parsed))
    if "package.toml" in generated:
        return None, ("package.toml must be a pinned input, not a generated "
                       "output: an entrypoint declaration that could drift "
                       "from what the gate exercised is refused")
    pkg_path = os.path.join(d, "package.toml")
    if not os.path.isfile(pkg_path):
        return None, "no package.toml found in claim: a runnable claim pins package.toml"
    if "package.toml" not in inputs:
        return None, ("package.toml must be a pinned input, not a generated "
                       "output: declare it under [claim] inputs")
    try:
        with open(pkg_path, "rb") as f:
            pkg = tomllib.load(f)
    except (tomllib.TOMLDecodeError, OSError) as e:
        return None, f"malformed package.toml: {e}"
    entry = (pkg.get("package") or {}).get("entrypoint")
    if not isinstance(entry, str) or not entry:
        return None, "package.toml [package] needs a string entrypoint"
    try:
        _safe_path(d, entry)
    except kernel.ClaimError as e:
        return None, f"entrypoint escapes the claim root: {e}"
    return entry, None


# -- launcher state: consent is a durable human act ------------------------


def _load_state(d: str) -> dict:
    path = os.path.join(d, STATE_DIR, STATE_FILE)
    default = {"accepted": None, "pending": None}
    if not os.path.isfile(path):
        return default
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError):
        return default
    if not isinstance(data, dict):
        return default
    return {"accepted": data.get("accepted"), "pending": data.get("pending")}


def _save_state(d: str, state: dict) -> None:
    dirpath = os.path.join(d, STATE_DIR)
    os.makedirs(dirpath, exist_ok=True)
    with open(os.path.join(dirpath, STATE_FILE), "w", encoding="utf-8") as f:
        json.dump(state, f)


# -- regrowing missing generated outputs with a producer -------------------


def _produce(d: str, parsed: dict, producer_cmd: str, missing: list) -> None:
    claim = parsed.get("claim", {})
    for out in missing:
        target = os.path.join(d, out)
        os.makedirs(os.path.dirname(target) or d, exist_ok=True)
        env = os.environ.copy()
        env["RETICULI_CLAIM"] = claim.get("name", "")
        env["RETICULI_OUTPUTS"] = json.dumps(missing)
        env["RETICULI_OUTPUT"] = target
        try:
            proc = subprocess.run(producer_cmd, shell=True, cwd=d, env=env,
                                   capture_output=True, timeout=600)
        except subprocess.TimeoutExpired as e:
            raise kernel.ClaimError(f"producer timed out: {e}") from e
        except OSError as e:
            raise kernel.ClaimError(f"producer failed to start: {e}") from e
        if proc.returncode != 0:
            raise kernel.ClaimError(
                f"producer exited {proc.returncode}: "
                f"{proc.stderr.decode('utf-8', 'replace')}"
            )


# -- sandboxed execution of the entrypoint ----------------------------------


def _seatbelt_usable() -> bool:
    try:
        probe = subprocess.run(
            ["/usr/bin/sandbox-exec", "-p", "(version 1)(allow default)", "/usr/bin/true"],
            capture_output=True, timeout=5,
        )
        return probe.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _bwrap_usable() -> bool:
    try:
        probe = subprocess.run(
            ["bwrap", "--ro-bind", "/", "/", "--unshare-net", "--", "true"],
            capture_output=True, timeout=5,
        )
        return probe.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _sandbox_backend(no_sandbox: bool) -> str:
    if no_sandbox:
        return "off"
    if os.environ.get(kernel._JAILED):
        return "inherited"
    system = platform.system()
    if system == "Darwin" and shutil.which("sandbox-exec") and _seatbelt_usable():
        return "seatbelt"
    if system == "Linux" and shutil.which("bwrap") and _bwrap_usable():
        return "bubblewrap"
    return "none"


def _quote_sb(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _seatbelt_profile(d: str) -> str:
    path = _quote_sb(os.path.realpath(d))
    return "\n".join([
        "(version 1)",
        "(deny default)",
        "(allow process-fork)",
        "(allow process-exec)",
        "(allow signal (target self))",
        "(allow file-read*)",
        f'(allow file-write* (subpath "{path}"))',
        '(allow file-write* (literal "/dev/null"))',
        "(allow sysctl-read)",
        "(allow mach-lookup)",
        "(allow iokit-open)",
        "",
    ])


def _wrap_sandbox(argv: list, backend: str, d: str) -> list:
    if backend == "seatbelt":
        return ["/usr/bin/sandbox-exec", "-p", _seatbelt_profile(d)] + argv
    if backend == "bubblewrap":
        real = os.path.realpath(d)
        return [
            "bwrap",
            "--ro-bind", "/", "/",
            "--dev-bind", "/dev", "/dev",
            "--proc", "/proc",
            "--bind", real, real,
            "--unshare-net",
            "--die-with-parent",
            "--",
        ] + argv
    return argv


def _execute(d: str, entry_rel: str, passthrough: list, backend: str) -> int:
    room = os.path.join(d, STATE_DIR, "room")
    os.makedirs(room, exist_ok=True)
    env = {k: os.environ[k] for k in ("PATH", "LANG", "LC_ALL", "TZ") if k in os.environ}
    env["HOME"] = room
    env["TMPDIR"] = room
    if backend in ("seatbelt", "bubblewrap", "inherited"):
        env[kernel._JAILED] = backend
    argv = ["python3", entry_rel] + list(passthrough)
    wrapped = _wrap_sandbox(argv, backend, d)
    _err(f'quarantine = "{backend}"')
    try:
        proc = subprocess.run(wrapped, cwd=d, env=env)
    except OSError as e:
        _err(f"failed to execute entrypoint: {e}")
        return EXIT_NOT_RUNNABLE
    return proc.returncode


# -- run ----------------------------------------------------------------


def _parse_run_args(args: list):
    claim = None
    accept = signed_only = no_sandbox = False
    passthrough = []
    i = 0
    while i < len(args):
        a = args[i]
        if a == "--":
            passthrough = args[i + 1:]
            break
        if a == "--accept-generated":
            accept = True
        elif a == "--signed-only":
            signed_only = True
        elif a == "--no-sandbox":
            no_sandbox = True
        elif claim is None:
            claim = a
        i += 1
    return claim, accept, signed_only, no_sandbox, passthrough


def cmd_run(args: list) -> int:
    claim, accept, signed_only, no_sandbox, passthrough = _parse_run_args(args)
    if claim is None:
        _err("run requires a claim directory")
        return EXIT_NOT_RUNNABLE
    d = os.path.abspath(claim)
    if not os.path.isdir(d):
        _err(f"no such claim directory: {claim!r}")
        return EXIT_NOT_RUNNABLE

    try:
        parsed = kernel.load_recipe(d)
    except kernel.ClaimError as e:
        _err(f"malformed claim: {e}")
        return EXIT_NOT_RUNNABLE

    try:
        resolved_generated = {out: _safe_path(d, out) for out in _generated_outputs(parsed)}
    except kernel.ClaimError as e:
        _err(f"refuses: {e}")
        return EXIT_NOT_RUNNABLE

    try:
        phase = kernel.phase(d)
    except kernel.ClaimError:
        phase = "draft"
    name = parsed.get("claim", {}).get("name", "?")
    _err(f"reticuli launcher: claim {name!r} phase={phase}")

    entry_rel, msg = _package_contract(d, parsed)
    if entry_rel is None:
        _err(msg)
        return EXIT_NOT_RUNNABLE

    missing = [out for out, path in resolved_generated.items() if not os.path.isfile(path)]
    just_produced = False
    if missing:
        producer = os.environ.get("RETICULI_PRODUCER")
        if not producer:
            _err("latent: no generated outputs present and RETICULI_PRODUCER "
                 "is not set; set RETICULI_PRODUCER to a producer command to regrow")
            return EXIT_NO_PRODUCER
        try:
            _produce(d, parsed, producer, missing)
        except kernel.ClaimError as e:
            _err(f"producer failed: {e}")
            return 1
        just_produced = True

    state = _load_state(d)
    current_digest = kernel.build_digest(d)

    if state["accepted"] is not None and state["accepted"] != current_digest:
        _err("drifted build: an accepted implementation's bytes have changed; "
             "nothing executed, nothing modified; run `strip` to recover")
        return EXIT_DRIFT

    if state["accepted"] == current_digest:
        status = "accepted"
    elif just_produced or state["pending"] == current_digest:
        status = "pending"
        if state["pending"] != current_digest:
            _save_state(d, {"accepted": state["accepted"], "pending": current_digest})
    else:
        status = "standing"

    if status == "pending":
        if accept:
            _save_state(d, {"accepted": current_digest, "pending": None})
        else:
            _err("freshly generated bytes are unaccepted; pass "
                 "--accept-generated to execute and accept them")
            return EXIT_CONSENT_REQUIRED

    if signed_only and phase != "signed":
        _err(f"--signed-only refuses: this claim is not signed to you (phase={phase})")
        return EXIT_TRUST_REFUSED

    backend = _sandbox_backend(no_sandbox)
    return _execute(d, entry_rel, passthrough, backend)


# -- strip ----------------------------------------------------------------


def cmd_strip(args: list) -> int:
    if not args:
        _err("strip requires a claim directory")
        return EXIT_NOT_RUNNABLE
    d = os.path.abspath(args[0])
    if not os.path.isdir(d):
        _err(f"no such claim directory: {args[0]!r}")
        return EXIT_NOT_RUNNABLE
    try:
        parsed = kernel.load_recipe(d)
    except kernel.ClaimError as e:
        _err(f"malformed claim: {e}")
        return EXIT_NOT_RUNNABLE
    try:
        resolved = {out: _safe_path(d, out) for out in _generated_outputs(parsed)}
    except kernel.ClaimError as e:
        _err(f"refuses: {e}")
        return EXIT_NOT_RUNNABLE
    for path in resolved.values():
        if os.path.isfile(path) or os.path.islink(path):
            os.remove(path)
    state_dir = os.path.join(d, STATE_DIR)
    if os.path.isdir(state_dir):
        shutil.rmtree(state_dir)
    _err("stripped: generated bytes removed; claim is latent")
    return 0


# -- ls ----------------------------------------------------------------


def _ls_line(d: str) -> str:
    try:
        manifest = kernel.read_manifest(d)
    except kernel.ClaimError:
        return f"{os.path.basename(d)}  (draft, no sealed manifest)"
    name, root = manifest.get("name", "?"), manifest.get("root", "?")
    try:
        phase = kernel.phase(d)
    except kernel.ClaimError:
        phase = "draft"
    try:
        parsed = kernel.load_recipe(d)
        generated = _generated_outputs(parsed)
        present = [g for g in generated if os.path.isfile(os.path.join(d, g))]
        state = "materialized" if generated and len(present) == len(generated) else "latent"
    except kernel.ClaimError:
        state = "latent"
    return f"{name}  {root[:8]}  phase={phase}  {state}"


def cmd_ls(args: list) -> int:
    if not args:
        _err("ls requires at least one claim directory")
        return EXIT_NOT_RUNNABLE
    lines = [_ls_line(os.path.abspath(a)) for a in args]
    print("\n".join(lines))
    return 0


# -- entry point ----------------------------------------------------------


def main(argv: list) -> int:
    if not argv or argv[0] in ("--help", "-h"):
        print(HELP_TEXT)
        return 0
    verb, rest = argv[0], argv[1:]
    if verb == "run":
        return cmd_run(rest)
    if verb == "strip":
        return cmd_strip(rest)
    if verb == "ls":
        return cmd_ls(rest)
    _err(f"unknown verb: {verb!r}")
    return 2


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except kernel.ClaimError as e:
        _err(str(e))
        sys.exit(EXIT_NOT_RUNNABLE)
