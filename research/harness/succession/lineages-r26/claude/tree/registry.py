"""The claim registry: claims meeting claims within one workspace.

A workspace (`ws`) holds sealed claims under `.reticuli/sealed/<name>` (and,
after a transfer, blind component residue under `.reticuli/deps/<name>` --
the component's claim without its generated bytes). `detect_components`
finds a content-addressed link between a pinned input and a sealed
component's output; `seal_with` records such links (and a recorded proof)
onto a claim's manifest; `claims`/`deps` are read views of the store;
`rebuild_chain` is the DAG-aware rebuild (leaves first); `pull` brings a
claim's whole closure into a fresh workspace, compactly; `sign_root` folds
a signed identity bottom-up over the DAG; `audit_deep`/`crosscheck_deep`
re-earn a composed claim's ENTIRE chain, not just its direct components --
gates compose, verdicts never carry.

Only `reticuli.kernel`'s pinned public surface, plus `reticuli._util`, are
consumed -- no layer imports a kernel private (`spec/layers.md`).
"""
import os
import shutil
import tempfile

from reticuli import kernel
from . import _util


# ==============================================================================
# the store: finding a sealed or transferred component by name or by root
# ==============================================================================


def _iter_store(ws: str, subdirs=("sealed", "deps")):
    """(name, path) pairs for every claim directory in `ws`'s store."""
    for sub in subdirs:
        base = os.path.join(ws, kernel.STORE, sub)
        if not os.path.isdir(base):
            continue
        for name in sorted(os.listdir(base)):
            p = os.path.join(base, name)
            if os.path.isdir(p):
                yield name, p


def _find_component(ws: str, root: str):
    """The directory in `ws`'s store whose manifest names `root`.

    Resolved by ROOT, wherever it lives in the store -- never by name
    alone, and never by physical nesting (`spec/verification.md`'s
    flat-store-resolution finding).
    """
    for _name, p in _iter_store(ws):
        try:
            if kernel.read_manifest(p)["root"] == root:
                return p
        except kernel.ClaimError:
            continue
    return None


# ==============================================================================
# detect_components: a content-addressed link between a pinned input and a
# sealed component's output
# ==============================================================================


def detect_components(ws: str, paths) -> list:
    """Every (input path, sealed component) pair whose bytes match."""
    links = []
    comps = list(_iter_store(ws))
    for path in paths:
        full = os.path.join(ws, path)
        if not os.path.isfile(full):
            continue
        h = _util.hash_bytes(full)
        for name, comp_dir in comps:
            try:
                manifest = kernel.read_manifest(comp_dir)
            except kernel.ClaimError:
                continue
            parts = manifest.get("parts", {})
            match = None
            for key, value in parts.items():
                if value == h and (key.startswith("pinned:") or key.startswith("input:")):
                    match = key.split(":", 1)[1]
                    break
            if match is not None:
                links.append({"input": path, "component": manifest.get("name", name),
                              "root": manifest["root"], "output": match})
                break
    return links


# ==============================================================================
# seal_with: seal, then record component links and/or a recorded proof
#
# Recorded in a side file (`.reticuli/registry.json`) that survives a BARE
# `kernel.seal()` call made outside this module -- identity moves, the
# attribution stays, because the kernel's own manifest write never touches
# it. Also patched onto the manifest itself, so a reader that only knows
# `kernel.read_manifest` still sees the provenance a rebuild preserved.
# ==============================================================================


def _meta_path(d: str) -> str:
    return os.path.join(d, kernel.STORE, "registry.json")


def _read_meta(d: str) -> dict:
    path = _meta_path(d)
    if os.path.isfile(path):
        try:
            return _util.read_json(path)
        except kernel.ClaimError:
            return {}
    return {}


def components_of(d: str) -> list:
    """`d`'s declared component links -- durable across a bare reseal."""
    meta = _read_meta(d)
    if "components" in meta:
        return meta["components"]
    try:
        return kernel.read_manifest(d).get("components", [])
    except kernel.ClaimError:
        return []


def proof_of(d: str):
    """`d`'s recorded proof, if any -- durable across a bare reseal."""
    meta = _read_meta(d)
    if "proof" in meta:
        return meta["proof"]
    try:
        return kernel.read_manifest(d).get("proof")
    except kernel.ClaimError:
        return None


def _record_meta(d: str, components=None, proof=None) -> None:
    meta = _read_meta(d)
    if components is not None:
        meta["components"] = components
    if proof is not None:
        meta["proof"] = proof
    _util.write_json(_meta_path(d), meta)
    manifest = kernel.read_manifest(d)
    if "components" in meta:
        manifest["components"] = meta["components"]
    if "proof" in meta:
        manifest["proof"] = meta["proof"]
    _util.write_json(os.path.join(d, kernel.MANIFEST), manifest)


def seal_with(d: str, components=None, proof=None) -> dict:
    """`kernel.seal`, plus recording declared component links and/or a
    recorded proof -- store metadata, outside the root."""
    kernel.seal(d)
    if components is not None or proof is not None:
        _record_meta(d, components=components, proof=proof)
    return kernel.read_manifest(d)


# ==============================================================================
# claims / deps: read views of a workspace's sealed store
# ==============================================================================


def claims(ws: str) -> list:
    """Every sealed claim in `ws`'s store: name, root, and live phase."""
    out = []
    for name, d in _iter_store(ws, subdirs=("sealed",)):
        try:
            manifest = kernel.read_manifest(d)
        except kernel.ClaimError:
            continue
        out.append({"name": manifest.get("name", name), "root": manifest.get("root"),
                    "phase": kernel.phase(d)})
    return out


def deps(ws: str) -> dict:
    """The DAG: every sealed claim and the resolution status of its
    declared components."""
    out = []
    for name, d in _iter_store(ws, subdirs=("sealed",)):
        try:
            manifest = kernel.read_manifest(d)
        except kernel.ClaimError:
            continue
        rows = []
        for link in components_of(d):
            comp = _find_component(ws, link["root"])
            rows.append({"component": link["component"], "root": link["root"],
                        "status": "ok" if comp is not None else "missing"})
        out.append({"name": manifest.get("name", name), "depends_on": rows})
    return {"claims": out}


# ==============================================================================
# rebuild_chain: the DAG-aware rebuild -- leaves first
# ==============================================================================


def rebuild_chain(d: str, producer: str, into: str, ws: str = None, reuse: bool = False,
                   produce_from: dict = None, input_from: dict = None,
                   guidance: bool = True, producer_env: dict = None) -> dict:
    """Regrow `d`'s whole chain: every declared component, leaf first, then
    `d` itself -- reusing a sealed component's bytes instead of rebuilding
    it when `reuse` is true and the producer has no rule for its output."""
    ws = ws or d
    parsed = kernel.load_recipe(d)
    links = components_of(d)

    produce_from = dict(produce_from or {})
    rebuilt_components = []
    staged = {}
    stage_root = tempfile.mkdtemp(prefix="reticuli-chain-")
    try:
        for link in links:
            name = link["component"]
            if name not in staged:
                comp_src = _find_component(ws, link["root"])
                if comp_src is None:
                    raise kernel.ClaimError(
                        f"rebuild_chain: missing declared component {name!r}")
                comp_into = os.path.join(stage_root, name)
                if reuse:
                    shutil.copytree(comp_src, comp_into)
                    comp_root = kernel.read_manifest(comp_src)["root"]
                else:
                    sub = rebuild_chain(comp_src, producer, comp_into, ws=ws, reuse=reuse,
                                         guidance=guidance, producer_env=producer_env)
                    rebuilt_components.extend(sub["rebuilt_components"])
                    comp_root = sub["root"]
                staged[name] = comp_into
                rebuilt_components.append({"component": name, "root": comp_root})
            comp_into = staged[name]

            step = next((s for s in parsed.get("step", [])
                         if s.get("kind") == "produce" and s.get("output") == link["input"]
                         and s.get("from") == name), None)
            if step is not None:
                produce_from[link["input"]] = os.path.join(comp_into, link["output"])

        result = kernel.rebuild(d, producer, into, produce_from=produce_from,
                                 input_from=input_from, guidance=guidance,
                                 producer_env=producer_env)

        if links:
            for name, comp_into in staged.items():
                dest = os.path.join(into, kernel.STORE, "sealed", name)
                if not os.path.isdir(dest):
                    shutil.copytree(comp_into, dest)
            _record_meta(into, components=links)
    finally:
        shutil.rmtree(stage_root, ignore_errors=True)

    return {"root": result["root"], "name": result.get("name"),
            "gates": result.get("gates"), "rebuilt_components": rebuilt_components}


# ==============================================================================
# pull: a claim becomes a dependency of a fresh workspace, compactly
# ==============================================================================


def _materialize_claim(src: str, dest: str) -> None:
    """Copy a claim's declared content -- recipe, pinned inputs, and every
    present step output -- into `dest`. Never the undeclared bytes a bare
    directory walk would pick up."""
    parsed = kernel.load_recipe(src)
    os.makedirs(dest, exist_ok=True)
    recipe_name = _util.recipe_filename(src)
    shutil.copy2(os.path.join(src, recipe_name), os.path.join(dest, recipe_name))
    for p in _util.declared_inputs(src, parsed):
        s = _util.safe_path(src, p)
        t = os.path.join(dest, p)
        os.makedirs(os.path.dirname(t) or dest, exist_ok=True)
        shutil.copy2(s, t)
    for step in parsed.get("step", []):
        out = step.get("output")
        full = os.path.join(src, out)
        if os.path.isfile(full):
            t = os.path.join(dest, out)
            os.makedirs(os.path.dirname(t) or dest, exist_ok=True)
            shutil.copy2(full, t)
    manifest_src = os.path.join(src, kernel.MANIFEST)
    if os.path.isfile(manifest_src):
        os.makedirs(os.path.join(dest, kernel.STORE), exist_ok=True)
        shutil.copy2(manifest_src, os.path.join(dest, kernel.MANIFEST))


def _pull_into_store(claim_dir: str, ws: str, name: str, seen: set) -> None:
    if name in seen:
        return
    seen.add(name)
    dest_dir = os.path.join(ws, kernel.STORE, "sealed", name)
    if not os.path.isdir(dest_dir):
        _materialize_claim(claim_dir, dest_dir)
    for link in components_of(claim_dir):
        comp_name = link["component"]
        if comp_name in seen:
            continue
        comp_src = _find_component(claim_dir, link["root"])
        if comp_src is not None:
            _pull_into_store(comp_src, ws, comp_name, seen)


def pull(src: str, dest: str, ws: str = None) -> dict:
    """Bring `src` into `dest`: its own files at `dest`'s root, and its
    whole closure (itself included) stored flat and compactly in `dest`'s
    store -- a dependency never appears more than once per name."""
    ws = ws or dest
    manifest = kernel.read_manifest(src)
    name = manifest["name"]
    _materialize_claim(src, dest)
    _pull_into_store(src, ws, name, set())
    return {"materialized": True, "root": manifest["root"]}


# ==============================================================================
# sign_root: the bottom-anchored signature chain, folded over the DAG
# ==============================================================================


def sign_root(d: str, ws: str = None) -> str:
    """The signed-identity node for `d`, folding every declared
    component's own node in bottom-up -- refuses a chain over an
    incomplete DAG rather than eliding the missing link."""
    ws = ws or d
    seen = set()
    child_nodes = []
    for link in components_of(d):
        name = link["component"]
        if name in seen:
            continue
        seen.add(name)
        comp_dir = _find_component(ws, link["root"])
        if comp_dir is None:
            raise kernel.ClaimError(
                f"sign_root: missing declared component {name!r}")
        child_nodes.append(sign_root(comp_dir, ws))
    root = kernel.verify(d)["root"]
    bd = kernel.build_digest(d)
    return kernel.sign_node(root, bd, child_nodes)


# ==============================================================================
# audit_deep: the deep audit -- gates compose, verdicts never carry
# ==============================================================================


def _recipe_parsed(d: str) -> dict:
    return kernel.load_recipe(d)


def _reearn_gate(comp_dir: str, shipper_dir: str, shipped_path: str, output: str) -> bool:
    """Re-run `comp_dir`'s own gates in a fresh room assembled from its own
    pinned inputs and present generated outputs, with `output` overridden
    by the SHIPPED bytes -- the dependent's own file, not the component's."""
    comp_parsed = _recipe_parsed(comp_dir)
    room = tempfile.mkdtemp(prefix="reticuli-deep-")
    try:
        recipe_name = _util.recipe_filename(comp_dir)
        shutil.copy2(os.path.join(comp_dir, recipe_name), os.path.join(room, recipe_name))
        for p in _util.declared_inputs(comp_dir, comp_parsed):
            s = _util.safe_path(comp_dir, p)
            t = os.path.join(room, p)
            os.makedirs(os.path.dirname(t) or room, exist_ok=True)
            shutil.copy2(s, t)
        for step in comp_parsed.get("step", []):
            if step.get("kind") != "produce":
                continue
            out = step.get("output")
            full = os.path.join(comp_dir, out)
            if os.path.isfile(full):
                t = os.path.join(room, out)
                os.makedirs(os.path.dirname(t) or room, exist_ok=True)
                shutil.copy2(full, t)

        shipped_src = _util.safe_path(shipper_dir, shipped_path)
        override_dst = os.path.join(room, output)
        os.makedirs(os.path.dirname(override_dst) or room, exist_ok=True)
        shutil.copy2(shipped_src, override_dst)

        for step in comp_parsed.get("step", []):
            if step.get("kind") != "gate":
                continue
            outcome = kernel.run_gate(step["run"], room, comp_parsed)
            if outcome["status"] != "ok":
                return False
        return True
    finally:
        shutil.rmtree(room, ignore_errors=True)


def _reearn_match(comp_dir: str, shipper_dir: str, shipped_path: str, output: str) -> bool:
    """Re-earn a DATA dependency's content match: the shipped bytes must
    still hash the same as the component's own current output."""
    try:
        a = _util.hash_bytes(_util.safe_path(shipper_dir, shipped_path))
        b = _util.hash_bytes(_util.safe_path(comp_dir, output))
    except kernel.ClaimError:
        return False
    return a == b


def _audit_link(ws: str, shipper_dir: str, shipped_path: str, link: dict) -> list:
    """Every layer entry this one declared link resolves to -- a pass-
    through component emits its OWN entry and then recurses to the
    component it in turn attributes the same output to."""
    name = link["component"]
    comp_dir = _find_component(ws, link["root"])
    if comp_dir is None:
        return [{"name": name, "root": link["root"], "ok": False,
                "status": "unresolved", "bytes_from": [shipped_path]}]

    comp_parsed = _recipe_parsed(comp_dir)
    output = link["output"]
    step = next((s for s in comp_parsed.get("step", [])
                 if s.get("kind") == "produce" and s.get("output") == output), None)

    if step is not None and "from" in step:
        ok = _reearn_gate(comp_dir, shipper_dir, shipped_path, output)
        this_entry = {"name": name, "root": link["root"], "ok": ok,
                      "status": "ok" if ok else "failed", "bytes_from": [shipped_path]}
        deeper = next((l for l in components_of(comp_dir)
                       if l.get("output") == output), None)
        if deeper is None:
            this_entry["ok"] = False
            this_entry["status"] = "unresolved"
            return [this_entry]
        return [this_entry] + _audit_link(ws, shipper_dir, shipped_path, deeper)

    if step is not None:
        ok = _reearn_gate(comp_dir, shipper_dir, shipped_path, output)
        status = "ok" if ok else "failed"
    else:
        ok = _reearn_match(comp_dir, shipper_dir, shipped_path, output)
        status = "ok" if ok else "attribution mismatch"
    return [{"name": name, "root": link["root"], "ok": ok,
            "status": status, "bytes_from": [shipped_path]}]


def audit_deep(d: str, ws: str = None) -> dict:
    """Re-earn `d`'s ENTIRE chain: every declared component, and every
    ancestor a `from` step attributes an output's origin to, however deep
    -- a broken grandparent fails the composed verdict."""
    ws = ws or d
    layers = []
    ok = True
    for link in components_of(d):
        entries = _audit_link(ws, d, link["input"], link)
        layers.extend(entries)
        if not all(e["ok"] for e in entries):
            ok = False
    return {"ok": ok, "layers": layers}


# ==============================================================================
# crosscheck_deep: the three-machine test, with a deep audit on every leg
# ==============================================================================


def crosscheck_deep(m1, m2, m3, **kwargs) -> dict:
    """`kernel.crosscheck`, plus requiring every directory leg's deep
    audit to hold -- a forged layer a shallow crosscheck cannot see still
    fails the composed verdict."""
    base = kernel.crosscheck(m1, m2, m3, **kwargs)
    deep_ok = True
    for leg in (m1, m2, m3):
        if os.path.isdir(leg):
            try:
                d = audit_deep(leg)
            except kernel.ClaimError:
                d = {"ok": False}
            if not d.get("ok", True):
                deep_ok = False
    result = dict(base)
    result["deep_ok"] = deep_ok
    result["satisfied"] = base["satisfied"] and deep_ok
    return result
