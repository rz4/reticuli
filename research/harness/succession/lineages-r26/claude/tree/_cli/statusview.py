"""Rendering `status`, a draft, a dependency DAG, and a file tree.

`status` has its own family apart from `report.py`'s action verbs because
it never DOES anything -- it only reads a claim (or a workspace's whole
store) and shows it, at two altitudes: `_t_status_claim` is the terse
one-liner a plain `status` prints, `_v_status_claim` is the `-v` walk
over every gate, signature, and ledger entry. `_r_status_draft` is the
one-line answer for a claim that has never been sealed. `_r_claims`/
`_r_deps`/`_r_structure` render a workspace's store as a whole;
`_r_tree`/`_files_claim` render one claim's declared files.

Reaches `reticuli.kernel`'s pinned public surface, `reticuli.registry`
(claims meeting claims, within one workspace), `reticuli.render`'s
formatting primitives, and `reticuli._util`'s shared helpers -- never a
`reticuli._kernel` private. Stdlib only.
"""
import os

from reticuli import kernel, registry, _util
from reticuli import render as _render
from . import report as _report

_DECLARED_ROLE = {
    "pinned": "pinned input",
    "generated": "generated by the producer",
    "validated": "gate verdict",
}


# -- one claim's declared files ------------------------------------------------


def _files_claim(d: str) -> list:
    """Every path `d`'s recipe declares, each tagged with its step class
    and whether the bytes are actually present on disk right now."""
    try:
        parsed = kernel.load_recipe(d)
    except kernel.ClaimError:
        return []

    rows = []
    for p in _util.declared_inputs(d, parsed):
        rows.append({"path": p, "class": "pinned",
                     "role": _DECLARED_ROLE["pinned"],
                     "present": os.path.isfile(os.path.join(d, p))})
    for step in parsed.get("step", []):
        output = step.get("output")
        if not output:
            continue
        default = "generated" if step.get("kind") == "produce" else "pinned"
        cls = step.get("class", default)
        rows.append({"path": output, "class": cls,
                     "role": _DECLARED_ROLE.get(cls, cls),
                     "present": os.path.isfile(os.path.join(d, output))})
    return rows


def _r_tree(d: str) -> str:
    """`d`'s declared files, as an indented tree -- one leaf per path
    component, each labeled with the role its step class names."""
    files = _files_claim(d)
    if not files:
        return "(no declared files)"
    nested = {}
    for row in sorted(files, key=lambda r: r["path"]):
        parts = row["path"].split("/")
        node = nested
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        mark = "" if row["present"] else " (missing)"
        node[f"{parts[-1]} -- {row['role']}{mark}"] = None
    return _render.tree(nested)


def _r_structure(d: str) -> str:
    """`d`'s recipe, as a kind/output/class table -- the claim's own
    shape, distinct from `_r_tree`'s view of its bytes on disk."""
    try:
        parsed = kernel.load_recipe(d)
    except kernel.ClaimError as e:
        return f"- (no recipe: {e})"
    rows = []
    for step in parsed.get("step", []):
        default = "generated" if step.get("kind") == "produce" else "pinned"
        rows.append((step.get("kind", "?"), step.get("output", "?"),
                     step.get("class", default)))
    if not rows:
        return "(no steps declared)"
    return _render.table(rows, headers=("kind", "output", "class"))


# -- a workspace's whole store -------------------------------------------------


def _r_claims(ws: str) -> str:
    rows = registry.claims(ws)
    if not rows:
        return "no sealed claims"
    table_rows = [(r.get("name", "?"), _render.short(r.get("root") or "-"),
                   r.get("phase", "-")) for r in rows]
    return _render.table(table_rows, headers=("name", "root", "phase"))


def _r_deps(ws: str) -> str:
    data = registry.deps(ws)
    claims = data.get("claims", [])
    if not claims:
        return "no sealed claims"
    nested = {}
    for c in claims:
        children = {}
        for row in c.get("depends_on", []):
            label = (f"{row.get('component')} ({row.get('status')}, "
                     f"{_render.short(row.get('root') or '-')})")
            children[label] = None
        nested[c.get("name", "?")] = children or None
    return _render.tree(nested)


# -- the ledger, summarized ----------------------------------------------------


def _ledger_status_claim(d: str) -> str:
    """A one-line tally of `d`'s cost-ledger events, by kind."""
    events = kernel.ledger_events(d)
    if not events:
        return "no ledger events"
    counts = {}
    for e in events:
        key = e.get("event", "?")
        counts[key] = counts.get(key, 0) + 1
    return ", ".join(f"{k}×{v}" for k, v in sorted(counts.items()))


# -- status, at two altitudes --------------------------------------------------


def _r_status_draft(view: dict) -> str:
    """The one-line answer for a claim that has never been sealed."""
    return (f"{view.get('name', '?')}: draft -- not yet sealed; "
            f"next: {view.get('next', 'seal')}")


def _t_status_claim(view: dict) -> str:
    """The terse, plain `status` line: name, verdict, short root."""
    phase = view.get("phase", "draft")
    if phase == "draft":
        return _r_status_draft(view)
    ok = bool((view.get("verified") or {}).get("ok"))
    label = phase if ok else "broken"
    root = view.get("root")
    suffix = f" {_render.short(root)}" if root else ""
    return f"{view.get('name', '?')}: {label}{suffix}"


def _v_status_claim(view: dict, d: str = None) -> str:
    """The `-v` walk: every gate, every signature, the mutation-score
    residue if any, and (given `d`) the ledger tally."""
    lines = [_t_status_claim(view), _report._row("root", view.get("root"))]
    for g in view.get("gates", []):
        lines.append(f"  gate {g.get('output')}: {g.get('deciding')}")
    for s in view.get("signatures", []):
        proof = "recorded" if s.get("proof_recorded") else "not recorded"
        lines.append(f"  signed by {s.get('identity')} (proof {proof})")
    residue = view.get("residue")
    if residue:
        lines.append(_report._row("mutation score",
                                   f"{residue.get('rate')} ({residue.get('mutants')} mutants)"))
    if d is not None:
        lines.append(_report._row("ledger", _ledger_status_claim(d)))
    lines.append(_report._row("next", view.get("next")))
    return "\n".join(lines)
