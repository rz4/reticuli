class ClaimError(Exception):
    """A refusal with a reason -- the only kernel error."""


def _hash_file(path: str) -> str:
    """The bytes boundary: a plain sha256 of a regular file's bytes.

    Refuses anything that is not a single-hard-link regular file (a FIFO,
    device, socket, directory, or a hardlink to an outside inode) -- the
    filesystem-aliasing rules of spec/identity.md.
    """
    st = os.lstat(path)
    if os.path.islink(path) or not os.path.isfile(path):
        raise ClaimError(f"not a regular file: {path}")
    if st.st_nlink != 1:
        raise ClaimError(f"refused: {path} has more than one hard link")
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _safe(claim_dir: str, name: str) -> str:
    """The path boundary: a recipe-declared name resolves under the claim.

    Refuses an absolute path, an empty name, any `..` or `.` component, and
    any component that is a symlink -- even one whose target stays inside
    the claim, since it could alias generated bytes as a pinned name.
    """
    if not isinstance(name, str) or name == "" or os.path.isabs(name):
        raise ClaimError(f"refused path: {name!r}")
    parts = name.split("/")
    if any(p in ("", ".", "..") for p in parts):
        raise ClaimError(f"refused path: {name!r}")

    base = os.path.realpath(claim_dir)
    cur = base
    for part in parts:
        cur = os.path.join(cur, part)
        if os.path.islink(cur):
            raise ClaimError(f"refused symlink component: {name!r}")

    resolved = os.path.realpath(os.path.join(base, name))
    if resolved != base and not resolved.startswith(base + os.sep):
        raise ClaimError(f"refused path escaping claim: {name!r}")
    return resolved


def _write_json(path: str, obj) -> None:
    """Write JSON atomically: build the bytes off to the side, then rename."""
    d = os.path.dirname(path) or "."
    fd, tmp = tempfile.mkstemp(prefix=".tmp-", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(obj, f, sort_keys=True, indent=2)
            f.write("\n")
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _now() -> str:
    """UTC time of recording, `YYYY-MM-DDTHH:MM:SSZ` (spec/record.md)."""
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _copy_into(src: str, dst: str) -> None:
    """Copy a file or directory tree at src to the path dst, stdlib only."""
    if os.path.isdir(src) and not os.path.islink(src):
        shutil.copytree(src, dst, symlinks=False)
    else:
        shutil.copy2(src, dst)


def _judging_host() -> dict:
    """The host that ran the gates: `platform`, `machine`, `runtime`."""
    return {
        "platform": sys.platform,
        "machine": platform.machine(),
        "runtime": f"CPython {platform.python_version()}",
    }
