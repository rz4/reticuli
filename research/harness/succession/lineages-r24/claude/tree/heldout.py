"""reticuli.heldout: measuring a claim's strength against tests it never pinned.

A pinned acceptance suite can be satisfied by a producer that only reads the
suite; a held-out case -- a command the claim's own recipe never declares --
run against the same generated bytes tells you whether the claim generalizes
past exactly what it pinned. A held-out result is diagnostic only: it never
enters the root, the ledger, or any gate's verdict.

Stdlib only; builds on the public kernel surface, never a kernel private.
"""
import subprocess


def run_case(d, run, timeout=None):
    """Run one held-out command the way a gate runs (cwd=d), but outside
    the sealed root and outside the ledger."""
    try:
        proc = subprocess.run(run, shell=True, cwd=d, capture_output=True,
                               text=True, timeout=timeout)
        status = "ok" if proc.returncode == 0 else "failed"
        return {"run": run, "status": status, "returncode": proc.returncode}
    except subprocess.TimeoutExpired:
        return {"run": run, "status": "timeout", "returncode": None}


def evaluate(d, cases, timeout=None):
    """Run every held-out case in `cases` against `d`'s present bytes;
    report pass/fail counts plus per-case detail. Never affects `verify`
    or any pinned verdict."""
    results = [run_case(d, c, timeout=timeout) for c in cases]
    passed = sum(1 for r in results if r["status"] == "ok")
    return {
        "total": len(results),
        "passed": passed,
        "failed": len(results) - passed,
        "cases": results,
    }
