"""reticuli.launcher: run software that exists only latently in a claim
(spec/claim-format.md's `[package]` table; checks/launcher_check.py is this
module's definition).

Verbs: `run <claim> [--accept-generated] [--signed-only] [--no-sandbox]
[-- args...]`, `strip <claim>`, `ls <claim>...`. Stdlib only; the only
import from the package is the public kernel surface (`reticuli.kernel`) --
no layer imports a kernel private (spec/layers.md).
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import tomllib

from reticuli import kernel

LAUNCHER_DIR = ".launcher"
STATE_FILE = "state.json"
RUN_FLAGS = ("--accept-generated", "--signed-only", "--no-sandbox")

HELP = """reticuli.launcher -- run software that is only latent in a claim.

verbs:
  run   <claim> [--accept-generated] [--signed-only] [--no-sandbox] [-- args...]
  strip <claim>
  ls    <claim>...

flags (run):
  --accept-generated   execute and accept freshly generated bytes
  --signed-only        refuse a claim that is not signed to you
  --no-sandbox         run the entrypoint unconfined (reports quarantine = "off")
"""


class _Refusal(Exception):
    """A launcher refusal: an exit code and the reason spoken on stderr."""

    def __init__(self, code, message):
        super().__init__(message)
        self.code = code
        self.message = message


def _stderr(message):
    print(message, file=sys.stderr)


# ==== path confinement: every recipe- or package-derived name stays inside
# ==== the claim, or the launcher refuses before touching anything =========

def _confine(root_real, name):
    if not isinstance(name, str) or name == "" or os.path.isabs(name):
        raise _Refusal(3, f"refused path: {name!r}")
    parts = name.split("/")
    if any(p in ("", ".", "..") for p in parts):
        raise _Refusal(3, f"refused path: {name!r}")
    cur = root_real
    for part in parts:
        cur = os.path.join(cur, part)
        if os.path.islink(cur):
            raise _Refusal(3, f"refused symlink component: {name!r}")
    resolved = os.path.realpath(os.path.join(root_real, name))
    if resolved != root_real and not resolved.startswith(root_real + os.sep):
        raise _Refusal(3, f"refused path escaping claim: {name!r}")
    return resolved


def _generated_outputs(parsed):
    outs = []
    for step in parsed.get("step", []):
        if step.get("kind") != "produce":
            continue
        cls = step.get("class")
        if cls is None:
            cls = "generated"
        if cls == "generated":
            outs.append(step["output"])
    return outs


# ==== the package contract: a pinned package.toml, a confined entrypoint ==

def _load_claim(claim_dir):
    try:
        return kernel.load_recipe(claim_dir)
    except kernel.ClaimError as e:
        raise _Refusal(3, f"not runnable: {e}")


def _package_pinned(parsed):
    inputs = parsed.get("claim", {}).get("inputs") or []
    if "package.toml" in inputs:
        return True
    for step in parsed.get("step", []):
        if step.get("output") != "package.toml":
            continue
        cls = step.get("class")
        if cls is None:
            cls = "generated" if step.get("kind") == "produce" else "pinned"
        return cls in ("pinned", "validated")
    return False


def _package_contract(claim_dir, parsed, claim_real):
    if not _package_pinned(parsed):
        raise _Refusal(3, "not runnable: package.toml must be a pinned input "
                          "(declare it in [claim] inputs) -- not generated, "
                          "not absent")
    pkg_path = os.path.join(claim_dir, "package.toml")
    if not os.path.isfile(pkg_path):
        raise _Refusal(3, "not runnable: package.toml is declared but missing")
    try:
        with open(pkg_path, "rb") as f:
            pkg = tomllib.load(f)
    except Exception as e:
        raise _Refusal(3, f"not runnable: malformed package.toml: {e}")
    entrypoint = (pkg.get("package") or {}).get("entrypoint")
    if not isinstance(entrypoint, str) or not entrypoint:
        raise _Refusal(3, "not runnable: package.toml names no [package] entrypoint")
    return _confine(claim_real, entrypoint)


# ==== launcher state: freshness and acceptance, under <claim>/.launcher/ ==

def _state_path(claim_dir):
    return os.path.join(claim_dir, LAUNCHER_DIR, STATE_FILE)


def _read_state(claim_dir):
    path = _state_path(claim_dir)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError):
        return None
    if (not isinstance(data, dict) or data.get("status") not in ("fresh", "accepted")
            or not isinstance(data.get("digest"), str)):
        return None
    return data


def _write_state(claim_dir, status, digest):
    d = os.path.join(claim_dir, LAUNCHER_DIR)
    os.makedirs(d, exist_ok=True)
    data = {"status": status, "digest": digest}
    with open(_state_path(claim_dir), "w", encoding="utf-8") as f:
        json.dump(data, f)
    return data


# ==== regrowing: a fresh room, landed onto the claim, never auto-accepted =

def _regrow(claim_dir, confined_outputs, producer):
    room = tempfile.mkdtemp(prefix="reticuli-launcher-room-")
    try:
        result = kernel.rebuild(claim_dir, producer, room)
        manifest = kernel.read_manifest(claim_dir)
        if manifest.get("root") != result.get("root"):
            raise _Refusal(6, "regrown bytes diverge from the sealed root")
        for name, dst in confined_outputs:
            src = os.path.join(room, name)
            if os.path.isfile(src):
                parent = os.path.dirname(dst)
                if parent:
                    os.makedirs(parent, exist_ok=True)
                shutil.copy2(src, dst)
    except kernel.ClaimError as e:
        raise _Refusal(6, f"regrow failed: {e}")
    finally:
        shutil.rmtree(room, ignore_errors=True)


# ==== execution: scrubbed, sandboxed where the host provides one =========

def _seatbelt_profile(real_d):
    def q(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return "\n".join([
        "(version 1)",
        "(allow default)",
        "(deny network*)",
        "(deny file-write*)",
        f"(allow file-write* (subpath {q(real_d)}))",
        f"(allow file-write* (literal {q('/dev/null')}))",
    ])


def _wrap_sandbox(argv, real_d, backend):
    if backend == "seatbelt":
        return ["sandbox-exec", "-p", _seatbelt_profile(real_d)] + argv
    if backend == "bubblewrap":
        return (["bwrap", "--ro-bind", "/", "/", "--dev", "/dev", "--proc", "/proc",
                 "--unshare-net", "--die-with-parent", "--bind", real_d, real_d,
                 "--chdir", real_d] + argv)
    return argv


def _execute(claim_real, entry_path, entry_args, no_sandbox):
    if no_sandbox:
        backend = "off"
    else:
        _functional, backend = kernel.sandbox()

    launcher_dir = os.path.join(claim_real, LAUNCHER_DIR)
    os.makedirs(launcher_dir, exist_ok=True)
    scratch = tempfile.mkdtemp(prefix="run-", dir=launcher_dir)

    env = {k: os.environ[k] for k in ("PATH", "LANG", "LC_ALL", "TZ") if k in os.environ}
    env["HOME"] = scratch
    env["TMPDIR"] = scratch
    if os.environ.get(kernel._JAILED):
        env[kernel._JAILED] = os.environ[kernel._JAILED]
    if backend in ("seatbelt", "bubblewrap"):
        env[kernel._JAILED] = backend

    argv = [sys.executable, entry_path] + list(entry_args)
    wrapped = _wrap_sandbox(argv, claim_real, backend)
    try:
        proc = subprocess.run(wrapped, cwd=claim_real, env=env)
        rc = proc.returncode
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    return rc, backend


def _phase_or_draft(claim_dir):
    try:
        return kernel.phase(claim_dir)
    except kernel.ClaimError:
        return "draft"


# ==== run ===================================================================

def _parse_run_args(args):
    if not args:
        raise _Refusal(3, "run requires a claim path")
    claim_arg = args[0]
    flags = set()
    entry_args = []
    i = 1
    while i < len(args):
        tok = args[i]
        if tok == "--":
            entry_args = args[i + 1:]
            break
        if tok in RUN_FLAGS:
            flags.add(tok)
            i += 1
            continue
        entry_args = args[i:]
        break
    return claim_arg, flags, entry_args


def _cmd_run(args):
    claim_arg, flags, entry_args = _parse_run_args(args)
    claim_dir = os.path.abspath(claim_arg)
    claim_real = os.path.realpath(claim_dir)

    parsed = _load_claim(claim_dir)
    entry_path = _package_contract(claim_dir, parsed, claim_real)

    outputs = _generated_outputs(parsed)
    confined_outputs = [(o, _confine(claim_real, o)) for o in outputs]

    phase = _phase_or_draft(claim_dir)
    _stderr(f'phase = "{phase}"')

    if "--signed-only" in flags and phase != "signed":
        raise _Refusal(5, "refused: this claim is not signed to you (--signed-only)")

    present = all(os.path.isfile(p) for _, p in confined_outputs)
    state = _read_state(claim_dir)

    if not present:
        producer = os.environ.get("RETICULI_PRODUCER")
        if not producer:
            raise _Refusal(7, "latent and no producer configured: "
                              "set RETICULI_PRODUCER")
        _regrow(claim_dir, confined_outputs, producer)
        state = _write_state(claim_dir, "fresh", kernel.build_digest(claim_dir))

    if state is not None:
        if state["status"] == "fresh":
            if "--accept-generated" not in flags:
                raise _Refusal(4, "freshly generated bytes are unaccepted: "
                                  "pass --accept-generated to execute and accept them")
        elif state["status"] == "accepted":
            current = kernel.build_digest(claim_dir)
            if current != state["digest"]:
                raise _Refusal(6, "drifted build: the accepted bytes no longer "
                                  "match what was accepted; run `strip` to recover")

    rc, backend = _execute(claim_real, entry_path, entry_args, "--no-sandbox" in flags)
    _stderr(f'quarantine = "{backend}"')

    if state is not None and state.get("status") == "fresh" and "--accept-generated" in flags:
        _write_state(claim_dir, "accepted", kernel.build_digest(claim_dir))

    return rc


# ==== strip =================================================================

def _cmd_strip(args):
    if not args:
        raise _Refusal(3, "strip requires a claim path")
    claim_dir = os.path.abspath(args[0])
    claim_real = os.path.realpath(claim_dir)
    parsed = _load_claim(claim_dir)

    outputs = _generated_outputs(parsed)
    targets = [_confine(claim_real, o) for o in outputs]

    for target in targets:
        if os.path.islink(target) or os.path.isfile(target):
            os.remove(target)
        elif os.path.isdir(target):
            shutil.rmtree(target)

    launcher_dir = os.path.join(claim_real, LAUNCHER_DIR)
    if os.path.isdir(launcher_dir):
        shutil.rmtree(launcher_dir)
    return 0


# ==== ls =====================================================================

def _describe(claim_dir):
    try:
        parsed = kernel.load_recipe(claim_dir)
    except kernel.ClaimError as e:
        return f"{claim_dir}  error: {e}"
    name = parsed.get("claim", {}).get("name", "")
    try:
        root = kernel.read_manifest(claim_dir).get("root", "")
    except kernel.ClaimError:
        root = ""
    try:
        phase = kernel.phase(claim_dir)
    except kernel.ClaimError:
        phase = "draft"
    outputs = _generated_outputs(parsed)
    present = all(os.path.isfile(os.path.join(claim_dir, o)) for o in outputs)
    state_word = "materialized" if present else "latent"
    root_disp = root[:8] if root else "--------"
    return f"{name}  {root_disp}  phase={phase}  {state_word}"


def _cmd_ls(args):
    if not args:
        raise _Refusal(3, "ls requires at least one claim path")
    lines = [_describe(os.path.abspath(a)) for a in args]
    sys.stdout.write("\n".join(lines) + "\n")
    return 0


# ==== entry point ===========================================================

def main(argv=None):
    argv = sys.argv[1:] if argv is None else list(argv)
    if not argv or argv[0] in ("-h", "--help"):
        sys.stdout.write(HELP)
        return 0
    verb, rest = argv[0], argv[1:]
    try:
        if verb == "run":
            return _cmd_run(rest)
        if verb == "strip":
            return _cmd_strip(rest)
        if verb == "ls":
            return _cmd_ls(rest)
        raise _Refusal(3, f"unknown verb: {verb!r}")
    except _Refusal as r:
        _stderr(r.message)
        return r.code
    except kernel.ClaimError as e:
        _stderr(f"refused: {e}")
        return 3


if __name__ == "__main__":
    sys.exit(main())
