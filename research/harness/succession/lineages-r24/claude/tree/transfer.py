"""transfer: deterministic export/import of a claim (spec/layers.md "exchange").

`export` writes a byte-deterministic tar of exactly a claim's DECLARED
content -- its recipe, pinned inputs, and non-generated/generated step
outputs (generated ones withheld under `blind=True`) -- never a stray file
the workspace happens to hold, and never the ledger (volatile history
stays home). Every declared component travels too, under
`.reticuli/deps/<name>/...`, always blind: a dependent ships a component's
CLAIM, never its generated bytes, so an import can re-earn every layer
from the bytes it received. `import_` extracts and verifies identity.
"""
import io
import os
import tarfile

from reticuli import _util, kernel, registry

ATTEST = ".reticuli/attest"


def _effective_class(step: dict) -> str:
    cls = step.get("class")
    if cls is not None:
        return cls
    return "generated" if step.get("kind") == "produce" else "pinned"


def _recipe_name(d: str) -> str:
    for name in ("reticuli.toml", "claim.toml"):
        if os.path.isfile(os.path.join(d, name)):
            return name
    raise kernel.ClaimError(f"no recipe found in {d!r}")


def _read_inputs_manifest(path: str) -> list:
    paths = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            head, _, tail = line.partition(" ")
            if len(head) == 64 and tail.strip() and all(c in "0123456789abcdef" for c in head):
                paths.append(tail.strip())
            else:
                paths.append(line)
    return paths


def _declared_inputs(parsed: dict, d: str) -> list:
    claim = parsed.get("claim", {})
    paths = list(claim.get("inputs", []) or [])
    manifest_name = claim.get("inputs_manifest")
    if manifest_name:
        paths.append(manifest_name)
        paths.extend(_read_inputs_manifest(os.path.join(d, manifest_name)))
    env = claim.get("environment")
    if env:
        paths.append(env)
    return paths


def _declared_entries(d: str, blind: bool) -> dict:
    """arcname -> absolute path, for exactly `d`'s declared content."""
    parsed = kernel.load_recipe(d)
    recipe_name = _recipe_name(d)
    entries = {recipe_name: os.path.join(d, recipe_name)}
    for p in _declared_inputs(parsed, d):
        entries[p] = os.path.join(d, p)
    for step in parsed.get("step", []) or []:
        output = step["output"]
        path = os.path.join(d, output)
        if not os.path.isfile(path):
            continue
        if _effective_class(step) != "generated" or not blind:
            entries[output] = path
    manifest_path = os.path.join(d, kernel.MANIFEST)
    if os.path.isfile(manifest_path):
        entries[kernel.MANIFEST] = manifest_path
    links_path = os.path.join(d, _util.STORE, "links.json")
    if os.path.isfile(links_path):
        entries[_util.STORE + "/links.json"] = links_path
    return entries


def _add_file(tar: tarfile.TarFile, arcname: str, path: str) -> None:
    with open(path, "rb") as f:
        data = f.read()
    info = tarfile.TarInfo(name=arcname)
    info.size = len(data)
    info.mtime = 0
    info.uid = 0
    info.gid = 0
    info.uname = ""
    info.gname = ""
    info.mode = 0o644
    info.type = tarfile.REGTYPE
    tar.addfile(info, io.BytesIO(data))


def export(d: str, tar_path: str, blind: bool = False) -> None:
    """Write a byte-deterministic tar of `d`'s declared content at
    `tar_path`; `blind=True` withholds every generated output."""
    entries = _declared_entries(d, blind)

    attest_dir = os.path.join(d, ATTEST)
    if os.path.isdir(attest_dir):
        for fname in sorted(os.listdir(attest_dir)):
            fpath = os.path.join(attest_dir, fname)
            if os.path.isfile(fpath):
                entries[ATTEST + "/" + fname] = fpath

    index = registry._root_index(registry._home(d))
    for name, _root, _group, resolved in registry._resolve_components(d, index):
        comp_entries = _declared_entries(resolved, blind=True)
        for arc, path in comp_entries.items():
            entries[f"{_util.STORE}/deps/{name}/{arc}"] = path

    with tarfile.open(tar_path, "w") as tar:
        for arcname in sorted(entries):
            _add_file(tar, arcname, entries[arcname])


def _safe_member(name: str) -> bool:
    if os.path.isabs(name):
        return False
    parts = name.split("/")
    return not any(p == ".." for p in parts)


def _reseal_all(root_dir: str) -> None:
    """Reseal every claim found under `root_dir` (itself and every nested
    `.reticuli/deps/<name>`): re-earns the store's own pin-comparison
    residue from the bytes actually received, which travel but whose
    concrete filename the spec leaves implementation-defined."""
    for dirpath, _dirnames, _filenames in os.walk(root_dir):
        manifest_path = os.path.join(dirpath, _util.STORE, "manifest.json")
        if os.path.isfile(manifest_path):
            try:
                kernel.seal(dirpath)
            except kernel.ClaimError:
                pass


def import_(tar_path: str, into: str) -> dict:
    """Extract `tar_path` into `into`, reseal everything received, and
    verify identity."""
    os.makedirs(into, exist_ok=True)
    with tarfile.open(tar_path) as tar:
        for member in tar.getmembers():
            if not _safe_member(member.name):
                raise kernel.ClaimError(f"refused tar member escaping target: {member.name!r}")
        tar.extractall(into)
    _reseal_all(into)
    v = kernel.verify(into)
    return {"ok": v["ok"], "root": v["root"]}
