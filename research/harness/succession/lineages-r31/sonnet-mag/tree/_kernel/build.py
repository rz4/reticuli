"""Kernel build: materialize a room, re-earn gates (audit), regrow outputs
(rebuild).

A *room* is a scratch directory holding exactly what a judge may see: the
recipe the root was computed from (guidance-stripped at format 3+, byte-for-
byte before that), the pinned inputs, pinned outputs, and -- for an audit --
the generated bytes present.  Verdict files are never carried in: a gate must
write them again, and they must reproduce the pinned bytes.
"""
import json
import math
import os
import re
import shutil
import subprocess
import tempfile
import time

from . import core, identity, recipe as _recipe, run, seal
from .core import ClaimError


# ------------------------------------------------------------- helpers

def _step_guidance(step):
    """The producer hint of a step (`guidance`, else older `request`), or None."""
    if not isinstance(step, dict):
        return None
    for key in core.GUIDANCE_KEYS:
        v = step.get(key)
        if isinstance(v, str) and v:
            return v
    return None


def _compare_pin(room: str, src: str, out: str) -> bool:
    """Do the bytes of `out` in the room equal those in the claim `src`?"""
    try:
        a = core._hash_file(core._safe(room, out))
        b = core._hash_file(core._safe(src, out))
    except ClaimError:
        return False
    return a == b


def _read_usage(path: str) -> dict:
    """Usage a producer reported: usd/tokens/calls (never seconds), vendor,
    model.  Malformed or absent usage is simply nothing."""
    out = {}
    try:
        with open(path, "rb") as f:
            data = json.loads(f.read().decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError, RecursionError):
        return out
    if not isinstance(data, dict):
        return out
    for key in ("usd", "tokens", "calls"):
        v = data.get(key)
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            continue
        if isinstance(v, float) and not math.isfinite(v):
            continue
        if v < 0:
            continue
        out[key] = v
    for key in ("vendor", "model"):
        v = data.get(key)
        if isinstance(v, str) and v:
            out[key] = v
    return out


def _ssh_verify(allowed_signers: str, principal: str, namespace: str,
                data: bytes, signature: str) -> bool:
    """Verify a detached ssh signature over `data` with ssh-keygen -Y."""
    if not (isinstance(allowed_signers, str) and os.path.isfile(allowed_signers)):
        return False
    tmp = tempfile.mkdtemp(prefix="reticuli-ssh-")
    try:
        sigfile = os.path.join(tmp, "sig")
        with open(sigfile, "w", encoding="utf-8") as f:
            f.write(signature)
        try:
            done = subprocess.run(
                ["ssh-keygen", "-Y", "verify", "-f", allowed_signers,
                 "-I", principal, "-n", namespace, "-s", sigfile],
                input=data, capture_output=True, timeout=60, check=False)
        except (OSError, subprocess.SubprocessError):
            return False
        return done.returncode == 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _authorized(d: str, root: str, signers=None) -> list:
    """Principals whose signature over `root` verifies against the verifier's
    own allowed_signers file (argument, else RETICULI_SIGNERS)."""
    signers = signers or os.environ.get(core._ENV_SIGNERS)
    if not signers:
        return []
    try:
        sdir = core._safe(d, core.SIGN_DIR)
        names = sorted(os.listdir(sdir))
    except (ClaimError, OSError):
        return []
    found = []
    for name in names:
        if not name.endswith(".sign.json"):
            continue
        try:
            with open(os.path.join(sdir, name), "rb") as f:
                pkt = json.loads(f.read().decode("utf-8"))
        except (OSError, UnicodeDecodeError, ValueError, RecursionError):
            continue
        if not isinstance(pkt, dict) or pkt.get("root") != root:
            continue
        who, sig = pkt.get("signer"), pkt.get("signature")
        if not isinstance(who, str) or not isinstance(sig, str):
            continue
        if _ssh_verify(signers, who, core.SIGN_NAMESPACE,
                       root.encode("utf-8"), sig) and who not in found:
            found.append(who)
    return found


# ---------------------------------------------------------- toml writer

_BARE = re.compile(r"^[A-Za-z0-9_-]+$")


def _tstr(s: str) -> str:
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\b":
            out.append("\\b")
        elif ch == "\f":
            out.append("\\f")
        elif o < 0x20 or o == 0x7f:
            out.append("\\u%04x" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _tkey(k: str) -> str:
    return k if _BARE.match(k) else _tstr(k)


def _tval(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if math.isnan(v):
            return "nan"
        if math.isinf(v):
            return "inf" if v > 0 else "-inf"
        return repr(v)
    if isinstance(v, str):
        return _tstr(v)
    if isinstance(v, list):
        return "[" + ", ".join(_tval(x) for x in v) + "]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        return "{ " + ", ".join(f"{_tkey(k)} = {_tval(x)}"
                                for k, x in v.items()) + " }"
    raise ClaimError(f"cannot write {type(v).__name__} as TOML")


def _is_aot(v) -> bool:
    return isinstance(v, list) and bool(v) and all(isinstance(x, dict) for x in v)


def _emit(table: dict, path: list, lines: list) -> None:
    for k, v in table.items():
        if not isinstance(v, dict) and not _is_aot(v):
            lines.append(f"{_tkey(k)} = {_tval(v)}")
    for k, v in table.items():
        if isinstance(v, dict):
            lines.append("")
            lines.append("[" + ".".join(_tkey(p) for p in path + [k]) + "]")
            _emit(v, path + [k], lines)
        elif _is_aot(v):
            for item in v:
                lines.append("")
                lines.append("[[" + ".".join(_tkey(p) for p in path + [k]) + "]]")
                _emit(item, path + [k], lines)


def _toml_dumps(doc: dict) -> str:
    lines = []
    _emit(doc, [], lines)
    return "\n".join(lines).lstrip("\n") + "\n"


# ---------------------------------------------------------- materialize

def _copy_checked(src_path: str, dst_path: str) -> None:
    core._hash_file(src_path)          # regular, singly linked, readable
    core._copy_into(src_path, dst_path)


def _from_dir(produce_from, step, src):
    comp = step.get("from")
    if isinstance(produce_from, dict):
        base = produce_from.get(comp)
        return os.fspath(base) if base is not None else None
    if produce_from is not None:
        base = os.fspath(produce_from)
        sub = os.path.join(base, comp) if isinstance(comp, str) else None
        if sub and os.path.isdir(sub):
            return sub
        return base
    return src


def _materialize(src: str, room: str, rec: dict, generated: bool = False,
                 inputs_from=None, produce_from=None) -> str:
    """Build the judging room for claim `src` in `room`; returns the room path.

    Formats 1-2 receive the recipe file byte for byte; format 3+ receive the
    preimage recipe (guidance-stripped) written as TOML."""
    os.makedirs(room, exist_ok=True)
    room = os.path.realpath(room)
    base = os.fspath(inputs_from) if inputs_from is not None else src
    if identity._claim_format(rec) < 3:
        rp = _recipe.recipe_path(src)
        _copy_checked(rp, os.path.join(room, os.path.basename(rp)))
    else:
        pre = identity._preimage_recipe(rec)
        text = _toml_dumps(pre)
        try:
            back = _recipe._toml.loads(text)
        except Exception as e:                       # pragma: no cover
            raise ClaimError(f"cannot write the room recipe: {e}")
        if back != pre:                              # pragma: no cover
            raise ClaimError("the room recipe does not round-trip")
        with open(os.path.join(room, core.RECIPE), "w", encoding="utf-8",
                  newline="\n") as f:
            f.write(text)
    for p in _recipe._inputs(base, rec):
        _copy_checked(core._safe(base, p), core._safe(room, p))
    for s in _recipe._steps(rec):
        if s.get("kind") != "produce":
            continue
        out = s["output"]
        if "from" in s:
            fdir = _from_dir(produce_from, s, src)
            if fdir is None:
                continue
            sp = core._safe(fdir, out)
            if os.path.lexists(sp):
                _copy_checked(sp, core._safe(room, out))
        elif _recipe._class(s) == "generated":
            if generated:
                sp = core._safe(src, out)
                if os.path.lexists(sp):
                    _copy_checked(sp, core._safe(room, out))
        else:
            _copy_checked(core._safe(base, out), core._safe(room, out))
    return room


# ---------------------------------------------------------------- gates

def _run_gates(room: str, rec: dict, src: str) -> list:
    rows = []
    for s in _recipe.gates(rec):
        out = s["output"]
        r = run.run_gate(s["run"], room, rec)
        status = r.get("status", "failed")
        if status == "ok" and _recipe._class(s) != "generated":
            status = "reproduced" if _compare_pin(room, src, out) else "mismatch"
        rows.append({"output": out, "run": s["run"], "status": status,
                     "quarantine": r.get("quarantine", "none"),
                     "seconds": r.get("seconds"),
                     "log": r.get("output", "")})
    return rows


def _gates_ok(rows: list) -> bool:
    return bool(rows) and all(g["status"] in ("ok", "reproduced") for g in rows)


# ---------------------------------------------------------------- audit

def audit(d: str, **kwargs) -> dict:
    """Re-earn every gate cold, in a fresh sandboxed room.  Never trusts a
    stored verdict: identity is recomputed, verdict files are regrown, pinned
    bytes must reproduce."""
    result = {"ok": False, "verdict": "", "gates": [], "root": None,
              "name": None}
    room = None
    try:
        v = seal.verify(d)
        result["name"], result["root"] = v.get("name"), v.get("root")
        if not v["ok"]:
            result["verdict"] = ("identity mismatch: the bytes present do not "
                                 "recompute to the sealed root"
                                 + (f" ({v['reason']})" if v.get("reason") else ""))
            return result
        rec = _recipe.load_recipe(d)
        room = tempfile.mkdtemp(prefix="reticuli-audit-")
        _materialize(d, room, rec, generated=True)
        rows = _run_gates(os.path.realpath(room), rec, d)
        result["gates"] = rows
        if not rows:
            result["verdict"] = "nothing earned: the claim has no gates"
        elif _gates_ok(rows):
            result["ok"] = True
            result["verdict"] = "earned: every gate re-run clean on present bytes"
        else:
            bad = [f"{g['output']}: {g['status']}" for g in rows
                   if g["status"] not in ("ok", "reproduced")]
            result["verdict"] = "carried or broken: " + "; ".join(bad)
        try:
            who = _authorized(d, v["root"])
        except Exception:
            who = []
        if who:
            result["authorized"] = who
    except ClaimError as e:
        result["verdict"] = f"refused: {e}"
    finally:
        if room:
            shutil.rmtree(room, ignore_errors=True)
    return result


# -------------------------------------------------------------- produce

def _produce(room: str, rec: dict, producer: str, targets: list,
             guidance: bool = True, producer_env=None) -> dict:
    """Invoke the producer once per still-missing generated output.

    The producer is the caller's oracle: unconfined, the caller's HOME and
    network, a scrubbed environment plus the claim's own variables."""
    room = os.path.realpath(room)
    usage_path = os.path.join(room, core.USAGE)
    os.makedirs(os.path.dirname(usage_path), exist_ok=True)
    steps = _recipe.produces(rec)
    totals = {"calls": 0, "seconds": 0.0}
    last_rc = 0
    notes = []
    for target in targets:
        if os.path.lexists(core._safe(room, target)):
            continue
        extra = {}
        if producer_env:
            for k, v in producer_env.items():
                if isinstance(k, str) and isinstance(v, str):
                    extra[k] = v
        extra[core._ENV_OUTPUT] = os.path.join(room, target)
        extra[core._ENV_OUTPUTS] = json.dumps(list(targets))
        extra[core._ENV_USAGE] = usage_path
        if guidance:
            hint = [_step_guidance(s) for s in steps if s["output"] == target]
            hint = [h for h in hint if h]
            if hint:
                extra[core._ENV_REQUEST] = "\n".join(hint)
        env = run._scrub_env(room, rec, "none", extra)
        try:
            os.unlink(usage_path)
        except OSError:
            pass
        t0 = time.monotonic()
        rc, out, timed_out = run._run([core._SHELL, "-c", producer], room, env,
                                      core.PRODUCER_TIMEOUT)
        elapsed = time.monotonic() - t0
        totals["calls"] += 1
        totals["seconds"] += elapsed
        usage = _read_usage(usage_path)
        for key in ("usd", "tokens"):
            if key in usage:
                totals[key] = totals.get(key, 0) + usage[key]
        for key in ("vendor", "model"):
            if key in usage:
                totals[key] = usage[key]
        if "calls" in usage:
            totals["calls"] += usage["calls"] - 1
        last_rc = rc
        if rc != 0 or timed_out:
            notes.append(f"{target}: producer "
                         + ("timed out" if timed_out else f"exited {rc}")
                         + (": " + out.strip()[-300:] if out.strip() else ""))
    try:
        os.unlink(usage_path)
    except OSError:
        pass
    totals["returncode"] = last_rc
    totals["notes"] = notes
    return totals


# -------------------------------------------------------------- rebuild

def rebuild(d: str, producer: str, into: str, produce_from=None,
            input_from=None, guidance: bool = True, producer_env=None) -> dict:
    """Regrow the generated outputs of claim `d` in a blind room `into`, run
    the gates there, and seal the room.  The result's `root` is the room's
    root (None when the room could not be sealed)."""
    v = seal.verify(d)
    if not v["ok"]:
        raise ClaimError("the claim's identity does not hold; refusing to rebuild")
    if not isinstance(producer, str) or not producer.strip():
        raise ClaimError("a rebuild needs a producer command")
    rec = _recipe.load_recipe(d)
    into = os.path.abspath(into)
    if os.path.lexists(into) and (not os.path.isdir(into) or os.listdir(into)):
        raise ClaimError(f"refusing a non-empty rebuild target: {into!r}")
    room = _materialize(d, into, rec, generated=False,
                        inputs_from=input_from, produce_from=produce_from)

    targets = []
    for out in _recipe.generated_outputs(rec):
        if out not in targets:
            targets.append(out)
    spent = _produce(room, rec, producer, targets, guidance, producer_env)

    rows = _run_gates(room, rec, d)
    quarantine = rows[0]["quarantine"] if rows else run.sandbox_backend()

    event = {"event": "rebuild", "calls": spent["calls"],
             "seconds": spent["seconds"], "quarantine": quarantine}
    for key in ("usd", "tokens", "vendor", "model"):
        if key in spent:
            event[key] = spent[key]
    try:
        run.ledger(room, event)
    except (ClaimError, OSError):
        pass

    root = None
    digest = None
    reason = None
    try:
        root = seal.seal(room)["root"]
        digest = identity.build_digest(room)
    except ClaimError as e:
        reason = str(e)
    ok = bool(_gates_ok(rows) and root == v["root"])
    out = {"ok": ok, "root": root, "expected_root": v["root"],
           "name": v.get("name"), "build_digest": digest,
           "quarantine": quarantine, "gates": rows, "into": room,
           "producer": {"returncode": spent["returncode"],
                        "notes": spent["notes"]}}
    if reason:
        out["reason"] = reason
    return out
