"""The argv grammar: fourteen porcelain verbs, their folded aliases, and the
plumbing (`hook`, `help`, `completion`) -- `checks/parser_check.py`, this
module's definition.

`PORCELAIN` and `ALIASES` are the single source of truth: `_parser()` builds
every subcommand from them (plus the three plumbing verbs), and `verbs()`
reads the names back off the parser it built -- so the registered grammar
and the advertised one cannot drift apart. `_completion` does the same: it
lists `verbs()`, not a second hand-written roster, so a shell's completion
script always matches whatever is actually registered.

A handful of v1-era verbs were retired outright (`seal`, `hooks`, `tree`,
`claims`, `attest`, and the still-older `condense`, `realize`, `prove`,
`mint`, `records`, `hydrate`, `inspect`): each was folded into a flag on a
surviving porcelain verb rather than kept as its own top-level word. `_FOLDED`
records where each one went, so `ret help -a` can still explain an old
spelling instead of just failing on it.

Built from the standard library only -- this module parses argv, it does not
dispatch to the kernel or any layer above it.
"""
