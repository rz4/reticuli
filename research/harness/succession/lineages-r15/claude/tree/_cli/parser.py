def _parser():
    """Build the top-level parser and every subparser it registers.
    Returns `(parser, subparsers)` where `subparsers` maps every registered
    verb name (porcelain, alias, and plumbing) to its subparser -- the
    thing `verbs()` and `_help_topic` both read from, so nothing here can
    disagree with what argv actually accepts.
    """
    p = argparse.ArgumentParser(
        prog="ret",
        description=_DESC,
        epilog=_EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = p.add_subparsers(dest="verb", metavar="<command>")
    subs = {}

    for name in PORCELAIN:
        sp = sub.add_parser(name, help=_SHORT_HELP[name])
        _add_verbose_json(sp)
        _VERB_SETUP[name](sp)
        subs[name] = sp

    for alias, target in ALIASES.items():
        sp = sub.add_parser(alias, help=f"alias for {target!r}")
        _add_verbose_json(sp)
        _VERB_SETUP[target](sp)
        subs[alias] = sp

    hook_sp = sub.add_parser("hook", help=_SHORT_HELP["hook"])
    subs["hook"] = hook_sp

    help_sp = sub.add_parser("help", help=_SHORT_HELP["help"])
    help_sp.add_argument("topic", nargs="?", help="the command to explain")
    help_sp.add_argument("-a", "--all", action="store_true",
                          help="list everything, including accepted older spellings")
    subs["help"] = help_sp

    completion_sp = sub.add_parser("completion", help=_SHORT_HELP["completion"])
    completion_sp.add_argument("shell", nargs="?", default="bash",
                                choices=("bash", "zsh"))
    subs["completion"] = completion_sp

    return p, subs


def verbs():
    """Every name argv accepts as a command: the porcelain verbs, their
    aliases, and the plumbing -- read directly off `_parser()`'s
    subparsers so this can never drift from what is actually registered.
    """
    _, subs = _parser()
    return tuple(subs.keys())


def _completion(shell: str = "bash") -> None:
    """Print a completion script for `shell`, generated from `verbs()` --
    never a separately maintained list -- so it always matches the actual
    grammar.
    """
    names = " ".join(sorted(verbs()))
    if shell == "zsh":
        script = (
            "#compdef ret\n"
            "_reticuli_completion() {\n"
            f"    local -a commands\n"
            f"    commands=({names})\n"
            "    _describe 'command' commands\n"
            "}\n"
            "compdef _reticuli_completion ret\n"
        )
    else:
        script = (
            "_reticuli_completion() {\n"
            '    local cur="${COMP_WORDS[COMP_CWORD]}"\n'
            f'    COMPREPLY=( $(compgen -W "{names}" -- "${{cur}}") )\n'
            "}\n"
            "complete -F _reticuli_completion ret\n"
        )
    print(script)


def _help_topic(topic: str) -> None:
    """Print detailed help for one command: a retired spelling's
    replacement, a registered verb's usage plus its long-form help, or a
    plain "no such command" for anything else.
    """
    if topic in _FOLDED:
        print(f"{topic!r} is retired; use {_FOLDED[topic]} instead.")
        return
    _, subs = _parser()
    sp = subs.get(topic)
    if sp is None:
        print(f"no such command: {topic!r}")
        return
    print(sp.format_help())
    detail = _FULL_HELP.get(topic)
    if detail:
        print(detail)


def _help_all() -> None:
    """Print the full top-level help, then every retired spelling and what
    replaced it -- the listing `ret help -a` promises in `_EPILOG`.
    """
    p, _ = _parser()
    print(p.format_help())
    print("Accepted older spellings (retired; shown for reference):")
    for old in sorted(_FOLDED):
        print(f"  {old:<10} -> {_FOLDED[old]}")
