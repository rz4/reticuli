def _add_verbose_json(sp) -> None:
    """Add the two flags every porcelain subcommand accepts: `--json` for
    machine-readable output and `-v/--verbose` for progress detail."""
    sp.add_argument("--json", action="store_true",
                     help="emit machine-readable JSON")
    sp.add_argument("-v", "--verbose", action="store_true",
                     help="emit progress detail")


