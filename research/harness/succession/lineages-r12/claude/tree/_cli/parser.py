def _add_verbose_json(sp: argparse.ArgumentParser) -> None:
    """Add the three flags every verb's output contract reads
    (`_cli/output.py`'s `_finish`/`_use_color`): `--json` (the machine
    envelope, and nothing else on stdout), `--verbose` (print result
    detail under the human line), `--color` (`always`/`never`/`auto`).
    """
    sp.add_argument("--json", action="store_true",
                     help="emit the machine-readable envelope, and nothing else")
    sp.add_argument("--verbose", action="store_true",
                     help="print result detail under the human-facing line")
    sp.add_argument("--color", choices=("auto", "always", "never"), default="auto",
                     help="color the human-facing line (default: auto)")


def _parser():
    """The top-level `ArgumentParser`, and a `dict` of every registered
    verb name (porcelain, alias, and plumbing) to the subparser that
    parses it -- `_help_topic`/`_completion` read the same dict so help
    and completion cannot drift from the grammar `_parser` builds.
    """
    p = argparse.ArgumentParser(
        prog="ret", description=_DESC, epilog=_EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--version", action="store_true", help="print the version and exit")
    sub = p.add_subparsers(dest="verb", metavar="<command>")
    subparsers = {}

    def add(name: str, help_text: str) -> argparse.ArgumentParser:
        canonical = ALIASES.get(name, name)
        sp = sub.add_parser(name, help=help_text, description=_FULL_HELP.get(canonical),
                             formatter_class=argparse.RawDescriptionHelpFormatter)
        subparsers[name] = sp
        return sp

    sp = add("init", "initialize a workspace")
    sp.add_argument("path", nargs="?", default=".")
    sp.add_argument("--name")
    sp.add_argument("--no-agent", action="store_true")
    _add_verbose_json(sp)

    sp = add("run", "run and observe a command")
    sp.add_argument("cmd")
    sp.add_argument("--ws", default=".")
    _add_verbose_json(sp)

    sp = add("status", "show work, claims, and unresolved inputs")
    sp.add_argument("path", nargs="?", default=".")
    sp.add_argument("--tree", action="store_true")
    sp.add_argument("--claims", action="store_true")
    sp.add_argument("--deps", action="store_true")
    sp.add_argument("--structure", action="store_true")
    _add_verbose_json(sp)

    sp = add("pack", "create a claim from a project")
    sp.add_argument("root")
    sp.add_argument("name")
    sp.add_argument("--generated", nargs="*", default=[], metavar="PATTERN")
    sp.add_argument("--inputs", nargs="*", default=[], metavar="PATTERN")
    sp.add_argument("--gate")
    sp.add_argument("--accept", action="store_true",
                     help="also seal the result into the local store (was: `seal`)")
    _add_verbose_json(sp)

    sp = add("pull", "add another claim as a dependency")
    sp.add_argument("claim")
    sp.add_argument("ws")
    _add_verbose_json(sp)

    sp = add("export", "write a portable claim archive")
    sp.add_argument("claim")
    sp.add_argument("tar_path", metavar="tar-path")
    sp.add_argument("--blind", action="store_true")
    _add_verbose_json(sp)

    sp = add("import", "restore a claim archive")
    sp.add_argument("tar_path", metavar="tar-path")
    sp.add_argument("into")
    _add_verbose_json(sp)

    sp = add("verify", "verify claim identity")
    sp.add_argument("claim")
    _add_verbose_json(sp)

    sp = add("audit", "rerun acceptance criteria")
    sp.add_argument("claim")
    _add_verbose_json(sp)

    sp = add("assess", "measure specification strength")
    sp.add_argument("claim")
    sp.add_argument("--mutants", type=int)
    _add_verbose_json(sp)

    sp = add("rebuild", "rebuild an implementation from a claim")
    sp.add_argument("claim")
    sp.add_argument("producer")
    sp.add_argument("into")
    sp.add_argument("--ws", help="rebuild every declared component first, leaf first")
    sp.add_argument("--reuse", action="store_true",
                     help="thread an existing sealed component through instead of regrowing it")
    sp.add_argument("--no-guidance", dest="guidance", action="store_false", default=True)
    _add_verbose_json(sp)

    sp = add("crosscheck", "compare independent realizations")
    sp.add_argument("leg1")
    sp.add_argument("leg2")
    sp.add_argument("leg3")
    sp.add_argument("--mutants", type=int)
    sp.add_argument("--deep", action="store_true",
                     help="also crosscheck each leg's own declared components")
    _add_verbose_json(sp)

    sp = add("record", "write an execution record")
    sp.add_argument("claim")
    sp.add_argument("--out", metavar="PATH")
    sp.add_argument("--key", help="authorize instead of recording (was: `attest`)")
    sp.add_argument("--as", dest="identity", metavar="IDENTITY")
    sp.add_argument("--check", nargs="?", const="", default=None, metavar="SIGNERS",
                     help="verify existing signatures instead of recording")
    _add_verbose_json(sp)

    sp = add("sign", "authorize a claim or proof")
    sp.add_argument("target")
    sp.add_argument("key")
    sp.add_argument("--as", dest="identity", metavar="IDENTITY")
    sp.add_argument("--ws")
    sp.add_argument("--proof", action="store_true",
                     help="target is a proof document written by `record`, not a claim")
    _add_verbose_json(sp)

    sp = add("hook", "internal: the coding-agent event hook")
    _add_verbose_json(sp)

    sp = add("help", "show detailed help for a command")
    sp.add_argument("topic", nargs="?")
    sp.add_argument("-a", "--all", action="store_true",
                     help="list every command, including accepted older spellings")

    sp = add("completion", "print a shell completion script")
    sp.add_argument("shell", nargs="?", default="bash", choices=("bash", "zsh"))

    return p, subparsers


def verbs() -> set:
    """Every verb name this parser registers: the porcelain, the folded
    aliases, and the plumbing -- the one place that union is written
    down; `_parser()`'s subcommands are asserted to agree with it."""
    return set(PORCELAIN) | set(ALIASES) | set(_PLUMBING)


# -- help and completion, both read back from the grammar above ------------

def _help_topic(name: str) -> None:
    """Print `name`'s detailed help -- `ret help <command>`. An alias
    resolves to its canonical verb's text, named as what it is."""
    canonical = ALIASES.get(name, name)
    text = _FULL_HELP.get(canonical)
    if text is None:
        sys.stderr.write(f"ret: help: no such command: {name!r}\n")
        return
    if canonical != name:
        print(f"{name!r} is an older spelling of {canonical!r}.\n")
    print(text)


def _help_all() -> None:
    """`ret help -a`: every porcelain verb, grouped as `_DESC` groups
    them, then the accepted older spellings."""
    print(_DESC)
    if ALIASES:
        print("\nOlder spellings\n" + "\n".join(
            f"    {alias:<10}  (now: {canonical})"
            for alias, canonical in sorted(ALIASES.items())
        ))


def _completion(shell: str) -> None:
    """A shell completion script for the full grammar, generated from
    `verbs()` so it cannot drift from the commands this module actually
    registers."""
    names = sorted(verbs())
    if shell == "zsh":
        print("#compdef ret")
        print("_ret() {")
        print(f"    compadd {' '.join(names)}")
        print("}")
        print("compdef _ret ret")
        return
    words = " ".join(names)
    print("_ret_complete() {")
    print('    local cur="${COMP_WORDS[COMP_CWORD]}"')
    print(f'    COMPREPLY=( $(compgen -W "{words}" -- "$cur") )')
    print("}")
    print("complete -F _ret_complete ret")
