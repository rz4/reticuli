"""The argv grammar (`spec/layers.md`'s surface layer, the half of it that
is pure structure -- no layer call happens here, only `argparse` wiring).

Fourteen porcelain verbs (`PORCELAIN`), grouped in `_DESC` the same way
`ret -h` prints them; the folded aliases that keep an older spelling
working (`ALIASES`); and the plumbing every porcelain verb sits beside --
`hook` (the coding-agent event sink `hooks.main` wires up), `help`
(`_help_topic`/`_help_all`, reading `_FULL_HELP`), and `completion`
(`_completion`, generated from `verbs()` so it cannot drift from the
grammar it describes). `verbs()` is the one place that union is written
down; the conformance check asserts `_parser()`'s subcommands agree with
it.

A few verbs still carry a retired sibling's job as a flag, not a
separate word -- `pack --accept` (was `seal`), `status --tree` / `status
--claims` (were `tree` / `claims`), `record --key --as` / `record
--check` (was `attest`) -- so the word is gone from `verbs()` but the
behavior is not gone from the CLI.

Stdlib only.
"""
