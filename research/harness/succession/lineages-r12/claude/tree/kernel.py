# -- rebuild / audit --------------------------------------------------------

def _scrubbed_produce(step: dict, into: str, producer: str, outs: list,
                      guidance: bool, producer_env: dict) -> None:
    """Run one produce step with the CALLER's ambient environment reduced
    to the same host allowlist a gate gets, for the window of the
    producer's own subprocess call only -- an inherited secret must never
    reach a producer unhanded, but furnishing and gate execution (which
    read their own `RETICULI_*` controls from the real process
    environment) run outside this window, untouched.
    """
    saved = dict(os.environ)
    try:
        for key in list(os.environ):
            if key not in core._KEEP_ENV:
                del os.environ[key]
        build_mod._produce(step, into, producer, outs, guidance, producer_env)
    finally:
        os.environ.clear()
        os.environ.update(saved)


def rebuild(d: str, producer: str, into: str, produce_from: dict = None,
            input_from: str = None, guidance: bool = True,
            producer_env: dict = None) -> dict:
    """Regrow a claim's generated outputs into `into` until its gates pass
    (v1: `realize`).

    A reimplementation of `_kernel/build.py`'s `rebuild`, not a delegation:
    the producer's own subprocess call runs with a scrubbed ambient
    environment (`_scrubbed_produce`), and this layer ledgers what the
    build layer computes but does not itself record -- the gate's
    sandbox and judging environment, the declared producer
    (vendor/model, and a call count the kernel itself measures), and a
    reuse event per component-supplied output.
    """
    d = _abs(d)
    into = _abs(into)
    vendor = os.environ.get(core._ENV_VENDOR)
    model = os.environ.get(core._ENV_MODEL)

    def _run():
        recipe = load_recipe(d)
        missing = build_mod._authorized(recipe)
        if missing:
            raise ClaimError(
                f"refused: environment requirement(s) missing: {missing}"
            )
        if os.path.isdir(into) and os.listdir(into):
            raise ClaimError(f"refused: rebuild target is not empty: {into!r}")
        os.makedirs(into, exist_ok=True)

        recipe_src = recipe_mod.recipe_path(d)
        core._copy_into(recipe_src, os.path.join(into, os.path.basename(recipe_src)))
        crosscheck_mod._rewrite_room_recipe(d, into, recipe)
        threaded = input_from or {}
        for path in recipe_mod._inputs(d, recipe):
            alt = threaded.get(path)
            source = alt if alt is not None else core._safe(d, path)
            core._copy_into(source, core._safe(into, path))
        env_file = recipe.get("claim", {}).get("environment")
        if env_file:
            core._copy_into(core._safe(d, env_file), core._safe(into, env_file))
        os.makedirs(os.path.join(into, core.STORE), exist_ok=True)

        # A producer cannot change the question: snapshot every pinned
        # path (the recipe and the declared inputs, as materialized --
        # deliberate threading via `input_from` included) and refuse if
        # the producer rewrote any of them, rather than silently sealing
        # a different, self-consistent claim.
        pinned_paths = [os.path.join(into, os.path.basename(recipe_src))]
        pinned_paths += [core._safe(into, p) for p in recipe_mod._inputs(d, recipe)]
        snapshot = {p: core._hash_file(p) for p in pinned_paths if os.path.isfile(p)}

        outs = recipe_mod.generated_outputs(recipe)
        supplied = produce_from or {}
        n_invoked = 0
        for step in recipe_mod.produces(recipe):
            output = step["output"]
            source = supplied.get(output)
            if source is not None:
                core._copy_into(source, core._safe(into, output))
                run_mod.ledger(into, {"event": "reuse", "output": output})
                continue
            if "from" in step:
                continue
            n_invoked += 1
            _scrubbed_produce(step, into, producer, outs, guidance, producer_env)

        for path, digest in snapshot.items():
            if not os.path.isfile(path) or core._hash_file(path) != digest:
                raise ClaimError(
                    f"refused: the producer rewrote a pinned path: {path!r}"
                )

        furnished = crosscheck_mod.furnish(into, recipe)
        quarantine = "none"
        with crosscheck_mod._prepended_path((furnished or {}).get("path")):
            for step in recipe_mod.gates(recipe):
                result = run_mod.run_gate(step["run"], into, recipe)
                quarantine = result["quarantine"]
                if result["status"] != "ok":
                    raise ClaimError(
                        f"refused: rebuild's gate did not pass: "
                        f"{step['output']!r} ({result['status']})"
                    )
        manifest = seal(into)
        return ({"root": manifest["root"], "name": manifest["name"],
                "quarantine": quarantine}, n_invoked)

    result, n_invoked = _in_band(_run)

    run_mod.ledger(into, {"event": "gate", "when": core._now(),
                          "quarantine": result["quarantine"]})
    run_mod.ledger(into, {"event": "environment", "when": core._now(),
                          "python": platform.python_version(),
                          "platform": sys.platform,
                          "quarantine": result["quarantine"]})
    run_mod.ledger(into, {"event": "producer", "when": core._now(),
                          "calls": n_invoked, "vendor": vendor, "model": model,
                          "blind": True})
    return result


