"""The kernel's public surface (`spec/kernel-api.md`).

This module is the one thing above the kernel ever imports: it wires the
primitives in `_kernel/` (path/byte boundaries, recipe parsing, identity,
seal/verify, gate execution, rebuild/audit, records, crosscheck) into the
~21 pinned names a conforming kernel exposes, and fixes the handful of
seams those primitives deliberately leave to the façade:

- every directory argument is resolved to an absolute path before it
  reaches a lower layer, so a caller's relative `into` (after `os.chdir`)
  cannot alias itself through a child process's own cwd;
- `run_gate`/`sandbox` apply the host sandbox and, when one is really
  applied, tell the wrapped process which backend it is inside
  (`RETICULI_JAILED` = the backend name, not a bare flag) -- the sending
  half of the no-nesting contract (`checks/kernel_check.py`'s
  `_apply_battery`);
- `rebuild` ledgers what `_kernel/build.py` computes but does not itself
  record: the gate's sandbox, the judging environment, the producer's
  declared vendor/model/call count, and component-supplied reuse;
- `audit` and `phase` turn a damaged claim into a refusal, never a raw
  exception, and translate the audit engine's internal vocabulary
  (`reproduced`) to the kernel's pinned success spelling (`ok`);
- `phase` additionally evaluates `signed`: a trusted (anchored) ssh
  signature over a packet whose root and build digest still match the
  claim's current bytes, binding a recorded proof.

Stdlib only, never the network.
"""
