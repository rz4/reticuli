def _abs(path: str) -> str:
    return os.path.abspath(path)


# -- identity -----------------------------------------------------------

def root(recipe: dict, d: str) -> str:
    """The claim's identity (`spec/identity.md`)."""
    return _in_band(crosscheck_mod.root, recipe, _abs(d))


def build_digest(d: str) -> str:
    """The digest of the generated bytes present (`spec/identity.md`)."""
    return _in_band(identity.build_digest, _abs(d))


def load_recipe(d: str) -> dict:
    """Parse and validate `reticuli.toml` (or legacy `claim.toml`).

    `_kernel/crosscheck.py`'s parser, not `_kernel/recipe.py`'s: the
    latter checks path confinement on every step's OUTPUT regardless of
    class, which refuses a GENERATED output that happens to be a symlink
    at load time -- before a producer has even regrown it, and before
    `audit`'s own confinement check (which does cover generated outputs,
    at the moment it copies one) gets a chance to be the one that
    refuses. Confinement on a generated output belongs to the gates that
    touch its bytes, not to parsing.
    """
    return _in_band(crosscheck_mod.load_recipe, _abs(d))


def read_manifest(d: str) -> dict:
    """`.reticuli/manifest.json`: `{name, root}`."""
    return _in_band(seal_mod.read_manifest, _abs(d))


def seal(d: str) -> dict:
    """Compute the root and write the manifest; returns it.

    Uses this module's own `load_recipe`, not `_kernel/seal.py`'s (which
    calls the stricter parser) -- see `load_recipe`'s docstring.
    """
    d = _abs(d)

    def _run():
        recipe = load_recipe(d)
        root_value = crosscheck_mod.root(recipe, d)
        name = recipe["claim"]["name"]
        manifest = {"name": name, "root": root_value}
        os.makedirs(os.path.join(d, core.STORE), exist_ok=True)
        core._write_json(os.path.join(d, core.MANIFEST), manifest)
        return manifest
    return _in_band(_run)


def verify(d: str) -> dict:
    """Identity only -- recompute the root and compare to the sealed one."""
    d = _abs(d)

    def _run():
        manifest = seal_mod.read_manifest(d)
        recipe = load_recipe(d)
        recomputed = crosscheck_mod.root(recipe, d)
        return {"ok": recomputed == manifest["root"], "root": manifest["root"],
                "recomputed": recomputed, "name": manifest["name"]}
    return _in_band(_run)


# -- gate execution -------------------------------------------------------

def run_gate(cmd: str, d: str, recipe: dict = None) -> dict:
    """Run one gate command: scrubbed, sandboxed, bounded.

    Unlike `_kernel/run.py`'s internal helper, when a real sandbox is
    applied the wrapped process is told WHICH one
    (`RETICULI_JAILED` = the backend name) -- the sending half of the
    no-nesting contract; a gate that is itself a claim runner must be able
    to inherit rather than re-apply.
    """
    d = _abs(d)
    backend = run_mod.sandbox_backend()
    timeout = run_mod.gate_timeout(recipe)
    extra_env = {}
    scratch = None
    if backend in ("seatbelt", "bubblewrap"):
        room = os.path.join(d, core.STORE, "room")
        os.makedirs(room, exist_ok=True)
        scratch = tempfile.mkdtemp(dir=room)
        extra_env["TMPDIR"] = scratch
        extra_env["HOME"] = scratch
        extra_env[core._JAILED] = backend
    env = run_mod._scrub_env(extra_env)
    argv = run_mod._sandbox_argv(backend, d, scratch, [core._SHELL, "-c", cmd])
    result = _in_band(run_mod._run, argv, cwd=d, env=env, timeout=timeout)
    if result["timed_out"]:
        status = "timeout"
    elif result["returncode"] == 0:
        status = "ok"
    else:
        status = "failed"
    return {"status": status, "quarantine": backend}


def sandbox(cmd: str, d: str, recipe: dict = None):
    """A functional probe of the host sandbox, applied to `cmd` in `d`:
    `(status, backend)`."""
    result = run_gate(cmd, d, recipe)
    return (result["status"], result["quarantine"])


