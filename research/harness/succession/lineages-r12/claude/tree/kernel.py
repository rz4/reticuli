def record_proof(m1: str, m2: str, m3: str) -> dict:
    """Run the crosscheck; on a pass, seal the proof onto M1's manifest.

    M1 must be a directory -- a proof is residue on a manifest. Any
    record leg among M2/M3 must verify against the anchor
    (`RETICULI_SIGNERS`); directory legs need none. A durable proof
    embeds each record leg's digest and signer identity.
    """
    m1_abs = _abs(m1)
    if not os.path.isdir(m1_abs):
        raise ClaimError("refused: a proof must land on a directory M1")

    records_trail = []
    anchor = os.environ.get(core._ENV_SIGNERS)
    for leg in (m2, m3):
        if os.path.isdir(leg):
            continue
        if not anchor or not os.path.isfile(anchor):
            raise ClaimError(
                f"refused: record leg {leg!r} has no trust anchor"
            )
        signer = crosscheck_mod.record_signer(leg, anchor)
        doc = crosscheck_mod._record_read(leg)
        records_trail.append({"digest": crosscheck_mod.record_digest(doc), "signer": signer})

    result = crosscheck(m1, m2, m3)
    proof_recorded = result["satisfied"]
    if proof_recorded:
        manifest = read_manifest(m1_abs)
        proof = {"kind": "crosscheck"}
        if records_trail:
            proof["records"] = records_trail
        manifest["proof"] = proof
        core._write_json(os.path.join(m1_abs, core.MANIFEST), manifest)

    out = dict(result)
    out["proof_recorded"] = proof_recorded
    return out


# -- phase: draft / sealed / signed ------------------------------------------

def _packet_bytes_valid(sign_dir: str, base: str, statement: dict,
                        current_root: str, current_digest: str) -> bool:
    packet_path = os.path.join(sign_dir, base + ".packet.json")
    if not os.path.isfile(packet_path):
        return False
    with open(packet_path, "rb") as f:
        packet_bytes = f.read()
    if hashlib.sha256(packet_bytes).hexdigest() != statement.get("packet_digest"):
        return False
    try:
        packet = json.loads(packet_bytes)
    except json.JSONDecodeError:
        return False
    if not isinstance(packet, dict):
        return False
    if packet.get("root") != current_root or packet.get("build_digest") != current_digest:
        return False
    return bool(packet.get("proof"))


def _is_signed(d: str, current_root: str, current_digest: str, manifest: dict) -> bool:
    if not manifest.get("proof"):
        return False
    anchor = os.environ.get(core._ENV_SIGNERS)
    if not anchor or not os.path.isfile(anchor):
        return False
    sign_dir = os.path.join(d, core.SIGN_DIR)
    if not os.path.isdir(sign_dir):
        return False
    for name in sorted(os.listdir(sign_dir)):
        if not name.endswith(".sign.json"):
            continue
        spath = os.path.join(sign_dir, name)
        sig_path = spath + ".sig"
        if not os.path.isfile(sig_path):
            continue
        try:
            with open(spath, "rb") as f:
                stmt_bytes = f.read()
            statement = json.loads(stmt_bytes)
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(statement, dict):
            continue
        identity_name = statement.get("identity")
        if not isinstance(identity_name, str):
            continue
        if statement.get("root") != current_root or not statement.get("proof_recorded"):
            continue
        base = name[: -len(".sign.json")]
        if not _packet_bytes_valid(sign_dir, base, statement, current_root, current_digest):
            continue
        try:
            done = subprocess.run(
                ["ssh-keygen", "-Y", "verify", "-f", anchor, "-I", identity_name,
                 "-n", core.SIGN_NAMESPACE, "-s", sig_path],
                input=stmt_bytes, capture_output=True, timeout=10,
            )
        except OSError:
            continue
        if done.returncode == 0:
            return True
    return False


def phase(d: str) -> str:
    """`draft` / `sealed` / `signed` (`spec/verification.md`)."""
    d = _abs(d)
    recipe = load_recipe(d)
    manifest_path = os.path.join(d, core.MANIFEST)
    if not os.path.isfile(manifest_path):
        return "draft"
    manifest = _in_band(seal_mod.read_manifest, d)
    verified = _in_band(seal_mod.verify, d)
    if not verified["ok"]:
        return "sealed"
    current_digest = _in_band(identity.build_digest, d)
    if _is_signed(d, manifest["root"], current_digest, manifest):
        return "signed"
    return "sealed"


# -- signature-chain nodes ----------------------------------------------

def sign_node(root_value: str, digest: str, links: list) -> str:
    """One node of the bottom-anchored signature chain: a deterministic
    fold of a layer's root, its build digest, and the SET of signatures
    beneath it (order-independent)."""
    payload = {"root": root_value, "build_digest": digest, "links": sorted(links)}
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True).encode("utf-8")
    ).hexdigest()


