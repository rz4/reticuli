"""Crosscheck: the three-machine test, cold audit, and mutation testing.

`_audit_dir` re-earns a claim's verdict cold (identity first, then every
gate re-run in a fresh room against the generated bytes present); it is the
one place "earned vs. carried" is decided, and both `kernel.audit` and this
module's own leg inspection in `crosscheck` share it. `gate_deciders` /
`vacuous_gates` read a gate's `run` command to name the workspace files that
decide it, so a gate whose every decider is itself generated can be told
apart from a claim. `mutation_score` draws deterministic mutants of the
generated code from the claim's root and re-audits each one, cold, to
measure what the pinned criteria actually catch. `crosscheck` composes all
of this into the three-machine test (`spec/verification.md`): one root
across all three legs, byte reuse from M1 to M2, every verdict earned, the
cost band and every condition the claim itself declares -- a three-valued
verdict, because a declared condition nobody measured is neither proven nor
disproven.

A leg is a claim directory (judged live) or a signed record file
(`spec/record.md`, judged as relayed fact) -- the two transports mix freely
and must reach the same verdict.

Stdlib only, never the network.
"""
