"""Authoring: turning a recorded session into a claim
(`spec/layers.md`'s authoring layer).

A session's agent/hook writes a trace of what happened --
`.reticuli/draft.jsonl`, one JSON event per line (`prompt`, `write`,
`read`, `bash`). `propose` reads that trace and previews the claim it
would make: which files the session touched look like pinned inputs,
without copying or certifying anything. `build_claim` does the real
work -- it classifies every touched path as a pinned input or a
generated output (the trace has no authority here; `claim=`/`generated=`
override it), confines every one of them to the session directory
*before* touching a single byte, refuses a gate whose every decider is
itself generated (a vacuous check cannot be the claim), then certifies
cold: a fresh room gets only the recipe, the pinned inputs, and the
generated bytes already produced, and every gate is re-run there. A
verdict that does not reproduce -- a nondeterministic gate -- refuses to
seal. Runs every gate through `kernel.run_gate` only, never
`kernel.sandbox` directly, so a cold certification cannot skip the scrub,
the bound, or the sandbox.

Stdlib only.
"""
import json
import os
import re
import shlex
import shutil

from . import _util
from . import kernel
from . import render

TRACE = ".reticuli/draft.jsonl"

_SEGMENT_SPLIT = re.compile(r"\|\||&&|[;&|\n]")
_REDIRECTS = frozenset({">", ">>", "<", "1>", "2>", "2>>", "&>"})


# ---------------------------------------------------------------------------
# Reading a trace and guessing at candidate inputs
# ---------------------------------------------------------------------------

def _read_trace(ws: str) -> list:
    path = os.path.join(ws, TRACE)
    if not os.path.isfile(path):
        return []
    events = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                events.append(json.loads(line))
    return events


def _bash_candidate_tokens(cmd: str) -> list:
    """Every non-flag, non-redirect-target token in one shell command --
    candidates for "a real file this command names", filtered to actual
    files by the caller."""
    tokens = []
    for segment in _SEGMENT_SPLIT.split(cmd):
        segment = segment.strip()
        if not segment:
            continue
        try:
            toks = shlex.split(segment)
        except ValueError:
            continue
        skip_next = False
        for tok in toks:
            if skip_next:
                skip_next = False
                continue
            if tok in _REDIRECTS:
                skip_next = True
                continue
            if tok.startswith("-"):
                continue
            tokens.append(tok)
    return tokens


def _case_sensitive_file(base: str, relpath: str) -> bool:
    """Does `relpath` name a real file under `base`, matched component by
    component against the actual directory entries -- never folded by a
    case-insensitive filesystem (`spec/identity.md`: identity must not
    depend on the host filesystem)."""
    if not relpath or relpath.startswith("/"):
        return False
    parts = relpath.split("/")
    if any(p in ("", ".", "..") for p in parts):
        return False
    cur = base
    for part in parts:
        try:
            entries = os.listdir(cur)
        except OSError:
            return False
        if part not in entries:
            return False
        cur = os.path.join(cur, part)
    return os.path.isfile(cur) and not os.path.islink(cur)


def _scan_events(ws: str, events: list) -> tuple:
    """`(written, candidates)`: paths the session wrote, and paths it
    looks like it read -- an explicit `read` event's path, trusted as
    given, or a token of a `bash` command that names a real file."""
    written = set()
    candidates = set()
    for event in events:
        kind = event.get("event")
        if kind == "write":
            path = event.get("path")
            if path:
                written.add(path)
        elif kind == "read":
            path = event.get("path")
            if path:
                candidates.add(path)
        elif kind == "bash":
            for tok in _bash_candidate_tokens(event.get("cmd", "")):
                if _case_sensitive_file(ws, tok):
                    candidates.add(tok)
    return written, candidates


def propose(ws: str, outputs: list, name: str = None) -> dict:
    """Preview the claim a session's trace suggests: candidate pinned
    inputs, with no copying and no certification."""
    ws = os.path.abspath(ws)
    events = _read_trace(ws)
    written, candidates = _scan_events(ws, events)
    outputs_set = set(outputs)
    inputs = sorted(p for p in candidates if p not in outputs_set and p not in written)
    return {"claim": {"name": name, "inputs": inputs}}


# ---------------------------------------------------------------------------
# Certifying a claim cold
# ---------------------------------------------------------------------------

def _classify(events: list, outputs: list, candidates: set, written: set,
              explicit_claim: set, explicit_generated: set) -> tuple:
    outputs_set = set(outputs)
    raw_inputs = set()
    for p in candidates:
        if p in outputs_set or p in explicit_generated:
            continue
        if p in written and p not in explicit_claim:
            continue
        raw_inputs.add(p)
    for p in explicit_claim:
        if p not in outputs_set:
            raw_inputs.add(p)

    raw_generated = set()
    for p in written:
        if p in outputs_set or p in explicit_claim:
            continue
        raw_generated.add(p)
    for p in explicit_generated:
        if p not in outputs_set:
            raw_generated.add(p)
    return raw_inputs, raw_generated


def build_claim(ws: str, outputs: list, rec: str, name: str = None,
                claim: list = None, generated: list = None) -> dict:
    """Certify a session cold into the claim directory `rec`.

    `claim`/`generated` override the trace's own classification of a
    path: a file the trace shows being written is generated by default,
    unless `claim` names it as a pinned input; a file `generated` names
    is treated as an untraced implementation even with no `write` event
    for it at all.
    """
    ws = os.path.abspath(ws)
    rec = os.path.abspath(rec)
    outputs = list(outputs)
    events = _read_trace(ws)
    written, candidates = _scan_events(ws, events)
    explicit_claim = set(claim or [])
    explicit_generated = set(generated or [])

    raw_inputs, raw_generated = _classify(
        events, outputs, candidates, written, explicit_claim, explicit_generated)

    # confine every declared path to the session directory BEFORE a
    # single byte is copied -- a trace-derived path that escapes must
    # never reach the staging room on its way to the refusal.
    all_paths = raw_inputs | raw_generated
    resolved = {p: _util.safe_path(ws, p) for p in sorted(all_paths)}

    produce_steps = [
        {"kind": "produce", "output": p, "class": "generated",
         "guidance": f"regenerate {p} to pass the gate"}
        for p in sorted(raw_generated)
    ]
    bash_cmds = [e["cmd"] for e in events if e.get("event") == "bash"]
    if not bash_cmds:
        raise kernel.ClaimError("refused: no gate command recorded in the trace")
    gate_cmd = " && ".join(bash_cmds)
    gate_steps = [
        {"kind": "gate", "output": o, "class": "validated", "run": gate_cmd}
        for o in outputs
    ]
    recipe = {"claim": {"name": name or "claim", "inputs": sorted(raw_inputs)},
              "step": produce_steps + gate_steps}

    vacuous = set(kernel.vacuous_gates(recipe))
    hit = [o for o in outputs if o in vacuous]
    if hit:
        raise kernel.ClaimError(
            f"refused: vacuous gate(s), every decider is generated: {hit}")

    staging = rec + ".building"
    if os.path.isdir(staging):
        shutil.rmtree(staging)
    os.makedirs(staging)
    try:
        with open(os.path.join(staging, kernel.RECIPE), "w", encoding="utf-8") as f:
            f.write(render.dump_recipe(recipe))
        for p in sorted(all_paths):
            _util.copy_into(resolved[p], os.path.join(staging, p))

        result = kernel.run_gate(gate_cmd, staging, recipe)
        if result["status"] != "ok":
            raise kernel.ClaimError(
                f"refused: gate did not pass cold ({result['status']})")

        for o in outputs:
            cold_path = os.path.join(staging, o)
            warm_path = os.path.join(ws, o)
            if not os.path.isfile(cold_path):
                raise kernel.ClaimError(
                    f"refused: gate did not produce its verdict cold: {o!r}")
            if not os.path.isfile(warm_path):
                raise kernel.ClaimError(
                    f"refused: no warm verdict to certify against: {o!r}")
            if _util.hash_bytes(cold_path) != _util.hash_bytes(warm_path):
                raise kernel.ClaimError(
                    f"refused: verdict did not reproduce cold "
                    f"(nondeterministic gate?): {o!r}")

        calls = sum(1 for e in events if e.get("event") == "prompt")
        timestamps = [e["ts"] for e in events if isinstance(e.get("ts"), (int, float))]
        seconds = (max(timestamps) - min(timestamps)) if len(timestamps) >= 2 else 0.0
        kernel.ledger(staging, {"event": "session", "calls": calls, "seconds": seconds})

        manifest = kernel.seal(staging)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise

    os.makedirs(os.path.dirname(rec) or ".", exist_ok=True)
    if os.path.isdir(rec):
        shutil.rmtree(rec)
    shutil.move(staging, rec)
    return {"ok": True, "root": manifest["root"], "name": manifest["name"]}
