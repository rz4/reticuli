"""Deterministic transfer of a claim: declared content only, verify on
import, volatile history stays home (spec/layers.md, spec/claim-format.md).

A claim's declared content is its recipe, its pinned inputs, its
pinned/validated outputs, and (unless the export is blind) its generated
outputs present on disk -- never a stray file someone dropped in the
directory, and never the cost ledger, which is host residue about how the
claim was produced, not part of what it is. An embedded component travels
under `.reticuli/deps/<name>/`, always blind: a component's claim, never its
generated bytes, so an import can re-earn every ancestor layer from the
bytes it actually received.
"""
import io
import os
import shutil
import tarfile

from reticuli import kernel, _util

_SEALED = "sealed"
_DEPS = "deps"
_ATTEST = "attest"


def _recipe_name(d: str) -> str:
    for name in (kernel.RECIPE, _util.RECIPE):
        if os.path.isfile(os.path.join(d, name)):
            return name
    raise kernel.ClaimError(f"no recipe found in {d!r}")


def _own_files(d: str, blind: bool) -> list:
    """`d`'s own declared paths: the recipe, every pinned input, and --
    unless `blind` -- every generated output present now."""
    parsed = kernel.load_recipe(d)
    candidates = [_recipe_name(d)]
    candidates.extend(_util.declared_inputs(d))

    for step in parsed.get("step", []):
        output, cls = _util.step_output(step)
        if not isinstance(output, str):
            continue
        if cls == "generated":
            if blind:
                continue
            if os.path.isfile(_util.safe_path(d, output)):
                candidates.append(output)
        else:
            candidates.append(output)

    candidates.append(kernel.MANIFEST)

    seen, ordered = set(), []
    for rel in candidates:
        if rel in seen:
            continue
        if os.path.isfile(os.path.join(d, rel)):
            seen.add(rel)
            ordered.append(rel)
    return sorted(ordered)


def _attest_files(d: str) -> list:
    base = os.path.join(d, kernel.STORE, _ATTEST)
    if not os.path.isdir(base):
        return []
    out = []
    for root_dir, _dirs, names in os.walk(base):
        for name in names:
            full = os.path.join(root_dir, name)
            out.append(os.path.relpath(full, d).replace(os.sep, "/"))
    return sorted(out)


def _component_dir(d: str, name: str):
    for sub in (_SEALED, _DEPS):
        cand = os.path.join(d, kernel.STORE, sub, name)
        if os.path.isdir(cand):
            return cand
    return None


def _component_names(d: str) -> list:
    names = set()
    for sub in (_SEALED, _DEPS):
        base = os.path.join(d, kernel.STORE, sub)
        if os.path.isdir(base):
            names.update(n for n in os.listdir(base) if os.path.isdir(os.path.join(base, n)))
    return sorted(names)


def _entries(d: str, blind: bool) -> list:
    """`(arcname, source path)` pairs for everything `d` declares,
    components (always blind) and attestation residue included."""
    out = [(rel, os.path.join(d, rel)) for rel in _own_files(d, blind)]

    for name in _component_names(d):
        comp_dir = _component_dir(d, name)
        for rel in _own_files(comp_dir, True):
            arcname = f"{kernel.STORE}/{_DEPS}/{name}/{rel}"
            out.append((arcname, os.path.join(comp_dir, rel)))

    out.extend((rel, os.path.join(d, rel)) for rel in _attest_files(d))
    out.sort(key=lambda e: e[0])
    return out


def _tarinfo(arcname: str, size: int) -> tarfile.TarInfo:
    """A fixed-metadata member so two exports of one claim are byte-identical."""
    info = tarfile.TarInfo(arcname)
    info.size = size
    info.mtime = 0
    info.uid = info.gid = 0
    info.uname = info.gname = ""
    info.mode = 0o644
    info.type = tarfile.REGTYPE
    return info


def export(d: str, tar_path: str, blind: bool = False) -> dict:
    """Write a deterministic tar of `d`'s declared content to `tar_path`."""
    entries = _entries(d, blind)
    directory = os.path.dirname(tar_path) or "."
    os.makedirs(directory, exist_ok=True)
    with tarfile.open(tar_path, "w", format=tarfile.USTAR_FORMAT) as tar:
        for arcname, src in entries:
            with open(src, "rb") as f:
                data = f.read()
            tar.addfile(_tarinfo(arcname, len(data)), io.BytesIO(data))
    return {"path": tar_path, "members": [e[0] for e in entries]}


def import_(tar_path: str, dest: str) -> dict:
    """Extract `tar_path`'s declared content into `dest`, confined to it,
    then verify the claim's identity holds from the received bytes alone."""
    if os.path.exists(dest) and os.listdir(dest):
        raise kernel.ClaimError(f"refuses to import into a non-empty directory: {dest!r}")
    os.makedirs(dest, exist_ok=True)

    with tarfile.open(tar_path, "r") as tar:
        for member in tar.getmembers():
            if not member.isfile():
                continue
            target = _util.safe_path(dest, member.name)
            os.makedirs(os.path.dirname(target) or dest, exist_ok=True)
            src = tar.extractfile(member)
            with src, open(target, "wb") as out:
                shutil.copyfileobj(src, out)

    _util._sync_aliases(dest)
    verified = kernel.verify(dest)
    return {"ok": verified["ok"], "root": verified["root"]}
