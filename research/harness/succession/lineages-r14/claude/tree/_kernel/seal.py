"""Sealing and verifying identity (spec/identity.md, spec/verification.md).

`seal` computes a claim's root from the bytes present and freezes it onto
`.reticuli/manifest.json`, the pure-identity record (`{name, root}`).
`verify` recomputes the root from the bytes present now and reports
whether it still matches the sealed value -- identity only; no gate runs
here, by the `verify`/`audit` division of spec/verification.md. The root
is a function of the recipe and the pinned inputs and outputs; the
generated bytes never enter it (spec/identity.md), so rewriting an
implementation keeps the root and editing a pinned byte moves it.
"""
import json
import os

from . import core
from . import identity as _identity
from . import recipe as _recipe
from .core import ClaimError

_PARTS_RESIDUE = ".reticuli/parts.json"


def _changed_parts(old_parts: dict, new_parts: dict) -> list:
    """Keys whose value differs between two root-preimage `parts` maps
    (spec/identity.md), including a key present on only one side."""
    keys = set(old_parts) | set(new_parts)
    return sorted(k for k in keys if old_parts.get(k) != new_parts.get(k))


def seal(d: str) -> dict:
    """Compute `d`'s root and write `.reticuli/manifest.json` (name, root)."""
    parsed = _recipe.load_recipe(d)
    name = parsed.get("claim", {}).get("name")
    parts = _identity._parts(parsed, d)
    root = _identity._sha256_text(_identity._canonical_json(parts))
    manifest = {"name": name, "root": root}

    os.makedirs(os.path.join(d, core.STORE), exist_ok=True)
    core._write_json(os.path.join(d, core.MANIFEST), manifest)
    core._write_json(os.path.join(d, _PARTS_RESIDUE), parts)
    return manifest


def read_manifest(d: str) -> dict:
    """Read `d`'s manifest; malformed bytes refuse as a `ClaimError`."""
    path = os.path.join(d, core.MANIFEST)
    try:
        with open(path, "r", encoding="utf-8") as f:
            raw = f.read()
    except OSError as e:
        raise ClaimError(f"no manifest found in {d!r}: {e}") from e

    try:
        doc = json.loads(raw)
    except json.JSONDecodeError as e:
        raise ClaimError(f"malformed manifest {path!r}: {e}") from e

    if not isinstance(doc, dict):
        raise ClaimError(f"malformed manifest {path!r}: not a JSON object")
    name = doc.get("name")
    root = doc.get("root")
    if not isinstance(name, str):
        raise ClaimError(f"manifest {path!r}: missing or invalid 'name'")
    if not isinstance(root, str) or len(root) != 64:
        raise ClaimError(f"manifest {path!r}: missing or invalid 'root'")
    return doc


def _read_parts_residue(d: str) -> dict:
    """The parts map recorded at the last `seal`, or `{}` if none was kept."""
    path = os.path.join(d, _PARTS_RESIDUE)
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}


def verify(d: str) -> dict:
    """Recompute `d`'s root from the bytes present and compare it with the
    sealed manifest -- identity only, no gate runs (spec/verification.md)."""
    manifest = read_manifest(d)
    parsed = _recipe.load_recipe(d)

    try:
        parts = _identity._parts(parsed, d)
        recomputed = _identity._sha256_text(_identity._canonical_json(parts))
    except ClaimError as e:
        return {"ok": False, "root": manifest["root"], "recomputed": None,
                "error": str(e)}

    ok = recomputed == manifest["root"]
    result = {"ok": ok, "root": manifest["root"], "recomputed": recomputed}
    if not ok:
        result["changed"] = _changed_parts(_read_parts_residue(d), parts)
    return result
