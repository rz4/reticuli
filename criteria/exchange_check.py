"""Exchange conformance gate — the acceptance check of the `exchange` layer.

Claims meeting claims — and other parties: the registry (claim stores,
content-addressed component links, DAG-aware rebuild), transfer (deterministic
tar, verify-on-import, volatile history stays home), attestation (a
keyholder's signed statement of a build: signs only claims whose verdicts
reproduce from their own bytes — never a carried verdict — refuses tampered
statements, anchors identity to allowed signers), and records (spec/record.md:
the one document other programs may parse — emitted by re-earning the gates,
canonical in its bytes, closed in its vocabulary, signed in a namespace of its
own). Layers on the kernel; knows nothing of authoring or the CLI. Writes
EXCHANGE_OK iff the layer conforms. Stdlib only, so it runs in any clean
workspace.

    python3 checks/exchange_check.py       (from the repository root)
"""
