"""Kernel-identity conformance gate — the canonical serialization.

The root and the build digest are interchange currency: pinned by value so every
conformant kernel computes the same hex for the same claim (claims travel) and
the same digest for the same generated bytes (signatures travel). A rebuilt
identity layer iterates `root()` and `build_digest()` against these golden
vectors until the bytes agree. (This is spec/identity.md, byte for byte.) Writes
IDENTITY_OK.

    python3 criteria/identity_check.py        (from the repository root)
"""
