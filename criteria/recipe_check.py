"""Kernel-recipe conformance gate — parsing an untrusted recipe.

`load_recipe` reads a claim's recipe under either name (reticuli.toml, or
claim.toml for older claims), exposes its steps (`gates`, `produces`,
`generated_outputs`), and refuses hostile or malformed bytes in band (a
ClaimError, never a raw traceback). Writes RECIPE_OK.

    python3 criteria/recipe_check.py        (from the repository root)
"""
import os
import sys
import tempfile

SRC = "src" if os.path.isdir("src/reticuli") else "."
sys.path.insert(0, SRC)
from reticuli._kernel import core, recipe

GOOD = ('[claim]\nname = "fx"\ninputs = ["spec.txt"]\n\n[[step]]\n'
        'kind = "produce"\noutput = "impl.py"\nclass = "generated"\n'
        'request = "x"\n\n[[step]]\nkind = "gate"\noutput = "V"\n'
        'class = "validated"\nrun = "printf v > V"\n')


def _claim(d: str, toml: str, name: str = "reticuli.toml") -> str:
    room = os.path.join(d, name.replace(".", "_"))
    os.makedirs(room, exist_ok=True)
    with open(os.path.join(room, name), "w", encoding="utf-8") as f:
        f.write(toml)
    return room




# ==== seam block for recipe_check.py ====
# Paste into the check; call _seam() from its battery()/main.

# --- _kernel/recipe.py: 8 seam names (0 value, 0 kind, 8 callable) ---
_SEAM__kernel_recipe_VALUES = {
}
_SEAM__kernel_recipe_KINDS = {}
_SEAM__kernel_recipe_CALLABLES = ('_inputs', '_read_input_manifest', '_steps', 'gates', 'generated_outputs', 'load_recipe', 'produces', 'recipe_path')

def _seam() -> None:
    from reticuli._kernel import recipe as _m__kernel_recipe
    for _n, _v in _SEAM__kernel_recipe_VALUES.items():
        assert getattr(_m__kernel_recipe, _n) == _v, f'_kernel/recipe.py seam {_n} changed'
    for _n in _SEAM__kernel_recipe_KINDS:
        assert hasattr(_m__kernel_recipe, _n), f'_kernel/recipe.py must export {_n}'
    for _n in _SEAM__kernel_recipe_CALLABLES:
        assert callable(getattr(_m__kernel_recipe, _n, None)), f'_kernel/recipe.py must export callable {_n}'


def battery() -> None:
    _seam()
    d = tempfile.mkdtemp()
    try:
        r = _claim(d, GOOD)
        parsed = recipe.load_recipe(r)
        assert [s["kind"] for s in recipe._steps(parsed)] == ["produce", "gate"], \
            "the steps are read in order"
        assert [g["output"] for g in recipe.gates(parsed)] == ["V"], "gates() names the gate"
        assert [p["output"] for p in recipe.produces(parsed)] == ["impl.py"], \
            "produces() names the produce steps"
        assert recipe.generated_outputs(parsed) == ["impl.py"], \
            "generated_outputs() names the generated bytes"

        # the older recipe name still reads
        r2 = _claim(d, GOOD, "claim.toml")
        assert recipe.load_recipe(r2)["claim"]["name"] == "fx", \
            "claim.toml is read under its legacy name"

        # malformed or hostile recipes refuse IN BAND, never a raw traceback
        bad_recipes = (
            'not = [valid\n',
            ('[claim]\nname = "x"\n\n[[step]]\n'
             'kind = "explode"\noutput = "V"\nclass = "validated"\n'),
        )
        for bad in bad_recipes:
            rb = _claim(d, bad, "reticuli.toml")
            # reuse one dir: overwrite
            with open(os.path.join(rb, "reticuli.toml"), "w", encoding="utf-8") as f:
                f.write(bad)
            try:
                recipe.load_recipe(rb)
            except core.ClaimError:
                pass
            else:
                raise AssertionError(f"a malformed recipe must refuse in band: {bad!r}")

        # THE FORMAT-5 VOCABULARY GATES AT PARSE (the APEIRON batch). Each
        # new key carries semantics an older kernel would not enforce —
        # carried bytes copied not regrown, constrains held at seal, members
        # held to their declared roots — so a declaration below format 5
        # refuses in words, and format 5 closes the class vocabulary (an
        # unknown class used to silently mean "pinned", a typo deciding
        # identity). Format 4 and below keep the loose reading: no sealed
        # claim is stranded.
        gate5 = ('[[step]]\nkind = "gate"\noutput = "V"\nclass = "validated"\n'
                 'run = "printf v > V"\n')
        refusals = (
            ('[claim]\nname = "x"\nformat = 4\ninputs = []\n\n[[step]]\n'
             'kind = "produce"\noutput = "N.md"\nclass = "carried"\n\n' + gate5,
             "carried below 5"),
            ('[claim]\nname = "x"\nformat = 4\ninputs = ["c.py"]\n'
             'constrains = { "c.py" = ["i.py"] }\n\n' + gate5,
             "constrains below 5"),
            ('[claim]\nname = "x"\nformat = 4\ninputs = []\n'
             'assembles = ["m@' + "0" * 64 + '"]\n\n' + gate5,
             "assembles below 5"),
            ('[claim]\nname = "x"\nformat = 5\ninputs = []\n\n[[step]]\n'
             'kind = "produce"\noutput = "i.py"\nclass = "pined"\n\n' + gate5,
             "an unknown class at 5"),
            (('[claim]\nname = "x"\nformat = 5\ninputs = []\n\n[[step]]\n'
              'kind = "gate"\noutput = "V"\nclass = "carried"\n'
              'run = "printf v > V"\n'),
             "a carried gate"),
            ('[claim]\nname = "x"\nformat = 5\ninputs = []\n'
             'assembles = ["m@short"]\n\n' + gate5,
             "a member without a 64-hex root"),
            ('[claim]\nname = "x"\nformat = 5\ninputs = ["c.py"]\n'
             'constrains = { "other.py" = ["i.py"] }\n\n' + gate5,
             "a constrains key that is not an input"),
        )
        rb5 = _claim(d, "placeholder = 1\n", "reticuli.toml")
        for text, why in refusals:
            with open(os.path.join(rb5, "reticuli.toml"), "w",
                      encoding="utf-8") as f:
                f.write(text)
            try:
                recipe.load_recipe(rb5)
            except core.ClaimError:
                pass
            else:
                raise AssertionError(f"{why} must refuse in band")
        # and the vocabulary used correctly at format 5 parses
        with open(os.path.join(rb5, "reticuli.toml"), "w",
                  encoding="utf-8") as f:
            f.write('[claim]\nname = "x"\nformat = 5\ninputs = ["c.py"]\n'
                    'constrains = { "c.py" = ["i.py"] }\n'
                    'assembles = ["m@' + "a" * 64 + '"]\n\n'
                    '[[step]]\nkind = "produce"\noutput = "i.py"\n'
                    'class = "generated"\n\n'
                    '[[step]]\nkind = "produce"\noutput = "N.md"\n'
                    'class = "carried"\n\n' + gate5)
        parsed5 = recipe.load_recipe(rb5)
        assert [s.get("class") for s in recipe.produces(parsed5)] \
            == ["generated", "carried"], "format 5 reads its own vocabulary"
    finally:
        import shutil
        shutil.rmtree(d, ignore_errors=True)


if __name__ == "__main__":
    battery()
    if os.path.isfile("reticuli.toml") or os.path.isfile("claim.toml"):
        with open("RECIPE_OK", "w", encoding="utf-8") as f:
            f.write("recipe-ok\n")
    print("recipe-ok")
