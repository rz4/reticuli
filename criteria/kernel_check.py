"""Kernel conformance gate — the fixed check that defines "a correct kernel".

This is the pinned input of the `kernel-core` claim. It imports the
(re)generated kernel and confirms it implements the invariant: seal + verify
hold, an independent rebuild lands on the *same root* (the root is the
claim's identity), the three-machine test is satisfied — and is SOUND:
verdicts must be earned, not carried, so a fabricated machine that shares
the root but whose gates cannot reproduce its verdicts from its own bytes
neither crosschecks nor signs (audit). Cost is accounted: a rebuild leaves a
ledger (residue, outside the root), an unmeasured machine is reported rather
than failed, an incomparable rebuild fails the test. And gates run
sandboxed: where the platform has a sandbox, an escaping gate refuses, and
the ledger tells the truth about the sandbox either way. Gates COMPOSE and
verdicts never carry: audit can judge substituted generated bytes by a
claim (how a dependent's shipped code is re-earned by its component's
check). Failures are told apart (mismatch / failed / timeout /
environment), a declared `requires` that the host lacks is an environment
failure and never a verdict, a gate whose every decider is generated is
VACUOUS, the check's MUTATION SCORE is measurable (mutants of the generated
code, drawn deterministically from the root) and a declared floor gates the
test, and the rebuild's producer is declared on the ledger. v2.2 pins three
more: a declared path may contain NO symlink component and no `..` (an
internal link aliases generated bytes as pinned ones); RECORDS
(spec/record.md) are the crosscheck's second transport — the reader is
pinned (canonical bytes, closed vocabulary, refusals in band, the
reticuli.record namespace), a frozen leg reaches the directory verdict, and
a durable proof from records embeds anchored signer identities or refuses;
and audit of a claim whose gate is itself a kernel reports completely —
gate name, status, sandbox — never a shrug. v2.3 pins three more: the
recipe's TWO NAMES (reticuli.toml is canonical, claim.toml stays readable
forever, and twins under the two names share one root — finding 13, the
gap that made two earlier kernels unable to read the claim they satisfied);
the PINNED ENVELOPE and the THREE-VALUED VERDICT (`[claim] envelope`
ceilings enforced on the redo's ledger: a measured overrun rejects, a
declared-but-unmeasured condition — ceiling or mutation floor — makes the
verdict incomplete, which can never accept, and damaged tables refuse at
parse); and the DECLARED ENVIRONMENT (`[claim] environment` is a pinned
input, the room is furnished from exactly its hash-named artifacts before
judging, and an unfurnishable room is untested, never disproven). Writes
KERNEL_OK iff it conforms. Stdlib only, so it runs in any clean room.

THE EXECUTION CONTRACT: gates are judged *inside* a platform sandbox when the
host has one (sandbox-exec on darwin, bwrap on linux), and sandboxes do not
nest. The environment variable RETICULI_JAILED means "you are already inside
one" — a conformant kernel must then inherit (run the gate unwrapped, record
its sandbox status as inherited) rather than re-apply a sandbox, which would
refuse. To make a producer's test environment equal the verdict environment,
this check re-execs itself under the host sandbox when run bare — so a
kernel that re-applies fails here, visibly, not only at the final gate. BOTH
HALVES of that contract are pinned, because two independent rebuilds split on
the second: a kernel that APPLIES a sandbox must also SAY so to the process it
wraps (RETICULI_JAILED = the backend), or a gate that is itself a claim runner
nests and dies with `sandbox_apply: Operation not permitted`; and the gate it
wraps must be handed a TMPDIR and a HOME it can actually write, since a real
sandbox permits writes only inside the claim while the host's point outside
it. Both are observable only where a sandbox is really APPLIED, which is the
one moment this check is not already inside one — before the re-exec, in
_apply_battery.

Any kernel that passes this check hashes to the same kernel-core root — the
equivalence class of kernels is what the claim *is*. The whole toolchain
layers on top: each layer's own gate certifies what it builds over a
conformant kernel, layer by layer.
"""
