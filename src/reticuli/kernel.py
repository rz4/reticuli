"""The kernel layer: a claim's identity, its seal, and the verdicts it earns.

A CLAIM is a directory holding

    claim.toml        the recipe: what is pinned, what is generated, what gates
    <pinned bytes>    the inputs the recipe names and the outputs it pins
    <generated bytes> the implementation, free within the claim
    .reticuli/        residue: the manifest, the ledger, signing material

THE ROOT is the claim's identity: a hash over the recipe, the pinned input
bytes, and the pinned (non-generated) output bytes.  Generated bytes never
enter it -- that freedom IS the equivalence class, the set of implementations
the claim admits.  Its preimage is canonical (see `root`) so a claim travels:
two independent kernels compute the same hex for the same claim, and each can
verify what the other sealed.

THE BUILD DIGEST is the concrete generated bytes the root ignores.  A
signature binds it, so authorization freezes an implementation even though the
identity floats above it.  Its preimage is canonical too, so signatures travel.

VERDICTS ARE EARNED, NOT CARRIED.  `verify` only says the bytes still hash to
the sealed root; `audit` re-runs the claim's gates against the bytes present
and re-checks that the claim itself still holds.  `crosscheck` is the
three-machine test: one root across an original, a byte-reuse, and an
independent redo, with every verdict re-earned on its own bytes.

GATES RUN SANDBOXED, and sandboxes do not nest: when RETICULI_JAILED says we
are already inside one, a gate is run unwrapped and its quarantine is recorded
as `inherited` rather than re-applied.

Stdlib only.  The kernel touches the machine -- files, and subprocess for the
sandbox -- but it never reaches the network.
"""
