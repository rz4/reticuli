class ClaimError(Exception):
    """A claim is damaged, hostile, or cannot be judged here.

    Everything the kernel refuses, it refuses in band with this: hostile bytes
    never surface as a raw TOMLDecodeError / JSONDecodeError / KeyError, and a
    verifier facing a wreck neither crashes nor blesses it.
    """


# ------------------------------------------------------------- small helpers

def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _write_json(path: str, payload) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(payload, f, sort_keys=True, indent=2)
        f.write("\n")
    os.replace(tmp, path)


def _safe(claimdir: str, name: str) -> str:
    """THE PATH BOUNDARY.  Resolve `name` inside the claim, or refuse.

    A claim's own recipe is untrusted input: a name that is absolute, climbs
    out with `..`, or is a symlink whose target leaves the claim would let the
    kernel read or write outside the claim it is judging.  Links are resolved
    before judging -- a lexical check would follow them.
    """
    if not isinstance(name, str) or not name:
        raise ClaimError(f"not a usable path: {name!r}")
    if "\x00" in name:
        raise ClaimError("a path may not contain NUL")
    if os.path.isabs(name) or name.startswith("~"):
        raise ClaimError(f"path escapes the claim (not relative): {name}")
    base = os.path.realpath(claimdir)
    resolved = os.path.realpath(os.path.join(base, name))
    if resolved == base:
        raise ClaimError(f"path is the claim directory itself: {name}")
    if not resolved.startswith(base + os.sep):
        raise ClaimError(f"path escapes the claim directory: {name}")
    return resolved


def _hash_file(path: str) -> str:
    """THE BYTES BOUNDARY.  sha256 of a file that lives inside the claim.

    A declared file must be a REGULAR file with a SINGLE link, so its bytes are
    the claim's own.  A hardlink to an outside inode keeps a local-looking name
    yet seals foreign bytes; a FIFO or device would block or feed nonsense into
    the claim; a directory is not a file.  All are refused here.
    """
    try:
        st = os.lstat(path)
    except OSError as exc:
        raise ClaimError(f"declared file is unreadable: {path} ({exc.strerror})") from None
    if stat.S_ISLNK(st.st_mode):
        raise ClaimError(f"declared file is a symlink: {path}")
    if stat.S_ISDIR(st.st_mode):
        raise ClaimError(f"declared file is a directory: {path}")
    if not stat.S_ISREG(st.st_mode):
        raise ClaimError(f"declared file is not a regular file: {path}")
    if st.st_nlink != 1:
        raise ClaimError(f"declared file has {st.st_nlink} links, so its bytes "
                         f"live outside the claim too: {path}")
    digest = hashlib.sha256()
    try:
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                digest.update(chunk)
    except OSError as exc:
        raise ClaimError(f"declared file is unreadable: {path} ({exc})") from None
    return digest.hexdigest()


def _copy_into(src: str, dst: str) -> None:
    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    try:
        shutil.copyfile(src, dst)
        # Carry the permission bits: a generated output may legitimately BE an
        # executable (a compiled binary), and copyfile drops the exec bit, so a
        # gate that runs its own output would fail with "Permission denied" the
        # moment the claim is materialized anywhere. Only the low 9 bits travel
        # -- setuid, setgid and sticky are deliberately not carried into a
        # workspace the kernel just created.
        os.chmod(dst, stat.S_IMODE(os.stat(src).st_mode) & 0o777)
    except (OSError, shutil.Error) as exc:
        raise ClaimError(f"cannot materialize {dst}: {exc}") from None


def _steps(recipe) -> list:
    steps = (recipe or {}).get("step") or []
    return [s for s in steps if isinstance(s, dict)]


MANIFEST_KEY = "inputs_manifest"


def _read_input_manifest(claimdir: str, name: str) -> list:
    """Read a pinned list of input paths from a file instead of the recipe.

    A claim over a real corpus enumerates hundreds of files, and putting every
    path in the recipe body makes it unreadable and its diffs useless -- the
    TOML conformance example is 920 paths in a 44KB recipe. The list moves into
    a file, which is ITSELF a pinned input, so the whole set is still committed
    to by the root: change the corpus and the manifest changes and the root
    moves, exactly as before.

    What this must NOT become is a wildcard evaluated at read time. Identity
    would then depend on what happens to be in the directory when someone
    looks, which is the one thing a content address cannot tolerate. The
    manifest is a fixed list, written once at seal time.

    Format: one path per line, optionally `<sha256>  <path>` so the file is
    meaningful on its own. Blank lines and `#` comments are ignored.
    """
    path = _safe(claimdir, name)
    try:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    except (OSError, UnicodeDecodeError) as exc:
        raise ClaimError(f"unreadable [claim] {MANIFEST_KEY} {name}: {exc}") from None
    out = []
    for lineno, raw in enumerate(lines, 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        entry = parts[1].strip() if len(parts) == 2 and len(parts[0]) == 64 else line
        if not entry:
            raise ClaimError(f"{name}:{lineno}: empty input path")
        out.append(entry)
    return out


def _inputs(recipe, claimdir: str | None = None) -> list:
    claim = (recipe or {}).get("claim") or {}
    ins = claim.get("inputs") or []
    if isinstance(ins, str):
        ins = [ins]
    if not isinstance(ins, list):
        raise ClaimError("[claim] inputs must be a list of paths")
    for name in ins:
        if not isinstance(name, str):
            raise ClaimError(f"[claim] inputs must be paths: {name!r}")
    ins = list(ins)

    listed = claim.get(MANIFEST_KEY)
    if listed is not None:
        if not isinstance(listed, str) or not listed:
            raise ClaimError(f"[claim] {MANIFEST_KEY} must be a path, got {listed!r}")
        if claimdir is None:
            # The manifest names a file, so the paths cannot be resolved from
            # the recipe alone. Callers that only have a parsed recipe get the
            # declared list; every caller that hashes or materializes passes
            # the directory.
            return ins + [listed]
        return ins + [listed] + _read_input_manifest(claimdir, listed)
    return ins


# --------------------------------------------------------------- the recipe

def load_recipe(claimdir: str) -> dict:
    """Parse and validate `claim.toml`.  Hostile bytes are refused here.

    The step vocabulary is closed (produce, gate), so an unknown kind is caught
    at parse rather than surfacing later as a KeyError deep inside a rebuild.
    """
    path = os.path.join(claimdir, RECIPE)
    if not os.path.isfile(path):
        raise ClaimError(f"no recipe at {path}")
    try:
        with open(path, "rb") as f:
            recipe = tomllib.load(f)
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        raise ClaimError(f"damaged recipe {path}: {exc}") from None
    if not isinstance(recipe, dict):
        raise ClaimError(f"damaged recipe {path}: not a table")

    claim = recipe.get("claim")
    if not isinstance(claim, dict):
        raise ClaimError(f"recipe has no [claim] table: {path}")
    name = claim.get("name")
    if not isinstance(name, str) or not name.strip():
        raise ClaimError(f"recipe has no [claim] name: {path}")

    # Format version. Absent means 1, so today's claims declare nothing and
    # keep their roots. Its only job is DIAGNOSTIC: the recipe text is inside
    # the root, so a claim written in a future format already fails to verify
    # under an older kernel -- but it fails as a bare hash mismatch, which
    # says nothing about why. Declaring the format turns that into a sentence.
    declared = claim.get("format", 1)
    if isinstance(declared, bool) or not isinstance(declared, int) or declared < 1:
        raise ClaimError(f"[claim] format must be a positive integer, got {declared!r}")
    if declared > FORMAT:
        raise ClaimError(
            f"claim format {declared} is newer than this kernel understands "
            f"(format {FORMAT}); upgrade reticuli to read it")
    _inputs(recipe)

    steps = recipe.get("step")
    if steps is None:
        steps = []
    if not isinstance(steps, list) or any(not isinstance(s, dict) for s in steps):
        raise ClaimError(f"[[step]] must be a list of tables: {path}")
    for index, step in enumerate(steps):
        kind = step.get("kind")
        if kind not in KINDS:
            raise ClaimError(f"unknown step kind: {kind!r} "
                             f"(the vocabulary is {sorted(KINDS)})")
        output = step.get("output")
        if output is not None and (not isinstance(output, str) or not output):
            raise ClaimError(f"a step output must be a path: {output!r}")
        if kind == "gate":
            if not isinstance(step.get("run"), str) or not step["run"].strip():
                raise ClaimError(f"gate {output!r} has no run command")
            if not output:
                raise ClaimError(
                    f"a gate must declare the output it pins "
                    f"(step {index}, run {step.get('run')!r}): {path}")
    return recipe


def gates(recipe) -> list:
    return [s for s in _steps(recipe) if s.get("kind") == "gate"]


def produces(recipe) -> list:
    return [s for s in _steps(recipe) if s.get("kind") == "produce"]


def generated_outputs(recipe) -> list:
    return [s["output"] for s in produces(recipe)
            if s.get("class") == "generated" and isinstance(s.get("output"), str)]


# ------------------------------------------------------- identity and digest

def root(recipe, claimdir: str) -> str:
    """THE CANONICAL ROOT.  The claim's identity, and interchange currency.

    lowercase hex sha256 of json.dumps(parts, sort_keys=True) with DEFAULT
    separators, where parts is

        "digest"          -> "sha256"                       the algorithm, in-band
        "recipe"          -> json.dumps(recipe, sort_keys=True)
        "input:<path>"    -> sha256(input bytes)            per [claim].inputs
        "pinned:<output>" -> sha256(output bytes)           per non-generated step

    Generated outputs never enter the preimage.  Every path crosses `_safe`
    first, so a recipe cannot name its way out of its own directory.
    """
    if not isinstance(recipe, dict):
        raise ClaimError("a recipe must be a table")
    try:
        serialized = json.dumps(recipe, sort_keys=True)
    except (TypeError, ValueError) as exc:
        raise ClaimError(f"recipe is not serializable: {exc}") from None

    parts = {"digest": DIGEST, "recipe": serialized}
    for name in _inputs(recipe, claimdir):
        parts[f"input:{name}"] = _hash_file(_safe(claimdir, name))
    for step in _steps(recipe):
        if step.get("class") == "generated":
            continue                      # the equivalence class: never hashed
        output = step.get("output")
        if not isinstance(output, str) or not output:
            continue
        parts[f"pinned:{output}"] = _hash_file(_safe(claimdir, output))
    preimage = json.dumps(parts, sort_keys=True).encode("utf-8")
    return hashlib.sha256(preimage).hexdigest()


def build_digest(claimdir: str) -> str:
    """THE CANONICAL BUILD DIGEST.  The generated bytes a signature freezes.

    lowercase hex sha256 of json.dumps(sorted(own), sort_keys=True) with
    default separators, where `own` holds [output, sha256(bytes)] pairs for
    every step that is kind="produce", carries no `from` (a component's output
    is covered by folding that component's signature), is class="generated",
    and whose file is present.  An absent output is omitted; no such outputs
    digests the empty list.
    """
    recipe = load_recipe(claimdir)
    own = []
    for step in produces(recipe):
        if "from" in step:
            continue                      # belongs to a component, not to us
        if step.get("class") != "generated":
            continue                      # pinned bytes are the root's business
        output = step.get("output")
        if not isinstance(output, str) or not output:
            continue
        path = _safe(claimdir, output)
        if not os.path.isfile(path):
            continue                      # absent generated output: omitted
        own.append([output, _hash_file(path)])
    preimage = json.dumps(sorted(own), sort_keys=True).encode("utf-8")
    return hashlib.sha256(preimage).hexdigest()


def sign_node(root_hex: str, digest: str, below) -> str:
    """Fold one node of the signed identity chain, bottom-anchored.

    A layer's signature binds its root, the concrete generated bytes under that
    root, and the SET of signatures beneath it -- enumeration order is not
    identity, so the same DAG folds the same way however it is walked.
    """
    beneath = sorted({str(x) for x in (below or [])})
    payload = {"root": str(root_hex), "build_digest": str(digest), "below": beneath}
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()


# -------------------------------------------------------- manifest and seal

def read_manifest(claimdir: str) -> dict:
    """The sealed manifest, or a refusal.  Damaged residue is never data."""
    path = os.path.join(claimdir, MANIFEST)
    if not os.path.isfile(path):
        raise ClaimError(f"no manifest at {path}: the claim is not sealed")
    try:
        with open(path, "rb") as f:
            manifest = json.loads(f.read().decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        raise ClaimError(f"damaged manifest {path}: {exc}") from None
    if not isinstance(manifest, dict):
        raise ClaimError(f"damaged manifest {path}: not an object")
    if not isinstance(manifest.get("name"), str):
        raise ClaimError(f"damaged manifest {path}: name is not a string")
    stored = manifest.get("root")
    if stored is not None and not isinstance(stored, str):
        raise ClaimError(f"damaged manifest {path}: root is not a string")
    return manifest


def seal(claimdir: str) -> dict:
    """Freeze the claim's identity onto its manifest.

    Sealing computes the root and records it.  It does not run gates: the
    verdicts belong to `audit`, which earns them, and a seal that re-ran the
    gates in place would overwrite the very pinned bytes it is meant to fix.
    """
    recipe = load_recipe(claimdir)
    computed = root(recipe, claimdir)
    manifest = {}
    if os.path.isfile(os.path.join(claimdir, MANIFEST)):
        try:
            manifest = read_manifest(claimdir)
        except ClaimError:
            manifest = {}                 # a wreck is replaced, not trusted
    manifest.update({
        "name": recipe["claim"]["name"],
        "digest": DIGEST,
        "root": computed,
        "sealed": _now(),
    })
    _write_json(os.path.join(claimdir, MANIFEST), manifest)
    return manifest


def verify(claimdir: str) -> dict:
    """Does the claim still hash to what was sealed?

    This is the shallow check -- identity, not verdict.  `root` is the sealed
    identity, `recomputed` is what the bytes on disk say now.  A generated
    rebuild keeps them equal; an edited input moves them apart.
    """
    recipe = load_recipe(claimdir)
    manifest = read_manifest(claimdir)
    recomputed = root(recipe, claimdir)
    stored = manifest.get("root")
    return {
        "ok": isinstance(stored, str) and stored == recomputed,
        "root": stored,
        "recomputed": recomputed,
        "name": manifest.get("name"),
        "claim": os.path.abspath(claimdir),
    }


# ----------------------------------------------------------- the environment

def preflight(recipe) -> list:
    """What this host lacks of everything the claim declared it `requires`.

    A missing requirement is an ENVIRONMENT failure, never a verdict: the gate
    was not run, so nothing was proven and nothing was disproven.
    """
    claim = (recipe or {}).get("claim") or {}
    required = claim.get("requires") or []
    if isinstance(required, str):
        required = [required]
    if not isinstance(required, list):
        raise ClaimError("[claim] requires must be a list of tools")
    missing = []
    for want in required:
        if not isinstance(want, str) or not want.strip():
            missing.append(str(want))
            continue
        if not _have(want.strip()):
            missing.append(want)
    return missing


_REQ_OPS = ("<=", ">=", "==", "!=", "~=", "<", ">")


def _have(requirement: str) -> bool:
    name, op, want = requirement, None, None
    for candidate in _REQ_OPS:
        at = requirement.find(candidate)
        if at > 0:
            name = requirement[:at].strip()
            op = candidate
            want = requirement[at + len(candidate):].strip()
            break
    if not name:
        return False
    if name in ("python", "python3", "cpython"):
        have = ".".join(str(part) for part in sys.version_info[:3])
    else:
        if shutil.which(name) is None:
            return False
        if op is None:
            return True
        have = _tool_version(name)
        if have is None:
            return True               # present but unparseable: not "missing"
    if op is None:
        return True
    return _version_ok(have, op, want)


def _tool_version(name: str):
    try:
        proc = subprocess.run([name, "--version"], capture_output=True,
                              timeout=20, check=False)
    except (OSError, subprocess.SubprocessError):
        return None
    text = (proc.stdout or b"").decode("utf-8", "replace") + \
           (proc.stderr or b"").decode("utf-8", "replace")
    found = re.search(r"\d+(?:\.\d+)*", text)
    return found.group(0) if found else None


def _version_tuple(text: str) -> tuple:
    return tuple(int(part) for part in re.findall(r"\d+", text or "")[:4]) or (0,)


def _version_ok(have: str, op: str, want: str) -> bool:
    a, b = _version_tuple(have), _version_tuple(want)
    width = max(len(a), len(b))
    a = a + (0,) * (width - len(a))
    b = b + (0,) * (width - len(b))
    if op == ">=":
        return a >= b
    if op == ">":
        return a > b
    if op == "<=":
        return a <= b
    if op == "<":
        return a < b
    if op == "!=":
        return a != b
    return a == b                      # "==" and "~=" both mean "this version"


# ---------------------------------------------------------- the sandbox

_BWRAP_OK = None


def _bwrap_usable() -> bool:
    global _BWRAP_OK
    if _BWRAP_OK is None:
        if not shutil.which("bwrap"):
            _BWRAP_OK = False
        else:
            try:
                probe = subprocess.run(
                    ["bwrap", "--ro-bind", "/", "/", "--unshare-net", "true"],
                    capture_output=True, check=False, timeout=30)
                _BWRAP_OK = probe.returncode == 0
            except (OSError, subprocess.SubprocessError):
                _BWRAP_OK = False
    return _BWRAP_OK


def sandbox_backend() -> str:
    """Which jail a gate will be judged in, here, now.

    Sandboxes do not nest: inside one already (RETICULI_JAILED), the honest
    answer is `inherited` -- run the gate unwrapped and say so.  Re-applying a
    sandbox inside a sandbox refuses, which would turn every verdict into a
    platform artefact.
    """
    if os.environ.get(_JAILED):
        return "inherited"
    if sys.platform == "darwin" and shutil.which("sandbox-exec"):
        return "seatbelt"
    if _bwrap_usable():
        return "bubblewrap"
    return "none"


def _sandbox_argv(command: str, workdir: str):
    backend = sandbox_backend()
    inner = [_SHELL, "-c", command]
    work = os.path.realpath(workdir)
    if backend == "seatbelt":
        quoted = work.replace("\\", "\\\\").replace('"', '\\"')
        profile = ('(version 1)(allow default)(deny network*)(deny file-write*)'
                   f'(allow file-write* (subpath "{quoted}") (subpath "/dev"))')
        return ["sandbox-exec", "-p", profile] + inner, backend
    if backend == "bubblewrap":
        return (["bwrap", "--ro-bind", "/", "/", "--dev-bind", "/dev", "/dev",
                 "--proc", "/proc", "--bind", work, work, "--unshare-net",
                 "--die-with-parent", "--chdir", work] + inner), backend
    return inner, backend


def _scrub_env(extra=None) -> dict:
    """The environment a gate may see: an allowlist, nothing inherited."""
    env = {}
    for name in _KEEP_ENV:
        value = os.environ.get(name)
        if value:
            env[name] = value
    env.setdefault("PATH", os.defpath)
    if extra:
        env.update({k: str(v) for k, v in extra.items() if v is not None})
    return env


def _kill_tree(proc) -> None:
    try:
        os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
    except (OSError, AttributeError):
        try:
            proc.kill()
        except OSError:
            pass


def _run(argv, cwd=None, env=None, timeout=None) -> dict:
    """Run to completion or kill the whole process group at the ceiling.

    The group matters: `sh -c "sleep 30 && ..."` forks, so killing the shell
    alone leaves the child holding the pipes and the verifier hangs anyway.
    """
    started = time.monotonic()
    try:
        proc = subprocess.Popen(argv, cwd=cwd, env=env,
                                stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                start_new_session=True)
    except OSError as exc:
        raise ClaimError(f"cannot execute {argv[0]!r}: {exc}") from None
    timed_out = False
    try:
        out, err = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        _kill_tree(proc)
        try:
            out, err = proc.communicate(timeout=10)
        except (subprocess.TimeoutExpired, OSError, ValueError):
            out, err = b"", b""
    elapsed = time.monotonic() - started
    code = proc.returncode
    return {
        "status": "timeout" if timed_out else ("ok" if code == 0 else "failed"),
        "returncode": code,
        "seconds": elapsed,
        "stdout": (out or b"").decode("utf-8", "replace"),
        "stderr": (err or b"").decode("utf-8", "replace"),
        "timed_out": timed_out,
    }


def sandbox(command: str, workdir: str, timeout=None, env=None):
    """Run `command` in `workdir` under whatever jail this host has.

    Returns (result, backend).  The backend is reported even when it is
    "none" -- the ledger tells the truth about the sandbox either way.
    """
    argv, backend = _sandbox_argv(command, workdir)
    env = _scrub_env() if env is None else env
    if backend in ("seatbelt", "bubblewrap"):
        # SAY that a sandbox was applied. "Sandboxes do not nest" is only half a
        # contract if the wrapper never tells the wrapped process it is inside
        # one: a gate that itself runs claims would re-apply the sandbox and die
        # ("sandbox_apply: Operation not permitted"). Setting the signal here is
        # what lets a nested kernel inherit instead of nesting -- the same thing
        # this kernel's own check does when it re-execs itself.
        env = {**env, _JAILED: backend}
        # A REAL sandbox permits writes only inside the claim, but TMPDIR and
        # HOME are inherited from the host and point outside it -- so anything
        # the gate does with tempfile, or any tool that wants a home, is denied.
        # Hand the gate a scratch directory it can actually write. It lives in
        # the store, so it is residue: outside the root, and never a declared
        # file.
        scratch = os.path.join(os.path.realpath(workdir), STORE, "tmp")
        try:
            os.makedirs(scratch, exist_ok=True)
            env = {**env, "TMPDIR": scratch, "HOME": scratch}
        except OSError:
            pass                        # unwritable claim: let the gate report it
    result = _run(argv, cwd=workdir, env=env, timeout=timeout)
    result["quarantine"] = backend
    return result, backend


def gate_timeout(recipe=None, override=None) -> float:
    """A gate's wall-clock ceiling: declarable, capped by the environment."""
    claim = (recipe or {}).get("claim") or {}
    declared = override if override is not None else claim.get("gate_timeout")
    try:
        limit = float(declared) if declared is not None else GATE_TIMEOUT
    except (TypeError, ValueError):
        limit = GATE_TIMEOUT
    cap = os.environ.get(_ENV_TIMEOUT)
    if cap:
        try:
            limit = min(limit, float(cap))
        except (TypeError, ValueError):
            pass
    return max(limit, 0.001)


def run_gate(command: str, claimdir: str, recipe=None, timeout=None) -> dict:
    """THE GATE ENTRY POINT.  Everywhere a gate runs, it runs through here.

    Scrubbed environment (a hostile gate must not read an inherited secret and
    seal it into a verdict), a wall-clock ceiling (it must not hang the
    verifier), and the platform sandbox (it is not your shell).
    """
    if not isinstance(command, str) or not command.strip():
        raise ClaimError("a gate needs a run command")
    limit = gate_timeout(recipe, timeout)
    result, backend = sandbox(command, claimdir, timeout=limit, env=_scrub_env())
    result["quarantine"] = backend
    result["command"] = command
    result["timeout"] = limit
    return result


# ----------------------------------------------------------------- the ledger

def _ledger_path(claimdir: str) -> str:
    return os.path.join(claimdir, LEDGER)


def ledger(claimdir: str, event: dict) -> None:
    """Append one line of residue.  Residue lives outside the root."""
    path = _ledger_path(claimdir)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(event, sort_keys=True) + "\n")


def ledger_events(claimdir: str):
    """Every well-formed event on the ledger, or None if there is no ledger."""
    path = _ledger_path(claimdir)
    if not os.path.isfile(path):
        return None
    events = []
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    event = json.loads(line)
                except ValueError:
                    continue               # a damaged line is not an event
                if isinstance(event, dict):
                    events.append(event)
    except OSError:
        return None
    return events


def cost(claimdir: str):
    """What the redo cost, totalled from its ledger -- or None if unmeasured.

    Totals start at zero and carry only the keys the ledger actually names: an
    unmeasured machine is reported, never guessed at.
    """
    events = ledger_events(claimdir)
    if events is None:
        return None
    totals = {}
    for event in events:
        for key in COST_UNITS:
            value = event.get(key)
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                continue
            totals[key] = totals.get(key, 0) + value
    return totals or None


def _in_band(a, b, tolerance: float) -> bool:
    """Comparability is a BAND, [1/tol, tol] -- not equality."""
    if a == 0 and b == 0:
        return True
    if a == 0 or b == 0:
        return False
    ratio = float(a) / float(b)
    return (1.0 / tolerance) <= ratio <= tolerance


def independence(claimdir: str) -> dict:
    """What the redo DECLARED about who produced it.  A declaration, not proof."""
    declaration = {"vendor": None, "model": None, "blind": None, "declared": False}
    for event in ledger_events(claimdir) or []:
        if event.get("event") == "producer":
            declaration = {
                "vendor": event.get("vendor"),
                "model": event.get("model"),
                "blind": event.get("blind"),
                "declared": True,
            }
    return declaration


def _independence_line(claimdir: str) -> str:
    decl = independence(claimdir)
    vendor, model = decl.get("vendor"), decl.get("model")
    if not (isinstance(vendor, str) and vendor and isinstance(model, str) and model):
        return ("unestablished: content-independence cannot be established "
                "from content alone")
    blind = "blind workspace" if decl.get("blind") else "workspace not blind"
    return (f"declared: {vendor}/{model}, {blind} "
            f"(a declaration on the redo's ledger, not proven)")


# ------------------------------------------------------------ the workspace

def _materialize(claimdir: str, recipe, dest: str, produce_from=None,
                 input_from=None, include_generated=True) -> list:
    """Lay the claim out in a fresh workspace, every path crossing `_safe`.

    Gate outputs are never copied: a gate must re-earn its own output from the
    bytes present, and a stale copy would let a failed gate look answered.
    """
    produce_from = produce_from or {}
    input_from = input_from or {}
    os.makedirs(dest, exist_ok=True)
    _copy_into(os.path.join(claimdir, RECIPE), os.path.join(dest, RECIPE))

    for name in _inputs(recipe, claimdir):
        threaded = input_from.get(name)
        source = os.path.abspath(threaded) if threaded else _safe(claimdir, name)
        if not os.path.isfile(source):
            raise ClaimError(f"declared input is missing: {name}")
        _copy_into(source, _safe(dest, name))

    reused = []
    for step in produces(recipe):
        name = step.get("output")
        if not isinstance(name, str) or not name:
            continue
        supplied = produce_from.get(name)
        if supplied is not None:
            _copy_into(os.path.abspath(supplied), _safe(dest, name))
            reused.append(name)
            continue
        if step.get("class") == "generated" and not include_generated:
            continue                       # the producer will write it
        source = _safe(claimdir, name)      # refuses an output symlinked out
        if os.path.exists(source):
            _copy_into(source, _safe(dest, name))
    return reused


# ---------------------------------------------------------------- the audit

def audit(claimdir: str, produce_from=None) -> dict:
    """THE DEEP CHECK: re-earn every verdict on the bytes actually present.

    Claim-deep, not gate-shallow.  The root must still recompute (a spec
    substituted after sealing is caught even when the gate stays green), and
    every gate is re-run in a fresh workspace: a gate that fails is `failed`, a
    gate that passes but does not reproduce the pinned bytes is a `mismatch` (a
    carried verdict), a host that lacks a declared requirement is
    `environment` -- untested, not disproven.

    `produce_from` substitutes generated bytes, so gates COMPOSE: a dependent's
    shipped code is judged by the component's own claim rather than by the
    component's sealed copy of itself.
    """
    recipe = load_recipe(claimdir)
    manifest = read_manifest(claimdir)
    declared_gates = gates(recipe)

    missing = preflight(recipe)
    if missing:
        return {
            "ok": False,
            "claim_ok": None,
            "root": manifest.get("root"),
            "environment": missing,
            "gates": [{"output": g.get("output"), "status": "environment",
                       "quarantine": None, "returncode": None, "seconds": None,
                       "detail": f"host lacks {', '.join(missing)}"}
                      for g in declared_gates],
        }

    recomputed = root(recipe, claimdir)
    claim_ok = recomputed == manifest.get("root")

    scratch = tempfile.mkdtemp(prefix="reticuli-audit-")
    try:
        work = os.path.join(scratch, "work")
        _materialize(claimdir, recipe, work, produce_from=produce_from)
        results = []
        for step in declared_gates:
            name = step.get("output")
            outcome = run_gate(step["run"], work, recipe)
            entry = {
                "output": name,
                "status": outcome["status"],
                "quarantine": outcome["quarantine"],
                "returncode": outcome["returncode"],
                "seconds": round(outcome["seconds"], 3),
                "detail": "",
            }
            if outcome["status"] == "ok":
                entry.update(_compare_pin(claimdir, work, step))
            else:
                entry["detail"] = (outcome["stderr"] or outcome["stdout"])[-400:]
            results.append(entry)
        return {
            "ok": bool(claim_ok and all(g["status"] == "ok" for g in results)),
            "claim_ok": claim_ok,
            "root": manifest.get("root"),
            "recomputed": recomputed,
            "environment": [],
            "gates": results,
        }
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


def _compare_pin(claimdir: str, work: str, step) -> dict:
    """Did the gate reproduce the bytes the claim pins for it?"""
    name = step.get("output")
    if not isinstance(name, str) or not name:
        return {"status": "ok"}
    produced = os.path.join(work, name)
    if not os.path.exists(produced):
        return {"status": "failed", "detail": f"the gate produced no {name}"}
    if step.get("class") == "generated":
        return {"status": "ok"}            # nothing is pinned to compare against
    try:
        pinned_path = _safe(claimdir, name)
    except ClaimError:
        return {"status": "mismatch", "detail": f"{name} escapes the claim"}
    if not os.path.exists(pinned_path):
        return {"status": "mismatch", "detail": f"the claim pins no {name}"}
    try:
        same = _hash_file(pinned_path) == _hash_file(produced)
    except ClaimError as exc:
        return {"status": "mismatch", "detail": str(exc)}
    if same:
        return {"status": "ok"}
    return {"status": "mismatch",
            "detail": f"the gate passed but {name} is not the bytes it produces"}


def phase(claimdir: str) -> str:
    """draft -> sealed -> signed, and only ever for a well-formed claim.

    phase agrees with verify on validity: a claim verify refuses (a corrupt
    recipe or manifest, an input that escapes or is missing) is one phase
    refuses too, rather than answering a positive an auditor would misread.

    SIGNED = AUTHORIZED (a signature from a key this verifier anchors) AND
    PROVEN (a recorded proof) AND COHERENT (the stored packet matches both the
    signature and the bytes on disk).  Trust is verifier-relative.
    """
    recipe = load_recipe(claimdir)
    if not os.path.isfile(os.path.join(claimdir, MANIFEST)):
        return "draft"
    manifest = read_manifest(claimdir)
    recomputed = root(recipe, claimdir)
    if _authorized(claimdir, manifest, recomputed):
        return "signed"
    return "sealed"


def _authorized(claimdir: str, manifest, recomputed: str) -> bool:
    if manifest.get("root") != recomputed:
        return False                       # drifted claim: nothing is authorized
    proof = manifest.get("proof")
    if not proof:
        return False                       # authorized but not proven
    signdir = os.path.join(claimdir, SIGN_DIR)
    if not os.path.isdir(signdir):
        return False
    anchor = os.environ.get(_ENV_SIGNERS)
    if not anchor or not os.path.isfile(anchor):
        return False                       # no trust anchor: not signed TO YOU
    if not shutil.which("ssh-keygen"):
        return False
    try:
        digest = build_digest(claimdir)
    except ClaimError:
        return False
    for entry in sorted(os.listdir(signdir)):
        if not entry.endswith(".sign.json"):
            continue
        statement_path = os.path.join(signdir, entry)
        signature_path = statement_path + ".sig"
        if not os.path.isfile(signature_path):
            continue
        try:
            with open(statement_path, "rb") as f:
                statement = json.loads(f.read().decode("utf-8"))
        except (OSError, UnicodeDecodeError, ValueError):
            continue
        if not isinstance(statement, dict):
            continue
        identity = statement.get("identity")
        if not isinstance(identity, str) or not identity:
            continue
        packet_path = os.path.join(
            signdir, entry[:-len(".sign.json")] + ".packet.json")
        if not os.path.isfile(packet_path):
            continue
        try:
            with open(packet_path, "rb") as f:
                raw = f.read()
            packet = json.loads(raw.decode("utf-8"))
        except (OSError, UnicodeDecodeError, ValueError):
            continue
        if not isinstance(packet, dict):
            continue
        # the STORED packet is authoritative: the reviewable bundle on disk is
        # what the signature binds, so a swapped packet demotes even though the
        # live claim is untouched.
        if hashlib.sha256(raw).hexdigest() != statement.get("packet_digest"):
            continue
        if packet.get("root") != manifest.get("root"):
            continue
        if statement.get("root") != manifest.get("root"):
            continue
        # the signature froze the generated bytes: a rebuild after signing drifts
        if packet.get("build_digest") != digest:
            continue
        if not packet.get("proof") or packet.get("proof") != proof:
            continue
        # domain separation: an attestation must not authorize a mint
        if _ssh_verify(anchor, identity, SIGN_NAMESPACE,
                       signature_path, statement_path):
            return True
    return False


def _ssh_verify(anchor: str, identity: str, namespace: str,
                signature: str, data: str) -> bool:
    try:
        with open(data, "rb") as f:
            payload = f.read()
    except OSError:
        return False
    try:
        proc = subprocess.run(
            ["ssh-keygen", "-Y", "verify", "-f", anchor, "-I", identity,
             "-n", namespace, "-s", signature],
            input=payload, capture_output=True, check=False, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return False
    return proc.returncode == 0


# --------------------------------------------------------------- the rebuild

def rebuild(src: str, command: str, into: str, produce_from=None,
            input_from=None) -> dict:
    """Redo the claim in a blind workspace and seal what comes out.

    The workspace carries the claim and its pinned bytes but not its generated
    ones -- the producer writes those from the request alone (unless a
    component supplies them, which is ledgered as a reuse).  Every gate is run;
    the cost is accounted as residue; the verdict environment is ledgered.
    """
    recipe = load_recipe(src)
    missing = preflight(recipe)
    if missing:
        raise ClaimError("environment: this host cannot test the claim, it "
                         f"lacks {', '.join(missing)}")
    if not isinstance(command, str) or not command.strip():
        raise ClaimError("a rebuild needs a producer command")

    dest = os.path.abspath(into)
    if os.path.exists(dest) and (not os.path.isdir(dest) or os.listdir(dest)):
        raise ClaimError(f"the target already holds a claim: {dest}")
    os.makedirs(os.path.join(dest, STORE), exist_ok=True)

    backend = sandbox_backend()
    ledger(dest, {"event": "environment", "when": _now(),
                  "python": platform.python_version(),
                  "implementation": platform.python_implementation(),
                  "platform": sys.platform, "machine": platform.machine(),
                  "quarantine": backend, "shell": _SHELL})

    reused = _materialize(src, recipe, dest, produce_from=produce_from,
                          input_from=input_from, include_generated=False)
    for name in reused:
        ledger(dest, {"event": "reuse", "when": _now(), "output": name,
                      "note": "supplied by a component, not regenerated"})
    for name in input_from or {}:
        ledger(dest, {"event": "thread", "when": _now(), "input": name,
                      "note": "threaded from a rebuilt component"})

    _produce(recipe, dest, command, produce_from)

    for step in gates(recipe):
        name = step.get("output")
        outcome = run_gate(step["run"], dest, recipe)
        ledger(dest, {"event": "gate", "when": _now(), "output": name,
                      "status": outcome["status"],
                      "returncode": outcome["returncode"],
                      "quarantine": outcome["quarantine"],
                      "seconds": round(outcome["seconds"], 3)})
        if outcome["status"] != "ok":
            raise ClaimError(
                f"gate {name!r} {outcome['status']}: "
                f"{(outcome['stderr'] or outcome['stdout'])[-400:]}")
        if name and not os.path.exists(os.path.join(dest, name)):
            raise ClaimError(f"gate {name!r} passed but produced no {name}")

    manifest = seal(dest)
    return {"root": manifest["root"], "claim": dest, "reused": reused,
            "ledger": _ledger_path(dest), "quarantine": backend}


def _produce(recipe, dest: str, command: str, produce_from) -> None:
    """Run the oracle with cwd=dest and account what it cost."""
    outputs = generated_outputs(recipe)
    pending = [o for o in outputs
               if not os.path.exists(os.path.join(dest, o))]
    usage = os.path.join(dest, USAGE)
    try:
        os.remove(usage)
    except OSError:
        pass
    extra = {_ENV_CLAIM: dest,
             _ENV_USAGE: usage,                     # ABSOLUTE: `into` may be relative
             _ENV_OUTPUTS: json.dumps(outputs)}
    target = (pending or outputs or [None])[0]
    if target:
        extra[_ENV_OUTPUT] = _safe(dest, target)
        for step in produces(recipe):
            if step.get("output") == target and isinstance(step.get("request"), str):
                extra[_ENV_REQUEST] = step["request"]
    env = _scrub_env(extra)

    outcome = _run([_SHELL, "-c", command], cwd=dest, env=env,
                   timeout=PRODUCER_TIMEOUT)
    event = {"event": "oracle", "when": _now(), "calls": 1,
             "seconds": round(outcome["seconds"], 3),
             "status": outcome["status"]}
    for key, value in _read_usage(usage).items():
        if key in COST_KEYS and not isinstance(value, bool) \
                and isinstance(value, (int, float)):
            event[key] = value
    ledger(dest, event)
    ledger(dest, {"event": "producer", "when": _now(),
                  "vendor": os.environ.get(_ENV_VENDOR),
                  "model": os.environ.get(_ENV_MODEL),
                  "blind": not bool(produce_from),
                  "command": command})
    if outcome["status"] != "ok":
        raise ClaimError(
            f"the producer {outcome['status']} (rc={outcome['returncode']}): "
            f"{(outcome['stderr'] or outcome['stdout'])[-400:]}")


def _read_usage(path: str) -> dict:
    """A producer's self-reported cost.  Junk pollutes nothing."""
    try:
        with open(path, "rb") as f:
            raw = f.read()
    except OSError:
        return {}
    try:
        payload = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        return {}
    if not isinstance(payload, dict):
        return {}                          # a list is refused, not totalled
    return payload


# ------------------------------------------------------- the three machines

def crosscheck(m1: str, m2: str, m3: str, mutants=None, tolerance=None) -> dict:
    """THE THREE-MACHINE TEST.

    One root across an original (M1), a byte-reuse that travelled by content
    (M2), and an independent redo (M3) -- with every verdict re-earned on its
    own bytes.  Three DISTINCT machines: one directory presented thrice agrees
    with itself and proves nothing.  Root equality is identity, not soundness:
    a fabricated machine that shares the root but whose gates cannot reproduce
    its verdicts neither crosschecks nor signs.
    """
    machines = {"M1": m1, "M2": m2, "M3": m3}
    resolved = {}
    for label, path in machines.items():
        if not isinstance(path, str) or not os.path.isdir(path):
            raise ClaimError(f"{label} is not a claim directory: {path!r}")
        resolved[label] = os.path.realpath(path)
    if len(set(resolved.values())) != 3:
        raise ClaimError("the three-machine test needs three distinct machines; "
                         "the same directory presented twice proves nothing")

    roots, audited, digests = {}, {}, {}
    for label, path in machines.items():
        roots[label] = verify(path)["root"]
        audited[label] = bool(audit(path)["ok"])
        try:
            digests[label] = build_digest(path)
        except ClaimError:
            digests[label] = None

    equivalence = (all(isinstance(r, str) and r for r in roots.values())
                   and len(set(roots.values())) == 1)
    # REUSE is byte-reuse: M2 must be M1's generated bytes, not a second redo
    # that merely lands the same root.
    reuse = bool(digests["M1"] and digests["M2"]
                 and digests["M1"] == digests["M2"])

    recipe = load_recipe(m1)
    band = tolerance
    if band is None:
        band = (recipe.get("claim") or {}).get("tolerance")
    if band is None:
        band = os.environ.get(_ENV_TOLERANCE)
    try:
        band = float(band) if band is not None else TOLERANCE
    except (TypeError, ValueError):
        band = TOLERANCE
    if band <= 0:
        band = TOLERANCE

    original, redo = cost(m1), cost(m3)
    shared = {k for k in set(original or {}) & set(redo or {})
              if original[k] and redo[k]}
    unit = next((u for u in COST_LADDER if u in shared), None)
    comparable = None                      # unmeasured is REPORTED, not failed
    if unit is not None:
        comparable = _in_band(original[unit], redo[unit], band)

    score = None
    if mutants:
        score = mutation_score(m1, max_mutants=int(mutants))

    satisfied = bool(equivalence and reuse and all(audited.values())
                     and comparable is not False
                     and (score is None or score["ok"]))
    return {
        "satisfied": satisfied,
        "roots": roots,
        "equivalence": equivalence,
        "reuse": reuse,
        "audited": audited,
        "digests": digests,
        "cost": {"comparable": comparable, "M1": original, "M3": redo,
                 "unit": unit, "compared": sorted(shared), "tolerance": band},
        "mutation_score": score,
        "independence": _independence_line(m3),
        "machines": resolved,
    }


def record_proof(m1: str, m2: str, m3: str, mutants=None) -> dict:
    """Record a passing three-machine test as residue on M1's manifest.

    A recorded proof is not an authorization: it is the evidence a signature
    later binds.  A test that is not satisfied records nothing.
    """
    result = crosscheck(m1, m2, m3, mutants=mutants)
    recorded = False
    if result["satisfied"]:
        manifest = read_manifest(m1)
        manifest["proof"] = {
            "kind": "crosscheck",
            "root": result["roots"]["M1"],
            "m2": result["digests"]["M2"] or "",
            "m3": result["digests"]["M3"] or "",
            "independence": result["independence"],
            "recorded": _now(),
        }
        _write_json(os.path.join(m1, MANIFEST), manifest)
        recorded = True
    out = dict(result)
    out["proof_recorded"] = recorded
    return out


