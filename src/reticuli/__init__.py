"""Reticuli — claims that travel.

A claim is a directory holding a recipe (``claim.toml``), the pinned bytes the
recipe names, and the generated bytes an implementation is free to choose.  The
kernel layer is the bottom of the tower: it computes the claim's identity (the
root), seals and verifies it, re-earns its verdicts by running its gates inside
a platform sandbox, rebuilds it independently, and accounts what that cost.

Stdlib only, and it never reaches the network.
"""

__all__ = ["kernel"]

# One source of truth for the version: the installed distribution metadata
# (pyproject). ``ret --version`` and the record both read it, so a lone stale
# string here can never disagree with what the package actually is.
try:
    from importlib.metadata import version as _dist_version

    __version__ = _dist_version("reticuli")
except Exception:  # a bare source tree, not an installed distribution
    __version__ = "unversioned"
